/* 明细格里客户留的那句话，一句都不许丢 —— node 测试-明细格里的话.js

   ══ 这条路是怎么来的 ══
   2026-08-17 广东朱鲜生那张采购表，明细格里有两句话自己占一行、没写数量：
     第 7 行 水豆腐 底下　「盒装山水豆腐500g」   ← 那 4 斤其实是 4 盒山水豆腐 500g，¥3.50/盒
     第 11 行 南江豆腐 底下「要10板，5斤/板」     ← 分拣要按板装
   引擎把它们当空格子扔了（引擎-读结构.js 那个「空格子跳过」的 return），一声不吭。

   最要命的是【没有一道闸拦得住】：客户自己写的总数也没算这两句
     水豆腐 19 = 5+10+4　　南江豆腐 87 = 35+2+50
   我们算出来也是 19、87 —— 两边一起错、对得上，四道校验全绿。
   观麦那张单开的是 水豆腐 15斤 + 尝元山水豆腐（500g/盒）4盒，我们少开 8 块。

   老板 2026-08-18：「不要丢了，然后就直接跳出来一个弹窗，看需不需要添加。添加手动添加。」

   ══ 这份测试钉死四件事 ══
   ① 这种话必须捡回来（丢一句就是今天这种事故）
   ② 捡回来【不许动数量、不许动金额】—— 钱要跟捡之前一模一样，人点了才准变
   ③ 不许乱捡：写了数量的、纯点位码的（A3、S2944）都不归它管，不然窗天天弹，没人看
   ④ 页面真的把它接上了（引擎捡回来、页面不问，等于白捡）*/
global.window = {};
require("./引擎-解析.js");
require("./引擎-读结构.js");
var S = global.window.GM_STRUCT;
var fs = require("fs");

var pass = 0, fail = 0;
function ok(name, cond, why) {
  if (cond) { pass++; console.log("  ✅ " + name); }
  else { fail++; console.log("  ❌ " + name + (why ? "　—— " + why : "")); }
}

/* ══════════ 一、朱鲜生那张单：原样跑一遍 ══════════ */
console.log("\n── 朱鲜生 8/17（这个补丁就是它逼出来的）──");
var 朱鲜生 = {
  抬头: { 客户: "广东朱鲜生餐饮有限公司", 表上条数: 3 },
  行: [
    { 品名: "水豆腐", 单位: "斤", 表上总数: 19, 分布: [
      { 号: "11-8", 名: "佛山支队执勤二中队", 数: 5 },
      { 号: "11-9", 名: "佛山支队机动中队", 数: 10, 注: "8斤/板" },
      { 号: "2-3", 名: "西樵派出所（民乐）", 数: 4 },
      { 名: "盒装山水豆腐500g" }]},
    { 品名: "南江豆腐", 单位: "斤", 表上总数: 87, 分布: [
      { 号: "27-3", 名: "顺德机关服务中心-市监饭堂午餐", 数: 35 },
      { 号: "27-5", 名: "顺德机关服务中心-纪委饭堂", 数: 2 },
      { 号: "27-2", 名: "顺德机关服务中心-西座午餐", 数: 50 },
      { 名: "要10板，5斤/板" }]},
    { 品名: "百页", 单位: "斤", 表上总数: 6, 分布: [
      { 号: "11-6", 名: "佛山支队执勤四中队", 数: 6 }]}
  ]
};
{
  var r = S.读结构(朱鲜生);
  var 话 = (r.只有话 || []).map(function (x) { return x.话; });

  ok("★ 两句话都捡回来了，一句不少", 话.length === 2, JSON.stringify(话));
  ok("★「盒装山水豆腐500g」在里面", 话.some(function (t) { return /盒装山水豆腐500g/.test(t); }), JSON.stringify(话));
  ok("★「要10板，5斤/板」在里面", 话.some(function (t) { return /要10板/.test(t) && /5斤\/板/.test(t); }), JSON.stringify(话));
  ok("捡回来的话标着是哪一行哪样货（不然人不知道该往哪加）",
    (r.只有话 || []).every(function (x) { return x.行 > 0 && x.商品; }), JSON.stringify(r.只有话));

  /* ★★ 这四条是整个补丁「改不乱东西」的凭据：捡话只捡话，一分钱不碰。 */
  ok("★★ 水豆腐还是 19 斤（捡话不许动数量）", r.lines[0].qty === 19, String(r.lines[0].qty));
  ok("★★ 南江豆腐还是 87 斤（捡话不许动数量）", r.lines[1].qty === 87, String(r.lines[1].qty));
  ok("★★ 行数没变，没凭空多出一行货", r.lines.length === 3, String(r.lines.length));
  ok("★★ 段数没变：捡回来的话不许混进分布里当一段",
    r.lines[0].segs.length === 3 && r.lines[1].segs.length === 3,
    r.lines[0].segs.length + "/" + r.lines[1].segs.length);

  /* 客户自己写的总数也没算这两句 —— 所以总数那道账照样全绿。
     钉住这一条是为了记住：这个错【本来就没有闸拦得住】，只能靠捡回来问人。 */
  ok("总数那道账照旧全绿（正因为它绿，才必须有这个窗）",
    r.校验.length === 0, JSON.stringify(r.校验));
}

/* ══════════ 二、不许乱捡：窗要是天天弹，人就不看了 ══════════ */
console.log("\n── 什么不该捡 ──");
{
  var r2 = S.读结构({
    抬头: {}, 行: [
      { 品名: "大豆泡", 单位: "斤", 分布: [
        { 号: "A3" },                       /* 纯点位码，没汉字 → 这个点今天不要货 */
        { 号: "S2944" },                    /* 同上 */
        { 号: "E028", 名: "总店", 数: 5 },   /* 写了数量 → 正常一段，不归这儿管 */
        { 号: "B7", 名: "分店" }             /* 有汉字的点位名、没数量 → 会捡，见下面那条 */
      ]}
    ]
  });
  var 话2 = (r2.只有话 || []).map(function (x) { return x.话; });
  ok("★ 纯点位码（A3 / S2944）不捡 —— 没汉字就不是话",
    !话2.some(function (t) { return /A3|S2944/.test(t); }), JSON.stringify(话2));
  ok("★ 写了数量的那一段不捡（它是正常一段）",
    !话2.some(function (t) { return /总店/.test(t); }), JSON.stringify(话2));
  ok("大豆泡还是 5 斤，一个数没被带歪", r2.lines[0].qty === 5, String(r2.lines[0].qty));
  /* 「有汉字的点位名 + 没数量」确实会被捡起来问一句。
     这是【故意选的】：宁可多问一句，也不许再静默扔掉一句话。
     窗里默认就是「不加」，多问的那句人扫一眼跳过就完了；
     反过来漏一句就是 8/17 这种事故 —— 两边代价差着量级。 */
  ok("有汉字的点位名、没数量 → 捡起来问（宁可多问一句，不许再漏一句）",
    话2.some(function (t) { return /分店/.test(t); }), JSON.stringify(话2));
}

/* ══════════ 三、别踩到老规矩：数量写 0 的那条路是另一个人管的 ══════════
   「(A051 爱尔贝婴幼-1块)0斤」这种，真正的数量写在点位名尾巴上，
   引擎里 名带数 那段在捞（老板 2026-08-05 定的）。捡话绝不许伸手进去。 */
console.log("\n── 数量写 0 的老规矩不许被抢 ──");
{
  var r3 = S.读结构({
    抬头: {}, 行: [
      { 品名: "嫩豆腐", 单位: "斤", 分布: [
        { 号: "A051", 名: "爱尔贝婴幼-1块", 数: 0 },
        { 号: "B182", 名: "维比奇#幼儿-2块", 数: 0 },
        { 号: "A003", 名: "禧月荟", 数: 15 }
      ]}
    ]
  });
  ok("★ 名字尾巴带「-N块」的还是走老路捞成数量，没被捡话截胡",
    r3.lines[0].qty === 18, String(r3.lines[0].qty) + "（该是 15+1+2=18）");
  ok("★ 这三段一句话都不该捡", (r3.只有话 || []).length === 0, JSON.stringify(r3.只有话));
}

/* ══════════ 四、页面真的接上了没有 ══════════
   引擎捡回来、页面不问，等于白捡（记忆里那条「原型跑通≠已上线」就是栽在这儿）。 */
console.log("\n── 页面接上了没有 ──");
{
  var src = fs.readFileSync("./配送开单台.html", "utf8");
  ok("★ 页面有这个窗", /function 问要不要加\s*\(/.test(src));
  /* ⚠ 守意图不守写法：收下格子表 那条路上必须叫到「问要不要加」。
     原来这条钉的是 `innerHTML=头+下一步+补;` 这行字面，
     2026-08-21 那行改成先存进变量再赋值，它就误判成「没接上」了。 */
  ok("★ 格子那条路真调了它", /function 收下格子表\([\s\S]{0,9000}?问要不要加\(/.test(src));
  ok("★ 图片那条路也真调了它（两条路都得接，漏一条就有一半的单还在丢）",
    /ocr-msg"\)\.innerHTML=底;[\s\S]{0,400}问要不要加\(/.test(src));
  ok("★ 拿的是引擎给的 只有话", /问要不要加\(结构报告&&结构报告\.只有话\)/.test(src));
  ok("★ 没加成货的话要落进备注（不加也不许弄丢）", /function 备注添上\s*\(/.test(src));
  ok("★ 备注是往后接，不是「有字就算了」（丢一次就是事故）",
    /box\.value=\(有\?有\+"；":""\)\+添\.join/.test(src));
  ok("★ 选了「加」却没填数量 → 不许替人猜一个",
    /没填\.length/.test(src) && /我不会替你猜一个/.test(src));
  ok("★ 加进来的行带着来处（体检-行要有来处.js 盯着）",
    /addBlankLine\(\{text:a\.x\.话/.test(src));
  ok("★ 同一张单不许问第二遍（选完客户会重读一趟）", /话答过/.test(src));
}

console.log("\n" + (fail ? ("══ 没过 " + fail + " 项，过 " + pass + " 项")
                         : ("══ 全过（" + pass + " 项）")));
process.exit(fail ? 1 : 0);
