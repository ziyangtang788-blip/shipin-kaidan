/* ============================================================
   认列 —— 整张表按碎片类读，不看表头，不问 AI
   ============================================================

   ★ 现在上线的只有【钥匙()】那一段（老板 8/28 叫的「A」）：
     只换「这张单我见没见过」那把钥匙，怎么读还是老一套，旧单一个字不动。
   ★ 【认列() / 摊()】还没接进页面，留给下一轮（老板叫的「B」：新单走学习）。
     老板 8/28：「做完 A，B 始终也是要做的呀，不然你新带来的还是没入口。」
     ⚠ 写在同一个文件里是【故意的】：钥匙和认列量的是同一批东西
       （每一列什么类），拆成两份迟早各说各话。CLAUDE.md：只准一份。

   ============================================================

   老板 2026-08-28 点的题：
     「我要的就是任何一种新表，过来是走这一套的呀。
     　我的学习功能是干嘛的呢？就是为了做这个事情啊。」
     「这张表其实也很简单。」

   他的底层逻辑（8/27）：
     一张单无非四样 —— 什么东西、有多少、单位是什么、送去哪里，然后再备注。

   ⛔ 现在的路子错在哪：
     先问 AI「表头在第几行、第一样货叫什么、一共几行、哪列是哪列」——
     问的全是【这张表长什么样】，一个都不是那四样。
     形状是无穷的（抬头几层、表头叫什么、OCR 抄错一个字）；
     四样是有限的（货名有词库、数字一眼看得出、单位有表、地址是一坨中文）。
     系统架在无穷的那一边，所以每来一种新表都出事。

     8/28 轩宝那张：抬头压了 4 层，骨架只给 AI 看头 4 行 —— 一行货都没露出来，
     AI 只好拿最后一行当第一样货，18 行货出成 1 行，三道对账还全部自动对上。

   ★ 这个文件干的事，跟 引擎-碎片类.js 在【一格之内】干的完全是同一件，
     只是把对象从「一格里的碎片」换成「整张表的列」：
       代码只干一件事：机械归类，一个字都不猜
       算得出来的就不问（老板：「有知道的已经跑通了，那些就不需要问」）
       算不出唯一解 → 问一次，按整列记住

   ⚠ 本文件只管【认列 + 划货行】，不碰摊平、不弹窗、不存东西。
   ⚠ 一个字都不许看表头文字 —— 这正是它比老路子强的全部原因。
   ============================================================ */
(function (root) {
  "use strict";

  /* ⚠ 2026-08-28 真跑 OCR 撞出来的：OCR 会把某些格子输出成 markdown 粗体 —— `**5**`。
     星号一带上，那一格就从「数字」变成了「码」，整把钥匙跟着变，
     同一张表今天加粗、明天不加粗就成了两张表，白问一次。
     只削【首尾】的星号：「正方形6.5cm*厚1.5cm」当中那个星号是数据，一个都不许动。 */
  function 字(v) {
    if (v === null || v === undefined) return "";
    return String(v).trim().replace(/^\*+/, "").replace(/\*+$/, "").trim();
  }
  function 数(v) {
    var s = 字(v).replace(/,/g, "");
    if (!/^-?[0-9]+(\.[0-9]+)?$/.test(s)) return null;
    return parseFloat(s);
  }
  function 约等(a, b) { return Math.abs(a - b) < 0.005; }

  /* ═══ 货名词表 ═══
     老板 8/27：「品名很多词自己可以认得出来」—— 说的就是这个，我第一版漏了。
     把价格库那 217 个商品名拆成两字一片（豆腐 / 豆干 / 千张 / 腐竹 …），
     哪一列的格子命中得多，哪一列就是品名。
     ⚠ 用两字片段、不用整名：客户嘴里的叫法跟我们库里从来对不上
       （「千张（豆皮）」对「千张」、「白豆干」对「炸豆干」），
       但只要是豆制品，两字片段一定咬得住。
     ⚠ 这不是猜，是【查已知的】—— 词库里有的才算数。 */
  var _词表 = null;
  function 货名片() {
    if (_词表) return _词表;
    _词表 = {};
    var ps = ((root.GM_DATA || {}).prods) || [];
    ps.forEach(function (n) {
      var s = 字(n).replace(/[（(][^）)]*[)）]/g, "").replace(/尝元/g, "");
      for (var i = 0; i + 1 < s.length; i++) {
        var g = s.slice(i, i + 2);
        if (/^[一-龥]{2}$/.test(g)) _词表[g] = 1;
      }
    });
    return _词表;
  }
  function 像货名(v) {
    var 表 = 货名片(), s = 字(v);
    for (var i = 0; i + 1 < s.length; i++) if (表[s.slice(i, i + 2)]) return true;
    return false;
  }

  /* ═══ 零、钥匙：这张单我见过吗 ═══
     老板 2026-08-28 定的：
       「已经跑通的那些就不需要去学习了，就是新来的订单才要学。
       　之前的内容一定不能影响。所以你要有一个判定，它到底是新单还是旧单。」

     ⛔ 现在这把钥匙是拿【表头文字】算的，这正是 8/28 事故的根子：
       OCR 把「明细」抄成「限额」——一个词——钥匙就变了，
       读法本里 17 条一条都对不上，系统当它是没见过的表，
       掉进近道闷头读，19 行货压在一个点上出了单。

     ★ 换成拿【每一列是什么类】算：中文 / 字母数字 / 数字+单位 / 单位词。
       老板 8/27 那句：中文和字母数字的边界，是唯一不会变的东西。
       表头抄错、抬头多压一层、日期换一天 —— 这把钥匙都不变。

     ⚠ 空列记成「·」而不是丢掉：丢掉的话「备注这天没人填」就会换一把钥匙。 */
  function 钥匙(rows) {
    var 列数 = 0;
    (rows || []).forEach(function (r) { if ((r || []).length > 列数) 列数 = (r || []).length; });
    if (!列数) return "";
    var 片 = [];
    for (var c = 0; c < 列数; c++) {
      var z = 量一列(rows, c, 列数);
      if (!z.有几格) { 片.push("·"); continue; }
      if (z.单位占比 >= 0.8) { 片.push("单位"); continue; }
      if (z.数占比 >= 0.8) { 片.push("数"); continue; }
      if (z.像货占比 >= 0.5) { 片.push("货名"); continue; }
      片.push(z.主类 || "杂");
    }
    return 列数 + "×" + 片.join("|");
  }

  /* ═══ 一、每一列长什么样 ═══
     只统计三样最原始的东西：填了几格、碎片类怎么分布、是不是单位词。
     ⛔ 不看表头、不看列名词、不看位置。 */
  /* 抬头行：整行只有一两格有字（供应商／联系人／打印时间／单据日期）。
     它跟这张表的列结构没关系，【不许参与列统计】——
     8/28 实测：让它参与的话，多压一层抬头就有 7 张表换了钥匙，
     等于同一张表被当成没见过的新表，白问一次。
     ⚠ 这不是「猜哪几行是抬头」：判据只是「这一行填了几格」，一个字都不用看。 */
  function 算得上一行(r, 列数) {
    var n = 0;
    for (var i = 0; i < 列数; i++) if (字((r || [])[i])) n++;
    return n * 2 >= 列数;
  }

  function 量一列(rows, c, 列数) {
    var F = root.GM_碎片, P = root.GM_PARSE;
    var 单位表 = (P && P.单位字) ? new RegExp("^(" + P.单位字 + ")$") : /^(斤|板|盒|包|块|个|只|份|袋|箱|条|串|件|桶|把|碗|公斤|千克|kg|KG)$/;
    if (!列数) { 列数 = 0; (rows || []).forEach(function (r) { if ((r || []).length > 列数) 列数 = (r || []).length; }); }
    var 值 = [], 行号 = [];
    for (var i = 0; i < rows.length; i++) {
      if (!算得上一行(rows[i], 列数)) continue;
      var v = 字((rows[i] || [])[c]);
      if (v) { 值.push(v); 行号.push(i); }
    }
    var 类计 = {}, 是单位 = 0, 数们 = [], 像货 = 0;
    值.forEach(function (v) {
      var t = F ? F.归类(v) : "";
      类计[t] = (类计[t] || 0) + 1;
      if (单位表.test(v)) 是单位++;
      if (像货名(v)) 像货++;
      var n = 数(v);
      if (n !== null) 数们.push(n);
    });
    var 主类 = "", 最多 = 0;
    Object.keys(类计).forEach(function (k) { if (类计[k] > 最多) { 最多 = 类计[k]; 主类 = k; } });
    return {
      列: c + 1, 值: 值, 行号: 行号, 有几格: 值.length,
      主类: 主类, 主类占比: 值.length ? 最多 / 值.length : 0,
      单位占比: 值.length ? 是单位 / 值.length : 0,
      /* ⛔ 不许用「整列都是数字」当判据：表头那一格的字（「数量」「汇总合计」）
         也在这一列里，一混进来整列就不算数字列了 —— 8/28 第一版就栽在这儿。
         用占比：绝大多数是数字就算数字列，表头那一格是杂音。
         这也正是不看表头的意思 —— 表头不是要跳过的东西，它本来就只是一格杂音。 */
      数占比: 值.length ? 数们.length / 值.length : 0, 数们: 数们,
      像货占比: 值.length ? 像货 / 值.length : 0,
      和: Math.round(数们.reduce(function (a, b) { return a + b; }, 0) * 100) / 100,
      不同值: (function () { var s = {}; 值.forEach(function (v) { s[v] = 1; }); return Object.keys(s).length; })()
    };
  }

  /* ═══ 二、哪几行是货 ═══
     判据只有一条，跟表头没关系：
       这一行【既有一坨中文、又有一个数字】—— 那它就是一行货。
     抬头行（供应商/联系人/打印时间）没有数字跟中文并排；
     表头行整行都是词、一个数字都没有；
     合计行只有「合计」两个字加一个数，中文那格不带任何编号 —— 靠下面的账剔掉。 */
  function 划货行(rows, 中文列们, 数字列们) {
    var 出 = [];
    for (var i = 0; i < rows.length; i++) {
      var r = rows[i] || [];
      var 有中 = 中文列们.some(function (c) { return !!字(r[c - 1]); });
      var 有数 = 数字列们.some(function (c) { return 数(r[c - 1]) !== null; });
      if (有中 && 有数) 出.push(i);
    }
    return 出;
  }

  /* ═══ 三、认那四样 ═══ */
  function 认列(rows) {
    var 列数 = 0;
    (rows || []).forEach(function (r) { if ((r || []).length > 列数) 列数 = (r || []).length; });
    if (!列数) return { 要问的: ["这张表是空的"] };

    var 量 = [];
    for (var c = 0; c < 列数; c++) 量.push(量一列(rows, c, 列数));

    /* —— 单位列：纯中文，而且值几乎全都是单位表里的词 —— */
    var 单位列 = null;
    量.forEach(function (z) {
      if (z.有几格 >= 1 && z.单位占比 >= 0.8 && (!单位列 || z.单位占比 > 单位列.单位占比)) 单位列 = z;
    });

    /* —— 数字列 / 中文列 —— */
    var 数字列们 = 量.filter(function (z) { return z.有几格 >= 1 && z.数占比 >= 0.8; })
      .map(function (z) { return z.列; });
    var 中文列们 = 量.filter(function (z) {
      return z.有几格 >= 1 && z.数占比 < 0.8 && /中文/.test(z.主类) && z.主类占比 >= 0.7 &&
        (!单位列 || z.列 !== 单位列.列);
    }).map(function (z) { return z.列; });

    var 货行 = 划货行(rows, 中文列们, 数字列们);
    if (!货行.length) return { 要问的: ["一行货都认不出来"] };

    /* —— 数量列：货行上填得最满的那根数字列 ——
       ⚠ 汇总列（合并单元格那种）只在每一块的头一行有值，天生填不满。 */
    function 货行里填了几格(c) {
      var n = 0;
      货行.forEach(function (i) { if (数((rows[i] || [])[c - 1]) !== null) n++; });
      return n;
    }
    var 排 = 数字列们.map(function (c) { return { 列: c, 满: 货行里填了几格(c) }; })
      .sort(function (a, b) { return b.满 - a.满; });
    if (!排.length) return { 要问的: ["找不到数量那一列"] };
    var 数量列 = 排[0].列;
    /* 并列第一 —— 自己定不下来，问人（老板：算不出来的才问） */
    if (排.length > 1 && 排[1].满 === 排[0].满) {
      var 打平 = 排.filter(function (x) { return x.满 === 排[0].满; }).map(function (x) { return x.列; });
      return { 要问的: ["有 " + 打平.length + " 列数字都填得一样满，认不出哪列是数量"], 候选数量列: 打平 };
    }

    /* —— 表尾那行「合计」不是货 ——
       ⛔ 不许靠「合计」这两个字认它 —— 那又是在猜形状，换个词（总计/小计/合计数）就废。
       用账认：这一行的数字 = 【其余所有行加起来】，那它就是那一行的总账，不是一行货。
       ⚠ 只在货行 ≥4 时才敢这么剔：两三行的小表里，
         「3 和 3」这种也满足「等于其余之和」，会把真货剔掉。 */
    if (货行.length >= 4) {
      var 总 = 0;
      货行.forEach(function (i) { var n = 数((rows[i] || [])[数量列 - 1]); if (n !== null) 总 += n; });
      for (var q = 货行.length - 1; q >= 0; q--) {
        var v = 数((rows[货行[q]] || [])[数量列 - 1]);
        if (v !== null && v > 0 && 约等(v, 总 - v)) { 货行.splice(q, 1); break; }
      }
    }

    /* —— 汇总列：值 = 它所辖那几行的数量之和 ——
       11 = 3+8　163 = 140+3+8+8+4　30 = 12+18
       ★ 这条账是【角色的证据】，不是校验：能对上，它就是校验数，不是数量。 */
    var 汇总列 = null;
    数字列们.forEach(function (c) {
      if (c === 数量列) return;
      var z = 量[c - 1];
      if (!z.有几格 || z.有几格 >= 货行.length) return;      /* 填满的不是汇总 */
      var 块 = 切块(rows, c, 货行), 对上了 = 0;
      块.forEach(function (b) {
        var 和 = 0;
        b.行们.forEach(function (i) { var n = 数((rows[i] || [])[数量列 - 1]); if (n !== null) 和 += n; });
        if (约等(和, b.值)) 对上了++;
      });
      if (块.length && 对上了 === 块.length) 汇总列 = c;
    });

    /* —— 品名 / 送去哪里 ——
       两根都是中文列。分开靠【填得满不满】：
         送去哪里　每一行货都得写（不写就不知道往哪送）
         品名　　　合并单元格的表只在块首写一次
       ⚠ 一行一货的表两根都填满 —— 那就分不出来了，问人。 */
    var 中文排 = 中文列们.map(function (c) {
      var n = 0;
      货行.forEach(function (i) { if (字((rows[i] || [])[c - 1])) n++; });
      return { 列: c, 满: n };
    }).sort(function (a, b) { return b.满 - a.满; });

    var 地址列 = null, 品名列 = null;
    if (中文排.length === 1) { 品名列 = 中文排[0].列; }
    else if (中文排.length >= 2) {
      /* ① 先查词库 —— 哪一列的字在货名词表里咬得住，哪一列就是品名。
         ⚠ 这条排在【填得满不满】前面：一行一货的表两列都填满，
           光靠填充率永远分不开，可词库一查就分开了。 */
      var 按货 = 中文排.map(function (x) { return { 列: x.列, 货: 量[x.列 - 1].像货占比, 满: x.满 }; })
        .sort(function (a, b) { return b.货 - a.货; });
      if (按货[0].货 >= 0.5 && 按货[0].货 > 按货[1].货 + 0.2) {
        品名列 = 按货[0].列;
        /* 送去哪里 = 剩下的中文列里填得最满的那根 */
        var 剩 = 中文排.filter(function (x) { return x.列 !== 品名列; });
        if (剩.length) 地址列 = 剩[0].列;
      } else if (中文排[0].满 > 中文排[1].满) {
        /* ② 词库分不开，再看填得满不满：送去哪里每行都得写，
           品名在合并单元格的表里只在块首写一次。 */
        地址列 = 中文排[0].列; 品名列 = 中文排[1].列;
      } else {
        return {
          要问的: ["有两列中文都填得一样满、词库也分不开，认不出哪列是品名、哪列是送货点"],
          候选中文列: 中文排.map(function (x) { return x.列; }), 货行: 货行
        };
      }
    }

    return {
      货行: 货行, 品名列: 品名列, 数量列: 数量列,
      单位列: 单位列 ? 单位列.列 : null, 地址列: 地址列, 汇总列: 汇总列,
      /* 认不出是什么的列 —— 不是那四样，一个字都不动它（老板 8/2：只抓四样） */
      没认出来的列: 量.filter(function (z) {
        return z.有几格 >= 1 && [品名列, 数量列, 地址列, 汇总列, 单位列 && 单位列.列]
          .indexOf(z.列) < 0;
      }).map(function (z) { return z.列; })
    };
  }

  /* 合并单元格：一个值管到下一个值出现之前那几行 */
  function 切块(rows, c, 货行) {
    var 块 = [], 当前 = null;
    货行.forEach(function (i) {
      var v = 数((rows[i] || [])[c - 1]);
      if (v !== null) { 当前 = { 值: v, 行们: [i] }; 块.push(当前); }
      else if (当前) 当前.行们.push(i);
    });
    return 块;
  }

  /* ═══ 四、照认出来的列，把货摊出来 ═══ */
  function 摊(rows, 读法) {
    var 出 = [], 上一名 = "", 上一单位 = "";
    (读法.货行 || []).forEach(function (i) {
      var r = rows[i] || [];
      var 名 = 字(r[(读法.品名列 || 0) - 1]) || 上一名;      /* 合并单元格：接着上一行的名 */
      var 量 = 数(r[(读法.数量列 || 0) - 1]);
      var 单位 = 字(r[(读法.单位列 || 0) - 1]) || 上一单位;
      var 址 = 字(r[(读法.地址列 || 0) - 1]);
      if (名) 上一名 = 名;
      if (单位) 上一单位 = 单位;
      if (量 === null || !名) return;
      出.push({ 第几行: i + 1, 品名: 名, 数量: 量, 单位: 单位, 送去哪里: 址 });
    });
    return 出;
  }

  root.GM_整表碎片 = { 认列: 认列, 摊: 摊, 量一列: 量一列, 划货行: 划货行, 钥匙: 钥匙 };
})(typeof window !== "undefined" ? window : globalThis);
