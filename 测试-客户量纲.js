const path = require("path"), fs = require("fs");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./数据-客户量纲.js", "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js",
 "./引擎-读结构.js", "./引擎-认表.js"].forEach(f => require(path.resolve(__dirname, f)));
const W = global.window, 量纲 = W.GM_客户量纲, D = W.GM_DATA;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}

/* ══════ 一、该乘几 ══════ */
console.log("\n【一、哪些乘、哪些不乘】");
(function () {
  const 乘 = (cid, 名) => { const r = 量纲.该乘几(cid, 名); return r ? r.乘 : null; };
  ok("好好多 饺子皮 → ×2", 乘("S3114", "饺子皮") === 2);
  ok("好好多 云吞皮 → ×2", 乘("S3114", "云吞皮") === 2);
  ok("好好多 炸豆卜 → ×2", 乘("S3114", "炸豆卜") === 2);
  /* 表上写「豆串」，库里叫「尝元豆腐串（串）」—— 两个写法都不许乘 */
  ok("好好多 豆串 → 不乘", 乘("S3114", "豆串") === null);
  ok("好好多 尝元豆腐串（串） → 不乘", 乘("S3114", "尝元豆腐串（串）") === null);
  ok("好好多 豆腐串 → 不乘", 乘("S3114", "豆腐串") === null);
  /* ⚠ 别的客户一个字都不许沾 —— 单条特例不许动全局 */
  ok("别的客户（碧源 S2949）→ 不乘", 乘("S2949", "饺子皮") === null);
  ok("没客户 → 不乘", 乘("", "饺子皮") === null && 乘(null, "饺子皮") === null);
})();

/* ══════ 二、幂等 ★ 最要命 ══════
   照页面 rematch 里那段原样跑一遍，跑四次，结果必须跟跑一次一样。 */
console.log("\n【二、跑几次都只乘一次 ★】");
(function () {
  function 跑一遍(cid, L) {                    /* ← 跟 配送开单台.html rematch 里那段同构 */
    if (cid && 量纲 && !L.量纲乘过) {
      const 量 = 量纲.该乘几(cid, L.text);
      if (量) {
        const 倍 = 量.乘;
        (L.segs || []).forEach(g => { if (typeof g.qty === "number" && g.qty > 0) g.qty *= 倍; });
        if (typeof L.qty === "number" && L.qty > 0) L.qty *= 倍;
        L.量纲乘过 = 倍; L.量纲说明 = 量.从 + "→" + 量.到 + " ×" + 倍;
      }
    }
  }
  const L = { text: "饺子皮", qty: 3, segs: [{ qty: 1 }, { qty: 2 }] };
  跑一遍("S3114", L);
  ok("第一次：3 → 6", L.qty === 6, "qty=" + L.qty);
  ok("第一次：分布 1,2 → 2,4", L.segs[0].qty === 2 && L.segs[1].qty === 4,
     JSON.stringify(L.segs.map(g => g.qty)));
  跑一遍("S3114", L); 跑一遍("S3114", L); 跑一遍("S3114", L);
  ok("再跑三次：还是 6，没变成 48", L.qty === 6, "qty=" + L.qty);
  ok("再跑三次：分布还是 2,4", L.segs[0].qty === 2 && L.segs[1].qty === 4,
     JSON.stringify(L.segs.map(g => g.qty)));
  ok("留了痕（页面要摆出来）", L.量纲说明 === "公斤→斤 ×2", L.量纲说明);

  const 串 = { text: "豆串", qty: 10, segs: [{ qty: 10 }] };
  跑一遍("S3114", 串); 跑一遍("S3114", 串);
  ok("豆串跑两次也不动：还是 10", 串.qty === 10 && 串.segs[0].qty === 10, "qty=" + 串.qty);
  ok("豆串没留痕（本来就没改）", !串.量纲说明);
})();

/* ══════ 三、页面里那段必须带幂等闸 ══════
   node 跑不了页面，只能读源码钉住 —— 哪天有人把标记删了，这条当场变红。 */
console.log("\n【三、页面 rematch 里的幂等闸还在吗】");
(function () {
  const h = fs.readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  ok("页面调了 该乘几", /GM_客户量纲[\s\S]{0,80}该乘几/.test(h));
  ok("有幂等标记 L.量纲乘过", /!L\.量纲乘过/.test(h));
  ok("乘完打上标记", /L\.量纲乘过\s*=/.test(h));
  ok("分布里每段也乘了", /segs\|\|\[\]\)\.forEach[\s\S]{0,120}\*=\s*倍/.test(h));
  ok("页面上把它摆出来了（不许悄悄改）", /r\.量纲\?/.test(h));
  ok("script 标签引了这个文件", /数据-客户量纲\.js\?v=/.test(h));
})();

/* ══════ 四、拿好好多那 9 样货真算一遍 ══════ */
console.log("\n【四、好好多 8.20 那张单：该乘的乘、豆串不动】");
(function () {
  /* 8.20 那张表「总计」行的原数（公斤） */
  const 单 = [["饺子皮", 14], ["云吞皮", 5], ["炸豆卜", 11], ["攸县干", 6], ["乡下烟干", 2],
             ["散装豆皮", 7], ["油片", 2], ["豆串", 10], ["豆腐丝", 2]];
  let 原 = 0, 后 = 0, 乘了 = [], 没乘 = [];
  单.forEach(([n, q]) => {
    原 += q;
    const r = 量纲.该乘几("S3114", n);
    if (r) { 后 += q * r.乘; 乘了.push(n); } else { 后 += q; 没乘.push(n); }
  });
  ok("原总量 59（表上总计）", 原 === 59, "原=" + 原);
  ok("乘完 108 = (59−10)×2 + 10", 后 === 108, "后=" + 后);
  ok("只有豆串没乘", 没乘.length === 1 && 没乘[0] === "豆串", "没乘: " + 没乘.join("、"));
  ok("其余 8 样都乘了", 乘了.length === 8, "乘了 " + 乘了.length + " 样");
})();

/* ══════ 五、库里那 14 个品，单位是「串」的只有一个 ══════
   哪天好好多又添了按个数卖的货，这条会变红，提醒去 不乘的 里补一笔。 */
console.log("\n【五、库里按个数卖的货，都在「不乘的」名单里吗】");
(function () {
  const ci = (D.custs || []).findIndex(c => c[0] === "S3114");
  const 我 = (D.items || []).filter(x => x[0] === ci);
  const 非重量 = 我.filter(x => !/^(斤|公斤|千克)$/.test(String(x[3] || "")));
  console.log("     好好多名下 " + 我.length + " 个品，按个数/件卖的 " + 非重量.length + " 个：" +
              非重量.map(x => x[2] + "（" + x[3] + "）").join("、"));
  const 漏 = 非重量.filter(x => 量纲.该乘几("S3114", x[2]) !== null);
  ok("按个数卖的都已排除，没有漏网的", 漏.length === 0,
     漏.length ? "⚠ 这几个会被错误地 ×2：" + 漏.map(x => x[2] + "（" + x[3] + "）").join("、") : "");
})();

console.log("\n════════════════════════");
console.log("过 " + 过 + "　挂 " + 挂);
process.exit(挂 ? 1 : 0);
