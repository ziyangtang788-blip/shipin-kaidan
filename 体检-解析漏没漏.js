let 问题 = [];
/* 多字单位要排在前面，否则 2.6kg 会被当成「2.6k」+ 剩一个 g */
const U = "(?:公斤|kg|KG|Kg|中板|大板|小板|大盒|小盒|[斤板块条串包盒件袋桶个箱把张只gG])";

/* 该有几段 —— 只数「括号后面紧跟数字」这一种，因为掉段只可能掉在这里。
   商品名里的规格（2.6kg、14斤/板）一概不算，算了就是假警报。
   假警报比不报还坏：报多了人就不看了。 */
function 该有几段(raw) {
  /* 只看数量那一侧：有 Tab 就看 Tab 之后，商品名里的括号一概不管 */
  let s = P.toHalf(raw);
  const tab = s.lastIndexOf("\t");
  if (tab >= 0) s = s.slice(tab + 1);
  /* 括号里必须有数字或字母才算点位号 —— 「（小板）」「（靓）」这种是商品名的一部分 */
  const re = new RegExp("[(（\\[【]([^)）\\]】]{1,40})[)）\\]】]\\s*([0-9]+(?:\\.[0-9]+)?)\\s*(" + U + "?)", "g");
  let n = 0, m;
  while ((m = re.exec(s)) !== null) {
    if (!/[0-9A-Za-z]/.test(m[1])) continue;
    /* (5斤装)3板 里的括号是规格不是点位 */
    if (new RegExp("^[0-9.]+\\s*(?:[A-Za-z]{1,4}|" + U + ")?\\s*装$").test(m[1].trim())) continue;
    n++;
  }
  /* 冒号写法：点位:数量单位 + 点位:数量单位（观麦「明细」列）。
     只在有 Tab 时数，跟解析那边同一个门槛 —— 没 Tab 的「熟猪血： 12 斤」不算点位。 */
  if (tab >= 0) {
    let c = 0;
    s.split(/[+＋]/).forEach(seg => {
      if (new RegExp("^\\s*(.+?)\\s*[:：]\\s*[0-9]+(?:\\.[0-9]+)?\\s*(" + U + "?)").test(seg)) c++;
    });
    if (c > n) n = c;
  }
  return n;
}

function 查一条(raw) {
  let lines;
  try { lines = P.parseOrder(raw); }
  catch (e) { 问题.push({ raw, why: "解析直接抛错：" + e.message, 级别: "炸了" }); return; }

  if (!lines.length) {
    /* 整行只有标题（「鹏运：」）时是正常的 */
    if (!/[0-9]/.test(raw)) return;
    问题.push({ raw, why: "一行都没解析出来，但原文里有数字", 级别: "掉整行" });
    return;
  }

  const 段数 = lines.reduce((a, l) => a + l.segs.length, 0);
  const 应有 = 该有几段(raw);
  if (应有 > 段数) {
    问题.push({
      raw, 级别: "掉段",
      why: "原文里 " + 应有 + " 个「(点位)数量」，只解析出 " + 段数 + " 段 —— 会少发货",
      详: lines.map(l => l.text + " = " + l.qty + (l.unit || "") +
        "（段：" + l.segs.map(g => g.qty + "@" + (g.code || "-")).join(" ") + "）").join(" ｜ ")
    });
  }

  lines.forEach(l => {
    if (!(l.qty > 0)) 问题.push({ raw, 级别: "零数量", why: "「" + l.text + "」解析出来数量是 " + l.qty });
  });

  /* 原文括号里像点位号（有数字/字母），解析完却一个点位都没有 */
  const br = P.toHalf(raw).match(/[(（\[【]([^)）\]】]{1,40})[)）\]】]/g) || [];
  const 像点位 = br.filter(b => {
    const inner = b.slice(1, -1);
    if (!/[0-9A-Za-z]/.test(inner)) return false;
    if (new RegExp("^[0-9.]+\\s*(?:[A-Za-z]{1,4}|" + U + ")?\\s*装$").test(inner)) return false;
    if (/[\/／]/.test(inner)) return false;                 /* (40条/件) 是规格 */
    if (new RegExp("^[0-9.]+\\s*" + U + "$").test(inner)) return false;  /* (7盒) 是总数 */
    return true;
  });
  if (像点位.length) {
    const 有码 = lines.some(l => l.segs.some(g => g.code));
    if (!有码) 问题.push({ raw, 级别: "掉点位", why: "原文里 " + 像点位.join(" ") + " 像点位，解析完一个都没留下" });
  }
}

样例.forEach(查一条);

