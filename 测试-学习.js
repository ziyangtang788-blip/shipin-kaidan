/* 学过的对照 —— 会不会「教一个丢一个」
   node 测试-学习.js

   老板反复说过「教了很多次为什么还学不会」。查下来根子在这：
   原来学过的东西按「客户||词」存，不记单位。
   碧源的「水豆腐」按斤 ¥1.5、按板 ¥6.5，是两个商品；
   教会了斤那条，下次表上写「水豆腐 3板」会被斤那条整个截胡，
   还挂着「已学会」的绿标 —— 人根本看不出来它错了。
   不是没学会，是学到的互相覆盖了。

   现在键是「客户||单位||词」，另外再存一条不带单位的通用条，
   通用条和老键在读的时候都要过一道单位关。这个文件就是钉死这套规矩。 */
const P = (() => { global.window = {}; require("./引擎-解析.js"); return global.window.GM_PARSE; })();
const { lkey, keyParts, learnedLookup } = P;

let pass = 0, fail = 0;
function ok(name, got, want) {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; console.log("  ✅ " + name); }
  else { fail++; console.log("  ❌ " + name + "\n        实得 " + g + "\n        应为 " + w); }
}

/* 假装的价格表：同一个客户，「水豆腐」有斤装和板装两个商品 */
const UNITS = { "SKU水斤": "斤", "SKU水板": "板", "SKU中板": "板", "SKU千叶包": "包", "SKU外人": "斤" };
const IN_STOCK = { "SKU水斤": 1, "SKU水板": 1, "SKU中板": 1, "SKU千叶包": 1 };   /* SKU外人 不在这家售 */
const unitOf = sku => IN_STOCK[sku] ? UNITS[sku] : null;
const look = (maps, text, unit) => learnedLookup(maps, "S2949", text, unit, unitOf);

/* ---------- 教一个丢一个（这次修的正主） ---------- */
console.log("\n【教「水豆腐[斤]」之后，「水豆腐[板]」不能被带偏】");
{
  const m = {};
  m[lkey("S2949", "斤", "水豆腐")] = "SKU水斤";
  m[lkey("S2949", "", "水豆腐")] = "SKU水斤";
  ok("斤 → 认得", look(m, "水豆腐", "斤"), "SKU水斤");
  ok("板 → 不认（回去问人）", look(m, "水豆腐", "板"), null);

  /* 人把板的也教了 */
  m[lkey("S2949", "板", "水豆腐")] = "SKU水板";
  m[lkey("S2949", "", "水豆腐")] = "SKU水板";      /* 通用条被后教的覆盖，这是对的 */
  ok("教完板：板 → 板货", look(m, "水豆腐", "板"), "SKU水板");
  ok("教完板：斤 → 还是斤货（没被冲掉）", look(m, "水豆腐", "斤"), "SKU水斤");
}

/* ---------- 不带单位的通用条 ---------- */
console.log("\n【通用条要过单位关，串不到别的单位上去】");
{
  const m = {};
  m[lkey("S2949", "", "豆腐卜")] = "SKU水斤";              /* 只教了通用条，目标是斤货 */
  ok("单位没识别出来 → 用通用条", look(m, "豆腐卜", ""), "SKU水斤");
  ok("单位是斤 → 对得上，用", look(m, "豆腐卜", "斤"), "SKU水斤");
  ok("单位是板 → 对不上，当没学过", look(m, "豆腐卜", "板"), null);
}

/* ---------- 老格式的键不能丢 ---------- */
console.log("\n【以前教过的（老格式「客户||词」）还得认】");
{
  const m = { "S2949||胶板豆腐": "SKU中板" };
  ok("老键 + 单位对得上 → 认", look(m, "胶板豆腐", "板"), "SKU中板");
  ok("老键 + 没单位 → 认", look(m, "胶板豆腐", ""), "SKU中板");
  ok("老键 + 单位对不上 → 不认", look(m, "胶板豆腐", "斤"), null);
}

/* ---------- 单位不一致但人点过名 ---------- */
console.log("\n【表上写「盒」价格库记「包」—— 人点过名的那条要能跨单位】");
{
  const m = {};
  m[lkey("S2949", "盒", "千叶豆腐")] = "SKU千叶包";        /* 人在盒那一行点的 */
  ok("盒 → 认（不卡单位）", look(m, "千叶豆腐", "盒"), "SKU千叶包");
  ok("包 → 不认（没教过这个单位）", look(m, "千叶豆腐", "包"), null);
}

/* ---------- 商品下架 / 不在这家价格表里 ---------- */
console.log("\n【教过的商品不在这家价格表里了，要当没学过】");
{
  const m = {};
  m[lkey("S2949", "斤", "野生豆腐")] = "SKU外人";
  m[lkey("S2949", "", "野生豆腐")] = "SKU外人";
  ok("不在售 → 不认", look(m, "野生豆腐", "斤"), null);
}

/* ---------- 写法归一 ---------- */
console.log("\n【大小写/全半角/异体字，教一次就都认得】");
{
  const m = {};
  m[lkey("S2949", "板", P.norm("小豆付"))] = "SKU中板";    /* 手写「豆付」= 豆腐 */
  ok("教「小豆付」→ 写「小豆腐」也认得", look(m, "小豆腐", "板"), "SKU中板");
  ok("教「小豆付」→ 写「小豆付」也认得", look(m, "小豆付", "板"), "SKU中板");
}

/* ---------- 键的解析 ---------- */
console.log("\n【键要能拆回去（对照页要显示、要能整条删干净）】");
ok("新键", keyParts("S2949||板||水豆腐"), { cid: "S2949", unit: "板", text: "水豆腐" });
ok("新键·无单位", keyParts("S2949||||水豆腐"), { cid: "S2949", unit: "", text: "水豆腐" });
ok("老键", keyParts("S2949||水豆腐"), { cid: "S2949", unit: null, text: "水豆腐" });

console.log("\n══════════════════════════");
if (fail) { console.log("有 " + fail + " 项没过（通过 " + pass + " 项）"); process.exit(1); }
console.log("全部通过：" + pass + " 项");
