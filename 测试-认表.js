/* ══════ 六点五、★ 一个文件永远只读第一张工作表（2026-08-21 老板定）══════
   「8.22粉面订单」一个工作簿两张表、同一份数据横竖正好反过来：
     第1张 品名横排、店（总店…金叶）竖排　　第2张 店横排、品名竖排
   两张都端给 AI 看，它照第 2 张答，我们拿第 1 张去核对 → 一张好单被毙了。
   老板原话：「永远第一张」。
   ⛔ 新路子的提示词里没有「用第几张表」这个字段 —— AI 连自己看的是第几张都没处说，
      多给一张就是白白多一个看岔的地方。 */
console.log("\n── 永远只读第一张 ★ ──");
{
  const 两张 = [
    { n: 1, rows: [["8.22广泰"], ["品名", "一级沙河粉", "湿面"], ["单位", "公斤", "公斤"],
                   ["总店", 2.5, 1.5], ["金叶", 1, 1]] },
    { n: 2, rows: [["8.22广泰", "品名", "单位", "总店", "金叶"],
                   ["", "一级沙河粉", "公斤", 2.5, 1], ["", "湿面", "公斤", 1.5, 1]] }
  ];
  const 骨 = T.骨架(两张);
  ok("★ 骨架只端第一张给 AI 看", 骨.indexOf("第 2 张工作表") < 0,
     骨.indexOf("第 2 张工作表") < 0 ? "" : "第二张也给出去了");
  ok("第一张照旧给全（内容没被砍）", /一级沙河粉/.test(骨) && /总店/.test(骨));
  /* 第 2 张的指纹：只有它第一行才会同时出现「品名」和「总店」*/
  ok("骨架里没有第二张那种排法", !/品名.*单位.*总店/.test(骨));

  /* 摊平那头也得是第一张 —— 两头看的不是同一张，就会「校验说不行、摊平在摊另一张」 */
  const J = T.摊平(两张, { 用第几张表: 2, 版式: "明细", 表头在第几行: 2,
                          商品列: 1, 数量列: 2 });
  const 名 = J && J.行 && J.行.map(x => x.品名).join("／");
  ok("★ 读法里写着第 2 张，摊的照旧是第一张", /总店|金叶/.test(名 || ""),
     "摊出来：" + 名);
  ok("摊出来的不是第二张的货（一级沙河粉/湿面）", !/一级沙河粉|湿面/.test(名 || ""),
     "摊出来：" + 名);
}

