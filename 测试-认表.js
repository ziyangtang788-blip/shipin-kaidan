  ok("两个商品", J.行.length === 2, J && J.行.length);
  ok("空格子跳过（手工河粉只有 2 个点）", J.行[0].分布.length === 2, JSON.stringify(J.行[0].分布));
  ok("数量 0 也跳过（肠粉只有 2 个点）", J.行[1].分布.length === 2, JSON.stringify(J.行[1].分布));
  ok("合计列进「表上总数」当校验码，不当门店", J.行[0].表上总数 === 15);
  const r = S.读结构(J);
  ok("合计 18.5", 和(r) === 18.5, 和(r));
  ok("分布跟合计对得上 → 校验全绿", r.校验.length === 0, JSON.stringify(S.校验说人话(r.校验)));
  ok("「总计」那一行不当商品", !r.lines.some(L => L.text === "总计"));

  /* 合计对不上就要报 —— 只报不改 */
