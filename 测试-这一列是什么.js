/* 学习的另一半：这一列是什么（2026-08-24 老板：「一整列，你凭什么不问就扔掉」）

   上一版只并了「这一格怎么分」。那张「客户编码」表撞出来的是另一半：
   数量、单位、品名全读对，可第 2 列没人管 —— 既不用、也不问，12 行货全没有送货点。

   钉四件事：
     ① 人点过「这一列是什么」，引擎要认（选项.列读法）
     ② 老写法 选项.点位列 不许作废（别台电脑存着老答案）
     ③ 已经派上用场的列不许再问（那是骚扰）
     ④ 表头明说是商品编码的，信它，别问；说是客户/单位编码的，照旧要问 */
const path = require("path");
const 家 = __dirname;
global.window = global.window || {};
["数据-价格库.js", "对照-预置.js", "数据-常用规格.js", "数据-换算.js",
 "引擎-解析.js", "引擎-匹配.js", "引擎-抓取.js"].forEach(f => require(path.join(家, f)));
const G = global.window.GM_抓取;

let 过 = 0, 挂 = [];
function 该(话, 真) { if (真) 过++; else 挂.push(话); }
const 列号 = (r, k) => { const m = /第(\d+)列/.exec(String((r.挑的列 || {})[k] || "")); return m ? +m[1] : 0; };

const 那张单 = [
  ["广东尝元绿色食品有限公司(13288225393)-2026-08-25 默认库房仓库", "", "", "", "", "", ""],
  ["序号", "客户编码", "商品名称", "订购数量", "下单单位", "备注", "商品描述"],
  ["1", "H16", "熟猪红", "8", "斤", "", ""],
  ["2", "91", "白豆腐干/白豆干", "15", "斤", "", ""],
  ["3", "253", "大豆泡", "2", "斤", "", ""],
  ["", "606-2", "大豆泡", "15", "斤", "", ""]
];

/* ── ① 人点过的，引擎要认 ── */
{
  const r = G.抓(那张单, { 列读法: { "2": "点位", "5": "单位", "1": "不用" } });
  该("★ 人点「第 2 列是点位」→ 真当点位用", 列号(r, "点位") === 2);
  该("人点的不影响别的列", 列号(r, "品名") === 3 && 列号(r, "数量") === 4);
  const 点 = (r.行 || []).map(L => { const d = (L.分布 || [])[0] || {}; return d.点位号 || d.点位名 || ""; });
  该("★ 点位一个不少", JSON.stringify(点) === JSON.stringify(["H16", "91", "253", "606-2"]));
}

/* ── ② 老写法照旧认 ── */
{
  const r = G.抓(那张单, { 点位列: 2 });
  该("★ 老写法 点位列 不许作废（别台电脑存着老答案）", 列号(r, "点位") === 2);
}

/* ── ③ 人说「不用」就真不用 ── */
{
  const r = G.抓(那张单, { 列读法: { "6": "不用" } });
  该("人说不用的列，不许再占着角色", 列号(r, "备注") !== 6);
}

/* ── ④ 该问的问、不该问的不问 ── */
{
  const 要问的 = rows => {
    const r = G.抓(rows, {});
    const 用了 = {};
    Object.keys(r.挑的列 || {}).forEach(k => { const m = /第(\d+)列/.exec(String(r.挑的列[k])); if (m) 用了[+m[1]] = 1; });
    const s = new Set();
    (r.没抓到的 || []).forEach(q => { if (q.列 && !用了[q.列]) s.add(+q.列); });
    return s;
  };
  该("★ 「客户编码」那一列必须问（8/24 整列点位就是这么丢的）", 要问的(那张单).has(2));

  const 商编 = [
    ["序号", "商品编码", "菜名", "总数量", "订货明细"],
    ["1", "a00795", "水豆腐", "14板", "(105) 2板+(217) 5板"],
    ["2", "a00805", "攸县香干", "5斤", "(274) 5斤"],
    ["3", "a00807", "大豆泡", "2.5斤", "(229) 2.5斤"]
  ];
  该("★ 表头明说「商品编码」的，信它，不许问（不然每次都骚扰一句）", !要问的(商编).has(2));
  该("用上了的列不许再问（那是格子的事，不是这一列是什么的事）",
    !要问的(商编).has(3) && !要问的(商编).has(4) && !要问的(商编).has(5));
}

/* ── ⑤ 页面那头：问、记、下次直接套，三根线都得在 ── */
{
  const fs = require("fs");
  const H = fs.readFileSync(path.join(家, "配送开单台.html"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  该("有「一列一列问」这一步", /function 问这几列\(/.test(H));
  该("★ 答完存起来（按客户＋这张表长什么样）", /function 存列读法\(/.test(H) && /列读法键\(/.test(H));
  该("★ 教过的直接套，不再问", /查列读法\(列键\)/.test(H) && /列读法:教过\.读/.test(H));
  该("已经用上的列不收进要问的名单", /!用上了\[q\.列\]/.test(H));
  该("列读法要存服务器（漏了就等于没教）", /if\(!OV\.列读法\)OV\.列读法=\{\}/.test(H));
  const S = fs.readFileSync(path.join(家, "后端-server.js"), "utf8");
  该("★ 后端白名单带上列读法（漏了会被静默抹掉）", /列读法: \{\}/.test(S) && /incoming\.列读法/.test(S));
}

/* ── ⑥ 纯数字的点位编码（2026-08-25 老板那张「单位编码」补货单）──
   022520 / 770026 / 021053 全是 6 位纯数字 → 落进「像编码」→ 当商品编码静默扔掉。
   8/24 那条只认 H16 / 606-2 这种带字母横杠的，纯数字的漏在外面。
   ⛔ 位数分不开商品编码和点位编码。靠【跟货的关系】分：
      商品编码：一样货永远一个码｜点位编码：一样货送几个点就有几个码。 */
{
  const 补货单 = [
    ["", "补货单", "", "8月26日", ""],
    ["单位编码", "存货名称", "单位", "数量", ""],
    ["022520", "九龙炸豆腐", "斤", "3", ""],
    ["770026", "鲜豆腐干", "斤", "3", ""],
    ["021036", "中板豆腐", "板", "4", ""],
    ["021053", "中板豆腐", "板", "5", ""],
    ["022539", "中板豆腐", "板", "1", ""],
    ["22590", "猪红带水", "斤", "50", ""]
  ];
  const 要问的 = rows => {
    const r = G.抓(rows, {});
    const 用了 = {};
    Object.keys(r.挑的列 || {}).forEach(k => { const m = /第(\d+)列/.exec(String(r.挑的列[k])); if (m) 用了[+m[1]] = 1; });
    const s = new Set();
    (r.没抓到的 || []).forEach(q => { if (q.列 && !用了[q.列]) s.add(+q.列); });
    return s;
  };
  该("★ 纯数字的点位编码也要问（中板豆腐一样货四个码 = 送货点）", 要问的(补货单).has(1));

  const r = G.抓(补货单, { 列读法: { "1": "点位" } });
  const 点 = (r.行 || []).map(L => { const d = (L.分布 || [])[0] || {}; return d.点位号 || d.点位名 || ""; });
  该("★ 人点完，点位一个不少",
    JSON.stringify(点) === JSON.stringify(["022520", "770026", "021036", "021053", "022539", "22590"]));

  /* 别误伤：真商品编码 —— 一样货永远同一个码 */
  const 真编码 = [
    ["商品编码", "商品名称", "数量", "单位"],
    ["36010003", "熟猪红", "8", "斤"],
    ["36010004", "大豆泡", "2", "斤"],
    ["36010003", "熟猪红", "5", "斤"]
  ];
  该("★ 真商品编码（一样货一个码）不许拿去问人", !要问的(真编码).has(1));

  /* ★ 光标出来还不够 —— 必须标成【要问点位】。
     不标的话页面会把它当「硬伤」，整条近道作废、转去问 AI，
     而 AI 那条路上没有这一问 —— 点位照样丢，还一句不问（8/25 第二次撞）。 */
  {
    const rr = G.抓(补货单, {});
    const 那列 = (rr.没抓到的 || []).filter(q => q.列 === 1)[0];
    该("★ 那一列必须标成「要问点位」（不然近道作废，转去问 AI，白问）",
      !!那列 && 那列.问点位 === true);
    const 硬伤 = 那列 && !那列.问点位 && !那列.要手工填 &&
                 ["规格", "备注", "别的"].indexOf(那列.类型) < 0;
    该("★ 不许被当成硬伤（一当硬伤整条近道就废了）", !硬伤);
  }
}

if (挂.length) {
  console.log("没过 " + 挂.length + " 项：");
  挂.forEach(t => console.log("  ✗ " + t));
  process.exit(1);
}
console.log("全部通过：" + 过 + " 项");
