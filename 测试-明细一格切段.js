/* 测试-明细一格切段.js —— node 测试-明细一格切段.js
   ============================================================
   2026-08-21 朱鲜生 8-20 那张单（14 行）撞出来的。

   这种表长这样：一行一个商品，右边「明细」那一格里把好几个送货点挤成一串 ——
     白豆干  34.6斤 │ 老人院(碎菜)5-9 16斤 午餐/切碎  老人院(糊餐)5-5 6.6斤 …

   OCR 把整格原样抄下来了（字一个没错），可系统是把这一格当【一句话】去扫数字的，
   于是：
     · 白豆干 5 段只读出 1 段 4.8斤 —— 少发 29.8 斤
     · 炸腐竹「13-2 3斤 / 13-1 1斤」读成 13 + 13 —— 多开 22 斤
     · 「西樵派出所(官山)2-6(2) 2板」被拆成两行 —— 重复算

   所以这一份干的事：把那一格【按「点位号 + 数量」切开】，一格有几段就出几段。

   ⛔ 两条硬线，比切得准更重要：
     ① 采用规矩：每一行都切得出、每一行的各段之和都跟总数列一分不差 —— 才采用。
        差一条【整张退回老路】，不许半张用新的半张用旧的。
     ② 按内容认，不看表头叫什么（老板 8/11：不许把表结构写死）。
        哪一格里反复出现「点位号+数量」，哪一格就是明细。

   47 张真表实测：46 张连门都进不去，2 张进了自查没过退回，只有朱先 8-20 那张采用。
   ============================================================ */
