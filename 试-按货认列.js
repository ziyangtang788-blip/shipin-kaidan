/* ============================================================
   按货认列 —— 拿我们卖的货当尺子，量出哪一列是货名
   ★ 独立试验文件，没有接进开单台，不改任何在跑的东西
   node 试-按货认列.js
   ============================================================

   老板 2026-08-17（广垦那张单读错之后）：
     「先抓取我们需要的内容，最后再抓点位。」
     「不要把它限定在某个位置，因为你再换新的表格，肯定是位置不一样的。」
     「要抓就抓一整列，其他地方就都不是产品。」
     「剩下那列你最后问一下他是不是点位就可以了。」

   ────────────────────────────────────────────────
   为什么非改不可
   ────────────────────────────────────────────────
   现在跑的方法二（引擎-抓取.js）对价格库的引用是 0 次 —— 它不知道我们卖什么。
   它判货名列的全部依据是：「最左边那列汉字」。
   广垦 2026-08-17 那张：客户名称列排在产品名称列左边，于是
     8 行货全读成银行、医院的名字，两行客户同名还合并掉一行，8 行变 7 行。
   往表头词表里再加一条「客户名称」只是第三个补丁（8/14 已经为「分类名称」加过一次）。
   位置和词表都是猜；我们手上有 5892 条货，那才是尺子。

   ────────────────────────────────────────────────
   这个文件只干一件事
   ────────────────────────────────────────────────
   给一张表，回答：哪一列是货名？剩下哪列该问「是不是点位」？
   数量/单位/规格怎么读，一概不碰 —— 那是引擎-抓取.js 已经磨好的，不重写。

   ⚠ 匹配逻辑只准一份：判「这串字是不是我们的货」一律走 GM_MATCH 的索引，
     不许在这里另写一套模糊匹配。抄第二份 = 页面死了体检还全绿。
   ============================================================ */
