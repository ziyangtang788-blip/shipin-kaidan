const P = window.GM_PARSE, M = window.GM_MATCH, DATA = window.GM_DATA, G = window.GM_抓取;
const norm = P.norm, bare = P.bare;

/* ── 尺子：我们卖的货，一张查得飞快的表 ────────────────
   来源两处，都是现成的，不新造：
     IDX.aliasAll  每个客户对这货的叫法（5892 条里所有名字）
     DATA.prods    217 个标准品名
   ⚠ 只用来回答「这串字是不是我们的货」这一个问题。
     具体配到哪一条、什么价，还是走 GM_MATCH.matchOne，这里不碰。 */
const IDX = M.buildIndex(DATA, function () { return 0; });   /* usedN：用过几次，认列用不上，给个 0 */
const 尺 = new Set();
Object.keys(IDX.aliasAll).forEach(k => k && 尺.add(k));
(DATA.prods || []).forEach(p => { const n = norm(p); if (n) 尺.add(n); const b = bare(p); if (b) 尺.add(b); });

/* 一格是不是我们的货。
   ⚠ 只认「整格就是这个货」和「去掉规格后就是这个货」两种，不做模糊。
     模糊了就会把备注里随口一提的字也算成命中，那就又变成猜了。 */
function 是我们的货(v) {
  const s = String(v == null ? "" : v).trim();
  if (!s || s.length > 40) return false;
  if (尺.has(norm(s))) return true;
  const b = bare(s);
  return !!(b && 尺.has(b));
}

/* ── 量一列：从上往下抽，命中就停 ──────────────────────
   老板：「你只要挑出来一样或者两样，你就知道这一列是什么了。」
   抽到够数就收工，不整列扫 —— 一列几格、9 列不到 20 次查询。
   ⚠ 但不能死抽两格：抽到的正好是生僻货（熟猪红价格库里 0 条）会误杀整列，
     所以是「命中够数就停，不够就继续往下抽」，抽满上限才认输。 */
const 够数 = 2, 上限 = 12;
function 量一列(rows, 起, 列号) {
  let 看了 = 0, 中了 = 0, 例 = [];
  for (let r = 起; r < rows.length && 看了 < 上限; r++) {
    const v = (rows[r] || [])[列号 - 1];
    const s = String(v == null ? "" : v).trim();
    if (!s) continue;
    看了++;
    if (是我们的货(s)) { 中了++; if (例.length < 3) 例.push(s); if (中了 >= 够数) break; }
  }
  return { 列: 列号, 看了, 中了, 例, 密: 看了 ? 中了 / 看了 : 0 };
}

/* ── 认列：哪列是货名，剩下的谁该问 ────────────────────
   1) 每列抽样，0 命中的一律出局（客户名称、产品代码、日期…一刀切干净）
   2) 只剩一列 → 就是它，整列端走
   3) 还剩几列 → 比密度（货名列 8 中 7，备注列 8 中 1，一比就开）
   4) 密度也分不开、或者一列都没命中 → 不许自己挑，弹窗问人 */
function 认列(rows) {
  let 宽 = 0;
  for (const r of rows) if (r && r.length > 宽) 宽 = r.length;
  const 起 = G.找数据起点(rows, 宽);

  const 量 = [];
  for (let c = 1; c <= 宽; c++) {
    const m = 量一列(rows, 起, c);
    if (m.看了) 量.push(m);
  }
  const 中的 = 量.filter(m => m.中了 > 0).sort((a, b) => b.密 - a.密 || b.中了 - a.中了);

  if (!中的.length)
    return { 起, 宽, 货名列: null, 要问: "一列都没认出我们的货 —— 哪列是货名？", 量 };

  if (中的.length > 1 && 中的[0].密 - 中的[1].密 < 0.25)
    return { 起, 宽, 货名列: null, 量,
             要问: "第 " + 中的[0].列 + " 列和第 " + 中的[1].列 + " 列都像货名，分不开 —— 哪列是货名？" };

  const 货名列 = 中的[0].列;
  /* 剩下的列：整列都是汉字、又不是货名列的，最后问一句「是不是点位」。
     老板 8/17：「点位他明明就是有的，其实就是那一列，你最后问一下他是不是点位就可以了。」 */
  const 待问点位 = [];
  for (let c = 1; c <= 宽; c++) {
    if (c === 货名列) continue;
    let 汉 = 0, 有 = 0;
    for (let r = 起; r < rows.length && 有 < 8; r++) {
      const s = String(((rows[r] || [])[c - 1]) == null ? "" : rows[r][c - 1]).trim();
      if (!s) continue;
      有++;
      if (/[\u4e00-\u9fa5]/.test(s) && !/^[\d.,]+$/.test(s) && s.length >= 4) 汉++;
    }
    if (有 >= 2 && 汉 === 有) 待问点位.push(c);
  }
  return { 起, 宽, 货名列, 待问点位, 量, 要问: null };
}

