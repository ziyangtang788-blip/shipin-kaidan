/* 测试-交叉表认列.js —— node 测试-交叉表认列.js
   ============================================================
   钉 2026-08-19 尝元「要货交叉表」那两处改动，一分钱不花（指认手工构造，不调 AI）。

   那天撞到的：一张 27 行、逐行核对分毫不差、完全能出的单，
     ① 先是被毙掉 —— 「表头『采购量』在第 11 列，可它说的第一格内容却在第 8 列」
        那张表第 8 列「数量」和第 11 列「采购量」27 行【一模一样】，
        拿「41」去找撞上排在前面的第 8 列，就宣布矛盾了。
        漏的是最简单一步：回头看一眼第 11 列那一格 —— 也是 41，本来就不矛盾。
     ② 把 ① 解开之后炸得更狠 —— 这条路【从来没产生过】横轴起止两个字段，
        摊表那头默认「第 2 列吃到表尾」，于是 商品代码｜条码｜数量｜库存｜采购量
        全被当成收货方：整个文件总量 120,812,634（该 164）；只留 9 列也翻倍成 328。
        老板 8/19：「两个总数要分开，不要把那个数量也读进去了」。

   ★ 第一组是整份里最要紧的：【明细表一个字都不许变】。
     改动只在 版式==="矩阵" 时生效，为治一张交叉表碰坏天天在跑的明细表，
     比交叉表读不了严重得多。
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js",
 "./引擎-认表.js", "./引擎-点位册.js", "./新-按内容认单.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const N = global.window.GM_按内容认单;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}

/* ══════ 一、明细表：横轴那套一个字都不许沾上 ══════ */
console.log("\n【一、明细表不受影响 ★ 最要紧】");
const 明细表 = [
  ["尝元豆制品下单群12"],
  ["序号", "商品名", "规格", "采购总数", "明细"],
  ["1", "内脂嫩豆腐", "1盒/盒", "9盒(9盒)", "3盒*KC概念餐厅【515】"],
  ["2", "老豆腐", "1斤/斤", "33斤(33斤)", "2斤*KC概念餐厅【515】"],
  ["3", "凉粉", "1斤/斤", "4斤(4斤)", "4斤*多斯坦【-】"]
];
const 明细指认 = {
  版式: "明细",
  有什么: {
    品名: { 有: true, 表头写的是: "商品名", 第一格是: "内脂嫩豆腐" },
    数量: { 有: false, 为什么: "数字都挤在明细那一格里" },
    单位: { 有: true, 表头写的是: "规格", 第一格是: "1盒/盒" },
    单价: { 有: false },
    点位: { 有: true, 表头写的是: "明细", 第一格是: "3盒*KC概念餐厅【515】" },
    备注: { 有: false },
    校验数: { 有: true, 表头写的是: "采购总数", 第一格是: "9盒(9盒)" }
  },
  第一样货叫: "内脂嫩豆腐", 最后一样货叫: "凉粉", 数据区一共几行: 3, 不确定的: []
};
(function () {
  const r = N.认(明细表, 明细指认);
  ok("明细表 没被拦", !r.要问的, r.要问的 ? r.要问的[0] : "");
  ok("明细表 读法还是老样子", r.读法 &&
     r.读法.版式 === "明细" && r.读法.商品列 === 2 && r.读法.单位列 === 3 &&
     r.读法.分布列 === 5 && r.读法.合计列 === 4,
     JSON.stringify(r.读法));
  ok("明细表 没被塞进横轴字段", r.读法 &&
     r.读法.横轴从第几列开始 === undefined && r.读法.横轴到第几列 === undefined);
})();

/* 两列内容一样的表：底料 */
const 撞车表 = [
  ["要货交叉表"],
  ["部门", "商品", "规格", "数量", "采购量", "高村店", "罗村店"],
  ["粉面部", "猪红", "", "41", "41", "20", "5"],
  ["粉面部", "老豆腐", "", "24", "24", "5", "2"]
];
function 指认底() {
  return {
    版式: "矩阵",
    有什么: {
      品名: { 有: true, 表头写的是: "商品", 第一格是: "猪红" },
      数量: { 有: true, 表头写的是: "数量", 第一格是: "41" },
      单位: { 有: false }, 单价: { 有: false }, 备注: { 有: false },
      校验数: { 有: true, 表头写的是: "采购量", 第一格是: "41" }
    },
    第一样货叫: "猪红", 最后一样货叫: "老豆腐", 数据区一共几行: 2, 不确定的: []
  };
}
const 两头 = { 有: true, 横着一排: true, 第一列表头写的是: "高村店", 最后一列表头写的是: "罗村店" };

/* ══════ 二、改动①：撞车时回头看一眼表头那一列 ══════ */
console.log("\n【二、两列内容一模一样：按表头定，不再毙单】");
(function () {
  const 指认 = 指认底(); 指认.有什么.点位 = 两头;
  const r = N.认(撞车表, 指认);
  ok("过了，没毙单", !r.要问的, r.要问的 ? r.要问的[0].slice(0, 46) : "");
  ok("校验数认到「采购量」那一列（第 5 列）", r.读法 && r.读法.合计列 === 5, "合计列=" + (r.读法 || {}).合计列);
})();

/* ══════ 三、真错位不许跟着放宽 ══════
   改动①只在【表头那一列的那一格确实等于它说的内容】时才认。
   表头指到某列、那一格却是别的东西 —— 那是真错位，照旧拦。 */
console.log("\n【三、真错位照旧拦住】");
(function () {
  const 错位表 = [
    ["部门", "商品", "数量", "采购量", "高村店", "罗村店"],
    ["粉面部", "猪红", "41", "99", "20", "5"]   /* 采购量那格是 99，不是 41 */
  ];
  const 指认 = {
    版式: "矩阵",
    有什么: {
      品名: { 有: true, 表头写的是: "商品", 第一格是: "猪红" },
      数量: { 有: false }, 单位: { 有: false }, 单价: { 有: false }, 备注: { 有: false },
      点位: 两头,
      校验数: { 有: true, 表头写的是: "采购量", 第一格是: "41" }
    },
    第一样货叫: "猪红", 最后一样货叫: "猪红", 数据区一共几行: 1, 不确定的: []
  };
  const r = N.认(错位表, 指认);
  ok("表头那格对不上 → 拦", !!r.要问的, r.要问的 ? r.要问的[0].slice(0, 50) : "（放过去了，危险）");
})();

/* ══════ 四、改动②：收货方从哪列到哪列 ══════ */
console.log("\n【四、收货方范围】");
(function () {
  const 指认 = 指认底(); 指认.有什么.点位 = 两头;
  const r = N.认(撞车表, 指认);
  ok("两头齐 → 翻成第 6~7 列", r.读法 && r.读法.横轴从第几列开始 === 6 && r.读法.横轴到第几列 === 7,
     "横轴=" + (r.读法 || {}).横轴从第几列开始 + "~" + (r.读法 || {}).横轴到第几列);
  ok("横轴是什么 = 门店", r.读法 && r.读法.横轴是什么 === "门店");
})();

/* ★ 这一条是整份里第二要紧的：矩阵表没说清范围，【必须停下来】。
   不许沿用「默认第 2 列吃到表尾」—— 那套的错法是闷声重复算钱，人一点看不见。 */
console.log("\n【五、说不清范围就必须停，不许闷头猜 ★】");
(function () {
  const 只一列 = 指认底();
  只一列.有什么.点位 = { 有: true, 表头写的是: "高村店", 第一格是: "20" };
  ok("只报一列 → 停下来问人", !!N.认(撞车表, 只一列).要问的, "（1.2 亿就是这么来的）");

  const 没点位 = 指认底();
  没点位.有什么.点位 = { 有: false };
  ok("干脆说没点位 → 也得停", !!N.认(撞车表, 没点位).要问的);

  const 找不到尾 = 指认底();
  找不到尾.有什么.点位 = { 有: true, 横着一排: true, 第一列表头写的是: "高村店", 最后一列表头写的是: "没这个店" };
  ok("尾巴找不到 → 停", !!N.认(撞车表, 找不到尾).要问的);

  const 反了 = 指认底();
  反了.有什么.点位 = { 有: true, 横着一排: true, 第一列表头写的是: "罗村店", 最后一列表头写的是: "高村店" };
  ok("头尾写反 → 停", !!N.认(撞车表, 反了).要问的);
})();

/* ══════ 六、提示词里得留着那一格，不然 AI 根本没处填 ══════ */
console.log("\n【六、提示词教了「横着一排」这种写法】");
(function () {
  const p = String(N.提示词 || "");
  ok("提示词里有「横着一排」", p.indexOf("横着一排") >= 0);
  ok("提示词里教了报两头", p.indexOf("第一列表头写的是") >= 0 && p.indexOf("最后一列表头写的是") >= 0);
  ok("提示词里仍然写着「别报列号」", /一个列号都别报|不要报|别报/.test(p));
})();

console.log("\n════════════════════════");
console.log("过 " + 过 + "　挂 " + 挂);
process.exit(挂 ? 1 : 0);
