/* ══════ 五、说不清就必须停 ══════
   不许沿用「默认第 2 列吃到表尾」—— 那套的错法是闷声重复算钱，人一点看不见。 */
console.log("\n【五、交叉表说不清两个轴 → 必须停 ★】");
(function () {
  const 没矩阵块 = 正指认(); delete 没矩阵块.矩阵;
  ok("整块没填 → 停", !!N.认(正表, 没矩阵块).要问的, "（1.2 亿就是这么来的）");

  const 都横 = 正指认();
  都横.矩阵.商品.怎么排 = "横";
  ok("两个轴都说「横」→ 停", !!N.认(正表, 都横).要问的);

  const 没说排法 = 正指认();
  delete 没说排法.矩阵.收货方.怎么排;
  ok("有一个轴没说横竖 → 停", !!N.认(正表, 没说排法).要问的);

  const 找不到 = 正指认();
  找不到.矩阵.收货方.第一个叫 = "没这个店";
  ok("收货方第一个找不到 → 停", !!N.认(正表, 找不到).要问的);

  const 货找不到 = 正指认();
  货找不到.矩阵.商品.第一个叫 = "没这样货";
  ok("商品第一个找不到 → 停", !!N.认(正表, 货找不到).要问的);
})();

/* ══════ 六、横排那头报的尾巴不对时，自己数 ══════ */
console.log("\n【六、尾巴报歪了也不许乱来】");
(function () {
  const 尾找不到 = 正指认();
  尾找不到.矩阵.收货方.最后一个叫 = "没这个店";
  const r = N.认(正表, 尾找不到);
  ok("尾巴找不到 → 自己数到第 8 列（不是一路吃到表尾）",
     r.读法 && r.读法.横轴到第几列 === 8, "横轴到=" + (r.读法 || {}).横轴到第几列);

  /* ★ 头尾写反【必须拦】，不许退回去自己数。
     2026-08-19 测出来：自己数只数出头那一格（横轴 8~8），高村店周村店闷声漏掉，
     总量还照样对不上、人也看不见。漏货比麻烦一次严重得多。 */
  const 尾反了 = 正指认();
  尾反了.矩阵.收货方.第一个叫 = "罗村店"; 尾反了.矩阵.收货方.最后一个叫 = "高村店";
  const r2 = N.认(正表, 尾反了);
  ok("头尾写反 → 停下来问人（不许自己数，会漏店）", !!r2.要问的,
     r2.要问的 ? r2.要问的[0].slice(0, 56) : "（放过去了，会漏货）");

  /* 头尾不在同一条线上（一个在表头行、一个在数据行）也是搞混了 */
  const 不同行 = 正指认();
  不同行.矩阵.收货方.最后一个叫 = "老豆腐";
  ok("头尾不在同一条线上 → 停", !!N.认(正表, 不同行).要问的);
})();

/* ══════ 七、格子里数字后面跟的字，不许再吃掉 ══════ */
console.log("\n【七、「20大」的「大」要进备注】");
(function () {
  const 表 = [
    ["要货交叉表"],
    ["部门", "商品", "配送单位", "数量", "高村店", "周村店", "白岗店"],
    ["粉面部", "猪红", "斤", "36", "20大", "10", "6板"],
    ["粉面部", "老豆腐", "斤", "3", "1小", "1", "1"]
  ];
  const 读法 = {
    用第几张表: 1, 版式: "矩阵", 转置: false, 表头在第几行: 2, 商品列: 2, 单位列: 3,
    合计列: 4, 数据从第几行开始: 3, 数据到第几行: 4,
    横轴从第几列开始: 5, 横轴到第几列: 7, 横轴是什么: "门店", 抬头: {}
  };
  const J = T.摊平([{ n: 1, rows: 表 }], 读法);
  const 猪 = (J.行 || []).find(x => /猪红/.test(x.品名 || x.text || ""));
  const 段 = (猪 && (猪.分布 || 猪.segs)) || [];
  const 取 = i => 段[i] || {};
  const 备 = z => z.备注 || z.注 || z.note || "";
  const 量 = z => z.数量 !== undefined ? z.数量 : z.qty;

  ok("「20大」→ 数量还是 20", 量(取(0)) === 20);
  ok("「20大」→ 「大」进了备注", 备(取(0)) === "大", "备注=" + JSON.stringify(备(取(0))));
  /* ⚠ 正则写成 (\S{1,4}) 会被回溯坑：「10」→ [0-9]+ 只吃「1」，「0」成了备注。
     真表恰好全是一位数没暴露，备注又不进数量、总量照样对 —— 会一直静默。 */
  ok("「10」→ 备注是空的（两位数不许被拆）", !备(取(1)), "备注=" + JSON.stringify(备(取(1))));
  ok("「6板」→ 板是单位，不进备注", !备(取(2)), "备注=" + JSON.stringify(备(取(2))));
  ok("「6板」→ 数量还是 6", 量(取(2)) === 6);

  const L = (S.读结构(J).lines || []).find(x => /猪红/.test(x.text));
  ok("进了备注也不许动数量：整行还是 36", L && L.qty === 36, "整行 qty=" + (L || {}).qty);
})();

