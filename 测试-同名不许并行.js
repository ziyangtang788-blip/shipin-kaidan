/* 测试-同名不许并行.js —— node 测试-同名不许并行.js
   ============================================================
   2026-08-21 老板拿朱鲜生那张单跟观麦的单对着看，一眼看出来：

     客户单子上          我们出的单
      第3行 白豆干 10（26-2）     第3行 白豆干 10（26-2）
      …隔了 5 行…               第4行 白豆干  3（11-10）  ← 第9行那笔被拖上来了
      第9行 白豆干  3（11-10）

   他的原话：
     「为什么第9行那笔货会跑到第4行？这是不对的呀。」
     「我拆开的单，就是一定要跟它的顺序吻合。
       我合并的单就按照第一个来就可以了 —— 合并的订单，把下面的提上来都没所谓。」

   根子在 引擎-认表.js 摊表那一步：按「商品名｜单位｜规格」建组，
   同一样货不管在表上第几行都塞进同一个组，组的位置按【第一次出现】。
   原本是为了「一样货送好几个点位」那种表，可它分不出
   「客户自己分开写的两笔」，一律并了。

   ★ 改法：表上一行就是一行，谁也不并谁（键上带行号）。
   ⚠ 分两层，别混：
       摊表这一层    不许并  ← 这份测试管的
       页面合并模式   照旧并  ← 老板说「提上来没所谓」，那层不动
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js",
 "./引擎-认表.js"].forEach(f => require(path.resolve(__dirname, f)));
const T = global.window.GM_TABLE, S = global.window.GM_STRUCT;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}

/* ══════ 一、★ 朱鲜生那张：同名隔着好几行，各归各位 ══════ */
console.log("\n【一、同名分开写的两笔，位置不许挪 ★ 8/21 朱鲜生】");
(function () {
  const sheets = [{ n: 1, rows: [
    ["商品名称", "单位", "数量", "客户点位"],
    ["水豆腐（斤）", "斤", "2", "市政府下单"],
    ["千张", "斤", "3", "32-2"],
    ["尝元白豆干", "斤", "10", "26-2"],          /* ← 第 3 笔 */
    ["尝元小豆泡", "斤", "2", "33-4"],
    ["尝元中板豆腐（7斤）", "板", "2", "5-9"],
    ["尝元中板豆腐（7斤）", "板", "1", "5-5"],
    ["尝元小板豆腐（5斤）", "板", "3", "1-6"],
    ["九龙炸豆腐（斤）", "斤", "3", "1-6"],
    ["尝元白豆干", "斤", "3", "11-10"],          /* ← 第 9 笔，中间隔了 5 行 */
    ["百页", "斤", "1", "11-6"]
  ]}];
  const J = T.摊平(sheets, { 用第几张表: 1, 版式: "明细", 表头在第几行: 1,
                            商品列: 1, 单位列: 2, 数量列: 3, 点位号列: 4 });
  ok("摊出来了", !!J);
  const 行 = (J && J.行) || [];
  ok("★ 10 行货摊出 10 行（原来只剩 8 行）", 行.length === 10, "摊出 " + 行.length + " 行");
  const 名 = 行.map(r => String(r.品名));
  ok("★ 白豆干在第 3 和第 9 位（不是 3 和 4）",
     名[2] === "尝元白豆干" && 名[8] === "尝元白豆干",
     "第3位=" + 名[2] + "　第9位=" + 名[8]);
  ok("★ 中板豆腐在第 5 和第 6 位，各是各的",
     名[4] === "尝元中板豆腐（7斤）" && 名[5] === "尝元中板豆腐（7斤）");
  ok("每一行只有一段（没被并）", 行.every(r => (r.分布 || []).length === 1),
     JSON.stringify(行.map(r => (r.分布 || []).length)));
  /* 点位得跟着各自那一行走，不许串 */
  /* ⚠ 用 (行[n]||{}) 兜一下：没改之前第 9 行压根不存在，
     不兜的话测试当场抛异常、后面几组一条都跑不了，红得看不出全貌。 */
  const 点 = r => String((((r || {}).分布 || [])[0] || {}).点位号 || "") +
                  String((((r || {}).分布 || [])[0] || {}).点位名 || "");
  const 量 = r => (((r || {}).分布 || [])[0] || {}).数量;
  ok("第 3 行的点位是 26-2", /26-2/.test(点(行[2])), 点(行[2]));
  ok("第 9 行的点位是 11-10", /11-10/.test(点(行[8])), 点(行[8]) || "(这一行不存在)");
  ok("第 3 行 10 斤、第 9 行 3 斤，没串", 量(行[2]) === 10 && 量(行[8]) === 3,
     量(行[2]) + " / " + (量(行[8]) === undefined ? "(不存在)" : 量(行[8])));
})();

/* ══════ 二、江云那种：一格挤好几段 —— 一个字都不许变 ══════
   老板 8/21：「江云那种单应该不受影响啊。你那也是一个品类，
                拆下来按照顺序走，更简单，更不受影响。」
   他说得对：那种表一格里挤着十几段，本来就是【同一行】的东西，
   跟「不同行的同名货被并」是两回事。 */
console.log("\n【二、江云那种一格挤好几段，照旧拆】");
(function () {
  const sheets = [{ n: 1, rows: [
    ["商品名", "订菜总数", "订菜分布清单"],
    ["炸腐竹", "3.5斤", "(B163 南方明珠#火锅)0.5斤+(B135 多宝#员工)3斤"],
    ["煅豆腐", "11斤", "(A006 爱儿坊#教师餐)2斤+(B158 茂福#幼儿)9斤"],
    ["老豆腐/斤", "6斤", "(A849 增城店#月子)6斤"]
  ]}];
  const J = T.摊平(sheets, { 用第几张表: 1, 版式: "明细", 表头在第几行: 1,
                            商品列: 1, 合计列: 2, 分布列: 3 });
  const 行 = (J && J.行) || [];
  ok("3 行货还是 3 行", 行.length === 3, "摊出 " + 行.length + " 行");
  ok("炸腐竹那一格拆成 2 段", (行[0].分布 || []).length === 2,
     JSON.stringify((行[0].分布 || []).length));
  ok("煅豆腐那一格拆成 2 段", (行[1].分布 || []).length === 2);
  ok("老豆腐 1 段", (行[2].分布 || []).length === 1);
  ok("段的顺序照原样（0.5 在前、3 在后）",
     行[0].分布[0].数量 === 0.5 && 行[0].分布[1].数量 === 3,
     JSON.stringify(行[0].分布.map(d => d.数量)));
})();

/* ══════ 三、合并单元格的续行照旧要接上去 ══════
   名字那一格空着、只有数量的，是同一样货的续行（8/12 厨鲜达少 32 斤就是它）。
   ⚠ 这条跟「同名不许并」不冲突：续行【本来就没写名字】，
     它明摆着是上一行的一部分；而同名多行是客户自己写了两次。 */
console.log("\n【三、名字空着的续行，照旧接到上一行】");
(function () {
  const sheets = [{ n: 1, rows: [
    ["商品名", "数量", "单位"],
    ["(尝元) 老豆腐", "2", "斤"],
    ["", "3", "斤"],                    /* ← 名字空着，这 3 斤也是老豆腐的 */
    ["千张", "5", "斤"]
  ]}];
  const J = T.摊平(sheets, { 用第几张表: 1, 版式: "明细", 表头在第几行: 1,
                            商品列: 1, 数量列: 2, 单位列: 3 });
  const 行 = (J && J.行) || [];
  ok("2 样货", 行.length === 2, "摊出 " + 行.length + " 行：" + 行.map(r => r.品名).join("、"));
  ok("★ 老豆腐那一行接上了续行，共 2 段", (行[0].分布 || []).length === 2,
     JSON.stringify((行[0].分布 || []).map(d => d.数量)));
  ok("续行的 3 斤没丢", (行[0].分布 || []).some(d => d.数量 === 3));
})();

/* ══════ 四、只改摊表这一层，页面的合并模式不许动 ══════
   老板 8/21：「我合并的单就按照第一个来就可以了 —— 把下面的提上来都没所谓。」 */
console.log("\n【四、页面那层合并照旧（提到第一个位置）】");
(function () {
  const h = require("fs").readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  ok("合并行() 还在", /function 合并行\(rows\)/.test(h));
  ok("合并键还是 商品+单位+单价", /var k=名\+"｜"\+单位\+"｜"\+价;/.test(h));
  ok("照旧按第一次出现排（序 数组）", /序\.push\(k\);/.test(h));
})();

console.log("\n════════════════════════");
console.log("过 " + 过 + "　挂 " + 挂);
process.exit(挂 ? 1 : 0);
