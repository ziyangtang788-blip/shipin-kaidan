/* 走真链路读一张表，回 {数量们, 没拆开几行, 账不平几行} */
function 读(rows, 客户号) {
  const r = N.认列(rows);
  if (!r || r.要问的) return { 认不出: r && r.要问的 };
  const 备 = N.备好(rows, r, 客户号 || "");
  if (!备) return { 认不出: "备不好" };
  const 合 = T.摊平([{ n: 1, rows: 备.rows }], 备.读法);
  if (!合 || !合.行.length) return { 认不出: "摊不出" };
  const B = S.读结构({ 抬头: 合.抬头, 行: 合.行, 表怎么读的: 合.表怎么读的 });
  let 不平 = 0;
  (合.行 || []).forEach(l => {
    const 总 = l && l.表上总数;
    if (总 == null || 总 === "" || isNaN(+总)) return;
    const 段 = (l.分布 || []); if (!段.length) return;
    let s = 0, 好 = true;
    段.forEach(d => { const q = +d.数量; if (!isFinite(q)) 好 = false; else s += q; });
    if (好 && Math.abs(s - (+总)) >= 0.01) 不平++;
  });
  return { 数量们: B.lines.map(l => l.qty), 没拆开: G.没拆开(合), 账不平: 不平,
           段数们: B.lines.map(l => (l.segs || []).length) };
}

