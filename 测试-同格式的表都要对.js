function 跑一张(张) {
  const { rows, 答案 } = 张;
  const r = GZ.认列(rows);
  if (r.要问的) return { 挂: "认不出列：" + r.要问的.join("／") };
  const 备 = GZ.备好(rows, r, "S2944");
  if (!备) return { 挂: "备不出来" };
  const 读 = 备.读法;
  const 料 = [];
  for (let i = 读.表头在第几行; i < rows.length; i++) {
    const row = rows[i] || [];
    const 文 = String(row[读.分布列 - 1] == null ? "" : row[读.分布列 - 1]).trim();
    if (!文) continue;
    const c校 = 读.合计列 != null ? 读.合计列 : 读.数量列; let 校 = null;
    if (c校) { const m = /^([0-9]+(?:\.[0-9]+)?)/.exec(String(row[c校 - 1] == null ? "" : row[c校 - 1]).trim()); if (m) 校 = parseFloat(m[1]); }
    料.push({ 原文: 文, 表上总数: 校 });
  }
  const 解们 = 碎.找角色表(料) || [];
  if (!解们.length) return { 挂: "一种读法都算不出来" };
  读.碎片角色 = 解们[0];
  const 合 = T.摊平([{ n: 1, rows: 备.rows }], 读);
  if (!合 || !合.行.length) return { 挂: "摊不出行" };
  let 不平 = 0, 读不懂 = 0, 号不对 = 0, 头一个错 = "";
  (合.行 || []).forEach((Ln, i) => {
    const 段 = Ln.分布 || [], A = 答案[i]; if (!A) return;
    段.forEach(d => { if (d.读不懂 || d.数量 === "?") 读不懂++; });
    const 和 = Math.round(段.reduce((a, d) => a + (+d.数量 || 0), 0) * 100) / 100;
    if (Math.abs(和 - A.和) > 0.01) {
      不平++;
      if (!头一个错) 头一个错 = A.名 + " 读出 " + 和 + "、该是 " + A.和;
    }
    段.forEach((d, k) => {
      const 该 = A.各段[k] && A.各段[k].号;
      const 得 = String(d.点位名 || d.点位 || d.名 || "");
      if (该 && 得.indexOf(该) < 0) {
        号不对++;
        if (!头一个错) 头一个错 = A.名 + " 点位该是 " + 该 + "、读成「" + 得.slice(0, 20) + "」";
      }
    });
  });
  return { 解数: 解们.length, 行: 合.行.length, 该几行: 答案.length, 段数: 合.行.reduce((a, L) => a + (L.分布 || []).length, 0), 读不懂, 不平, 号不对, 头一个错 };
}

