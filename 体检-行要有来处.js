/* ============================================================
   体检：摆进单子的每一行，都得说得清自己从哪来
   node 体检-行要有来处.js
   ============================================================

   老板 2026-08-18（看到两行只写着「手动加的」）：
     「你这个就写一个手动加的，我哪知道是啥？我难道还要去对着去找吗？
     　你要把识别不出来的产品名称写出来，我才可以去做这个事情啊。」

   ────────────────────────────────────────────────
   为什么要有这一份
   ────────────────────────────────────────────────
   出事那天查出来是【一类】问题，不是一处：
     配送开单台.html 里往 ST.lines 塞行的地方有三处，
     其中两处写死 text:""，第三处没名字时也留空。
     而表格那一列显示的就是 text —— 空的，人就只看见「手动加的」。

   光把那三处填上还是补丁：下次谁再加一处造行的代码，照样可以留空，
   而且一声不吭。所以要有这一份体检把规矩钉死：
     ★ 凡是往 ST.lines 里塞行的地方，text 都不许是空字符串常量。

   ⚠ 这份查的是【源码写法】，不是跑起来的结果 ——
     跑起来才发现，就意味着已经发到老板手上了。

   ⚠ 允许 text:变量（那是把来处填进去了），只拦 text:"" 和 text:''。
   ============================================================ */
"use strict";
const fs = require("fs"), path = require("path");

const 页 = path.join(__dirname, "配送开单台.html");
const 源 = fs.readFileSync(页, "utf8");
const 行 = 源.split(/\r?\n/);

const 错 = [];
let 造行处 = 0;

行.forEach((l, i) => {
  if (!/ST\.lines\.(push|unshift)\s*\(/.test(l)) return;
  造行处++;
  /* 造行那一句可能跨几行写，往下再看两行 */
  const 整句 = [l, 行[i + 1] || "", 行[i + 2] || ""].join(" ");
  const m = 整句.match(/text\s*:\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')/);
  if (m && /^["']\s*["']$/.test(m[1]))
    错.push("第 " + (i + 1) + " 行：text 写死成空字符串 —— 这一行摆到单子上，人看不出它从哪来\n" +
            "        " + l.trim().slice(0, 90));
});

/* 显示那一头也得查：原文不许被标签顶掉。
   2026-08-18 就是栽在这儿 —— 原句填进去了，可显示是二选一，还是看不见。 */
if (/r\.L\.manual\s*\?\s*'<span[^']*手动加的[^']*'\s*:\s*esc\(r\.L\.text\)/.test(源))
  错.push("表格那一列还是【二选一】：manual 为真就只显示「手动加的」，把原文顶掉了。\n" +
          "        标签得跟原文并排，不能互相顶。");

console.log("• 摆进单子的行必须说得清从哪来");
console.log("    查了 " + 造行处 + " 处造行的地方");
if (!造行处) {
  console.log("    没过 ❌\n      一处都没找到 —— 是不是 ST.lines.push/unshift 改名了？改名了这份体检就成了摆设");
  process.exit(1);
}
if (错.length) {
  console.log("    没过 ❌");
  错.forEach(e => console.log("      " + e));
  console.log("      → 把客户写的那一整句填进 text（解析那边已经挂在 L.原句 上了）");
  process.exit(1);
}
console.log("    通过　" + 造行处 + " 处都带着来处，显示那一头也没顶掉原文");
