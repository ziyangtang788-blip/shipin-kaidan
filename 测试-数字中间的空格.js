/* 测试-数字中间的空格.js —— node 测试-数字中间的空格.js
   ============================================================
   2026-08-22 华丰大良那张手打单撞出来的。

   老板原话：「关键是写了 1 0 的那两个，没识别到，就中间有空格，没识别到是这个问题」

       饺子皮1 0斤   →  ✗ 整行没了（该 10 斤）
       千张1 0斤     →  ✗ 整行没了（该 10 斤）

   手机打字很容易在 1 和 0 中间多敲一下，客户自己看不出来。
   数字读不出来 → 整行当没写数量 → 文字路上直接扔掉，屏幕上一点痕迹都没有。

   ⛔ 判据卡到最死：只有【数字 空格 数字 …… 紧跟着单位】才把空格合掉。
      后面没有单位的一律不动：
        · 「保鲜膜件30 X 40」  那是规格 30×40，不是 3040
        · 日期「2026 08 22」、页码「第 1 2 页」
   ⚠ 只补空格，别的一个字不动 —— 合并完还是走原来那套认数量的规矩。

   ★ 第三组最要紧：文字路那条「没写数量 = 今天不要」的老规矩（8/2 定的）
     一点都不许被这次改动带歪。老板 8/22 又确认了一遍：
     「那些没有写数量的是不要的……这种是纯文字的路线，没写数量的是不要的」
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读结构.js"].forEach(f => require(path.resolve(__dirname, f)));
const P = global.window.GM_PARSE;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}
function 读(s) {
  const r = P.parseOrder(s) || [];
  return (r.lines || r)[0] || null;
}
const 数 = s => { const L = 读(s); return L ? L.qty : null; };
const 单 = s => { const L = 读(s); return L ? (L.unit || "") : null; };
const 名 = s => { const L = 读(s); return L ? L.text : null; };

/* ══════ 一、★ 真单上那两行 ══════ */
console.log("\n【一、华丰大良那两行 ★】");
{
  ok("★ 饺子皮1 0斤 → 10 斤", 数("饺子皮1 0斤") === 10 && 单("饺子皮1 0斤") === "斤",
     "读出 " + 数("饺子皮1 0斤") + 单("饺子皮1 0斤"));
  ok("★ 千张1 0斤 → 10 斤", 数("千张1 0斤") === 10 && 单("千张1 0斤") === "斤");
  ok("品名没被带歪", 名("饺子皮1 0斤") === "饺子皮", "名=" + 名("饺子皮1 0斤"));
  ok("全角空格也认（饺子皮1　0斤）", 数("饺子皮1　0斤") === 10);
  ok("单位前面再有空格也认（饺子皮1 0 斤）", 数("饺子皮1 0 斤") === 10);
  ok("三位数也认（河粉1 0 0斤）", 数("河粉1 0 0斤") === 100, "读出 " + 数("河粉1 0 0斤"));
}

/* ══════ 二、⛔ 后面没有单位的一律不许动 ══════ */
console.log("\n【二、后面没单位就不许动 ★】");
{
  /* 同一张单上的真句子：30 X 40 是保鲜膜的规格 */
  ok("⛔「保鲜膜件30 X 40」不许并成 3040",
     String(名("保鲜膜件30 X 40") || "").indexOf("3040") < 0 && 数("保鲜膜件30 X 40") !== 3040,
     "名=" + 名("保鲜膜件30 X 40") + " qty=" + 数("保鲜膜件30 X 40"));
  /* 纯数字之间有空格、后面没单位 —— 一个字都不该动 */
  const 日 = "打印时间 2026 08 22";
  ok("⛔ 日期「2026 08 22」不许被并", !/20260822/.test(JSON.stringify(P.parseOrder(日) || [])),
     JSON.stringify(P.parseOrder(日) || []).slice(0, 80));
}

/* ══════ 三、★ 老规矩一条都不许带歪（最要紧）══════ */
console.log("\n【三、老规矩不许带歪 ★ 最要紧】");
{
  /* 8/2 定：文字路上【没写数量 = 今天不要】，老板 8/22 又确认了一遍 */
  ok("★ 没写数量的照旧不要（米粉斤）", 读("米粉斤") === null, JSON.stringify(读("米粉斤")));
  ok("★ 没写数量的照旧不要（日本豆腐件）", 读("日本豆腐件") === null);
  ok("★ 没写数量的照旧不要（三角泡斤）", 读("三角泡斤") === null);
  /* 本来就读得对的，一个都不许变 */
  ok("饺子皮10斤 还是 10", 数("饺子皮10斤") === 10);
  ok("浓浆豆腐25板特价 还是 25 板", 数("浓浆豆腐25板特价") === 25 && 单("浓浆豆腐25板特价") === "板");
  ok("河粉30斤要红色包 还是 30 斤", 数("河粉30斤要红色包") === 30);
  ok("素鸡8条 还是 8 条", 数("素鸡8条") === 8 && 单("素鸡8条") === "条");
  ok("甜蕌头1件、补的 还是 1 件", 数("甜蕌头1件、补的") === 1);
  ok("名字和数字之间的空格照旧认（豆腐 2 板）", 数("豆腐 2 板") === 2);
  ok("★ 加法那条规矩不许坏（大豆泡 1.5+2斤 = 3.5）", 数("大豆泡 1.5+2斤") === 3.5,
     "读出 " + 数("大豆泡 1.5+2斤"));
  ok("小数不许被并（1.5斤）", 数("嫩豆腐1.5斤") === 1.5);
}

/* ══════ 四、整张真单：只多出那两行，别的一行不变 ══════ */
console.log("\n【四、整张华丰大良真单 ★】");
{
  const 单子 = [
    "顺德华丰大良店", "浓浆豆腐25板特价", "老豆腐1板", "大板豆腐1板",
    "湖南攸县香干5斤", "河粉30斤要红色包", "陈村粉10斤", "米粉斤",
    "云吞皮5斤", "饺子皮1 0斤", "大豆泡2斤", "三角泡斤",
    "豆串20串", "千张1 0斤", "素鸡8条", "日本豆腐件",
    "保鲜膜件30 X 40", "甜蕌头1件、补的", "鸡蛋干包"
  ].join("\n");
  const r = P.parseOrder(单子) || [];
  const 出 = (r.lines || r);
  const 找 = n => 出.find(L => (L.text || "").indexOf(n) >= 0);
  ok("★ 饺子皮进来了，10 斤", 找("饺子皮") && 找("饺子皮").qty === 10,
     找("饺子皮") ? "qty=" + 找("饺子皮").qty : "没进来");
  ok("★ 千张进来了，10 斤", 找("千张") && 找("千张").qty === 10);
  ok("⛔ 没写数量的照旧没进来（米粉／三角泡／日本豆腐／鸡蛋干）",
     !找("米粉") && !找("三角泡") && !找("日本豆腐") && !找("鸡蛋干"),
     JSON.stringify(出.map(L => L.text)));
  ok("本来读得对的还在（浓浆豆腐 25 板）", 找("浓浆豆腐") && 找("浓浆豆腐").qty === 25);
}

console.log("\n════════════════════════");
console.log(挂 ? "❌ 挂了 " + 挂 + " 项（过 " + 过 + "）" : "✅ 全过 " + 过 + " 项");
process.exit(挂 ? 1 : 0);
