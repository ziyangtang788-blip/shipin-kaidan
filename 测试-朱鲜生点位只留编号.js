/* 朱鲜生的点位只留字母数字 —— node 测试-朱鲜生点位只留编号.js

   老板 2026-08-28：
     「把朱鲜生的单点位哪里识别出来只要字母跟数字，不要中文，只有他一家这样。」

   他家明细里的点位是「佛山市顺德区机关服务中心-市监饭堂午餐A59-2」这种，
   前面一长串中文是店名，真正配货用的是尾巴那个 A59-2。

   钉四件事：
     ① 这一家的收窄成编号
     ② 【只有他一家】—— 别家一个字都不许动
     ③ 抠不出编号的原样留着（点位丢了 = 货不知道送哪儿）
     ④ 幂等 —— rematch 跑几遍结果都一样（好好多那条 ×2 就栽在这上头） */
global.window = global.window || {};
require("./数据-客户量纲.js");
const F = window.GM_客户点位写法;

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a === b) pass++; else { fail++; L("  ✗ " + name + "\n      应该 " + b + "\n      实际 " + a); }
}
const 朱 = s => F.收窄点位("S2944", s);

L("═══ ① 朱鲜生的收窄成编号 ═══");
ok("★ 一长串中文 + A59-2", 朱("佛山市顺德区机关服务中心-市监饭堂午餐A59-2"), "A59-2");
ok("带括号的店名 + A8-6", 朱("广州市老人院（上水院区）（老人糊餐）A8-6"), "A8-6");
ok("只有字母+数字的 C1", 朱("南粮大厦饭堂C1"), "C1");
ok("B2", 朱("西樵派出所（太平）B2"), "B2");
ok("C2-2", 朱("佛山市南海区财政局（午餐）C2-2"), "C2-2");
ok("A30（三位数）", 朱("肇庆端州武装部A30"), "A30");
/* 他家老单的点位是纯数字带横杠的，那种也得认 —— 换写法之前的单还会被调出来看 */
ok("★ 老写法 2-5 也认（换写法之前的单还要调出来看）", 朱("西樵派出所（西樵本部）2-5"), "2-5");
ok("老写法 33-1", 朱("昆仑33-1"), "33-1");

L("");
L("═══ ② 只有他一家 ═══");
ok("★ 别家（好好多）一个字都不动",
  F.收窄点位("S3114", "佛山市顺德区机关服务中心-市监饭堂午餐A59-2"),
  "佛山市顺德区机关服务中心-市监饭堂午餐A59-2");
ok("★ 没配规矩的客户，不动", F.收窄点位("S9999", "南粮大厦饭堂C1"), "南粮大厦饭堂C1");
ok("★ 客户号是空的，不动", F.收窄点位("", "南粮大厦饭堂C1"), "南粮大厦饭堂C1");
/* ⚠ 2026-09-01：原来这儿硬写着排除「收窄点位」一个名字，
   又往这张表上挂了个函数（明细挤一格）就红了。
   这条守的意思是【表里只挂了一家客户】—— 函数本来就不该算进去，改成排除所有函数。 */
/* ★★ 2026-09-01：编号也可能在【开头】。他家两种写法都有：
     广东省妇幼保健院A6                    编号在尾
     5-3 广州市老人院（上水院区）（老人餐） 编号在头
   原来只认尾巴，第二种一个都抠不出来 —— 拿他手上 4 张真单跑，这张全军覆没。 */
ok("★ 编号在开头也抠得出来（5-3 …）",
  F.收窄点位("S2944", "5-3 广州市老人院（上水院区）（老人餐）"), "5-3");
ok("★ 编号在开头·字母那种（11-8 …）",
  F.收窄点位("S2944", "11-8 佛山支队执勤二中队"), "11-8");
ok("⛔ 开头是数量不许当编号（5斤 不是点位号）",
  F.收窄点位("S2944", "5斤 广州市老人院"), "5斤 广州市老人院");
ok("表里只挂了朱鲜生这一家",
  Object.keys(F).filter(k => typeof F[k] !== "function").join(","), "S2944");

L("");
L("═══ ③ 抠不出编号的原样留着（点位丢了比留长名字严重）═══");
ok("★ 纯中文没编号 → 原样", 朱("广州市老人院上水院区"), "广州市老人院上水院区");
ok("空的还是空的", 朱(""), "");
ok("null 不炸", 朱(null), "");
/* 编号不在结尾的不算 —— 后面还跟着中文，说明那串数字是名字的一部分 */
ok("★ 编号后面还跟着中文 → 不当编号，原样留着",
  朱("A59-2号楼食堂"), "A59-2号楼食堂");

L("");
L("═══ ④ 幂等（rematch 会跑很多遍）═══");
{
  const a = 朱("佛山市顺德区机关服务中心-市监饭堂午餐A59-2");
  const b = 朱(a), c = 朱(b);
  ok("★ 收三遍结果一样", a + "|" + b + "|" + c, "A59-2|A59-2|A59-2");
}

L("");
L("═══ ⑤ 线接上了没有 ═══");
{
  const fs = require("fs"), path = require("path");
  const H = fs.readFileSync(path.join(__dirname, "配送开单台.html"), "utf8");
  const h = H.replace(/\/\*[\s\S]*?\*\//g, "");
  ok("★ rematch 里真的调了收窄点位", /GM_客户点位写法[\s\S]{0,120}收窄点位\(cid,g\.code\)/.test(h), true);
  /* 手动加的、钉住的、调出来冻住的行不许被改 —— 那几行在 rematch 里提前 return 了 */
  const i = h.indexOf("function rematch");
  const 段 = h.slice(i, i + 900);
  ok("★ 冻住/手动/钉住的行照旧提前跳过（不许改已出过的单）",
    段.indexOf("if(L.manual||L.pinned||L.冻) return;") < 段.indexOf("收窄点位"), true);
}

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
