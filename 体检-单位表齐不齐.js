/* 单位表齐不齐 —— node 体检-单位表齐不齐.js
   ================================================================
   老板 2026-08-17：「他根子并不是只加公斤跟张就能解决的，
                     把所有的单位全部加进来，以防下次出现别的单位没有了，
                     还有这种问题呀」

   系统认「多少」靠一张写死的单位表。表里没有的单位，代码【当没看见】：
     「3公斤」→ 只看到 3，公斤丢了 → 按行单位（多半是斤）算 → 少发一半
     「3张」  → 同上
   不是算错，是根本没看见。8/17 查出来漏了两个，而且都真在用
   （公斤 137 条货、张 8 条货）。

   光把这两个加进去还是打补丁 —— 下次来个「扎」「提」照样瞎。
   所以有了这份体检：价格库一出现表里没有的单位就红灯，逼人加，不靠人记。

   钉三件事：
     一、价格库里【真在用】的计价单位，一个都不许认不出来
     二、两份单位表（引擎-解析.js / 引擎-抓取.js）必须一模一样
     三、常见的多字单位（公斤/千克/中板/小包…）真能认出来，不是光在表里躺着
   ================================================================ */
const fs = require("fs"), path = require("path");
global.window = global.window || {};
["数据-价格库.js", "对照-预置.js", "引擎-解析.js", "引擎-抓取.js"]
  .forEach(f => require("./" + f));
const W = global.window, P = W.GM_PARSE, D = W.GM_DATA, G = W.GM_抓取;

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, 真, 说) {
  if (真) { pass++; L("  ✅ " + name); }
  else { fail++; L("  ❌ " + name + (说 ? ("\n      " + 说) : "")); }
}
/* 认不认得：拿「3<单位>」真跑一遍断句器和抓取，两条路都得认 */
function 认得吗(u) {
  let 断 = false, 抓 = false;
  try {
    const l = (P.extractSegs("(131)3" + u) || {}).list || [];
    断 = !!(l.length && l[0].qty === 3 && String(l[0].unit || "") === u);
  } catch (e) { }
  try {
    const t = G.认一格("3" + u);
    抓 = !!(t && t.是 === "数量" && t.值 === 3 && String(t.单位 || "") === u);
  } catch (e) { }
  return { 断, 抓, 都认: 断 && 抓 };
}

L("── 一、价格库里真在用的单位，一个都不许漏 ──");
{
  const 用到 = new Map();
  D.items.forEach(t => { const u = String(t[3] || "").trim(); if (u) 用到.set(u, (用到.get(u) || 0) + 1); });
  const 排 = [...用到.entries()].sort((a, b) => b[1] - a[1]);
  L("      价格库一共用到 " + 排.length + " 种计价单位");
  const 漏 = [];
  排.forEach(([u, n]) => {
    const r = 认得吗(u);
    if (!r.都认) 漏.push(`「${u}」${n} 条货在用　断句器:${r.断 ? "认得" : "⛔"}　抓取:${r.抓 ? "认得" : "⛔"}`);
  });
  ok("每一种都认得出来（认不出来 = 客户这么写就少发货）", 漏.length === 0,
     漏.join("\n      ") + (漏.length ? "\n      → 去 引擎-解析.js 的 UNITS/U1 和 引擎-抓取.js 的 订货单位/多字单位 里补上" : ""));
}

L("");
L("── 二、两份单位表必须一模一样 ──");
{
  const 解析 = fs.readFileSync(path.join(__dirname, "引擎-解析.js"), "utf8");
  const 抓取 = fs.readFileSync(path.join(__dirname, "引擎-抓取.js"), "utf8");
  const a单 = (解析.match(/var UNITS="([^"]+)"/) || [])[1] || "";
  const b单 = (抓取.match(/var 订货单位 = "([^"]+)"/) || [])[1] || "";
  ok("两边的单字单位表读得到", !!a单 && !!b单, "解析:" + a单 + "　抓取:" + b单);
  const 差A = [...a单].filter(c => b单.indexOf(c) < 0);
  const 差B = [...b单].filter(c => a单.indexOf(c) < 0);
  ok("单字单位表两边一致", 差A.length === 0 && 差B.length === 0,
     "解析多出：" + (差A.join("") || "无") + "　抓取多出：" + (差B.join("") || "无"));

  const a多 = (解析.match(/var U1="\(\?:([^"]+?)\|\["/) || [])[1] || "";
  const b多 = (抓取.match(/var 多字单位 = "([^"]+)"/) || [])[1] || "";
  const sa = new Set(a多.split("|").filter(Boolean));
  const sb = new Set(b多.split("|").filter(Boolean));
  const 缺A = [...sb].filter(w => !sa.has(w));
  const 缺B = [...sa].filter(w => !sb.has(w));
  ok("多字单位表两边一致", 缺A.length === 0 && 缺B.length === 0,
     "解析缺：" + (缺A.join("、") || "无") + "　抓取缺：" + (缺B.join("、") || "无"));
}

L("");
L("── 三、多字单位真认得（不是光在表里躺着）──");
{
  /* 「公斤」这种两个字的，必须排在字符组前面才匹得中 ——
     排后面的话「3公斤」只会匹到个空，公斤照样丢。这条就是钉这个。 */
  const 要认的 = ["公斤", "中板", "大板", "小板", "小包", "大包", "小袋", "小件"];
  const 不认的 = [];
  要认的.forEach(u => { if (!认得吗(u).都认) 不认的.push(u); });
  ok("多字单位全认得（" + 要认的.join("、") + "）", 不认的.length === 0,
     "认不出来的：" + 不认的.join("、") + "\n      多半是排在字符组后面了，正则从左往右试，得排前面");

  /* ⚠「千克」故意不在上面那串里 —— 8/17 查实：
       ① 价格库里【没有一条货按千克卖】
       ② 「3千克」被 像规格 拦下判成【规格】，跟 克/kg/ml 一个待遇，
          这是故意的：不然「500千克/件」这种规格会被当成 500 个
     哪天真有客户按千克下单，这一条会红 —— 到那时再决定是改规格判定还是加换算，
     别现在为了让考试好看就把代码掰弯。 */
  ok("「千克」目前当规格看（价格库 0 条按千克卖）—— 真出现了这条会红",
     D.items.filter(t => (t[3] || "") === "千克").length === 0);

  /* 8/17 出事的那两个，单独钉一遍 */
  ok("「公斤」认得 —— 137 条货按公斤卖，认不出就少发一半", 认得吗("公斤").都认);
  ok("「张」认得 —— 千张/腐皮按张卖", 认得吗("张").都认);
}

L("");
L("── 四、别误伤：不是单位的字不许当单位 ──");
{
  /* 加单位是往外扩，扩过头会把商品名里的字当成单位。这条兜着。 */
  const 不该认 = ["元", "页", "日", "号", "人"];
  const 误认 = 不该认.filter(u => 认得吗(u).断 || 认得吗(u).抓);
  ok("「元/页/日/号/人」这些不许当成单位", 误认.length === 0, "被当成单位了：" + 误认.join("、"));
}

L("");
L(fail ? ("══ " + pass + " 过，" + fail + " 没过") : ("══ 全过（" + pass + " 项）"));
process.exit(fail ? 1 : 0);
