/* 试-文字切成表格-验.js —— node 试-文字切成表格-验.js
   拿两堆真东西量这把新尺子准不准，一分钱不花：
     ① 35 张真表快照倒成文字（当作从 Excel 复制粘贴进来的）→ 应该【全部】判「格子」
     ② 测试里那些真单摘出来的微信手打句子              → 应该【全部】判「文字」
   判错哪一边都逐条打出来，不许只报个总分。 */
const fs = require("fs"), path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js",
 "./引擎-认表.js", "./引擎-点位册.js", "./试-文字切成表格.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const W = global.window, S = W.GM_STRUCT, X = W.GM_文字切表;

let 过 = 0, 挂 = 0;
const 挂的 = [];
function 判(名, 文, 应该) {
  const r = X.该走哪条(文);
  if (r.走 === 应该) { 过++; return r; }
  挂++; 挂的.push({ 名, 应该, 实际: r.走, 因: r.因, 文: String(文).slice(0, 60) });
  return r;
}

/* ══════ 一、35 张真表倒成文字 → 该走格子 ══════ */
console.log("── 一、35 张真表倒成文字（当成从 Excel 复制的）──");
const 快照 = fs.readdirSync(__dirname).filter(f => /^调试-格子表-.*\.json$/.test(f));
let 列数分布 = {};
for (const f of 快照) {
  const 家 = f.replace(/^调试-格子表-|\.json$/g, "");
  let j; try { j = JSON.parse(fs.readFileSync(path.join(__dirname, f), "utf8")); } catch (e) { continue; }
  let 文; try { 文 = S.结构变文字(j); } catch (e) { console.log("  变文字失败:", 家); continue; }
  /* 抬头那几行 # 开头的去掉 —— 那是我们自己加的注，客户粘不进来 */
  文 = 文.split("\n").filter(l => !/^#/.test(l)).join("\n");
  if (!文.trim()) continue;
  const r = 判(家, 文, "格子");
  if (r.走 === "格子") { const k = r.格子[0].rows[0].length; 列数分布[k] = (列数分布[k] || 0) + 1; }
}
console.log("  列数分布:", JSON.stringify(列数分布));

/* ══════ 二、微信手打的真句子 → 该走文字 ══════ */
/* 全部摘自 测试-解析引擎.js，是真单上撞出来的写法，不是编的 */
console.log("\n── 二、微信手打（真单摘的）──");
const 手打 = [
  ["单行带单位", "千张 5斤"],
  ["若干", "攸县香干 若干"],
  ["冒号", "熟猪血： 12 斤"],
  ["认错字的", "5oog山水豆腐透明包装2合"],
  ["件数", "2件30 X 40的"],
  ["一句话", "永超汇脆件要有青豆、补的"],
  ["常订名单（多行没数量）", "三角豆泡斤\n豆腐串串\n炸腐竹包\n米豆腐盒\n鸭血件\n千张3斤"],
  ["两行随手打", "水豆腐3板\n老豆腐2板"],
  ["带括号点位一行", "水豆腐 (H1171)14斤+(1090)8斤"]
];
手打.forEach(([名, 文]) => 判(名, 文, "文字"));

/* ══════ 三、从 Excel 复制的样子 → 该走格子 ══════ */
console.log("\n── 三、从 Excel 复制（带 Tab）──");
const 表样 = [
  ["蔬源三列", "客家豆腐\t7斤/板\t大沥人民法庭\t18\t斤\n华晨豆腐\t7斤/板\t里水燃气\t2\t板\n水豆腐\t\t九江燃气\t4\t斤"],
  ["两列", "水豆腐\t3板\n老豆腐\t1板\n攸干\t2斤"],
  ["观麦导出", "2026-08-03\t大豆泡\t斤\t6\t218\n2026-08-03\t千张\t斤\t3\t109"]
];
表样.forEach(([名, 文]) => 判(名, 文, "格子"));

/* ══════ 四、陷阱：这些【绝不许】被摆成表 ══════
   「认错为 0」这条死规矩管的就是这一头。
   漏判（该走格子走了猜）只是跟现在一样；
   误判（把一段话硬摆成表）是凭空多出来的新错，一条都不许有。 */
console.log("\n── 四、陷阱（绝不许判成格子）──");
const 陷阱 = [
  ["微信闲聊", "老板今天下午的货   麻烦早点送\n仓库那边说   四点前要到"],
  ["一段说明", "今天的单如下  请确认\n有问题随时打电话给我  谢谢"],
  ["随手打两行带空格", "豆腐串    10+60+40+5 串\n千张皮    2+4+6 斤"],
  ["加工要求", "水豆腐 1.5斤  要3块\n老豆腐 2斤  切厚一点"],
  ["地址", "送到  南海区大沥镇\n联系人  张生  13800138000"]
];
陷阱.forEach(([名, 文]) => {
  const r = X.该走哪条(文);
  if (r.走 === "格子") {
    挂++; 挂的.push({ 名: "陷阱-" + 名, 应该: "文字", 实际: "格子", 因: r.因, 文: String(文).slice(0, 60) });
  } else 过++;
});

/* ══════ 报账 ══════ */
console.log("\n════════════════════════");
if (挂的.length) {
  console.log("判错 " + 挂的.length + " 条：");
  挂的.forEach(z => console.log("  ✗ [" + z.名 + "] 该走「" + z.应该 + "」，实际「" + z.实际 + "」　因：" + z.因 + "\n      " + JSON.stringify(z.文)));
}
console.log("过 " + 过 + " 　挂 " + 挂);
process.exit(挂 ? 1 : 0);
