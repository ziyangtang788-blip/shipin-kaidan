let 过 = 0, 败 = 0;
function ok(题, 真, 补) {
  if (真) { 过++; console.log("  ✅ " + 题); }
  else { 败++; console.log("  ❌ " + 题 + (补 ? "　" + 补 : "")); }
}

function 跑(标题, rows, 改指认) {
  console.log("\n══ " + 标题 + " ══");
  const z = JSON.parse(JSON.stringify(指认));
  if (改指认) 改指认(z);
  const r = N.认(rows, z);
  if (r.要问的) {
    console.log("  ⛔ 停下来问人：");
    r.要问的.forEach(s => console.log("      · " + s));
    return { 停了: true, 要问的: r.要问的 };
  }
  console.log("  读法 = " + JSON.stringify(r.读法));
  const 合 = T.摊平([{ n: 1, rows: rows }], r.读法);
  const n = 合 ? 合.行.length : 0;
  const 段 = 合 ? 合.行.reduce((a, L) => a + (L.分布 || []).length, 0) : 0;
  const 账 = N.对账(合, r.对账);
  console.log("  摊出 " + n + " 样货、" + 段 + " 条分布");
  if (账.length) 账.forEach(s => console.log("  ⚠ " + s));
  return { 停了: false, 样数: n, 段数: 段, 账: 账, 合: 合 };
}

