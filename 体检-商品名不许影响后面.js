/* ============================================================
   体检：商品名那一格再脏，也不许影响后面的数量·单位·明细·点位
   node 体检-商品名不许影响后面.js
   ============================================================

   老板 2026-08-19（御口福那张表之后）：
     「商品名这一杠，它只能在商品名这一格里，不论商品名变得多脏，
     　它都不能影响后面的明细。明细你是要单独读取的。」
     「我们这个问题的总结原因就是互相串，所以该盯死的地方一定得盯死。」

   ────────────────────────────────────────────────
   这份是怎么逼出来的
   ────────────────────────────────────────────────
   御口福那张表，商品名那一格客户自己写成「水豆腐|1板/中板」——
   名字里带一根【竖线】。而 OCR 把表转成文字时，竖线正是分列的符号：

     |  1 | 内臟嫩豆腐      | 1盒/盒 | 8盒(8盒)  | 1盒*欧巢门窗【K53】…  |   ← 5 格
     |  4 | 水豆腐|1板/中板 | 1板/中板 | 7中板(7板) | 1中板*快乐家【511】… |   ← 6 格

   同一张表，有的行 5 格、有的行 6 格。
   「明细在第几列」这个说法当场失效 ——
   挑列按多数定成第 6 列，于是名字【干净】的那 3 行反而读不到明细，
   数量全空、对账的闸也拿不到总数、品名只剩「水豆腐」配成了斤货。

   ⛔ 一根竖线，明细·总数·品名 三样一起错。

   ⚠ 这份【不测某一张单】，测的是那条边：
     商品名那一格换成几十种脏写法，后面四样必须一格不变。
     变了就红 —— 新表、新代码、明天没见过的写法，都逃不掉。

   ⚠ 跟 体检-别的不许动这四样.js 是两条不同的边，别合并：
     那份盯的是「备注/规格 → 四样」，这份盯的是「商品名 → 后面」。

   ⚠ 品名自己读脏了不算错（配货那步本来就会存疑、让人挑）——
     这份只查【后面那几样有没有被带歪】。
   ============================================================ */
"use strict";
global.window = global.window || {};
require("./引擎-解析.js");
require("./数据-价格库.js");
require("./引擎-抓取.js");
require("./引擎-读结构.js");
const G = window.GM_抓取, S = window.GM_STRUCT, P = window.GM_PARSE;

/* ══════ 表形一：规规矩矩的明细表（商品名 / 规格 / 数量 / 单位 / 点位 / 备注 各占一列）══════ */
const 点 = "广东省中医院/大学城分院";
function 跑分列(品名) {
  const rows = [
    ["序号", "客户名称", "产品名称", "规格型号", "预定数量", "预定单位", "备注"],
    ["1", 点, 品名, "7斤/板", "100.00", "斤", ""],
    ["2", 点, "千张", "", "7.00", "斤", ""]
  ];
  let r; try { r = G.抓(rows); } catch (e) { return { 炸: e.message }; }
  if (!r || !(r.行 || []).length) return { 炸: "一行都没读出来" };
  const out = S.读结构({ 抬头: {}, 行: r.行, 没读懂的: [], 表怎么读的: { 版式: "x" } });
  return 摘(out);
}

/* ══════ 表形二：一格挤一串明细（御口福那种，明细里有点位+数量）══════
   ★ 这一种才是御口福栽的那种。只造表形一的话，竖线那个坑一点都验不出来。 */
function 跑一格(品名) {
  const rows = [
    ["序号", "商品名", "规格", "采购总数", "明细"],
    ["1", 品名, "1板/中板", "7中板(7板)",
      "1中板*快乐家（岭南店）-月结【511】 3中板*曼谷街角-厨房(月付)【534】 2中板*风铃湖私房菜【509】 1中板*林坑阁农庄（半月结）【K42】"],
    ["2", "焗香干", "1斤/斤", "12斤(12斤)", "12斤*田村长罗村店（月结）【K14】"]
  ];
  let r; try { r = G.抓(rows); } catch (e) { return { 炸: e.message }; }
  if (!r || !(r.行 || []).length) return { 炸: "一行都没读出来" };
  const out = S.读结构({ 抬头: {}, 行: r.行, 没读懂的: [], 表怎么读的: { 版式: "x" } });
  return 摘(out);
}

/* 只摘【后面那几样】—— 品名自己脏不脏不在这份的管辖内 */
function 摘(out) {
  const L = (out.lines || [])[0] || {};
  const segs = L.segs || [];
  return {
    行: (out.lines || []).length,
    段: segs.length,
    量: Math.round(segs.reduce((a, g) => a + (parseFloat(g.qty) || 0), 0) * 1000) / 1000,
    单: (segs[0] && segs[0].unit) || L.unit || "",
    /* 明细里的点位，一个都不许少、不许变 —— 按出现顺序拼起来比 */
    位: segs.map(g => g.code || "").join("§"),
    /* 第二行货（焗香干/千张）也得原样在 —— 商品名脏了不许把别人也带塌 */
    二: ((out.lines || [])[1] || {}).text || "",
    别: (P.别的货() || []).length
  };
}

/* ══════ 商品名那一格能出现的脏写法 ══════
   前 4 条是真单上出过的，后面是往死里造 —— 客户什么都可能写。 */
const 脏写法 = [
  "水豆腐|1板/中板",          /* ★ 御口福真单，竖线 */
  "水豆腐(斤)|1斤/斤",        /* ★ 御口福真单 */
  "鸡蛋干150g|1小包/小包",    /* ★ 御口福真单 */
  "益群山水豆腐400g|1盒/盒",  /* ★ 御口福真单 */
  "水豆腐||1板",              /* 连着两根竖线 */
  "|水豆腐",                  /* 开头一根 */
  "水豆腐|",                  /* 结尾一根 */
  "水豆腐/中板",              /* 斜杠 */
  "水豆腐 7斤/板",            /* 名字里粘着规格 */
  "水豆腐（约7斤）",           /* 全角括号 */
  "水豆腐(月付)【K53】",       /* 名字里混进点位样的东西 */
  "水豆腐 100",               /* 名字尾巴带纯数字 */
  "水豆腐 K53",               /* 名字尾巴带编号 */
  "水豆腐+老豆腐",             /* 加号 */
  "水豆腐*2",                 /* 星号 */
  "水豆腐,老豆腐",             /* 逗号 */
  "水豆腐\t中板",             /* 制表符 */
  "水  豆  腐",               /* 被拉开的字 */
  "水豆腐●",                  /* 怪符号 */
  "ＳＵＩ豆腐",                /* 全角字母 */
  "",                         /* 整格空的 */
  "   ",                      /* 只有空格 */
  "水豆腐" + "腐".repeat(40)  /* 超长 */
];

let 过 = 0, 败 = 0;
const 名 = ["表形一·分列明细表", "表形二·一格挤一串（御口福那种）"];
[跑分列, 跑一格].forEach((跑, 序) => {
  console.log("\n  ── " + 名[序] + " ──");
  const 基 = 跑("水豆腐");
  if (基.炸) { console.log("      ❌ 基准单都读不出来：" + 基.炸); 败++; return; }
  console.log("      基准：" + 基.段 + " 段　量 " + 基.量 + 基.单 + "　点位[" + 基.位 + "]");
  脏写法.forEach(v => {
    const r = 跑(v);
    const 坏 = [];
    if (r.炸) 坏.push("整张读不出来（" + r.炸 + "）");
    else {
      if (r.行 !== 基.行) 坏.push("行数 " + 基.行 + "→" + r.行);
      if (r.段 !== 基.段) 坏.push("明细段数 " + 基.段 + "→" + r.段);
      if (r.量 !== 基.量) 坏.push("数量 " + 基.量 + "→" + r.量);
      if (r.单 !== 基.单) 坏.push("单位「" + 基.单 + "」→「" + r.单 + "」");
      if (r.位 !== 基.位) 坏.push("点位「" + 基.位 + "」→「" + r.位 + "」");
      if (r.二 !== 基.二) 坏.push("把下一行货也带歪了「" + 基.二 + "」→「" + r.二 + "」");
      if (r.别 !== 基.别) 坏.push("凭空多出 " + (r.别 - 基.别) + " 行别的货");
    }
    const 看 = v === "" ? "(整格空)" : (v.trim() === "" ? "(只有空格)" : (v.length > 22 ? v.slice(0, 22) + "…" : v));
    if (坏.length) { 败++; console.log("      ❌ 商品名写「" + 看 + "」　" + 坏.join("；")); }
    else 过++;
  });
});

console.log("\n" + (败 ? ("══ 没过 " + 败 + " 项，过 " + 过 + " 项 —— 商品名串到后面去了")
                       : ("══ 全过（" + 过 + " 项）商品名怎么脏，后面都没动")));
process.exit(败 ? 1 : 0);
