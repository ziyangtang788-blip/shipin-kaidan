/* 客户按斤下单、库里按板计价 —— node 测试-斤转板.js

   老板 2026-08-02 原话：
     「这个水豆腐客户他要的 18 斤，我选了这个 6 斤的，它就应该是 3 板。
       现在还是变成 18 板。」
     「有的客户他只写斤，我就需要自动去匹配对应的板数。
       假如他要 18 斤，我就给他 6 斤的，刚好就是 3 板。
       如果他要 15 斤，6 斤的就不对，要给他 5 斤的。」

   两件事：
     ① 换算   —— 商品定了，单位对不上就把数量换过去（18斤 ÷ 6 = 3板）
     ② 挑板型 —— 几种板都可能时，谁能把斤数凑得整就是谁（15斤 → 5斤板）

   底线：凑不整、或者好几种都凑得整 —— 一律交给人。
         替他挑一个凑不整的，就是要么少发要么多发。 */
global.window = {};
require("./数据-价格库.js");
require("./对照-预置.js");
require("./引擎-解析.js");
require("./引擎-匹配.js");
require("./数据-常用规格.js");
const D = window.GM_DATA, SEED = window.GM_SEED || {}, P = window.GM_PARSE, M = window.GM_MATCH;
const USED = window.GM_USED || {};

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  if (JSON.stringify(got) === JSON.stringify(want)) { pass++; L("  ✅ " + name); }
  else { fail++; L("  ❌ " + name + "\n      应该 " + JSON.stringify(want) + "\n      实际 " + JSON.stringify(got)); }
}

const usedN = (cid, sku) => (USED[cid] || {})[sku] || 0;
const IDX = M.buildIndex(D, usedN);
const OV = { maps: {}, gmap: {} };
const C = {
  DATA: D, IDX, OV, usedN,
  seedLookup: (cid, t, u) => P.seedLookup(SEED[cid], t, u),
  learnedSku: (ci, t, u) => P.learnedLookup(OV.maps, D.custs[ci][0], t, u,
    sku => IDX.byCust[ci].sku[sku] === undefined ? null : D.items[IDX.byCust[ci].sku[sku]][3]),
  defaultSide: window.GM_DEFAULT_SIDE
};
const ciOf = id => { let k = -1; D.custs.forEach((c, i) => { if (c[0] === id) k = i; }); if (k < 0) throw new Error("没有 " + id); return k; };
const CI = ciOf("S2947");                    /* 裕丰：水豆腐（5斤）¥5.5 /（6斤）¥6.5 */
const b = IDX.byCust[CI];
const idxOf = a => { for (const i of b.list) if (D.items[i][2] === a) return i; throw new Error("裕丰没有「" + a + "」"); };

L("── ① 一板几斤，读得出来吗 ──");
const 读 = a => { const r = M.一份几个(D, idxOf(a)); return r ? (r.n + r.小 + "/" + r.大) : null; };
ok("水豆腐（6斤）→ 6斤/板", 读("水豆腐（6斤）"), "6斤/板");
ok("水豆腐（5斤）→ 5斤/板", 读("水豆腐（5斤）"), "5斤/板");
ok("尝元老豆腐（15斤）→ 15斤/板", 读("尝元老豆腐（15斤）"), "15斤/板");
ok("花泉山水豆腐（件）→ 12盒/件（规格列）", 读("花泉山水豆腐（件）"), "12盒/件");
ok("日本豆腐（件）→ 40条/件", 读("日本豆腐（件）"), "40条/件");
ok("九龙炸豆腐（块）→ 0.4斤/块", 读("九龙炸豆腐（块）"), "0.4斤/块");
/* 范围一律不算 —— 算 14 还是 15 差一板的钱 */
ok("大板豆腐（14-15斤）是范围 → 读不出，交给人", 读("尝元大板豆腐（14-15斤）"), null);
ok("九龙水豆腐（14-15斤）同理", 读("九龙水豆腐（14-15斤）"), null);
/* 单位本来就一样的不用换 */
ok("千张按斤卖 → 没有换算这回事", 读("千张"), null);

L("");
L("── ② 换算：数量要跟着变 ──");
const 换 = (a, u, q) => {
  const i = idxOf(a), r = M.换算比(D, i, u);
  return r ? (Math.round(q * r.mul * 1000) / 1000) + D.items[i][3] : "换不了";
};
ok("18斤 配 6斤板 → 3板（老板那一行）", 换("水豆腐（6斤）", "斤", 18), "3板");
ok("15斤 配 5斤板 → 3板", 换("水豆腐（5斤）", "斤", 15), "3板");
ok("24盒 配 12盒/件 → 2件", 换("花泉山水豆腐（件）", "盒", 24), "2件");
ok("80条 配 40条/件 → 2件", 换("日本豆腐（件）", "条", 80), "2件");
ok("2斤 配 0.4斤/块 → 5块", 换("九龙炸豆腐（块）", "斤", 2), "5块");
/* 反过来也要对：客户写板，库里按斤卖 */
ok("单位一样的不动", 换("千张", "斤", 5), "换不了");
ok("读不出比例的不硬换", 换("尝元大板豆腐（14-15斤）", "斤", 30), "换不了");

L("");
L("── ③ 总斤数必须对得上 ──");
/* 换完再乘回去，得回到客户写的那个数 —— 对不上就是发错货 */
[[18, "水豆腐（6斤）"], [15, "水豆腐（5斤）"], [30, "尝元老豆腐（15斤）"]].forEach(function (x) {
  const i = idxOf(x[1]), r = M.换算比(D, i, "斤"), 板 = x[0] * r.mul;
  const 回 = 板 * M.一份几个(D, i).n;
  ok(x[0] + "斤 → " + 板 + "板 → 乘回去还是 " + x[0] + "斤", Math.round(回 * 1000) / 1000, x[0]);
});

L("");
L("── ④ 挑板型：谁凑得整就是谁 ──");
/* 真实场景：人教过「优质豆腐 → 水豆腐（6斤）」，之后客户按斤报数。
   这个词本身不含板型信息 —— 客户报的是斤数，哪种板凑得整就发哪种。 */
const OVL = {};
(function 教() {
  const sku = D.items[idxOf("水豆腐（6斤）")][6];
  P.learnWrite(OV.maps, OV.gmap, "S2947", "优质豆腐", sku, "斤",
    D.items[idxOf("水豆腐（6斤）")][1], (ba, u) => M.bareRisky(D, b, ba, u));
})();
function 认(text, unit, qty) {
  const r = M.matchOne(C, CI, text, unit, null, qty);
  return [r.i >= 0 ? D.items[r.i][2] : "认不出", M.commits(r.how), r.how];
}
{
  const a18 = 认("优质豆腐", "斤", 18), a15 = 认("优质豆腐", "斤", 15);
  L("    18斤 → " + a18[0] + " [" + a18[2] + "]");
  L("    15斤 → " + a15[0] + " [" + a15[2] + "]");
  ok("18斤 → 6斤板（教过的那个，刚好整除）", a18[0], "水豆腐（6斤）");
  ok("15斤 → 换成 5斤板（6斤凑不整）", a15[0], "水豆腐（5斤）");
  ok("凑得整就敢拍板（18斤）", a18[1], true);
  ok("凑得整就敢拍板（15斤）", a15[1], true);
  ok("换过板型的要标出来", a15[2], "fitboard");
}
{
  /* 17 斤：5斤板 3.4、6斤板 2.833 —— 一种都凑不整 → 交给人 */
  const a = 认("优质豆腐", "斤", 17);
  L("    17斤 → " + a[0] + " [" + a[2] + (a[1] ? "" : " 存疑") + "]");
  ok("17斤 一种都凑不整 → 交给人，不许硬凑", a[1], false);
}
{
  /* 30 斤：教过的 6斤板刚好 5块，那就用它 —— 自己凑得整就没有歧义，
     不用因为「5斤板也凑得整」去打扰人。只有教过的那个凑不整时才去找同族。 */
  const a = 认("优质豆腐", "斤", 30);
  L("    30斤 → " + a[0] + " [" + a[2] + (a[1] ? "" : " 存疑") + "]");
  ok("30斤 教过的 6斤板自己就整除 → 用它，不打扰人", a[0], "水豆腐（6斤）");
  ok("而且直接拍板", a[1], true);
}
{
  /* 25 斤：6斤板 4.167 凑不整，5斤板 5块刚好 → 换过去 */
  const a = 认("优质豆腐", "斤", 25);
  L("    25斤 → " + a[0] + " [" + a[2] + "]");
  ok("25斤 → 换成 5斤板", a[0], "水豆腐（5斤）");
  ok("25斤 也敢拍板", a[1], true);
}
{
  /* 客户自己写了板数的，不受这条影响 —— 他说几板就是几板 */
  const a = 认("优质豆腐", "板", 3);
  ok("客户写板数的不受影响", a[0], "水豆腐（6斤）");
  ok("而且照旧拍板", a[1], true);
}

L("");
L("── ⑤ 不许乱伸手 ──");
/* 论斤卖的货有现成的斤价时，走「散称闸门」，轮不到凑板 */
/* 「7斤/板」是表格另一列标的，客户原话只有「客家豆腐」→ 走斤价，轮不到凑板。
   要是规格写在客户原话里（碧源「水豆腐（5斤装）」），那才是板货 —— 见下一条。 */
ok("蔬源 客家豆腐 7斤/板 18斤 → 还是论斤那条",
  (function () {
    const ci2 = ciOf("S2930");
    const r = M.matchOne(C, ci2, "客家豆腐 7斤/板", "斤", null, 18, { 名原: "客家豆腐" });
    return D.items[r.i][2];
  })(), "客家豆腐（斤）");
/* 碧源 S2949：板型只有 5斤（¥5.3），另有按斤 ¥1.3。

   ⚠⚠ 这里跟观麦开的那张单不一样，别照观麦改回去。
   老板 2026-08-02 当面确认过两次（原话）：
     「客户如果给的是斤，那么你要对应他这个产品里面有没有可以整除的斤的数量。
       如果没有，就是按单斤卖；如果有，就是按板卖。」
     「按金(斤)的规则来，不按观麦的规则来，按我的规则走。」

   所以：1斤、2斤、3斤 除不尽 5 → 按单斤卖 ¥1.3/斤。
   观麦那张单当时是折成 0.6 板开的 ¥3.18，按这条规矩是 ¥3.90 —— 差 ¥0.72，
   以老板这条为准。谁要改回「除不尽也折成小数板」，先去问他。 */
{
  const ci3 = ciOf("S2949");
  const 算 = q => {
    const r = M.matchOne(C, ci3, "水豆腐(5斤装)", "斤", null, q);
    const c = M.换算比(D, r.i, "斤");
    return [D.items[r.i][2], c ? Math.round(q * c.mul * 1000) / 1000 : q, D.items[r.i][3]];
  };
  ok("1斤 除不尽 5 → 按单斤卖", 算(1)[2], "斤");
  ok("3斤 除不尽 5 → 按单斤卖", 算(3)[2], "斤");
  ok("10斤 刚好 2板 → 按板卖", 算(10), ["尝元小板豆腐（5斤）", 2, "板"]);
  ok("15斤 刚好 3板 → 按板卖", 算(15), ["尝元小板豆腐（5斤）", 3, "板"]);
}

L("");
L("── ⑥ 单位闸门 —— 2026-08-02 轩宝真单，答案 ¥1860.30 ──");
/* 那张单 45 行只错一行，差 ¥11.08：
     原单「尝元韧豆腐5斤/板/厚度3cm  板  2」
     答案  尝元韧豆腐（5斤）按板 ¥7.00 × 2 = ¥14.00
     出成  尝元韧豆腐（斤）      ¥1.46 × 2 = ¥2.92
   客户白纸黑字写「板」，闷着按「斤」算，一板的钱就没了。 */
{
  const CI2 = ciOf("S2934");
  function 认2(text, unit, qty) {
    const r = M.matchOne(C, CI2, text, unit, null, qty);
    return [r.i >= 0 ? D.items[r.i][2] : "认不出", M.commits(r.how), r.how];
  }
  const a = 认2("尝元韧豆腐5斤/板/厚度3cm", "板", 2);
  L("    尝元韧豆腐5斤/板 2板 → " + a[0] + " [" + a[2] + (a[1] ? "" : " 存疑") + "]");
  ok("客户写「板」，不许落到按斤卖的那条", D.items.find(x => x[2] === a[0] && x[0] === CI2)[3], "板");
  ok("规格对不上（写5斤、库里6.5斤）→ 不敢拍板，交给人", a[1], false);

  /* 括号里那截才是真商品名：「豆腐嫂（大板豆腐）」 */
  const c = 认2("豆腐嫂(大板豆腐)(14斤/版)", "板", 2);
  L("    豆腐嫂(大板豆腐) 2板 → " + c[0] + " [" + c[2] + (c[1] ? "" : " 存疑") + "]");
  ok("括号里的「大板豆腐」要认出来，别整行认不出", c[0], "尝元大板豆腐（14-15斤）");
  ok("但只摆出来让人点，不拍板（括号更多时候装的是规格）", c[1], false);

  /* 这张单其余 44 行都对，别被这两条闸门带歪 */
  ok("千张 245斤 照旧", 认2("千张(豆皮)(薄)", "斤", 245)[0], "千张");
  ok("猪红（沥水）照旧", 认2("猪红(沥水)(含水15%)", "斤", 50)[0], "猪血");
  ok("华晨豆腐（净重15斤/板）照旧", 认2("华晨豆腐(净重15斤/板)", "板", 3)[0], "华晨豆腐（15斤）");
  ok("华晨胶板豆腐（净重5斤）照旧", 认2("华晨胶板豆腐(净重5斤)", "板", 28)[0], "华晨豆腐 (5斤 )");
  ok("胶板豆腐7斤 照旧", 认2("胶板豆腐7斤(净重7斤/板)", "板", 18)[0], "尝元中板豆腐（7斤）");
  ok("浓浆豆腐 照旧", 认2("浓浆豆腐(约8.5斤/板)", "板", 3)[0], "尝元浓浆豆腐（8.5斤）");
}

L("");
L("── ⑦ 并了规格列反而认不出 —— 2026-08-02 三颗菜真单 ──");
/* 表格有「规格」列时，解析会把它并进商品名。好处是能分开 7斤板 ¥8 和 15斤板 ¥17；
   坏处是并完之后有时反而配不上：
     「水豆腐/板」            → 预置命中 尝元小板豆腐[板] ¥4.5   ✓
     「水豆腐/板 中板/约5斤」  → 预置配不上，掉到 水豆腐[斤] ¥1.2  ✗
   三颗菜那张单 33 行全掉，¥463.50 掉成 ¥123.60。
   规矩：并过规格的，两个名字都试一遍，谁认得准用谁 ——
        多一条线索不该让结果变差。 */
{
  const CI4 = ciOf("S2999");
  const 认4 = (t, n0, u, q) => {
    const r = M.matchOne(C, CI4, t, u, null, q, { 名原: n0 });
    return [r.i >= 0 ? D.items[r.i][2] : "认不出", M.commits(r.how)];
  };
  ok("并了规格也要认得（拿客户原话再试一遍）",
    认4("水豆腐/板 中板/约5斤", "水豆腐/板", "板", 12), ["尝元小板豆腐", true]);
  ok("不带规格的照旧", 认4("水豆腐/板", "水豆腐/板", "板", 12), ["尝元小板豆腐", true]);
  /* 反过来，规格列真正有用的那种不能坏：蔬源 7斤板 ¥8 / 15斤板 ¥17 */
  const CI5 = ciOf("S2930");
  const 认5 = (t, n0) => {
    const r = M.matchOne(C, CI5, t, "板", null, 2, { 名原: n0 });
    return D.items[r.i][2];
  };
  ok("规格列该起作用的地方还起作用", 认5("华晨豆腐 7斤/板", "华晨豆腐"), "华晨豆腐7斤/板");
}

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
