/* ============================================================
   总闸 —— 出单之前回头看一眼：这张单齐了吗
   ============================================================

   老板 2026-09-06 定的：
     「我要的是总闸，不是一个单闸。」
     「不论是列出问题还是拆出问题都要跳出来。」
     「该有的明细都没有出来，这种你学习功能就跳出来，把不懂的给他弄出来，
     　不要直接就出单。而且更不要弹那么多弹窗。」

   为什么非要有这一道
   ------------------
   以前每条读表的路各带各的检查，各自只盯自己那一小块，
   谁都没有站在【出单前】回头看整张单。于是朱先生 9/6 那张：
     原文  昆仑实业33-1  老人院(碎菜)5-9  老人院(糊餐)5-5  老人院(糖餐)5-4  老人院(菜泥)5-6
     出单  20板，全压在一个点位上
   数量读得出来（不算读不懂）、段和 20 = 表上 20（账是平的）——
   两条老闸一条都拦不住，一句不问，单子照出。钱不错，货全发错地方。

   ⚠ 闸只管那四样（什么东西／多少／什么单位／送去哪里）。
     规格、备注没进单不归这儿管 —— 那是 CLAUDE.md 头一条铁律画的线。
   ⚠ 判据只认【原文自己写着的证据】，一个字都不猜。
   ⚠ 「一整列没派上用场」也不归这儿：那件事有专门的窗问一次、记住
     （配送开单台.html 里那道「这一列是什么」）。放进来会天天误伤
     「参考线路」「客户数」这种本来就不该进单的列 —— 36 张真表当场量到 13 张误伤。
   ============================================================ */
(function (root) {
  "use strict";

  /* 一串里明摆着有几段 —— ★★ 2026-09-07 老板定死：【只数数量，点位一概不管】。
       「20斤——186B—— 30斤——204A——」  → 2（两个数量，真该拆成两行）
       「昆仑实业33-1 老人院5-9 老人院5-5」 → 0（三个点位，可一个数量都没有）

     老板原话：「不要都拦，只要拆得出来几行就可以了，点位没有就没有，照样出单。」

     为什么只认数量：
       · 数量拆错 = 货发错量，那是事故，非拦不可
       · 点位拆不开顶多是「不知道送哪个门」，人看一眼就补得上 —— 拦了纯属挡着他干活
     ⛔ 别再把点位数回来。9/7 那次误报就是数点位数出来的，屏幕上一串
        「炸面筋（2个点位挤成一行）」，他一句话点破：「这个是BUG，不是两个点位。」

     ⛔⛔ 只许用【粗档】（只按空白切）。细档（连符号一起切）会把一个东西切碎：
       西樵派出所(官山)2-6(2)  →  西樵派出所 / 官山 / 2-6 / 2
     道理：名字自己就带括号横杠，可段与段之间永远是空白隔开的。
     ⚠ 切碎走 引擎-碎片类 那一份，不另写正则（CLAUDE.md：匹配逻辑只准一份）。 */
  function 明摆着几段(串) {
    var F = root.GM_碎片;
    var s = String(串 == null ? "" : 串).trim();
    if (!s || !F || !F.切碎) return 0;
    var n = 0;
    try {
      (F.切碎(s, false) || []).forEach(function (b) { if (b.类 === "数字+单位") n++; });
    } catch (e) { return 0; }
    return n;
  }

  /* 没拆开的行数：这一行只出了一段，可那一段里明摆着塞着两个以上点位/数量。
     ⚠ 只看【只出一段】的行 —— 已经拆成好几段的，拆得对不对是账那条闸的事。 */
  function 没拆开(合) {
    var n = 0;
    ((合 && 合.行) || []).forEach(function (L) {
      var 段 = (L && L.分布) || [];
      if (段.length !== 1) return;
      var d = 段[0] || {};
      var 串 = String(d.点位名 || d.点位号 || d.原文 || "");
      if (明摆着几段(串) >= 2) n++;
    });
    return n;
  }

  /* ══════════ 近道该让开吗 —— ★★ 2026-09-09 老板定的总规矩 ══════════
     「一格里挤着两个以上数量 → 老员工不许读这张单，交给会拆的那个。」

     为什么非有这条不可（9/9 查了三周的账才查明白）：
       页面读一张表的顺序是 ⓪按长相直接抓（8 月就有的「老员工」）
       → ①读法本 → B认列（9/6 才教会「地址一列数量一列按顺序配」）→ ②问 AI。
       ⓪ 只要出了货就 return，B 根本不跑。
       而 ⓪ 的毛病是：【只要一张单里大半行看着简单，它就整张包了】，
       那几行多点位的被它按简单行读 —— 地址整格当一个地名，
       数量那一列没人认领直接扔。账还是平的（总数列还在），一句不弹。

     实测（9/9，同一张表只加几行简单货）：
       2 行货全是多地址 → ⓪ 让开 → B 上场 → 读对
       9 行货（8 行简单 + 1 行多地址）→ ⓪ 接走 → B 没上场 → 明细全丢
     所以三周里为朱先生改的 31 次全打在 B 身上，一次都没生效过。
     ⛔ 测试也是这么绿的：那 8 张卷子全是「2 行货、行行多地址」，
       正好是 ⓪ 主动让开的形状 —— 考的是 B，跑的是 ⓪。

     判据【就用上面那份 明摆着几段】，不另写：
       9/7 老板定死「只数数量，点位一概不管」，这儿照搬同一把尺子。
       一格里有两个以上数量 = 这一格明摆着是好几笔货，⓪ 不会拆，让开。
     ⚠ 存档实测：13 张命中（朱鲜生 12 + 广晟 1），别家一张都不动。 */
  function 近道该让开(rows) {
    var 行们 = rows || [];
    for (var i = 0; i < 行们.length; i++) {
      var r = 行们[i] || [];
      for (var c = 0; c < r.length; c++) {
        if (明摆着几段(r[c]) >= 2) return true;
      }
    }
    return false;
  }

  root.GM_总闸 = { 没拆开: 没拆开, 明摆着几段: 明摆着几段, 近道该让开: 近道该让开 };
})(typeof window !== "undefined" ? window : globalThis);
