/* ── 把一格里的数字切成一串（4斤 1斤 3斤 → [4,1,3]，单位跟着走）── */
const 数字们 = s => {
  const out = [];
  const re = /([0-9]+(?:\.[0-9]+)?)\s*(斤|板|盒|包|箱|袋|件|条|串|个|块|桶|扎|把|瓶|罐|支|kg|g|克|公斤)?/gi;
  let m;
  while ((m = re.exec(String(s || ""))) !== null) out.push({ 数: parseFloat(m[1]), 单位: m[2] || "" });
  return out;
};
/* ── 一格里的点位切成一串。点位＝不是纯数量的那些块 ── */
const 点位们 = s => {
  const t = String(s || "").trim();
  if (!t) return [];
  /* 按空格切，但括号里的空格不算（「西樵派出所（西樵本部）2-5」是一整块） */
  const 块 = [], buf = [];
  let 当 = "", 深 = 0;
  for (const c of t) {
    if (c === "(" || c === "（") 深++;
    if (c === ")" || c === "）") 深 = Math.max(0, 深 - 1);
    if (深 === 0 && /\s/.test(c)) { if (当.trim()) 块.push(当.trim()); 当 = ""; continue; }
    当 += c;
  }
  if (当.trim()) 块.push(当.trim());
  /* 「佛山市南海区…有限公司(盐步饭堂) 33-3A」这种公司名和点位号被空格拆开的，
     后一块要是「纯编号」就并回前一块 —— 不并的话点位数会比数量多，配不上。 */
  const 出 = [];
  for (const b of 块) {
    if (出.length && /^[0-9]{1,3}-[0-9A-Za-z]{1,4}$/.test(b) && !/[0-9]-[0-9]/.test(出[出.length - 1].slice(-6)))
      出[出.length - 1] += " " + b;
    else 出.push(b);
  }
  return 出;
};
const 数值 = s => { const m = String(s || "").match(/([0-9]+(?:\.[0-9]+)?)/); return m ? parseFloat(m[1]) : null; };
const 近 = (a, b) => Math.abs(a - b) < 0.001;

/* ══════════════ 要试的那条规矩 ══════════════
   给一张格子表 + 已知的「合计列、明细(点位)列」，
   在剩下的列里找那一列：每一行分段加起来 == 这一行的合计。找到就当数量列。 */
function 找分配数量列(rows, 头行, 合计列, 点位列) {
  const 宽 = Math.max(...rows.map(r => r.length));
  const 候选 = [];
  for (let c = 0; c < 宽; c++) {
    if (c === 合计列 || c === 点位列) continue;
    let 对上 = 0, 看过 = 0, 段数对上 = 0;
    for (let r = 头行 + 1; r < rows.length; r++) {
      const 合 = 数值((rows[r] || [])[合计列]);
      if (合 === null) continue;
      const 段 = 数字们((rows[r] || [])[c]);
      if (!段.length) continue;
      看过++;
      const 和 = Math.round(段.reduce((a, x) => a + x.数, 0) * 1000) / 1000;
      if (近(和, 合)) 对上++;
      const 点 = 点位们((rows[r] || [])[点位列]);
      if (点.length === 段.length) 段数对上++;
    }
    /* 两头都要对：加起来等于总数（算术），而且段数跟点位数对得上（结构）。
       只对一头不敢认 —— 单点位那种行「15斤 vs 15斤」谁都对得上。 */
    if (看过 >= 2 && 对上 === 看过 && 段数对上 === 看过) 候选.push({ 列: c, 看过, 对上 });
  }
  return 候选.length === 1 ? 候选[0] : null;   /* 只有一列对得上才敢认，两列以上交给人 */
}

