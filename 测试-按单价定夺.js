/* 客户单据上自己写的单价，拿来定夺 —— node 测试-按单价定夺.js

   老板 8/2 原话：「价格是你选不上的，可以反推呀。它的名字跟价格，还有那个斤数，也可以反推」

   道理很直白：名字像不像是机器猜的，客户白纸黑字写的价钱不是猜的。
   两个候选差 6 倍、单据上写着 ¥8，那就是 ¥8 那个，不用问人。

   两条底线（比多认对几条重要）：
     · 只在「本来就要弹窗问人」的时候用它 —— 不抢已经确定的答案
     · 必须只有一条候选对得上价才算数 —— 两条都是 ¥8 就还是问人
     · 单据上的价一条都对不上（价格库过期了）→ 当没写，照旧问人 */
const fs = require("fs"), path = require("path");
global.window = {};
require("./数据-价格库.js");
require("./对照-预置.js");
require("./引擎-解析.js");
require("./引擎-匹配.js");
require("./数据-常用规格.js");
const D = window.GM_DATA, SEED = window.GM_SEED, P = window.GM_PARSE, M = window.GM_MATCH;
const USED = window.GM_USED || {};

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  if (JSON.stringify(got) === JSON.stringify(want)) pass++;
  else { fail++; L("  ✗ " + name + "\n      应该 " + JSON.stringify(want) + "\n      实际 " + JSON.stringify(got)); }
}

const usedN = (cid, sku) => (USED[cid] || {})[sku] || 0;
const IDX = M.buildIndex(D, usedN);
const OV = { maps: {}, gmap: {} };
const C = {
  DATA: D, IDX, OV, usedN,
  seedLookup: (cid, t, u) => P.seedLookup(SEED[cid], t, u),
  learnedSku: (ci, t, u) => P.learnedLookup(OV.maps, D.custs[ci][0], t, u,
    s => IDX.byCust[ci].sku[s] === undefined ? null : D.items[IDX.byCust[ci].sku[s]][3]),
  defaultSide: window.GM_DEFAULT_SIDE
};
const ciOf = id => { let k = -1; D.custs.forEach((c, i) => { if (c[0] === id) k = i; }); return k; };
/* 返回 [对到的叫法, 敢不敢拍板]
   第 5 个参数是数量 —— 「按斤还是按板」那条规矩要拿数量去除板型，
   不给数量它就不动手（见 引擎-匹配.js 的「斤怎么算」）。 */
function 认(sid, text, unit, price, qty) {
  const r = M.matchOne(C, ciOf(sid), text, unit, price, qty);
  return [r.i >= 0 ? D.items[r.i][2] : "认不出", M.commits(r.how), r.how];
}

L("── 解析：行尾的单价要摘出来，别当成数量 ──");
{
  const r = P.parseOrder("阳山豆腐卜\t1斤 ¥8");
  ok("摘到单价", r[0].price, 8);
  ok("数量还是 1（没被 8 顶掉）", r[0].qty, 1);
  ok("单位还是斤", r[0].unit, "斤");
  ok("商品名干净", r[0].text, "阳山豆腐卜");
}
{
  const r = P.parseOrder("水豆腐\t(H1171)14斤+(1090)8斤 ¥1.4");
  ok("带点位的也能摘价", r[0].price, 1.4);
  ok("两段都在", r[0].segs.length, 2);
  ok("总量 22", r[0].qty, 22);
}
{
  const r = P.parseOrder("千张\t5斤");
  ok("没写价就是 null", r[0].price, null);
}
{
  /* 「¥」出现在中间不算 —— 只认行尾，免得把备注里的钱当单价 */
  const r = P.parseOrder("千张(¥3.4那种)\t5斤");
  ok("¥ 在中间不当单价", r[0].price, null);
}

L("");
L("── 好来客 S2939：真实踩过的 6.8 倍 ──");
/* 单据原文：阳山豆腐卜 1.00 斤 单价 8.00
   不给价时默认落到「阳山豆腐（斤）」¥1.2，差 6.8 倍。 */
{
  const 不给价 = 认("S2939", "阳山豆腐卜", "斤", null);
  const 给价 = 认("S2939", "阳山豆腐卜", "斤", 8);
  ok("不给价：认到 ¥8 那条了吗（预置已经配过，应该认得）", 给价[0], "阳山小豆泡");
  ok("给了价，敢直接拍板", 给价[1], true);
  ok("拍板的依据写着是按价定的或预置", ["price", "seed", "learned"].indexOf(给价[2]) >= 0, true);
}

L("");
L("── 只有一条对得上价，才算数 ──");
{
  /* 裕丰 S2947：水豆腐（5斤）¥5.5 和 水豆腐（6斤）¥6.5，板货两条 */
  ok("单据写 ¥6.5 → 挑 6斤 那条", 认("S2947", "水豆腐", "板", 6.5)[0], "水豆腐（6斤）");
  ok("单据写 ¥5.5 → 挑 5斤 那条", 认("S2947", "水豆腐", "板", 5.5)[0], "水豆腐（5斤）");
  ok("两条都敢拍板", [认("S2947", "水豆腐", "板", 6.5)[1], 认("S2947", "水豆腐", "板", 5.5)[1]], [true, true]);
}
{
  /* 价格库里一条都没有 ¥99 → 当没写过，照旧问人 */
  const r = 认("S2947", "水豆腐", "板", 99);
  ok("单据写的价一条都对不上 → 还是问人（不能瞎挑）", r[1], false);
}

L("");
L("── 不许抢已经确定的答案 ──");
{
  /* 「千张」在很多家是精确命中，本来就敢拍板。
     就算单据写了个对不上的价，也不该把它推翻。 */
  const 无价 = 认("S2934", "千张", "斤", null);
  const 怪价 = 认("S2934", "千张", "斤", 999);
  ok("本来就认得的，不给价时敢拍板", 无价[1], true);
  ok("给个离谱的价也不动摇", [怪价[0], 怪价[1]], [无价[0], true]);
}

L("");
L("── 两条候选同价：还是要问人 ──");
{
  /* 找一家「同一个价有两条候选」的，验证不会瞎挑。
     鸿森 S2954：尝元大豆泡 ¥5.5 和 尝元小豆泡 ¥5.5（同价不同品） */
  const r = 认("S2954", "豆泡", "斤", 5.5);
  ok("同价两条 → 不拍板，交给人", r[1], false);
}

L("");
L("── 规格反推：公斤自动折成斤 ──");
/* 老板 8/2：「它的名字跟价格，还有那个斤数，它也可以反推呀」
   客户写 2.5kg，价格库里叫「水豆腐（5斤）」—— 光比 2.5 和 5 永远对不上。 */
ok("裕丰 2.5kg → 5斤 那条", 认("S2947", "水豆腐2.5kg", "板")[0], "水豆腐（5斤）");
ok("裕丰 3kg → 6斤 那条", 认("S2947", "水豆腐3kg", "板")[0], "水豆腐（6斤）");
ok("两条都敢拍板", [认("S2947", "水豆腐2.5kg", "板")[1], 认("S2947", "水豆腐3kg", "板")[1]], [true, true]);
ok("蔬源 3.5kg → 客家豆腐（7斤）", 认("S2930", "客家豆腐3.5kg", "板")[0], "客家豆腐（7斤）");
ok("直接写 7斤 的照旧对", 认("S2930", "客家豆腐7斤", "板")[0], "客家豆腐（7斤）");
ok("天晟 3.5kg → 6-7斤 那条", 认("S2952", "胶板豆腐3.5kg", "板")[0], "胶板豆腐6-7斤");
/* 折出来落在两条中间的，不许硬挑 */
ok("3kg=6斤，卡在 5-6 和 6-7 中间 → 交给人", 认("S2952", "胶板豆腐3kg", "板")[1], false);

L("");
L("── 没写清楚时按哪一头算（老板定的生意规矩）──");
/* 2026-08-02：「烟干没有备注要厚的，统一是薄的，除非备注要厚的。油片也是。」
   这是生意上的默认，不是机器猜 —— 所以直接拍板，不弹窗，否则每张单都要点一遍。 */
ok("华丰「烟干」不写厚薄 → 薄", 认("S4539", "烟干", "斤")[0], "尝元薄烟干");
ok("而且直接拍板，不弹窗", 认("S4539", "烟干", "斤")[1], true);
ok("写了「厚」的照旧给厚", 认("S4539", "厚烟干", "斤")[0], "尝元厚烟干");
ok("写了「薄」的照旧给薄", 认("S4539", "薄烟干", "斤")[0], "尝元薄烟干");
ok("华丰「油片」不写厚薄 → 薄", 认("S4539", "油片", "斤")[0], "薄油片");
ok("康瑞达「油片」也一样", 认("S9555", "油片", "斤")[0], "薄油片");
ok("康瑞达也直接拍板", 认("S9555", "油片", "斤")[1], true);
/* 规矩只管这一对，别的商品不受影响 */
ok("规矩不外溢：千张照旧", 认("S2934", "千张", "斤")[1], true);

L("");
L("── 单位写斤就按斤价，规格里的「7斤/板」不算数 ──");
/* 2026-08-02 老板原话：「客户下的是 7斤/板，但他只是 18 斤，没有对应的单位。
   这种情况，统一就是按单斤的价格去计算。」
   蔬源 S2930：客家豆腐（斤）¥2、客家豆腐（7斤）板 ¥8。
   18 斤按板价算是 ¥144，按斤价是 ¥36 —— 差 4 倍，而且原来是闷声算错的。 */
/* 蔬源板型 7斤/5斤：18 除不尽 → 按斤价 ¥2 */
ok("客家豆腐 订 18斤，7斤5斤都除不尽 → 论斤那条", 认("S2930", "客家豆腐 7斤/板", "斤", null, 18)[0], "客家豆腐（斤）");
/* ⛔ 2026-08-18 老板改口：单位不一样一律弹出来让人挑，系统不许自己折板。
   这里客户写斤、名字里粘着「7斤/板」（规格列并进来的），先配到板货，
   再退到同单位的「客家豆腐（斤）」—— 货是对的，但要人点一下。 */
ok("单位不一样 → 弹出来让人挑（8/18 新规矩）", 认("S2930", "客家豆腐 7斤/板", "斤", null, 18)[1], false);
/* 除得尽的要优先按板 —— 老板：「仓库里有可以整除的，要优先整除」 */
ok("订 14斤：不折板了，落在论斤那条（8/18）", 认("S2930", "客家豆腐 7斤/板", "斤", null, 14)[0], "客家豆腐（斤）");
ok("订 10斤：不折板了，落在论斤那条（8/18）", 认("S2930", "客家豆腐 7斤/板", "斤", null, 10)[0], "客家豆腐（斤）");
ok("同一句话单位写板 → 还是板货", 认("S2930", "客家豆腐 7斤/板", "板")[0], "客家豆腐（7斤）");
ok("华晨豆腐 7斤/板 订 2板 → 7斤那条 ¥8", 认("S2930", "华晨豆腐 7斤/板", "板")[0], "华晨豆腐7斤/板");
ok("水豆腐 7斤/板 订 1板 → 7斤那条 ¥8", 认("S2930", "水豆腐 7斤/板", "板")[0], "水豆腐7斤/板");
ok("水豆腐 7斤/板 订 3斤 → 论斤那条 ¥2", 认("S2930", "水豆腐 7斤/板", "斤", null, 3)[0], "水豆腐（斤）");
/* 公斤也是散称 */
/* 公斤也是散称，但库里这家没有「公斤」那个单位 —— 按 8/18 新规矩交给人挑。 */
ok("单位写公斤：库里没这个单位 → 交给人", 认("S2930", "客家豆腐 7斤/板", "公斤", null, 18)[1], false);
/* 这家没有论斤卖的货 → 不硬掰，维持原样 */
ok("没有论斤的同类货就不动它", 认("S2930", "中胶板豆腐 7斤/板", "板")[0], "中胶板豆腐7斤/板");

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
