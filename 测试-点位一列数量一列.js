function 读(rows) {
  const r = N.认列(rows);
  if (!r || r.要问的) return { 认不出: r && r.要问的 };
  const 备 = N.备好(rows, r, "");
  if (!备) return { 认不出: "备不好" };
  const 合 = T.摊平([{ n: 1, rows: 备.rows }], 备.读法);
  if (!合 || !合.行.length) return { 认不出: "摊不出" };
  const B = S.读结构({ 抬头: 合.抬头, 行: 合.行, 表怎么读的: 合.表怎么读的 });
  return {
    数量们: B.lines.map(l => l.qty),
    配出来: B.lines.map(l => (l.segs || []).map(s => (s.code || "") + ":" + s.qty + (s.unit || ""))),
    没拆开: G.没拆开(合)
  };
}

