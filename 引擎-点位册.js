/* ============================================================
   点位册 —— 一家客户一本，记住这家的送货点都叫什么
   ============================================================

   老板 2026-08-03：
     「点位号，你只用识别出来就可以了，识别出来把它加上去就可以了，
     　也可以做一个点位册。」
   老板 2026-08-04：
     「做那个点位册的时候，顺便也可以让他把对照表再完善一下，再顺便学习一下。」

   治的是什么毛病
   --------------
   全单只有「点位」这一栏没人校验：商品名读错了配不上价格库会报存疑，
   价格读错了金额对不上；点位是纯照搬，读成什么就印什么，错了没人管。
   于是同一个点，每识别一次就换一个写法：

     A031 沁园庭#教师  ↔  A031 沁园@#教师
     B173 嘉家贝#员工  ↔  B173 塞家岛#员工
     A829 铂轩#客餐    ↔  A829 铂骊#客餐
     A862 金铂全       ↔  A862 金铂

   分拣的人照着单去册子上找，找不着。

   办法：跟「学商品叫法」一模一样 —— 你确认一次，它记住，存服务器，换电脑不丢。
     · 号和名都对得上        → 直接过，不打扰你
     · 号对得上、名不一样    → 按册子上的改，标一下（不打扰你）
     · 号在册子里没有        → 摆出来问你；你确定订单 = 入册
     · 同一行里同号出现两次  → 摆出来问（多半是把号看错了）

   每家客户的写法都不一样，所以【册子按客户分，照那家的样子存】：
     江云   A017 总部#员工      有号有名
     祺之盛 E028                只有号
     广垦   工商银行佛山分行/员工餐  只有名
     广泰   总店                 只有名
   有什么存什么，不补、不改。

   ⚠ 点位【不参与算钱】（钱由商品定），所以册子错了顶多分拣看着别扭，
     不会算错钱 —— 风险比商品叫法低得多，可以放心自动归一。
   ============================================================ */
(function(root){
  "use strict";

  function P(){ return root.GM_PARSE; }
  function 半(s){ var p=P(); return p?p.toHalf(String(s==null?"":s)):String(s==null?"":s); }
  function 字(v){ return v===null||v===undefined?"":半(v).trim(); }

  /* 号里的空格是识别抖出来的（B118 读成「B 118」），比对时抹平；
     存进单据的还是客户原来那个写法，不替他改。 */
  function 平号(s){ return 字(s).replace(/\s+/g,"").toUpperCase(); }
  function 平名(s){
    return 字(s).replace(/\s+/g,"")
      .replace(/[（）]/g,function(c){return c==="（"?"(":")";})
      .toLowerCase();
  }

  /* 把「A017 总部#员工」拆成 号 + 名。
     号 = 开头那一段「字母和数字」（中间允许识别抖出来的空格）。
     拆不出号的（广垦「肇庆市第一人民医院/蔬菜类」、广泰「总店」）→ 号为空，整串是名。 */
  function 拆(code){
    var s=字(code);
    if(!s) return {号:"",名:"",原:""};
    /* 开头：可带 1~2 个字母，然后数字，中间可以有空格；后面可以再跟 -01 这种尾巴。
       ⚠ 横杠后面是纯数字/字母的，那是号的一部分（E002-01），不是名字。 */
    var m=s.match(/^([A-Za-z]{0,2}\s*\d{1,6}(?:\s*-\s*[A-Za-z0-9]{1,4})?)\s*[#＃\-—–\/／\s]*(.*)$/);
    if(m&&/\d/.test(m[1])) return {号:m[1].trim(),名:(m[2]||"").trim(),原:s};
    return {号:"",名:s,原:s};
  }
  function 拼(号,名){
    号=字(号); 名=字(名);
    if(号&&名) return 号+" "+名;
    return 号||名;
  }

  /* ---------------------------------------------------------
     册子长这样（存在 OV.spotbook 里，跟学过的对照一起上服务器）
       spotbook[客户ID] = { "平号": {号,名,原,n} , "@平名": {号:"",名,原,n} }
     没有号的按名字当键，前面加个 @ 免得跟号撞上。
     --------------------------------------------------------- */
  function 键(号,名){ return 号?平号(号):("@"+平名(名)); }

  function 本(册,cid){
    if(!册||!cid) return null;
    return 册[cid]||(册[cid]={});
  }

  /* 查一条点位：对得上？名字飘了？还是没见过？ */
  function 查(册,cid,code){
    var d=拆(code);
    var b=(册&&册[cid])||{};
    var k=键(d.号,d.名);
    var 有=b[k];
    if(!有) return {号:d.号,名:d.名,原:d.原,状态:"新的",该写:d.原};
    if(!d.号) return {号:"",名:有.名,原:d.原,状态:"对得上",该写:有.原};
    /* 号对得上，看名字 */
    if(!d.名||平名(d.名)===平名(有.名))
      return {号:有.号,名:有.名,原:d.原,状态:"对得上",该写:有.原};
    return {号:有.号,名:有.名,原:d.原,状态:"名不一样",该写:有.原,读成:d.名};
  }

  /* 学一条：你确认了这张单 = 这些点位是对的 */
  function 学(册,cid,code){
    var d=拆(code);
    if(!d.原) return false;
    /* 太短、纯符号的不收 —— 那多半是解析抖出来的碎片 */
    if(d.原.length<2) return false;
    var b=本(册,cid); if(!b) return false;
    var k=键(d.号,d.名), 有=b[k];
    if(有){
      有.n=(有.n||0)+1;
      /* 名字不一样时：见得多的那个说了算。头一回见的新写法不许顶掉老的。 */
      if(d.名&&平名(d.名)!==平名(有.名)) return false;
      return false;
    }
    b[k]={号:d.号,名:d.名,原:d.原,n:1};
    return true;
  }

  /* 把一张单的点位跟册子顺一遍。
     就地改：名字飘了的按册子上的写；号没见过的挑出来给人看。
     只动名字，不动号 —— 号是识别读出来的，改号等于替客户改送货点。 */
  /* ★ 2026-08-04 老板定死：册子【没有权威性】，它只是复制粘贴的辅助。
       「它作用就是复制粘贴。你如果用它能识别到更多的东西，就用；
         如果用不到、识别不到……就不用。但是一定不能识别错。」
       点位号 → 名字【会变】（「B189 现在是利丰，下一次就不一定是利丰」）。
       所以这里【只看不改】：一个字都不许覆盖这次读到的 code。
       以前这儿写 g.code=r.该写 —— 客户真给点位改了名，就被悄悄改回旧名，
       人还看不见。那是静默认错，正是最不能犯的错（见 zero-silent-errors-rule）。 */
  function 顺一遍(册,cid,lines){
    var 名异=[], 新=[], 重={};
    if(!cid||!lines) return {名不一样:名异,新的:新,重号:[]};
    lines.forEach(function(L){
      var 本行={};
      (L.segs||[]).forEach(function(g){
        var c=字(g.code); if(!c) return;
        var d=拆(c);
        /* 同一行里同一个号出现两次 —— 采购表一个点位一行，
           重号十有八九是把其中一个号看错了。挑出来问，不自作主张。 */
        if(d.号){
          var pk=平号(d.号);
          if(本行[pk]) (重[L.text||""]=重[L.text||""]||[]).push(d.号);
          本行[pk]=1;
        }
        var r=查(册,cid,c);
        if(r.状态==="名不一样"){
          /* 只留个记录，g.code 一动不动 —— 单据上写的才是这次的事实 */
          名异.push({商品:L.text||"",读成:c,册上:r.该写});
        }else if(r.状态==="新的"){
          新.push({商品:L.text||"",点位:c,号:r.号,名:r.名});
        }
      });
    });
    var 重号=Object.keys(重).map(function(k){ return {商品:k,号:重[k]}; });
    return {名不一样:名异,新的:新,重号:重号};
  }

  /* 确定订单时，把这张单上的点位全部入册（跟学商品叫法同一个时机） */
  function 学一单(册,cid,lines){
    var n=0;
    (lines||[]).forEach(function(L){
      (L.segs||[]).forEach(function(g){ if(学(册,cid,g.code)) n++; });
    });
    return n;
  }

  function 有几个(册,cid){ return Object.keys((册&&册[cid])||{}).length; }
  function 全部(册,cid){
    var b=(册&&册[cid])||{};
    return Object.keys(b).map(function(k){ return b[k]; })
      .sort(function(a,c){ return (a.号||a.名).localeCompare(c.号||c.名); });
  }

  root.GM_SPOTBOOK={ 拆:拆, 拼:拼, 查:查, 学:学, 学一单:学一单,
                     顺一遍:顺一遍, 有几个:有几个, 全部:全部,
                     平号:平号, 平名:平名, 键:键 };
})(typeof window!=="undefined"?window:globalThis);
