const path = require("path");
global.window = {};
["数据-价格库.js", "对照-预置.js", "数据-常用规格.js", "数据-换算.js", "数据-客户量纲.js",
  "引擎-解析.js", "引擎-读结构.js", "引擎-认表.js", "引擎-断句规矩.js", "引擎-碎片类.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const T = global.window.GM_TABLE, S = global.window.GM_STRUCT, Q = global.window.GM_客户点位写法;

let 过 = 0, 挂 = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(题, 真, 补) {
  if (真) { 过++; L("  ✅ " + 题); }
  else { 挂++; L("  ❌ " + 题 + (补 ? "　—— " + 补 : "")); }
}

/* 照老板 9/1 那张真单造的：明细列【被认成了点位名列】 */
function 跑(明细, 总数, cid) {
  const rows = [["序号", "商品名", "总数", "明细"], ["1", "千张豆皮", 总数, 明细]];
  const 读法 = {
    用第几张表: 1, 版式: "明细", 表头在第几行: 1,
    商品列: 2, 数量列: 3, 点位名列: 4,      /* ← 就是这儿认错了 */
    客户号: (cid === undefined ? "S2944" : cid)
  };
  const 合 = T.摊平([{ n: 1, rows: rows }], 读法);
  const out = S.读结构({ 抬头: 合.抬头, 行: 合.行, 表怎么读的: 合.表怎么读的 });
  const L0 = (out.lines || [])[0] || {};
  return (L0.segs || []);
}

/* ══════ 一、★ 一格里挤着好几段（老板那张千张豆皮）══════ */
L("\n【一、★ 一格挤 3 段，被认成了点位名】");
{
  const segs = 跑("佛山市瀚华高级中学C38 6斤 佛山市瀚华高级中学C38 34斤 " +
    "佛山市高明区荷城街道三洲机关幼儿园(老师菜类)A54-3 10斤", "50斤");
  ok("★ 该拆成 3 段（老板：「没有把每一列都单独列出来」）",
    segs.length === 3, "只有 " + segs.length + " 段");
  ok("★ 每段的数量各自对上（6／34／10）",
    JSON.stringify(segs.map(g => g.qty)) === "[6,34,10]",
    JSON.stringify(segs.map(g => g.qty)));
  const 收 = segs.map(g => Q.收窄点位("S2944", g.code || ""));
  ok("★ 点位收窄成编号（老板：「文字也进去了」）",
    JSON.stringify(收) === '["C38","C38","A54-3"]', JSON.stringify(收));
}

/* ══════ 二、一格里就一段，也一样（他那张小豆泡）══════ */
