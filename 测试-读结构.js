var S = global.window.GM_STRUCT, P = global.window.GM_PARSE;

var pass = 0, fail = 0;
function ok(name, cond, why) {
  if (cond) { pass++; console.log("  ✅ " + name); }
  else { fail++; console.log("  ❌ " + name + (why ? "　—— " + why : "")); }
}
function 跑(j) { return S.读结构(j); }

