/* 数量永远不是点位 —— node 测试-数量不许当点位.js

   老板 2026-08-18 撞到：朱鲜生那张表，系统把一整列【纯数量】拿去问
   「这一排是什么？」，他点了「点位」。于是一口气记住 12 条，全是数量：
       「4斤 1斤 3斤」→ 点位 　「35斤 2斤 50斤」→ 点位 　「1板」→ 点位
   还跟着同步上了服务器 —— 换台电脑照样错。

   老板原话：「你如果不确定这个是不是就可以问，但是你不能去这样子乱抓。」
   这一条根本不该问：数字＋单位就是数量。问了等于把「我不知道」推给人，
   还诱导他答错。

   所以钉三条：
     ① 认得出：纯数量的一律认出来，真点位一个都不许误伤
     ② 不记：就算人点了「点位」，纯数量也不许写进本子
     ③ 自愈：8/18 之前误记的那 12 条，开页面自动作废，不用谁去手动删 */
const fs = require("fs"), path = require("path");
const H = fs.readFileSync(path.join(__dirname, "配送开单台.html"), "utf8");

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a === b) pass++; else { fail++; L("  ✗ " + name + "\n      应该 " + b + "\n      实际 " + a); }
}
function grab(n) {
  const i = H.indexOf("function " + n + "(");
  if (i < 0) throw new Error("页面里找不到 " + n + "（改名了？）");
  let d = 0;
  for (let k = H.indexOf("{", i); k < H.length; k++) {
    if (H[k] === "{") d++; else if (H[k] === "}") { d--; if (!d) return H.slice(i, k + 1); }
  }
}
const m = H.match(/var 像数量=(\/[\s\S]*?\/i);/);
if (!m) throw new Error("页面里找不到 像数量（改名了？）");
const 像数量 = eval(m[1]);
const 纯数量 = new Function("像数量", grab("纯数量") + ";return 纯数量;")(像数量);

L("═══ ① 认得出纯数量（这 12 条就是 8/18 真被误记的）═══");
[
  "4斤 1斤 3斤", "3斤 2斤", "1板 1板 2板 1板 1板 18板", "1板", "15斤", "10盒",
  "5斤 10斤 4斤", "1斤 2斤 3斤", "17斤", "8斤 4斤", "35斤 2斤 50斤", "1箱"
].forEach(s => ok("是数量：" + s, 像数量.test(s), true));
["2.5斤", "1板+2板", "10盒、5盒", "18串"].forEach(s => ok("是数量：" + s, 像数量.test(s), true));

L("");
L("═══ ② 真点位一个都不许误伤 ═══");
[
  "11-10", "222", "263#长者", "308#老字号自选餐",
  "广州市老人院上水院区（老人碎菜）5-9", "西樵派出所（西樵本部）2-5",
  "A002 鹤峰#幼儿餐", "妇幼保健院天河院区4-3", "佛山支队高明中队11-10",
  "佛山市顺德区机关服务中心-市监饭堂午餐27-3", "肇庆端州武装部17-1"
].forEach(s => ok("不是数量：" + s, 像数量.test(s), false));
/* 规格、餐次也不许被当数量顶掉（它们有自己那几道网） */
["午餐", "小", "8斤/板", "大板"].forEach(s => ok("不是纯数量：" + s, 像数量.test(s), false));

L("");
L("═══ ③ 整排判定 ═══");
ok("一整排数量 → 是", 纯数量(["4斤 1斤 3斤", "1板", "10盒"]), true);
ok("一整排点位 → 不是", 纯数量(["11-10", "263#长者", "2-5"]), false);
ok("混着但数量过半 → 是", 纯数量(["1板", "2斤", "3盒", "11-10"]), true);
ok("空的 → 不是", 纯数量([]), false);

L("");
L("═══ ④ 就算人点了「点位」，也不许记进本子 ═══");
(function () {
  const OV = { 排名单: {} };
  const 排记 = new Function("OV", "ovTouch", "ovSave", "画排名单", "像数量", "Date",
    grab("排记") + ";return 排记;")(OV, () => { }, () => { }, () => { }, 像数量, Date);
  排记(["4斤 1斤 3斤", "35斤 2斤 50斤"], "点位");
  ok("纯数量点了「点位」→ 一条都没记", Object.keys(OV.排名单).length, 0);
  排记(["263#长者", "308#老字号自选餐"], "点位");
  ok("真点位照记不误", Object.keys(OV.排名单).length, 2);
  排记(["4斤 1斤 3斤"], "数量");
  ok("答「数量」的照记（只挡「点位」这一个答案）", OV.排名单["4斤 1斤 3斤"].是, "数量");
})();

L("");
L("═══ ⑤ 已经误记的，问都不问，直接作废 ═══");
(function () {
  /* 这排是什么 里那句「纯数量 → 是数量」必须排在「听人答过的」前面，
     否则本子里那 12 条错答案照样生效。 */
  const src = grab("这排是什么");
  const 排查 = n => (({ "4斤 1斤 3斤": "点位", "35斤 2斤 50斤": "点位" })[n] || null);
  const 这排是什么 = new Function("纯数量", "排查", "像日期", "像规格", "像餐次",
    src + ";return 这排是什么;")(纯数量, 排查, /(?!)/, /(?!)/, /(?!)/);
  const r = 这排是什么(["4斤 1斤 3斤", "35斤 2斤 50斤"]);
  ok("★ 本子里记着「点位」，也不许再当点位", r.是, "数量");
  ok("★ 而且不再弹窗问", !!r.要问, false);
})();

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
