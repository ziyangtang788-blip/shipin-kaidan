/* ---------- ② 页面：那几根线还在不在 ---------- */
/* 这一段是专门防「写了但没接上」的。8/10 那次就是代码全写好了、
   一根线没接，测试全绿，人在页面上一点反应都看不到。 */
const H = fs.readFileSync(path.join(家, "配送开单台.html"), "utf8");
function 数几处(k) { return H.split(k).length - 1; }

该("照读法摊() 里把客户号递下去了", /读法\.客户号\s*=/.test(H));
该("客户定了重读() 定义了，而且【真的有人调用】（1 处定义 + 至少 2 处调用）",
  数几处("客户定了重读") >= 3);
