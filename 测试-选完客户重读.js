该("学不成时窗留着不放行（先把这个弄对，才有下一步）",
  /配不上，没存[\s\S]{0,600}?return;\s*\/\*\s*窗留着/.test(H));
/* 读不懂的格子数量是「?」→ 走「没看清」那条 → 确定订单本来就拦得住。
   这一条是防以后有人把那道闸拆了。 */
/* ⚠ 2026-08-16 改：原来这条盯的是弹窗那句话（「先填一下」）——
   文案一改考试就红，可闸门根本没动。改成盯【闸门本身】：
   确定订单 里必须调 数量还空着() 并且 return。话怎么说随便改。 */
该("「确定订单」拦得住没看清的（读不懂的格子就是靠这道闸挡住的）",
  /function 确定订单\(\)\{[\s\S]{0,900}?if\(数量还空着\(\)\)\s*return;/.test(H));
该("那道闸真的在数「没看清」的格子", /function 数量还空着\(\)\{[\s\S]{0,400}?g\.没看清/.test(H));

/* 传图那一刻不许弹：问人的动作只能在 客户定了重读 里、而且在「还剩读不懂」之后。
   ⚠ 2026-08-24 改：原来盯的是 /剩>0\)\s*问怎么切/ —— 守写法不守意图。
     那天把入口换成新的第 3 步（学一次分法），老弹窗退到它后面当退路，
     闸门一点没动，这条却红了。这是第四次栽在「守写法」上，改成守意图：
       ① 问人的动作必须出现在 客户定了重读 里
       ② 而且必须在 if(剩>0) 那一句之后
       ③ 这个函数之外，除了定义，不许再有第二个地方调它 */
{
  const i定 = H.indexOf("function 客户定了重读");
  const i尾 = H.indexOf("\n  function 重摊一遍", i定 + 10);
  /* ⚠ 注释里也会写到函数名（「老弹窗 问怎么切() 留着当退路」），
     不剥掉注释就会把说明文字当成调用，位置全算错。 */
  const 剥 = s => s.replace(/\/\*[\s\S]*?\*\//g, "");
  const 段 = 剥(H.slice(i定, i尾 < 0 ? i定 + 3000 : i尾));
  const i剩 = 段.indexOf("if(剩>0)");
  const 问人 = ["问怎么切", "学一次分法"].filter(x => 段.indexOf(x) >= 0);
  该("问人只在「选完客户重读之后还剩读不懂」时才问（传图那一刻一个窗都不弹）",
    i剩 >= 0 && 问人.length > 0 && 问人.every(x => 段.indexOf(x) > i剩));
  /* 别的地方不许再弹同一个窗 —— 弹两处就等于回到「到处是窗」那个老毛病 */
  const 外 = 剥(H.slice(0, i定) + H.slice(i尾 < 0 ? H.length : i尾));
  该("问怎么切 只有定义，没有第二个调用点",
    (外.match(/问怎么切\(/g) || []).length <= 1);
}

