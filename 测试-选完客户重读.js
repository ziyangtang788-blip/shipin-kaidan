/* ★ 老板 8/11 亲口提的两条：点完窗要消失、不确定不许往下走 */
该("弹窗里有「接上一块」这一项（没有它，公司名+点位号那种永远学不成）",
  /'点位','接上','数量','不要'/.test(H));
该("点「存，就这么切」存成了以后，窗会收掉", /\$\("ocr-msg"\)\.innerHTML="";\s*\/\*[^*]*存成了/.test(H));
该("点「这几格先不管」也收窗（留个不动的窗，人只会以为页面卡死）",
  /qie-no"\)\.onclick=function\(\)\{\s*\$\("ocr-msg"\)\.innerHTML="";/.test(H));
