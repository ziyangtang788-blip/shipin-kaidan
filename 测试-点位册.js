/* 点位册回归测试 —— node 测试-点位册.js

   老板 2026-08-03：「点位号你只用识别出来就可以了…也可以做一个点位册。」
   老板 2026-08-04：「做那个点位册的时候，顺便也可以让他把对照表再完善一下，
   　　　　　　　　　再顺便学习一下。」

   治的毛病：全单只有「点位」这一栏没人校验，同一个点每识别一次换一个写法 ——
     A031 沁园庭#教师 ↔ 沁园@#教师、B173 嘉家贝 ↔ 塞家岛、A829 铂轩 ↔ 铂骊。
   分拣的人照着单去册子上找，找不着。 */
global.window = {};
require("./引擎-解析.js");
require("./引擎-点位册.js");
const B = global.window.GM_SPOTBOOK;

let pass = 0, fail = 0;
function ok(name, cond, why) {
  if (cond) { pass++; console.log("  ✅ " + name); }
  else { fail++; console.log("  ❌ " + name + (why ? "　—— " + why : "")); }
}

/* ══════ 一、拆号和名 —— 每家写法都不一样 ══════ */
console.log("\n── 拆号和名 ──");
{
  const t = (s, 号, 名) => {
    const d = B.拆(s);
    ok(JSON.stringify(s) + " → 号[" + 号 + "] 名[" + 名 + "]",
      d.号 === 号 && d.名 === 名, "实得 号[" + d.号 + "] 名[" + d.名 + "]");
  };
  t("A017 总部#员工", "A017", "总部#员工");        /* 江云：有号有名 */
  t("E002-01", "E002-01", "");                     /* 祺之盛：只有号，-01 是号的一部分 */
  t("020#西餐厅", "020", "西餐厅");                 /* 雅食乐 */
  t("B 118 幸悦荟", "B 118", "幸悦荟");             /* 识别抖出来的空格，原样留着 */
  t("A865宝德#员工", "A865", "宝德#员工");
  t("肇庆市第一人民医院/蔬菜类", "", "肇庆市第一人民医院/蔬菜类");  /* 广垦：只有名 */
  t("总店", "", "总店");                            /* 广泰：只有名 */
  ok("空的不炸", B.拆("").号 === "" && B.拆(null).名 === "");
}

/* ══════ 二、学一次就记住，飘了自动改回来 ══════ */
console.log("\n── 学 + 自动归一 ──");
{
  const 册 = {};
  const 单1 = [{ text: "水豆腐", segs: [
    { code: "A031 沁园庭#教师" }, { code: "B173 嘉家贝#员工" }, { code: "总店" }] }];
  ok("确定一单学到 3 条", B.学一单(册, "S1", 单1) === 3);
  ok("再确定一遍不重复记", B.学一单(册, "S1", 单1) === 0);
  ok("册子里就是 3 个", B.有几个(册, "S1") === 3);

  const 单2 = [{ text: "水豆腐", segs: [
    { code: "A031 沁园@#教师" },     /* 「庭」读成了 @ */
    { code: "B173 塞家岛#员工" },    /* 「嘉家贝」读成「塞家岛」 */
    { code: "A999 新点" },           /* 册子里没有 */
    { code: "总店" }] }];
  const r = B.顺一遍(册, "S1", 单2);
  /* ★ 2026-08-04 老板把这条掉了个头：
       「它作用就是复制粘贴……但是一定不能识别错。」
       点位号→名字会变（「B189 现在是利丰，下一次就不一定是利丰」），
       所以册子【没有权威性】：只许记录不一样，绝不许覆盖这次读到的写法。
       以前这里钉的是「都改回来了」「真的换成册子上的写法」—— 那是静默认错，已作废。 */
  ok("名字不一样的挑出来记着（2 处）", r.名不一样.length === 2, JSON.stringify(r.名不一样));
  ok("★ 单据上的写法一个字都没被改",
    单2[0].segs[0].code === "A031 沁园@#教师" && 单2[0].segs[1].code === "B173 塞家岛#员工",
    单2[0].segs.map(g => g.code).join(" | "));
  ok("★ 没有 改了 这个字段了（拆干净，不留半截）", r.改了 === undefined);
  ok("册上是什么也记着，方便人对照", r.名不一样[0].册上 === "A031 沁园庭#教师", JSON.stringify(r.名不一样[0]));
  ok("没见过的还是挑出来（页面不弹，但数据要有）",
    r.新的.length === 1 && r.新的[0].点位 === "A999 新点");
  ok("对得上的不打扰", 单2[0].segs[3].code === "总店");
  ok("号不许改（改号 = 替客户改送货点）", 单2[0].segs[0].code.indexOf("A031") === 0);
}

/* ══════ 三、同一行里同号出现两次 —— 拎出来问 ══════
   江云 8/3：识别读出 (A002 鹤峰)3板 + (A002 鹤峰)2板，
   第二个其实是 A056。采购表一个点位一行，重号十有八九是号读错了。 */
console.log("\n── 重号 ──");
{
  const 册 = {};
  const 单 = [{ text: "豆腐串", segs: [
    { code: "A002 鹤峰#幼儿餐" }, { code: "A002 鹤峰#幼儿餐" }, { code: "B185 博艺" }] }];
  const r = B.顺一遍(册, "S1", 单);
  ok("同号出现两次 → 报", r.重号.length === 1 && r.重号[0].商品 === "豆腐串", JSON.stringify(r.重号));
  ok("但不合并、不删（一段一行是老板定的）", 单[0].segs.length === 3);

  const 单2 = [{ text: "豆腐串", segs: [{ code: "A002 甲" }, { code: "A056 乙" }] }];
  ok("不同号不报", B.顺一遍({}, "S1", 单2).重号.length === 0);
  /* 不同【行】用同一个号是正常的（一个点位订好几个商品） */
  const 单3 = [{ text: "千张", segs: [{ code: "A002 甲" }] },
               { text: "香干", segs: [{ code: "A002 甲" }] }];
  ok("不同商品用同一个号不算重号", B.顺一遍({}, "S1", 单3).重号.length === 0);
}

/* ══════ 四、一家一本，不串门 ══════ */
console.log("\n── 按客户分本 ──");
{
  const 册 = {};
  B.学一单(册, "S1", [{ text: "x", segs: [{ code: "A017 总部#员工" }] }]);
  const 单 = [{ text: "x", segs: [{ code: "A017 别家的写法" }] }];
  B.顺一遍(册, "S2", 单);
  ok("别家的册子管不到这家", 单[0].segs[0].code === "A017 别家的写法");
  ok("S2 是空本", B.有几个(册, "S2") === 0);
}

/* ══════ 五、册子里谁说了算（只影响册子自己，不影响单据）══════
   见得多的写法留在册子里 —— 但那只是册子内部的事，
   2026-08-04 起【绝不外溢到单据上】。 */
console.log("\n── 谁说了算 ──");
{
  const 册 = {};
  for (let i = 0; i < 5; i++) B.学一单(册, "S1", [{ text: "x", segs: [{ code: "A031 沁园庭" }] }]);
  B.学一单(册, "S1", [{ text: "x", segs: [{ code: "A031 沁园@" }] }]);
  const 单 = [{ text: "x", segs: [{ code: "A031 沁园@" }] }];
  const r5 = B.顺一遍(册, "S1", 单);
  ok("★ 单据上还是这次读到的写法，没被册子顶掉",
    单[0].segs[0].code === "A031 沁园@", 单[0].segs[0].code);
  ok("册子里记的是见得多的那个（只在册子里）",
    r5.名不一样.length === 1 && r5.名不一样[0].册上 === "A031 沁园庭",
    JSON.stringify(r5.名不一样));
  ok("册子里还是 1 条（同号不另起一条）", B.有几个(册, "S1") === 1);
}

/* ══════ 六、太碎的不收 ══════ */
console.log("\n── 不收什么 ──");
{
  const 册 = {};
  ok("空的不收", !B.学(册, "S1", ""));
  ok("一个字的不收", !B.学(册, "S1", "A"));
  ok("收完还是空的", B.有几个(册, "S1") === 0);
}

/* ══════ 七、册子看得见 ══════ */
console.log("\n── 摆出来看 ──");
{
  const 册 = {};
  B.学一单(册, "S1", [{ text: "x", segs: [{ code: "B173 嘉家贝" }, { code: "A017 总部" }] }]);
  const 全 = B.全部(册, "S1");
  ok("两条都在", 全.length === 2);
  ok("按号排好序", 全[0].号 === "A017", JSON.stringify(全.map(z => z.号)));
  ok("原文留着（单据上照搬客户自己的写法）", 全[0].原 === "A017 总部");
}

console.log("\n══════════════════════════");
console.log(fail === 0 ? ("全部通过：" + pass + " 项") : ("通过 " + pass + " / 失败 " + fail));
process.exit(fail === 0 ? 0 : 1);
