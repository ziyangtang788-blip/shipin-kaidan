/* 试-文字切成表格.js —— 原型，没并进开单台，开单台一个字没动
   ============================================================
   老板 2026-08-19 拍板：「把所有数据都整理成一种格式，再交给 AI 处理」。

   查下来的实情（别照旧笔记，代码为准）：
     · Excel / Word / CSV / 老式表格  → 早就统一了，都变成一张「行×列」的格子
     · 图片 / PDF                     → 老板 8/19 定：不翻，AI 直接看原图
     · 粘进框里的文字                  → ★ 只有这一样没有「列」，靠 parseOrder 一个字一个字猜

   所以「统一格式」真正剩下的活，就是这一件：
     粘贴的文字，只要它本来就有列，就切成格子，跟 Excel 走同一条路。

   ⚠ 分两种，必须分清楚，这是整件事的要害：
     A 从 Excel / 网页 / 表格里复制来的  → 带 Tab 或对齐空格，【本来就有列】
       现在这种也在走「猜」—— 明明有列不用，白猜一场，这是纯浪费
     B 微信里手打的                      → 【本来就没有列】
       切不出来。硬切就是猜，而猜这件事 parseOrder 已经磨了两个月，不许重写

   所以这份东西只干一件事：把 A 挑出来，交给格子路。B 原样退回 parseOrder。
   ⛔ 不许改 parseOrder 一个字（记忆：别重写真单磨出来的东西，8/12 输过一次）。
   ============================================================ */
(function (root) {
  "use strict";

  /* 全角空格、不换行空格都算空格 —— 微信和 Excel 复制出来什么都有 */
  function 净(s) { return String(s == null ? "" : s).replace(/[ 　]/g, " ").replace(/\s+$/, ""); }

  /* ---------- 一行切成几格 ----------
     ★★ 只认 Tab，空格一概不认。这条是 2026-08-19 拿陷阱样本撞出来的，别放宽。

     一开始写的是「没 Tab 就按 2 个以上空格切」，结果 4 条陷阱全中，最凶的是这条：

         水豆腐 1.5斤  要3块

     按空格切，「要3块」就成了独立一列，摆进表里极可能被当成数量 —— 可它是
     【切成三块】的加工要求（祺之盛真单，规矩总表里记着）。1.5 斤发成 3 斤，多一倍。
     顺带还把「老板今天下午的货   麻烦早点送」这种闲聊也摆成了两列的表。

     Tab 敢认、空格不敢认，就一个理由：
       【微信里手打不出 Tab】—— 有 Tab 必是从表格复制的，没有第二种来路；
       空格谁都打得出，它证明不了任何事。

     代价是从 PDF / 记事本里复制的「空格对齐表」会漏判，走回老路去猜。
     认了 —— 漏判只是跟现在一样，误判是凭空多出来的新错。 */
  function 切一行(行) {
    var s = 净(行);
    if (s.indexOf("\t") >= 0) return s.split("\t").map(function (x) { return x.trim(); });
    return [s.trim()];
  }

  /* ---------- 有没有列 ----------
     判准三条，都要过：
       ① 至少 2 行 —— ★ 除非带 Tab，见下
       ② 主流列数 ≥ 2（只有 1 列 = 没有列）
       ③ 合得上主流列数的行 ≥ 6 成（差太多说明是一段话，不是表）

     ★ Tab 是免检金牌，1 行也算（2026-08-19 拿 35 张真表量出来的）：
       只订一样东西的单，倒出来就只有 1 行，35 张里有 5 张是这样
       （华晟隆「小豆腐 (5点左右送货)2板」、天晟「胶板豆腐 5-6斤 1板」…）。
       按「至少 2 行」判会把这 5 张全丢回去猜。
       敢为 Tab 破例、不敢为空格破例，理由只有一个：
       【微信里手打不出 Tab】—— 有 Tab 就一定是从表格复制的，没有第二种来路。
       空格不行，随手打一行「豆腐串    10+60+40+5 串」也有一堆空格。

     ⚠ 门槛整体拍得保守。判错两个方向的代价不一样：
       该走格子的走了猜 —— 跟现在一模一样，不会更差
       不该走格子的走了格子 —— 把一段话硬摆成表，那是【凭空多出来的新错】
     所以宁可漏判，不许误判。 */
  function 看有没有列(文本) {
    var 行们 = String(文本 || "").split(/\r?\n/).filter(function (l) { return 净(l).trim(); });
    if (!行们.length) return { 有: false, 因: "空的" };
    var 有Tab = 行们.some(function (l) { return l.indexOf("\t") >= 0; });
    if (行们.length < 2 && !有Tab) return { 有: false, 因: "只有 1 行、又没有 Tab，看不出列" };

    var 格们 = 行们.map(切一行);
    var 计 = {};
    格们.forEach(function (c) { var n = c.length; 计[n] = (计[n] || 0) + 1; });

    /* 主流列数 = 出现最多的那个列数；并列时取大的（列多的那种信息更全） */
    var 主 = 0, 主次 = 0;
    Object.keys(计).forEach(function (k) {
      var n = +k;
      if (计[k] > 主次 || (计[k] === 主次 && n > 主)) { 主 = n; 主次 = 计[k]; }
    });
    if (主 < 2) return { 有: false, 因: "切不出第二列，整段没有列结构", 主列数: 主 };

    var 占 = 主次 / 行们.length;
    if (占 < 0.6) return { 有: false, 因: "列数忽多忽少（" + Math.round(占 * 100) + "% 才对得上），不像表", 主列数: 主, 齐整度: 占 };

    return { 有: true, 主列数: 主, 齐整度: 占, 行数: 行们.length, 行们: 行们, 格们: 格们 };
  }

  /* ---------- 切成格子 ----------
     出来的形状跟 引擎-读文件.js 的 readXlsxGrid 一模一样：[{n:1, rows:[[..],[..]]}]
     一样才能原样喂进 引擎-认表.js 的 骨架 / 摊平 —— 那套是 Excel 磨出来的，
     不动它一个字，只是让它多吃一种输入。

     ⚠ 短的行用空串补齐，不许留洞：摊平是按列号取值的，
       行长参差不齐会让后面的列整体前移，读串位（8/12 江云那类事故的形状）。 */
  function 切成格子(文本) {
    var r = 看有没有列(文本);
    if (!r.有) return null;
    var 宽 = 0;
    r.格们.forEach(function (c) { if (c.length > 宽) 宽 = c.length; });
    var rows = r.格们.map(function (c) {
      var out = c.slice();
      while (out.length < 宽) out.push("");
      return out;
    });
    return [{ n: 1, rows: rows }];
  }

  /* ---------- 对外：这段文字该走哪条路 ----------
     只回答「走哪条」，不替谁做决定，也不碰 parseOrder。
     调用方拿到 走:"格子" 就照 Excel 那套跑，拿到 走:"文字" 就原样调 parseOrder。 */
  function 该走哪条(文本) {
    var r = 看有没有列(文本);
    if (!r.有) return { 走: "文字", 因: r.因 };
    return { 走: "格子", 因: "认出 " + r.主列数 + " 列 × " + r.行数 + " 行", 格子: 切成格子(文本), 齐整度: r.齐整度 };
  }

  root.GM_文字切表 = { 切一行: 切一行, 看有没有列: 看有没有列, 切成格子: 切成格子, 该走哪条: 该走哪条 };
})(typeof window !== "undefined" ? window : globalThis);
