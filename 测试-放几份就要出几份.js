/* 放几份就要出几份 —— node 测试-放几份就要出几份.js

   老板 2026-09-02 原话：
     「我要的不是这两个单没问题，我要的全部没问题。」

   撞出来的那张：客户微信发来广显的采购计划，一张单两页，两张图一起拖进去，
   第 2 页 13 行货【一格都没进来】，屏幕上照旧一片绿、金额也算得出来。
   根子是「新单自己认列」那条新路只摊了 份[0]。

   ⛔ 光修那一条不算数：出单的路有四条（按长相抓／照记住的读法／自己认／问 AI），
      将来还会加，每条各数各的份数，早晚再漏一条。
      所以这份测试守的是【总闸】那件事本身：
        拖进来几份，就得有几份出了货；少一份就拦下来说话，绝不闷着收单。 */
const fs = require("fs"), path = require("path");
const D = __dirname;
global.window = {};
["数据-价格库.js", "引擎-解析.js", "引擎-读结构.js", "引擎-认表.js",
  "引擎-OCR.js", "引擎-碎片类.js", "引擎-认列.js", "引擎-断句规矩.js"]
  .forEach(f => { try { require(path.resolve(D, f)); } catch (e) { } });
const T = global.window.GM_TABLE, O = global.window.GM_OCR, GZ = global.window.GM_整表碎片;
const H = fs.readFileSync(path.resolve(D, "配送开单台.html"), "utf8");

let 过 = 0, 挂 = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(题, 真, 补) {
  if (真) { 过++; L("  ✅ " + 题); }
  else { 挂++; L("  ❌ " + 题 + (补 ? "　—— " + 补 : "")); }
}

/* ══════ 一、总闸在不在，只有一份 ══════ */
L("\n【一、★★ 份数总闸】");
ok("有这道闸（份数够）", /function 份数够\(/.test(H));
ok("⛔ 只写了一份，没抄第二套（抄两份就会「这条路好了那条还是坏的」）",
  (H.match(/function 份数够\(/g) || []).length === 1);
ok("★ 收下格子表 一进门就过闸（所有格子路的总出口）",
  /function 收下格子表\([^)]*\)\s*\{[\s\S]{0,120}?if\(!份数够\(J\)\) return;/.test(H));
ok("★ 收尾 也过闸，而且排在最前面（拦住了就别再弹「这排是什么」「读法对不对」）",
  /function 收尾\([^)]*\)\s*\{[\s\S]{0,220}?if\(!份数够\(合\)\) return;/.test(H));
ok("★ 拦下来要说明白（说了放几份、出几份、差几份）",
  /份数够[\s\S]{0,900}?识别败了\([\s\S]{0,200}?放进来[\s\S]{0,200}?只读出了/.test(H));
ok("★ 给人留了出路（一份一份放 / 把不是订单的那张点掉）",
  /份数够[\s\S]{0,1200}?缩略图那排点掉/.test(H));
ok("⛔ 单份、以及没记账的路一律放行（这道闸只管「明明拖了好几份」）",
  /if\(!\(共>1\)\) return true;/.test(H) && /if\(!\(出>=0\)\) return true;/.test(H));

/* ══════ 二、四条路都得记份数账，不然闸量不到 ══════ */
L("\n【二、★ 每条出单的路都要记「放几份、出货几份」】");
ok("照读法摊（本子那条 + 问完 AI 那条）记了账",
  /合\._共几份=\(份\|\|\[\]\)\.length;/.test(H) && /合\._出货几份=成;/.test(H));
ok("★ 照读法摊：摊出 0 行的份不许算数（算了就等于没这道闸）",
  /if\(!J\|\|!\(J\.行\|\|\[\]\)\.length\) return;/.test(H));
ok("按长相直接抓（近道）记了账，而且按【份】数不是按表数",
  /_共几份:\(份\|\|\[\]\)\.length, _出货几份:出货的份/.test(H) &&
  /if\(这份出货了\) 出货的份\+\+;/.test(H));
ok("新单自己认（B）记了账", /合自\._共几份=\(份\|\|\[\]\)\.length; 合自\._出货几份=备们\.length;/.test(H));
ok("⛔ 拼一坨切的那条（明细一格切段）只走单份 —— 它认不出哪行来自哪份，闸量不了",
  /OCR走通&&OCR文本\.length===1&&PDFS\.length===0/.test(H));

/* ══════ 三、拿广显那张真的两页单跑一遍 ══════ */
L("\n【三、★★ 广显 9/2 那张两页单（真图 → 真 OCR → 真读法）】");
const 存 = f => path.join(D, "调试-真单OCR", "广显0902-" + f + ".ocr.json");
const 两页 = ["8344fa52cf1293bf34e6ca10cf4c3e0c.png", "fdf7a03c91026f275a4b71771c134688.png"];
if (!两页.every(f => fs.existsSync(存(f)))) {
  L("  · 没有那两张的 OCR 存档，这一节跳过（不算挂）");
} else {
  const 份 = 两页.map((f, i) => {
    const R = O.拆响应(JSON.parse(fs.readFileSync(存(f), "utf8")));
    return { name: "第" + (i + 1) + "张", grid: T.markdown转表(O.标不确定(R.文本, R.没把握的)) };
  });

  /* 照页面 出单自认() 那一段：第一份认出来的列，套给后面每一份 */
  function 摊几份(份, 认果) {
    const 备 = (认果 && !认果.要问的) ? GZ.备好(份[0].grid[0].rows, 认果, "") : null;
    if (!备) return null;
    const 合 = T.摊平([{ n: 1, rows: 备.rows }], 备.读法);
    if (!合 || !合.行.length) return null;
    const 备们 = [备];
    const 人定 = { 品名列: 认果.品名列, 数量列: 认果.数量列, 单位列: 认果.单位列, 地址列: 认果.地址列 };
    for (let qi = 1; qi < 份.length; qi++) {
      const rowsN = 份[qi].grid[0].rows;
      let 认N = null;
      try { 认N = GZ.认列(rowsN, 人定); } catch (e) { return null; }
      const 备N = (认N && !认N.要问的) ? GZ.备好(rowsN, 认N, "") : null;
      if (!备N) return null;
      if (备N.读法.表头在第几行 !== 备.读法.表头在第几行
        || 备N.读法.分布列 !== 备.读法.分布列
        || 备N.读法.点位名列 !== 备.读法.点位名列) return null;
      const 合N = T.摊平([{ n: 1, rows: 备N.rows }], 备N.读法);
      if (!合N || !合N.行.length) return null;
      合.行 = 合.行.concat(合N.行 || []);
      备们.push(备N);
    }
    return { 合, 份数: 备们.length };
  }
  const 和 = J => Math.round((J.行 || []).reduce((a, Ln) =>
    a + (Ln.分布 || []).reduce((s, d) => s + (+d.数量 || 0), 0), 0) * 100) / 100;

  /* 单页各自该是多少（第 2 页的 474 跟单子上印的「数量 474.00」一分不差） */
  const 认1 = GZ.认列(份[1].grid[0].rows);
  ok("序号 1-18 那页自己认得出来", !认1.要问的, (认1.要问的 || []).join("；"));

  const A = 摊几份([份[1], 份[0]], 认1);      /* 老板遇到的顺序：那页排在前 */
  ok("★★ 两页都进来了：31 行货", !!A && A.合.行.length === 31,
    A ? "只出了 " + A.合.行.length + " 行" : "整条没走通");
  ok("★★ 合计 886（第 1 页 412 ＋ 第 2 页 474，跟单上印的对得上）",
    !!A && 和(A.合) === 886, A ? "算出来 " + 和(A.合) : "-");
  ok("★ 重摊数据两份都存了（不然选完客户补拆只补第一页）", !!A && A.份数 === 2);

  /* 反过来：那页排在第一张时，自己认不出「哪列是数量」（序号列和数量列都是满的数字）——
     这不是坏，是该弹窗问人。问完点一下，照样两页都出来。 */
  const 认2 = GZ.认列(份[0].grid[0].rows);
  ok("序号 19-31 那页排第一张时会弹窗问「哪列是数量」（不是闷头猜）", !!认2.要问的);
  const B = 摊几份(份, GZ.认列(份[0].grid[0].rows, { 数量列: 7 }));
  ok("★ 人点完之后照样两页都出来（31 行 / 886）",
    !!B && B.合.行.length === 31 && 和(B.合) === 886,
    B ? B.合.行.length + " 行 / " + 和(B.合) : "整条没走通");
}

L("\n════════════════════════");
L(挂 ? "❌ 挂了 " + 挂 + " 项（过 " + 过 + "）" : "✅ 全过 " + 过 + " 项");
process.exit(挂 ? 1 : 0);
