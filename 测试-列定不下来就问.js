/* 列定不下来就问人，别把整张单拦死 —— node 测试-列定不下来就问.js

   老板 2026-08-28 拖一张表，屏幕上只有一句：
     「校验数：表头『汇总合计』在第 4 列，可它说的第一格内容却在第 6 列 —— 对不上」
   整张单就出不来了，货一样都没读出来。他问：「学习功能呢，为什么没出来？」
     —— 因为它停在识别这一步，学习还没轮到；
        而「这一列是什么」那一问，当时只装在【近道】那条路上，这条路没有。
   他的话：「这一列定不下来，就问我『这一列是什么』，我答一次你记住，别拦死。」

   钉三件事：
     ① 校验数（合计列）定不下来【不拦】—— 它不是那四样，只是拿来对个账的
     ② 要命的那几样定不下来 → 给出【两个候选列】，交给页面摆出来问人
     ③ 人点完 → 读法就齐了，往下走 */
global.window = global.window || {};
const fs = require("fs"), path = require("path"), 家 = __dirname;
["数据-价格库.js", "对照-预置.js", "数据-常用规格.js", "数据-换算.js",
  "引擎-解析.js", "新-按内容认单.js"].forEach(f => require(path.join(家, f)));
const N = window.GM_按内容认单;

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, 真的) { if (真的) pass++; else { fail++; L("  ✗ " + name); } }

/* 一张「表头在第 4 列、数据却在第 6 列」的表：第 4 列是空的 */
const rows = [
  ["序号", "商品名", "单位", "汇总合计", "规格", "总数"],
  ["1", "水豆腐", "板", "", "25板5斤装", "10"],
  ["2", "攸县香干", "斤", "", "", "85"]
];

L("═══ ① 校验数定不下来，不许拦 ═══");
{
  const r = N.认(rows, {
    有什么: {
      品名: { 有: true, 表头写的是: "商品名", 第一格是: "水豆腐" },
      数量: { 有: true, 表头写的是: "总数", 第一格是: "10" },
      校验数: { 有: true, 表头写的是: "汇总合计", 第一格是: "10" }
    }, 第一样货叫: "水豆腐"
  });
  ok("★ 整张单照常出得来（不再被一个辅助列拦死）", !r.要问的);
  ok("　　读法齐了：品名列、数量列都在", !!(r.读法 && r.读法.商品列 && r.读法.数量列));
  ok("★ 校验数不进「要挑的」—— 辅助列不该拿去烦人", !(r.要挑的 || []).some(x => x.名字 === "校验数"));
}

L("");
L("═══ ② 要命的那几样定不下来 → 摆出两个候选列 ═══");
{
  const 指认 = {
    有什么: {
      品名: { 有: true, 表头写的是: "商品名", 第一格是: "水豆腐" },
      数量: { 有: true, 表头写的是: "采购量", 第一格是: "10" }   /* 表头第4列、内容第6列 */
    }, 第一样货叫: "水豆腐"
  };
  const rows2 = rows.map(r => r.slice());
  rows2[0][3] = "采购量";
  const r = N.认(rows2, 指认);
  ok("★ 数量定不下来 → 拦（这一样错了就是钱错了）", !!r.要问的);
  const 挑 = (r.要挑的 || []).filter(x => x.名字 === "数量")[0];
  ok("★ 给出了「要挑的」，页面才有东西问人", !!挑);
  ok("　　字段名对得上读法（数量列）", 挑 && 挑.字段 === "数量列");
  ok("★ 两个候选列都在：第 4 列（表头）和第 6 列（内容）",
    挑 && 挑.候选.length === 2 && 挑.候选.indexOf(4) >= 0 && 挑.候选.indexOf(6) >= 0);

  L("");
  L("═══ ③ 人点完，读法就齐了 ═══");
  const r2 = N.认(rows2, 指认, { 数量列: 6 });
  ok("★ 点完不再拦", !r2.要问的);
  ok("★ 用的就是人点的那一列", r2.读法 && r2.读法.数量列 === 6);
  ok("　　说法里写明是人点的（将来排查看得出来）",
    (r2.说法 || []).some(s => /你点的/.test(s)));
  /* 人点的必须【压过】两条打架的线索，不许被覆盖回去 */
  const r3 = N.认(rows2, 指认, { 数量列: 4 });
  ok("★ 人点第 4 列就是第 4 列（人说了算）", r3.读法 && r3.读法.数量列 === 4);
}

L("");
L("═══ ④ 那根线接进页面了没有 ═══");
{
  const H = fs.readFileSync(path.join(家, "配送开单台.html"), "utf8");
  const h = H.replace(/\/\*[\s\S]*?\*\//g, "");
  const 数 = k => h.split(k).length - 1;
  ok("问哪一列：1 处定义 + 至少 1 处调用", 数("问哪一列") >= 2);
  ok("★ 真的把「要挑的」交给它了", /问哪一列\(认\.要挑的/.test(h));
  ok("★ 人答完会拿答案重认一遍", /N\.认\(rows头,答,人定的\)/.test(h));
  ok("★ 重认完接着往下摊（不是答完就没下文了）", /接着摊\(\);/.test(h));
  ok("接着摊 抽成了函数（原来那段直接写死在下面，答完没路回来）",
    /function 接着摊\(\)/.test(h));
  ok("★ 人点「先不管」还是退回原来那句报错，不硬闯", /if\(!人定的\)\{[\s\S]{0,200}识别败了/.test(h));
}

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
