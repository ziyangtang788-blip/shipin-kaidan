/* ══════ 六、★★ 真根子：没单位的「30-2」不许当数量（2026-08-21）══════
   老板拖朱鲜生 8-19 那张图，四行照错不误，前面几轮全没治到点上。
   最后逐格试出来的：

     认一格("广州医科大学附属第一医院 (海印院区) 30-2")
       → 数量 30、点位「海印院区」          ⛔ 就是屏幕上那个 30 斤
     认一格("佛山支队执勤二中队11-8")
       → 一句汉字，没数量                   ✓ 所以前 4 行没事

   差别只有点位号前面那个【空格】：有空格，「30-2」就成了一个独立的数字。

   根子在 extractSegs 的括号那条规则里：「(点位)数量单位」的【单位是可选的】，
   于是 "(海印院区) 30-2" 配成了 code=海印院区、qty=30、unit=空。

   ★ 判据（死的）：一个【没有单位】的数字，后面紧跟着「-数字」——
     那不是数量，那是点位号的前半截。数量不长这样。

   ⚠ 这一条只挡「没单位 + 后面紧跟 -数字」这一种，别的一个都不许碰：
     (A002)3板、(268-本地 干水)1板、(519)12  —— 照旧全认。 */
console.log("\n【六、★★ 没单位的「30-2」不许当数量 —— 8/21 朱鲜生 8-19 的真根子】");
(function () {
  const P = global.window.GM_PARSE;
  const 段 = s => (P.extractSegs(s) || {}).list || [];

  [["广州医科大学附属第一医院 (海印院区) 30-2", "攸县香干那行"],
   ["佛山市南海区财政局 (午餐) 26-2", "中板豆腐那行"],
   ["瀚蓝环境股份有限公司 (午餐) 31-2", "炸豆干那行"]].forEach(([s, 谁]) => {
    const l = 段(s);
    ok("★ " + 谁 + "：不许切出数量", l.length === 0, JSON.stringify(l));
  });

  /* ⛔ 别的一个都不许碰 —— 这条一放宽就会把正常的段吃掉 */
  ok("(海印院区)3斤 照旧是 3 斤",
     JSON.stringify(段("(海印院区)3斤").map(g => [g.qty, g.unit, g.code])) ===
     JSON.stringify([[3, "斤", "海印院区"]]), JSON.stringify(段("(海印院区)3斤")));
  ok("(A002)3板 照旧",
     JSON.stringify(段("(A002)3板").map(g => [g.qty, g.unit])) === JSON.stringify([[3, "板"]]));
  ok("(268-本地 干水)1斤 照旧（横杠是说明，不是点位号）",
     JSON.stringify(段("(268-本地 干水)1斤").map(g => [g.qty, g.unit, g.code])) ===
     JSON.stringify([[1, "斤", "268"]]), JSON.stringify(段("(268-本地 干水)1斤")));
  ok("没单位但后面不是「-数字」的，照旧算数量",
     JSON.stringify(段("(519)12").map(g => [g.qty, g.unit])) === JSON.stringify([[12, ""]]),
     JSON.stringify(段("(519)12")));
  ok("多段照旧：(020#西餐厅)6斤+(089)3斤",
     段("(020#西餐厅)6斤+(089)3斤").length === 2);
  /* 「?」是「看不清」，不是数量 —— 这条老规矩别被新判据带歪 */
  ok("(海印院区)? 照旧标成没看清",
     段("(海印院区)?").length === 1 && 段("(海印院区)?")[0].没看清 === true);

  /* 端到端：整格交给 认一格，不许再冒出数量 */
  const G = global.window.GM_抓取;
  if (G && G.认一格) {
    const r = G.认一格("广州医科大学附属第一医院 (海印院区) 30-2");
    ok("★ 认一格：整格认成一句汉字，不是分布", r.是 !== "分布" && r.是 !== "数量",
       JSON.stringify(r));
  }
})();

/* ══════ 七、★★ 切不出段 ≠ 这一格没用 —— 整格就是点位（2026-08-21）══════
   上一节把「30-2 不许当数量」挡住了，可点位跟着一起没了 ——
   老板一眼看出来：「你是不是偷懒了？后面的点位那些都没有了呢？」

   他框着原图说的（原话）：
     「广州市老人院（上水院区）（老人糊餐）5-5 │ 1板 │ 午餐
       这一整块全部是点位，这个可以不用去断，
       它是不是属于这里的断句的问题？」

   ★ 他说对了。断句器只该在【一格里挤着好几段】时出手：
       (020#西餐厅)6斤 + (089)3斤 + (131#2)1斤     ← 这种才断
     这张表是【一格一个点位、数量在另一列】—— 它一出手就必错。

   所以：分布列那一格切不出段 → 整格当点位（号在末尾、前面全是名），
   数量照旧从数量列拿。两样各归各位，谁也不吃掉谁。 */
console.log("\n【七、★★ 切不出段的那一格 = 点位，不是垃圾（8/21 老板框图指出来的）】");
(function () {
  const T = global.window.GM_TABLE;
  if (!T || !T.摊平) { console.log("  （没有 GM_TABLE，跳过）"); return; }
  /* 朱鲜生 8-19 那张表的真形状：序号│商品名│总数│明细
     明细一格一个点位；那一列 OCR 抄全了，数量那列被 OCR 整列丢了，
     所以数量只能从「总数」这一列来。 */
  const sheets = [{ n: 1, rows: [
    ["序号", "商品名", "总数", "明细"],
    ["1", "中板豆腐 (7斤/板)", "20板", "佛山市南海区昆仑实业有限公司33-1"],
    ["5", "攸县香干", "3斤", "广州医科大学附属第一医院 (海印院区) 30-2"],
    ["6", "中板豆腐", "3板", "佛山市南海区财政局 (午餐) 26-2"],
    ["7", "炸豆干", "8斤", "瀚蓝环境股份有限公司 (午餐) 31-2"],
    ["8", "九龙炸豆腐", "10斤", "瀚蓝环境股份有限公司 (午餐) 31-2"]
  ] }];
  const J = T.摊平(sheets, { 用第几张表: 1, 版式: "明细", 表头在第几行: 1,
                            商品列: 2, 数量列: 3, 分布列: 4 });
  ok("摊出来了", !!J);
  const r = J && S.读结构(J);
  const 平 = [];
  ((r && r.lines) || []).forEach(L => (L.segs || []).forEach(g =>
    平.push({ 名: L.text, 数: g.qty, 位: g.unit, 点位: g.code })));

  ok("5 行都在", 平.length === 5, JSON.stringify(平.map(x => x.名)));
  /* ★ 数量：一个都不许再被点位号顶掉 */
  ok("★ 数量 20/3/3/8/10（不是 33/30/26/31/31）",
     JSON.stringify(平.map(x => x.数)) === JSON.stringify([20, 3, 3, 8, 10]),
     JSON.stringify(平.map(x => x.数)));
  /* ★ 点位：号 + 名都得在，一个都不许丢 */
  ok("★ 攸县香干点位 = 30-2 + 医院全名",
     (平[1] || {}).点位 === "30-2 广州医科大学附属第一医院 (海印院区)", (平[1] || {}).点位);
  ok("★ 中板豆腐点位 = 26-2 + 财政局", /^26-2\s.*财政局/.test((平[2] || {}).点位 || ""), (平[2] || {}).点位);
  ok("★ 炸豆干点位 = 31-2 + 瀚蓝", /^31-2\s.*瀚蓝/.test((平[3] || {}).点位 || ""), (平[3] || {}).点位);
  /* 号跟名连着写的（没空格）也得拆对 */
  ok("★ 「昆仑实业有限公司33-1」拆成 33-1 + 昆仑实业",
     /^33-1\s.*昆仑实业/.test((平[0] || {}).点位 || ""), (平[0] || {}).点位);
  ok("★ 一条校验都不报（各段跟总数全对得上）", r && (r.校验 || []).length === 0,
     JSON.stringify(r && r.校验));
})();

/* ══════ 八、⛔ 一格里好几个点位、却一个数量都没有 —— 不许拼成一个假点位 ══════
   补上一节的坑：上一节让「切不出段的那一格整个当点位」，
   可朱鲜生 8-19 第 1 行那一格里【有六个点位】：
     昆仑实业33-1 │ 老人院(碎菜)5-9 │ 老人院(糊餐)5-5 │ (糖餐)5-4 │ (菜泥)5-6 │ (老人餐)5-3
   右边「12板 2板 1板 1板 1板 3板」那一整列 OCR 一个字都没抄。

   硬拼成一个点位 → 单子上「20板 送 5-3 昆仑实业…老人碎菜…」，
   看着填满了、其实六个点全错 —— 比空着更糟，而且一声不吭。
   （我 2026-08-21 真的这么干过一版，老板当场看出来。）

   ★ 规矩：好几个点位号 + 一个数量都没有 = 数量那一列没抄到。
     摆成「读不懂」让人处理，绝不许编。 */
console.log("\n【八、⛔ 六个点位一个数量都没有 → 摆出来，不许拼成一个假点位】");
