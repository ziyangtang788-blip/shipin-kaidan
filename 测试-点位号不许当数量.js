/* 测试-点位号不许当数量.js —— node 测试-点位号不许当数量.js
   ============================================================
   2026-08-19 朱鲜生（打印时间 20:07）那张单，四行算错钱，合计多开约 ¥443：

     原单                     系统开的
     攸县香干   3斤            30斤     ← 明细「（海印院区）30-2」的 30
     中板豆腐   3板            26板     ← 「（午餐）26-2」的 26
     炸豆干     8斤            31斤     ← 「（午餐）31-2」的 31
     九龙炸豆腐 10斤           31斤     ← 同上

   查下来【本地两条路都没错】：
     · 文字路 parseOrder 六个例子全读对
     · 明细格切段 extractSegs 把「（海印院区）30-2」整个当点位名，没把 30 当数量
     · 8/18 存下来的朱鲜生格子表快照里，AI 也读对了（明确认出「5-9 是点位号」）
   是这一次 AI 填格子表时，把点位号后面那个数字填进了「分布.数」。

   ★ 真正要命的是【一声不吭】：
     表上明明有「总数」列（3斤/3板/8斤/10斤），是现成的对账网。
     可那道网只认「表上总数」这个字段 —— AI 这次把总数填进了「数量」，
     网就拿不到校验码，全程沉默，四行错数直接开进单子。

   所以这份测试钉两件事：
     ① 有分布时，行上的总数不管填在哪个字段（表上总数／总数／数量），都得当校验码
     ② 对不上就必须报出来，绝不许闷声放过
   （不改识别、不替人改数 —— 老板的规矩是「存疑不算错，读错一个数字才是事故」。）
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const S = global.window.GM_STRUCT;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}
const 报了 = r => ((r.校验 || []).filter(x => x && x.类 === "总数"));

/* ══════ 一、AI 填「表上总数」—— 这道网本来就是好的，别改坏了 ══════ */
console.log("\n【一、填在「表上总数」时照旧报警】");
(function () {
  const r = S.读结构({ 行: [
    { 品名: "攸县香干", 单位: "斤", 表上总数: 3,
      分布: [{ 号: "30-2", 名: "广州医科大学附属第一医院（海印院区）", 数: 30 }] }
  ]});
  const 报 = 报了(r);
  ok("报出来了", 报.length === 1, JSON.stringify(报));
  ok("报的是 30 对 3", 报[0] && 报[0].和 === 30 && 报[0].总 === 3);
})();

/* ══════ 二、★ AI 填进「数量」—— 8/19 就是这么漏过去的 ══════ */
console.log("\n【二、填进「数量」也得报 ★ 8/19 那四行】");
(function () {
  const 单 = { 行: [
    { 品名: "攸县香干", 单位: "斤", 数量: 3,
      分布: [{ 号: "30-2", 名: "广州医科大学附属第一医院（海印院区）", 数: 30 }] },
    { 品名: "中板豆腐", 单位: "板", 数量: 3,
      分布: [{ 号: "26-2", 名: "佛山市南海区财政局（午餐）", 数: 26 }] },
    { 品名: "炸豆干", 单位: "斤", 数量: 8,
      分布: [{ 号: "31-2", 名: "瀚蓝环境股份有限公司（午餐）", 数: 31 }] },
    { 品名: "九龙炸豆腐", 单位: "斤", 数量: 10,
      分布: [{ 号: "31-2", 名: "瀚蓝环境股份有限公司（午餐）", 数: 31 }] }
  ]};
  const r = S.读结构(单);
  const 报 = 报了(r);
  ok("四行全报出来（原来一声不吭）", 报.length === 4, "报了 " + 报.length + " 条");
  const 拿 = n => 报.find(x => x.行 === n) || {};
  ok("攸县香干 30 对 3", 拿("攸县香干").和 === 30 && 拿("攸县香干").总 === 3);
  ok("中板豆腐 26 对 3", 拿("中板豆腐").和 === 26 && 拿("中板豆腐").总 === 3);
  ok("炸豆干 31 对 8", 拿("炸豆干").和 === 31 && 拿("炸豆干").总 === 8);
  ok("九龙炸豆腐 31 对 10", 拿("九龙炸豆腐").和 === 31 && 拿("九龙炸豆腐").总 === 10);
  /* ⚠ 只报、不改 —— 数字仍旧是识别读出来的那个，等人拍板。
     老板的规矩：不许替人编数，也不许拿总数去反推（8/3：「一切都以后面为准」）。 */
  const L = (r.lines || []).find(x => x.text === "攸县香干");
  ok("只报不改：数量还是识别读出来的 30", L && L.qty === 30, "qty=" + (L || {}).qty);
})();

/* ══════ 三、对得上就别吵 ══════
   误报比漏报还烦人 —— 天天弹，人就不看了，真出事那次也被当成狼来了。 */
console.log("\n【三、对得上的一声都不许吭】");
(function () {
  const r = S.读结构({ 行: [
    { 品名: "中板豆腐", 单位: "板", 数量: 4,
      分布: [{ 号: "5-9", 名: "老人碎菜", 数: 2 }, { 号: "5-5", 名: "老人糊餐", 数: 1 },
             { 号: "5-6", 名: "老人菜泥", 数: 1 }] }
  ]});
  ok("2+1+1=4，不报", 报了(r).length === 0, JSON.stringify(报了(r)));
})();

/* ══════ 四、没有分布时，「数量」就是数量，不是校验码 ══════
   这条是分界线：一行一个点的普通单子，数量填多少就是多少，
   拿它跟自己比一场没有意义，还会把好好的单子搅成一片红。 */
console.log("\n【四、没有分布时不许拿数量自己跟自己比】");
(function () {
  const r = S.读结构({ 行: [{ 品名: "白豆干", 单位: "斤", 数量: 110 }] });
  ok("不报", 报了(r).length === 0);
  const L = (r.lines || []).find(x => x.text === "白豆干");
  ok("数量照旧是 110", L && L.qty === 110, "qty=" + (L || {}).qty);
})();

/* ══════ 五、「表上总数」优先，两个都填了听它的 ══════ */
console.log("\n【五、两个字段都填了，以「表上总数」为准】");
(function () {
  const r = S.读结构({ 行: [
    { 品名: "攸县香干", 单位: "斤", 表上总数: 3, 数量: 99,
      分布: [{ 号: "30-2", 名: "海印院区", 数: 30 }] }
  ]});
  const 报 = 报了(r);
  ok("报的是 30 对 3（不是对 99）", 报.length === 1 && 报[0].总 === 3, JSON.stringify(报));
})();

console.log("\n════════════════════════");
console.log("过 " + 过 + "　挂 " + 挂);
process.exit(挂 ? 1 : 0);
