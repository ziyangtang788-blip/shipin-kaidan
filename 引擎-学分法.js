/* ============================================================
   学分法 —— 一格里挤着好几个点位，到底怎么分开
   ============================================================

   老板 2026-08-23～24 定的：
     「不要给我看符号。给我看分完长什么样。」
     「这种都没有问的必要，肯定是分成 9 份的。」
     「问哪些要问，你得衡量清楚，不是什么东西都是要问的。」

   为什么要有这个文件
   ------------------
   原来那个「帮我认一下」弹窗（配送开单台.html 里的 问怎么切）是这样问的：
     把一格切成好几块，每块给一个下拉框，让人挨个选「点位 / 接上一块 / 数量 / 不要」。
   三个毛病，老板 8/23 一条条指出来的：
     ① 人根本看不出该选什么 —— 那是在问机制，不是在问事实
     ② 一次最多问三种（挑=挑.slice(0,3)），多的悄悄扔掉
     ③ 挤在 ocr-msg 那一块地，「回头核」十几秒后回来就把窗盖了

   这个文件换一种问法：
     现有的断句规矩说到底只有两个旋钮 —— 【分隔】(空格/加号/顿号) × 【合连点】(要不要并)。
     六种组合，挨个拿【整列】切一遍，跟表上写的总数对账，
     然后只把最好的那一种摆给人看：「分成 9 份，这一列 12 行加起来都跟表上对得上，对吗？」

   ⛔ 这里【不写第二套切法】。切还是 GM_CUT.照规矩切 在切（引擎-断句规矩.js），
      本文件只负责【把六种组合各试一遍、拿账排个名】。
      抄第二份切法就会出现「这条路好了那条路还是坏的」——CLAUDE.md：匹配逻辑只准一份。

   ⚠ 账是唯一的判据，不是「看着像」：
      这一列 N 行，每行各段加起来 == 表上写的总数，才算这种分法对。
      对不上就摆出来让人挑别的，或者干脆「分不开，我自己填」。
   ============================================================ */
(function (root) {
  "use strict";

  function 字(v) { return v === null || v === undefined ? "" : String(v).trim(); }

  /* 六种组合。顺序无所谓 —— 最后按「整列对上几行」排名。 */
  var 分隔们 = ["空格", "加号", "顿号"];

  /* 拿一种分法切一格，返回 [{qty,unit,code,note}] 或 null。
     ★ 「通用」是那七种写法（引擎-解析.js extractSegs，121 份真单验过的）——
        它是【第一候选】，也是绝大多数表真正在用的那一种。
        少了它，这儿量出来的全是「切不出来」，会把本来就会读的表也拿去问人。
     ⚠ 一律走现成的两个零件，本文件不碰切的逻辑。 */
  function 切一格(串, 分隔, 合连点) {
    if (分隔 === "通用") {
      var P = root.GM_PARSE;
      if (!P || !P.extractSegs) return null;
      try {
        var g = P.extractSegs(串, { 整格是明细: true }) || {};
        return (g.list && g.list.length) ? g.list : null;
      } catch (e) { return null; }
    }
    var C = root.GM_CUT;
    if (!C || !C.照规矩切) return null;
    try {
      return C.照规矩切(串, { 分隔: 分隔, 合连点: !!合连点, 模式: "交替" });
    } catch (e) { return null; }
  }

  /* 一格切出来的各段加起来是多少。切不出来返回 null。 */
  function 加起来(段们) {
    if (!段们 || !段们.length) return null;
    var s = 0, 有 = 0;
    段们.forEach(function (g) {
      if (g && typeof g.qty === "number" && isFinite(g.qty)) { s += g.qty; 有++; }
    });
    return 有 ? Math.round(s * 100) / 100 : null;
  }

  /* ═══════════════════════════════════════════════════
     几种分法：把六种组合各拿【整列】试一遍，按账排名
     ═══════════════════════════════════════════════════
     料 = [{原文:"…", 表上总数: 12 或 null, 商品:"千张"}]  ← 这一列每一格
     回 [{分隔, 合连点, 份, 对, 量过, 例}]，对得上的行数多的排前面。

     ⚠ 「量过」= 这一列里【表上真写了总数】的行数。表上没写总数的行验不了，不计入。
       量过 = 0 意味着这张表没有对账的凭据 —— 那就只能让人自己看，不许自作主张。 */
  function 几种分法(料) {
    料 = (料 || []).filter(function (x) { return x && 字(x.原文); });
    if (!料.length) return [];
    var 出 = [], 见 = {};
    ["通用"].concat(分隔们).forEach(function (d) {
      (d === "通用" ? [false] : [false, true]).forEach(function (合) {
        var 对 = 0, 量过 = 0, 切得出 = 0, 和们 = [], 例 = null;
        料.forEach(function (x) {
          var 段 = 切一格(x.原文, d, 合);
          var 和 = 加起来(段);
          和们.push(和);
          if (段 && 段.length) { 切得出++; if (!例) 例 = { 原文: x.原文, 段: 段 }; }
          if (x.表上总数 == null || 和 == null) return;
          量过++;
          if (Math.abs(和 - x.表上总数) < 0.001) 对++;
        });
        if (!切得出) return;
        /* 去重按【整列的结果】，不是按第一格 —— 两种分法在第一格上碰巧一样、
           换一行就不一样，是常有的事（8/23 江云撞过）。 */
        var k = 和们.join(",") + "|" + 切得出;
        if (见[k]) return; 见[k] = 1;
        出.push({ 分隔: d, 合连点: 合, 份: (例 && 例.段) || [], 例: 例 && 例.原文,
                  对: 对, 量过: 量过, 切得出: 切得出, 共: 料.length });
      });
    });
    /* 排名：整列对上的行数最多 → 切得出的格子最多 → 分得最细 */
    出.sort(function (a, b) {
      return (b.对 - a.对) || (b.切得出 - a.切得出) || (b.份.length - a.份.length);
    });
    return 出;
  }

  /* 这一种分法能不能【自己定下来，不问人】。
     老板 8/23：「账能证明的就没有问的必要。」
     判据卡死三条，缺一条都要问：
       · 这一列真有总数可对（量过 > 0）
       · 每一行都对上了（对 === 量过）
       · 只有这一种全对（两种都全对 = 真有岔路，得人拍板） */
  function 不用问吗(法们) {
    法们 = 法们 || [];
    var 全对 = 法们.filter(function (f) { return f.量过 > 0 && f.对 === f.量过; });
    if (全对.length === 1) return 全对[0];
    /* ★ 只有一种切得出东西来 —— 那就没得选，问了也白问（老板 8/24：
         「问哪些要问，你得衡量清楚，不是什么东西都是要问的」）。
       账对不上的那几行照旧一行一行摆在核对里让人看 —— 那是【那几行】的事，
       不是【这一列怎么分】的事，别拿它去烦人。 */
    var 切得出的 = 法们.filter(function (f) { return f.切得出 > 0; });
    if (切得出的.length === 1) return 切得出的[0];
    return null;
  }

  /* 挑一格【最难的】当例子 —— 教一次要教得住整列，就得拿最花的那格教。
     拿头一格教的下场：祺之盛第一格「1斤**E004」只有一个点位，
     看不出该怎么分，人只会挑「整格算一个」，第二行三个点位就全糊成一团。 */
  function 挑例子(料) {
    var 好 = null;
    (料 || []).forEach(function (x) {
      var t = 字(x && x.原文); if (!t) return;
      var f = (t.match(/[+＋、，,\s]/g) || []).length * 100 + t.length;
      if (!好 || f > 好.f) 好 = { x: x, f: f };
    });
    return 好 ? 好.x : null;
  }

  /* 把选中的那一种，翻成能存进本子的规矩（跟 数据-切法规矩.js 同一个形状）。
     ⚠ 模式这一项 照规矩切() 根本不看（它是把点位和数量各归各堆再一一配对），
       存着只是为了回头能看懂当初学的是什么。 */
  function 立成规矩(客户, 法, 样本) {
    if (!法) return null;
    return {
      客户: 字(客户), 分隔: 法.分隔, 模式: "交替", 合连点: !!法.合连点,
      样本: 字(样本 || 法.例).slice(0, 120),
      状态: "试用", 对上: 0
    };
  }

  root.GM_学分法 = {
    几种分法: 几种分法, 不用问吗: 不用问吗, 挑例子: 挑例子,
    立成规矩: 立成规矩, 切一格: 切一格, 加起来: 加起来
  };
})(typeof window !== "undefined" ? window : globalThis);
