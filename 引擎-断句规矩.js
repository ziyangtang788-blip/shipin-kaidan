/* ============================================================
   断句规矩 —— 通用七种切不动时，用「学过的」切
   ============================================================

   老板 2026-08-10：
     「我的终极目的是，所有的全部都是用代码去切。新来的需要教一次，
     　教完他不就有代码了吗？后面就用这种代码切。」
     「不要让我去写，我只想选择。」

   为什么要有这个文件
   ------------------
   断句原来是【白名单】：认识的写法才切得动。这本身没错，
   错在【切不动的时候不吭声】—— 0 段跟「这格本来就空」在代码里一模一样，
   于是整行货悄悄没了。朱鲜生 8/9 那张单 13 行货读出 1 行，页面上一句提示都没有。

   所以这里做两件事：
     ① 切不动的，明确报「读不懂」，不许当空的
     ② 人点选一次「哪块是点位、哪块是数量」→ 反推成一条规矩 → 以后这家自动切

   规矩长什么样（存服务器，跟「学过的对照」一块）
   --------------------------------------------
   {
     客户: "S2944",
     分隔: "空格",              // 空格 / 加号 / 顿号
     模式: "交替",              // 交替 | 先点位后数量
     样本: "朱鲜生食堂A01 2斤 …", // 学的时候那一格原文，出错时好回溯
     状态: "试用",              // 试用 → 转正
     对上: 0                    // 试用期连着对上几次，满 3 转正
   }

   两种模式是拿真单逼出来的（朱鲜生同一家就有两种）：
     交替　　　　朱鲜生食堂A01 2斤  西樵派出所（西樵本部）2-5 3斤
     先点位后数量 昆仑33-1 南粮7-1 老人院5-4  2板 2板 1板

   ⚠ 只在【通用七种都切不动】时才轮到这里 —— 学过的规矩优先级最高，
     但通用的先试，因为通用的是拿 121 份真单验过的，比一条新学的稳。
     顺序：通用七种 → 这家学过的 → 都不行就报「读不懂」。
   ============================================================ */
(function(root){
  "use strict";

  function P(){ return root.GM_PARSE; }
  function 字(v){ return v===null||v===undefined?"":String(v).trim(); }

  var 单位字 = "斤|板|盒|包|块|串|条|件|箱|袋|桶|个|只|份|把|碗|底|公斤|kg|KG|克|g";
  var 是数量 = new RegExp("^[0-9]+(?:\\.[0-9]+)?\\s*(?:"+单位字+")?$");
  var 带单位 = new RegExp("^[0-9]+(?:\\.[0-9]+)?\\s*(?:"+单位字+")$");

  /* ---------------------------------------------------------
     切块：把一格原文切成「块」，供人点选，也供规矩套用
     括号里的空格不算分隔 —— 「西樵派出所（西樵本部）2-5」是一整块，
     不然点位名一进括号就被切碎了。
     --------------------------------------------------------- */
  function 切块(s,分隔){
    var t=字(s);
    if(!t) return [];
    if(分隔==="加号") return t.split(/[+＋]/).map(字).filter(Boolean);
    if(分隔==="顿号") return t.split(/[、,，]/).map(字).filter(Boolean);
    /* 空格：括号内的空格不切 */
    var 出=[], 当="", 深=0;
    for(var i=0;i<t.length;i++){
      var c=t.charAt(i);
      if(c==="("||c==="（") 深++;
      if(c===")"||c==="）") 深=Math.max(0,深-1);
      if(深===0&&/\s/.test(c)){ if(当.trim()){ 出.push(当.trim()); } 当=""; continue; }
      当+=c;
    }
    if(当.trim()) 出.push(当.trim());
    return 出;
  }

  /* 猜每一块是什么 —— 弹窗里的默认值，人只改错的那几块。
     ⚠ 认不出来的那种（「午餐」「靓的/少水可炸的」「晚餐/切丝」）一律当【备注】，不是扔掉。
       老板 2026-08-10：「那些我选择不要的直接丢到备注里面就行了。」
       它们是客户对这一段货的交代（怎么切、什么时候送），扔了就等于漏传要求。 */
  function 猜身份(块){
    var t=字(块);
    if(带单位.test(t)) return "数量";
    if(/^[0-9]+(?:\.[0-9]+)?$/.test(t)) return "数量";
    if(/(午餐|晚餐|早餐|夜宵|切丝|切碎|切中条|切块|要厚|要薄|靓的|少水|可炸|不要太|质量好)/.test(t)) return "备注";
    return "点位";
  }
  /* ---------------------------------------------------------
     「接上」= 这一块跟上一块其实是【同一个点位】，被空格拆开了　★2026-08-11
     ---------------------------------------------------------
     老板 8/11 那张单卡在这儿：
       「佛山市南海区南鞍机动车检测有限公司(盐步饭堂) 33-3A 1板」
     公司名和点位号 33-3A 中间有个空格 → 切成两块 → 两个点位配一个数量 →
     一一对应不上 → 认模式() 返回 null → 规矩学不成 → 弹窗点了跟没点一样。

     ⚠ 只在【点位比数量多】的时候才默认标「接上」。
       「昆仑33-1 南粮7-1 老人院5-4  2板 2板 1板」那种点位和数量一样多的，
       一块都不许并 —— 并了就把三个点位并成一个，货全送错地方。
     ⚠ 这只是【弹窗里的默认值】，人看得见也改得动。
       真正照着切的时候看规矩上的「合连点」那面旗，不在这儿现猜。 */
  function 默认接上(块们){
    var 点=0, 量=0;
    块们.forEach(function(b){ if(b.是==="点位")点++; else if(b.是==="数量")量++; });
    if(!量||点<=量) return 块们;
    var 多=点-量, 上是点=false, 出=[];
    块们.forEach(function(b){
      if(b.是==="点位"&&上是点&&多>0){ 多--; 出.push({文:b.文,是:"接上"}); return; }
      上是点=(b.是==="点位");
      出.push({文:b.文,是:b.是});
    });
    return 出;
  }
  /* 把标了「接上」的并回前一块点位。并完就没有「接上」这个身份了。 */
  function 合块(块们){
    var 出=[];
    (块们||[]).forEach(function(b){
      var 上=出[出.length-1];
      if(b.是==="接上"&&上&&上.是==="点位"){ 上.文=上.文+" "+b.文; return; }
      出.push({文:b.文, 是:(b.是==="接上"?"点位":b.是)});
    });
    return 出;
  }
  function 切块带猜(s,分隔){
    return 默认接上(切块(s,分隔||"空格").map(function(x){ return {文:x,是:猜身份(x)}; }));
  }

  /* ---------------------------------------------------------
     从人点选的结果，反推出一条规矩
     只认两种模式；认不出来就返回 null（那种还得报错找人）
     --------------------------------------------------------- */
  function 认模式(身份们){
    var 有效=身份们.filter(function(x){ return x==="点位"||x==="数量"; });
    if(有效.length<2) return null;
    var 点数=有效.filter(function(x){ return x==="点位"; }).length;
    var 量数=有效.filter(function(x){ return x==="数量"; }).length;
    if(点数!==量数) return null;                 /* 一一对应不上，不敢学 */
    /* 交替：点位 数量 点位 数量 … */
    var 交替=true;
    for(var i=0;i<有效.length;i++) if(有效[i]!==(i%2===0?"点位":"数量")) { 交替=false; break; }
    if(交替) return "交替";
    /* 先点位后数量：前一半全点位、后一半全数量 */
    var 前后=true;
    for(var j=0;j<有效.length;j++) if(有效[j]!==(j<点数?"点位":"数量")) { 前后=false; break; }
    if(前后) return "先点位后数量";
    return null;
  }

  function 学一条(客户,原文,块们,分隔){
    var 合=合块(块们);
    var 模式=认模式(合.map(function(x){ return x.是; }));
    if(!模式) return null;
    return { 客户:字(客户), 分隔:分隔||"空格", 模式:模式,
             /* 这家的点位会被空格拆开（公司名 + 点位号）—— 照着切的时候要并回去。
                人点过「接上一块」才立这面旗，代码自己不许猜。 */
             合连点:块们.some(function(x){ return x.是==="接上"; }),
             样本:字(原文).slice(0,120), 状态:"试用", 对上:0 };
  }

  /* ---------------------------------------------------------
     照一条规矩切一格。切不出来返回 null（不许返回半截）
     --------------------------------------------------------- */
  function 照规矩切(s,规矩){
    if(!规矩||!s) return null;
    var 原块=切块(s,规矩.分隔);
    if(原块.length<2) return null;
    var 带=原块.map(function(x){ return {文:x, 是:猜身份(x)}; });
    /* 这家教的时候说过「公司名和点位号是被空格拆开的」→ 这儿照样并回去。
       没立这面旗的（朱鲜生那两条）走的还是原来的路，一个字都没变。 */
    if(规矩.合连点) 带=合块(默认接上(带));
    var 点=[], 量=[], 注=[];
    带.forEach(function(b){
      if(b.是==="数量") 量.push(b.文);
      else if(b.是==="备注") 注.push(b.文);
      else 点.push(b.文);
    });
    if(!点.length||点.length!==量.length) return null;   /* 配不上就不切，宁可报错 */

    /* 备注跟着段走：只有一条备注就挂到最后一段（客户通常写在末尾，
       「…8斤 1.5斤 不要太干」那个「不要太干」说的是整格）；
       条数跟段数一样就一一对应。都不是就并起来挂到第一段，不许丢。
       老板 8/10：「那些不要的直接丢到备注里面。」—— 丢的是位置，不是内容。 */
    var out=[];
    for(var i=0;i<点.length;i++){
      var m=String(量[i]).match(new RegExp("^([0-9]+(?:\\.[0-9]+)?)\\s*("+单位字+")?$"));
      if(!m) return null;
      var n="";
      if(注.length===点.length) n=注[i];
      else if(注.length&&i===点.length-1) n=注.join(" ");
      out.push({qty:parseFloat(m[1]),unit:m[2]||"",code:点[i],note:n,没看清:false});
    }
    return out;
  }

  /* 这家有哪几条规矩，挨个试，哪条切得通用哪条 */
  function 试学过的(客户,s,规矩们){
    var 出=null;
    (规矩们||[]).forEach(function(r){
      if(出) return;
      if(字(r.客户)!==字(客户)) return;
      var l=照规矩切(s,r);
      /* 一段也算数 —— 朱鲜生一半的行就是「一个点位 一个数量」（西樵派出所2-5 3斤）。
         原来要求 ≥2 段，把这些全漏成「读不懂」了。
         切出 1 段不危险：点位和数量都对上了才切得出来，配不上照样返回 null。 */
      if(l&&l.length>=1) 出={list:l,用的规矩:r};
    });
    return 出;
  }

  root.GM_CUT={ 切块:切块, 切块带猜:切块带猜, 猜身份:猜身份, 合块:合块,
                认模式:认模式, 学一条:学一条, 照规矩切:照规矩切, 试学过的:试学过的 };
})(typeof window!=="undefined"?window:globalThis);
