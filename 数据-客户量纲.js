/* 客户量纲 —— 某个客户下单时用的量，跟我们仓库的计价量不是一个量
   ============================================================
   老板 2026-08-19：
     「把好好多这个客户…他下单的是公斤，但是我们仓库只有斤，
       下次下单过来数量自动 ×2，豆腐串不动。」

   ⚠ 这跟 2026-08-04 停掉的 `数据-换算.js` 【不是一回事】，别混：
     停掉的那套是「1件 = 几斤」——系数是问出来的、会错，老板原话
     「你换算又换算错了呢」，一错就差好几倍还看不出来。
     这一条是【公斤 ↔ 斤】，1 公斤 = 2 斤是死数，不存在猜错。
     所以只放死换算，⛔ 谁也不许往这张表里加「件→斤」那类猜出来的系数。

   ⚠ 为什么按【客户】不按【单位】：好好多那张表根本没有单位列 ——
     光秃秃一排数字（第2行商品名、第3行起东鄱店/桂华店…），
     "公斤" 是他们跟我们口头约的，纸上一个字都没有。
     所以规则只能挂在客户身上：这家的数字默认就是公斤。

   ⚠ 不乘的那几样：按【个数】卖的货跟重量无关，乘了就是凭空翻倍。
     好好多表上写「豆串」，库里叫「尝元豆腐串（串）」¥0.6/串 —— 老板点名不动。

   ⚠ 乘完必须【看得见】：页面上那一行要标出来，不许悄悄改数字
     （跟「备注里捞的数量」挂 qtyFromNote 是一个道理）。
   ============================================================ */
(function (root) {
  root.GM_客户量纲 = {

    /* 好好多超市 —— 2026-08-19 老板定 */
    "S3114": {
      名: "好好多超市",
      乘: 2,
      从: "公斤", 到: "斤",
      因为: "他们按公斤下单（表上不写单位），仓库按斤计价",
      /* 按个数卖的，不参与重量换算。写宽松点：表上写「豆串」，库里叫「尝元豆腐串（串）」 */
      不乘的: ["豆串", "豆腐串"],
      定于: "2026-08-19"
    }

  };

  /* 这一行要不要乘、乘几 —— 只回答，不改任何东西。
     ⚠ 名字用「包含」判断，两头都试：表上写的可能比库里的短（豆串 vs 尝元豆腐串（串）），
       也可能比库里的长。哪头包含哪头都算命中。 */
  function 该乘几(cid, 品名) {
    var r = root.GM_客户量纲[cid];
    if (!r || !(r.乘 > 1)) return null;
    var n = String(品名 == null ? "" : 品名).replace(/\s/g, "");
    var 免 = (r.不乘的 || []).some(function (w) {
      var k = String(w).replace(/\s/g, "");
      return k && (n.indexOf(k) >= 0 || k.indexOf(n) >= 0);
    });
    if (免) return null;
    return r;
  }
  root.GM_客户量纲.该乘几 = 该乘几;

  /* ═══════════ 点位只留编号（按客户挂）★2026-08-28 ═══════════
     老板原话：「把朱鲜生的单点位哪里识别出来只要字母跟数字，不要中文，
     　　　　　 只有他一家这样。」

     他家明细里的点位长这样：
       佛山市顺德区机关服务中心-市监饭堂午餐A59-2
       广州市老人院（上水院区）（老人糊餐）A8-6
     前面一长串中文是店名，真正用来配货的是尾巴那个 A59-2 / A8-6。

     ⚠ 只对这张表里列出来的客户生效 —— 老板明说「只有他一家这样」，
       别家的点位一个字都不许动（好些客户的点位本来就是纯中文名）。
     ⚠ 抠不出编号的【原样不动】：宁可留着一长串，也绝不许把点位弄没了。
       点位丢了 = 货不知道送哪儿，比留一串长名字严重得多。
     ⚠ 天然幂等：A59-2 再收一次还是 A59-2 —— rematch 换客户、改单位、
       重画都会跑，跑几遍结果都一样（好好多那条 ×2 就栽在幂等上，见上面）。 */
  /* ═══ 明细挤一格（按客户挂）★2026-09-01 ═══
     老板原话：「我想只针对朱先生，先不影响别的。」

     他家的表是 序号│商品名│总数│明细，【明细那一格里挤着好几段】：
       佛山市瀚华高级中学C38 6斤 佛山市瀚华高级中学C38 34斤 …A54-3 10斤
     认表这一步常把这一列指成【点位名列】而不是【分布列】，一指错三样一起废：
       ① 整格当成一个点位 → 不拆行，老板：「没有把每一列都单独列出来」
       ② 数量拿整行合计顶上（50），单段的 6／34／10 全没了，也改不了
       ③ 点位收窄要掐尾巴的编号，尾巴成了「10斤」→ 掐不动，中文原样留着

     ⚠ 本来该由 引擎-认表.js 的「自己找分布列」兜住的，可它探测时调切段器
       【没传 整格是明细】，比正式切段那套弱，所以永远探不到这种列。
       那是个通用毛病（不只他一家），老板 9/1 说先不动别家，所以这儿按客户挂。
     ⚠ 只有【识别没指出分布列、却指了点位名列】时才出手；它指对了就不抢。 */
  root.GM_客户点位写法 = {
    "S2944": { 名: "广东朱鲜生餐饮有限公司", 只留编号: true,
               明细挤一格: true, 定于: "2026-08-28／2026-09-01" }
  };
  function 明细挤一格(cid) {
    var r = root.GM_客户点位写法[cid];
    return !!(r && r.明细挤一格);
  }
  root.GM_客户点位写法.明细挤一格 = 明细挤一格;
  /* 编号长什么样：字母+数字（A59 / C1 / K006），或者数字-数字（2-5 / 33-1），
     后面可以再跟一段 -数字（A59-2 / A8-6）。 */
  var 编号 = "[A-Za-z]{1,3}[0-9]{1,4}(?:-[0-9]{1,3})?|[0-9]{1,3}-[0-9]{1,2}(?:\\([0-9]+\\))?";
  var 编号尾 = new RegExp("(" + 编号 + ")\\s*$");
  /* ★★ 2026-09-01：编号也可能在【开头】。
     他家单子两种写法都有，同一天的两张单就不一样：
       广东省妇幼保健院A6                       编号在尾
       5-3 广州市老人院（上水院区）（老人餐）    编号在头
     原来只认尾巴，第二种一个都抠不出来，中文原样留着 ——
     9/1 拿他手上 4 张真单跑，就是这张全军覆没。
     ⚠ 开头这条要求编号后面【跟着空白】：不这么卡的话，
       「5斤」「20板」这种也会被当成编号抠出来。 */
  var 编号头 = new RegExp("^(" + 编号 + ")\\s+");
  function 收窄点位(cid, code) {
    var s = String(code == null ? "" : code).trim();
    var r = root.GM_客户点位写法[cid];
    if (!r || !r.只留编号 || !s) return s;
    var m = 编号尾.exec(s);
    if (m) return m[1];
    var m2 = 编号头.exec(s);
    return m2 ? m2[1] : s;      /* 两头都抠不出就原样留着 —— 点位丢了比留长名字严重 */
  }
  root.GM_客户点位写法.收窄点位 = 收窄点位;

})(typeof window !== "undefined" ? window : globalThis);
