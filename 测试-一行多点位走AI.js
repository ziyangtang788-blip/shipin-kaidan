/* 测试-一行多点位走AI.js —— node 测试-一行多点位走AI.js
   ============================================================
   2026-08-21 老板定：一个商品底下列着好几个送货点的表，
   【OCR 那份不要了，把图交给 AI 看】。

   为什么：朱鲜生同一种表，OCR 三张单三种坏法 ——
     8-01  点位排一堆、数量排一堆，两边脱节：
           「…(碎菜)5-9 …(糊餐)5-5 …(菜泥)5-6  2板 1板 1板  午餐 午餐」
     8-19  数量那一整列【一个字都没抄】
     8-20  点位和数量穿插着，能切开（代码已经修好）

   老板原话（2026-08-21）：
     「你是一张表读得全不能代表什么东西，知道吗，不用担心钱，我只担心准确率」

   ★ 他这句戳中了要害：「各段之和 = 总数」这道账【证明不了每个点发多少是对的】。
     8-01 那张：三个点位、数量 2/1/1 —— 不管哪个数配给哪个点，加起来永远是 4，
     总数这道账永远绿灯，配错了也发现不了。
     所以不能拿它当「代码读对了」的凭据，干脆不用代码赌，直接走 AI 看图。

   判据只有一条，按【表长什么样】认，不认客户、不认表头：
     ⚠ 同一格里出现 2 个以上点位号 → 这就是「一行好几个送货点」的表

   ⛔ 日期要排掉：2026-08-01 长得也像点位号，一分利的标题栏踩过。
   ============================================================ */
const path = require("path"), fs = require("fs");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js",
 "./引擎-抓取.js"].forEach(f => require(path.resolve(__dirname, f)));
const G = global.window.GM_抓取;

let 过 = 0, 挂 = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(名, 条件, 说) {
  if (条件) { 过++; } else { 挂++; L("  ❌ " + 名 + (说 ? "\n      " + 说 : "")); }
}
const 中 = s => !!(G && G.一行好几个点位 && G.一行好几个点位(s));

/* ══════ 朱鲜生三张单，三种坏法，都得命中 ══════ */
L("═══ ① 朱鲜生三种坏法，一张都不许漏 ═══");
{
  const 单01 = "|  序号 | 商品名 | 总数 | 明细  |\n| --- | --- | --- | --- |\n" +
    "|  1 | 中板豆腐（7斤/板） | 4板 | 广州市老人院上水院区（老人碎菜）5-9 广州市老人院（上水院区）（老人糊餐）5-5 广州市老人院（上水院区）（老人菜泥）5-6 2板 1板 1板 午餐 午餐  |\n" +
    "|  2 | 水豆腐（4.5斤/板） | 1板 | 西樵派出所（西樵本部）2-5 1板  |";
  const 单19 = "|  序号 | 商品名 | 总数 | 明细  |\n| --- | --- | --- | --- |\n" +
    "|  1 | 中板豆腐 (7斤/板) | 20板 | 佛山市南海区昆仑实业有限公司33-1 广州市老人院上水院区 (老人碎菜) 5-9 广州市老人院 (上水院区) (老人糊餐) 5-5 广州市老人院 (上水院区) (老人餐) 5-3  |\n" +
    "|  5 | 攸县香干 | 3斤 | 广州医科大学附属第一医院 (海印院区) 30-2  |";
  const 单20 = "|  序号 | 商品名 | 总数 | 明细  |\n| --- | --- | --- | --- |\n" +
    "|  4 | 白豆干 | 34.6斤 | 广州市老人院上水院区 (老人碎菜) 5-9 16斤 午餐/切碎 广州市老人院 (上水院区) (老人糊餐) 5-5 6.6斤 午餐/切碎 广州市老人院 (上水院区) (老人菜泥) 5-6 4.8斤 午餐/切碎  |";
  ok("★ 8-01（点位一堆、数量一堆，两边脱节）", 中(单01));
  ok("★ 8-19（数量整列没抄到）", 中(单19));
  /* ⛔ 8-20 那张【不走 AI】—— 它每个点位号后面就紧跟着自己的数量（5-9 16斤），
     配对关系是白纸黑字写在那儿的，代码照着切就行，不用猜。
     这条线才是判据的本意：
       点位和数量【明确配对】       → 代码读（不花钱，也不会配错）
       配对关系【缺了或要靠猜】     → 交给 AI 看图
     8-01 是「三个点位、三个数量各排一堆」，谁配谁得靠猜；8-19 干脆没数量。 */
  ok("★ 8-20（每个点位后面紧跟自己的数量）→ 留在代码这条路", !中(单20));
}

L("═══ ② ⛔ 不该碰的一个都不许碰 ═══");
{
  /* 一行一个点位 —— 朱鲜生自己那几行也在内 */
  ok("一行一个点位（西樵派出所 2-5 1板）",
     !中("|  2 | 水豆腐 | 1板 | 西樵派出所（西樵本部）2-5 1板  |"));
  ok("一行一个点位（医院 30-2 3斤）",
     !中("|  5 | 攸县香干 | 3斤 | 广州医科大学附属第一医院 (海印院区) 30-2  |"));
  /* ⛔ 日期长得像点位号 —— 一分利标题栏踩过 */
  ok("⛔ 标题里的日期不算点位号",
     !中("|  崇元豆腐(12345678)-2026-08-01&2026-08-01 东莞仓仓库  |   |   |   |"));
  /* 一分利：一格挤一串，但每段都带着数量，OCR 抄得好好的 —— 照旧走 OCR */
  ok("★ 一分利（1435:2斤+1440:1斤，每段都有数量）→ 不碰",
     !中("|  干张 | 3 | 斤 | 1435:2斤+1440:1斤  |"));
  ok("★ 一分利长的那种也不碰",
     !中("|  小油豆腐 | 37 | 斤 | 1337:2斤+1489:2斤+1475:2斤+1441:2斤+1524:5斤  |"));
  /* 三棵菜：一行一个点位，列是分开的 */
  ok("三棵菜（点位单独一列）→ 不碰",
     !中("|  豆蕉品类 | 豆制品 | 水豆腐/板 | 中板/约5斤 | 1 | 和盛隆 | 10-1  |"));
  ok("空文本 → 不碰", !中(""));
  ok("不是表格的一段话 → 不碰", !中("千张 3斤\n水豆腐 5板"));
}

L("═══ ③ ★ 47 家真表离线扫一遍：只有朱鲜生该走 ═══");
{
  const 目 = path.join(__dirname, "调试-OCR原始");
  if (!fs.existsSync(目)) { L("  （没有 调试-OCR原始，跳过这一节）"); }
  else {
    const 命中 = [], 总 = [];
    fs.readdirSync(目).filter(f => /\.json$/.test(f)).forEach(f => {
      let j; try { j = JSON.parse(fs.readFileSync(path.join(目, f), "utf8")); } catch (e) { return; }
      const pg = (j.pages || [])[0] || {};
      const t = (pg.tables && pg.tables[0] && pg.tables[0].content) || pg.markdown || "";
      if (!t) return;
      总.push(f);
      if (中(t)) 命中.push(f.replace(/^[b\d-]*/, "").replace(/\.json$/, ""));
    });
    L("  扫了 " + 总.length + " 家，命中 " + 命中.length + " 家：" + (命中.join("、") || "无"));
    ok("★ 命中的全是朱鲜生（别人一个都不许碰）",
       命中.every(x => /朱鲜生|朱先/.test(x)), JSON.stringify(命中));
  }
}

L("═══ ④ 页面真接上了没 ═══");
{
  const H = fs.readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  ok("页面调了 一行好几个点位", /一行好几个点位\(/.test(H));
  /* 命中之后必须把 OCR 那份丢掉，让下面走【图】那条路 —— 不丢就等于白判 */
  ok("★ 命中就丢掉 OCR 那份（改走图）",
     /一行好几个点位[\s\S]{0,600}?OCR走通=false/.test(H));
  ok("⛔ 引擎里只有一份，页面没抄第二份", !/function\s+一行好几个点位/.test(H));
  /* 判据得排在【认表】和【断句】前面，不然还没轮到判就被那两条路截走了 */
  ok("★ 判据排在认表/断句前面",
     H.indexOf("一行好几个点位") < H.indexOf("认表跑一趟(表份"), );
}

L(挂 ? "\n❌ 挂了 " + 挂 + " 项（过 " + 过 + "）" : "\n✅ 全过 " + 过 + " 项");
process.exit(挂 ? 1 : 0);
