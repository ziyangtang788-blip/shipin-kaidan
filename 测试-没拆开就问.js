/* 明细没拆开 → 当场问，不等点客户 —— node 测试-没拆开就问.js

   老板 2026-08-28：
     「学习不是某条路，是应该总的。」
     「没拆开要问了才出单。」
     「一张单无非就是什么东西、有多少、单位是什么、送去哪里，然后再备注。
     　这一列，品名很多词自己可以认得出来，无非是明细那里他怎么拆分的问题。」

   8-27 朱鲜生那张撞出来的：屏幕上明明印着「读出 19 样货，其中 19 格没读懂」，
   系统却一声不吭等着人点客户 —— 因为学习只挂在 客户定了重读() 里。

   这里钉四件事：
     ① 「怎么拆」那条链【只有一份】，两个入口共用
     ② 识别完那一刻就叫它，而且只在真有格子没读懂时叫
     ③ 走近道那条路不许拿【上一单】的格子去问
     ④ 三层的先后不许被人改掉：碎片角色 → 学分法 → 老弹窗 */
const fs = require("fs");
const path = require("path");
const 家 = __dirname;

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, 真的) { if (真的) pass++; else { fail++; L("  ✗ " + name); } }

const H = fs.readFileSync(path.join(家, "配送开单台.html"), "utf8");
/* ⚠ 注释里也写到函数名，不剥掉就会把说明文字当成调用 —— 这是第五次栽在这上头之后立的规矩 */
const 剥 = s => s.replace(/\/\*[\s\S]*?\*\//g, "");
const h = 剥(H);
const 数 = k => h.split(k).length - 1;

L("═══ ① 「怎么拆」那条链只有一份 ═══");
ok("问一次怎么拆：1 处定义 + 至少 2 处调用（两个入口共用）", 数("问一次怎么拆") >= 3);
{
  /* 三层必须都在这一个函数里，不许散在别处各写一遍 */
  const i = h.indexOf("function 问一次怎么拆");
  const j = h.indexOf("function 识别完就问", i);
  const 段 = h.slice(i, j < 0 ? i + 2000 : j);
  ok("★ 三层都在这一份里：碎片角色", 段.indexOf("学一次碎片角色") >= 0);
  ok("★ 三层都在这一份里：学分法", 段.indexOf("学一次分法") >= 0);
  ok("★ 三层都在这一份里：老弹窗退路", 段.indexOf("问怎么切") >= 0);
  ok("★ 先后不许改：碎片角色 → 学分法 → 老弹窗",
    段.indexOf("学一次碎片角色") < 段.indexOf("学一次分法") &&
    段.indexOf("学一次分法") < 段.indexOf("问怎么切"));
  /* 人点了「分不开我自己填」就收手，不许换个窗再问同一件事 */
  ok("★ 每一层「算了」都当场收手", (段.match(/==="算了"\)\s*return/g) || []).length >= 2);
}
/* 老板 8/28 说的「学习不是某条路，是应该总的」—— 两个入口都得走这一份 */
/* ⚠ 2026-09-02：判据后面接上了「||账不平(合)」（老板 9/2：账不平也要叫学习一次），
   所以这儿只对到 剩>0，别把整句写死 —— 守的是「走的是同一份」，不是那一句怎么写。 */
ok("★ 选完客户那条路走的是这一份", /if\(剩>0[^)]*\)?[^;]*\)\s*问一次怎么拆\(合\)/.test(h));
ok("★ 识别完那条路走的是这一份", /function 识别完就问[\s\S]{0,900}?问一次怎么拆\(合\)/.test(h));

/* ★★ 老板 2026-09-02：「我要的是学习功能，在任何不对的情况下都要弹出来，
   　不然我要这个学习功能干嘛。」
   以前判「读懂没读懂」看的是【有没有读出东西】，不是【读全了没有】——
   一格两段只切出一段，系统当读懂了，学习那道门压根没被叫到，
   最后拿「以哪个为准」那个窗顶着（点完就没了，下次照样弹）。
   9/2 那张「公司采购订单」的图：50→30、460→440、70→10、21→1，四行。 */
ok("★★ 有「账不平」这道判据", /function 账不平\(/.test(h));
ok("⛔ 只写了一份（抄两份就会一条路好了另一条还坏着）",
  (h.match(/function 账不平\(/g) || []).length === 1);
/* ⚠ 2026-09-06 起这两句后面又接上了「||没拆开(…)」（老板：任何地方不齐都要跳出来），
   所以别再对整句写死 —— 守的是【账不平这一条还在里面】，不是那一行长什么样。 */
ok("★★ 识别完那一刻：账不平也叫学习", /!数读不懂\(合\)&&!账不平\(合\)/.test(h));
ok("★★ 选完客户那一趟：账不平也叫学习",
  /读不懂数>0\)&&!\(ST\.重摊\.账不平数>0\)/.test(h) &&
  /if\(剩>0\|\|账不平\(合\)/.test(h));
ok("★ 重摊数据里记了账不平的行数（不记的话选完客户那趟量不到）",
  /读不懂数:数读不懂\(合\), 账不平数:账不平\(合\)/.test(h) &&
  /读不懂数:数读不懂\(合自\), 账不平数:账不平\(合自\)/.test(h));
/* ⚠ 账不平【不许】拿去改数字：老板 8/4 定的「总数那列客户自己也常填错，
   不许拿它凑数」。这儿只是叫学习去试一次，学出来的读法照样要整列过账。 */
/* ⚠ 它只许【数】，不许【改】—— 老板 8/4 定的「总数那列客户自己也常填错，
   不许拿它凑数」。函数体里出现给数量/分布/总数赋值，就是越界了。
   （测试里的 h 是剥过注释的，所以只能验代码本身，验不了注释。） */
ok("⚠ 账不平只用来叫学习，不许拿它改数字",
  !/function 账不平\([\s\S]{0,900}?(\.数量\s*=[^=]|\.分布\s*=[^=]|\.表上总数\s*=[^=])/.test(h));

L("");
L("═══ ② 识别完那一刻就问（不等点客户）═══");
ok("识别完就问：1 处定义 + 至少 1 处调用", 数("识别完就问") >= 2);
/* ⚠ 只在【真有格子没读懂】时叫；重来那趟不叫（那趟有 客户定了重读 管着） */
ok("★ 只在 没读懂>0 时叫", /!重来\s*&&\s*读不懂\s*>\s*0\s*\)\s*识别完就问\(\)/.test(h));
ok("★ 重来那一趟不在这儿问（不然同一件事弹两遍）",
  /if\(!重来\s*&&\s*读不懂[\s\S]{0,40}识别完就问/.test(h));
{
  const i = h.indexOf("function 识别完就问");
  const 段 = h.slice(i, i + 700);
  ok("★ 它自己也要过一遍秤：摊不出行、没有读不懂的，一句不问",
    段.indexOf("数读不懂(合)") >= 0 && /if\(!合\|\|!合\.行\.length\)\s*return/.test(段));
}

L("");
L("═══ ③ 不许拿上一单的格子去问 ═══");
{
  const i = h.indexOf("function 认表再摊平");
  const 段 = h.slice(i, i + 500);
  ok("★ 认表再摊平 开头把上一单的 ST.重摊 清掉了", /ST\.重摊\s*=\s*null/.test(段));
  const j = h.indexOf("function 识别完就问");
  const 段2 = h.slice(j, j + 400);
  ok("★ 识别完就问 里先确认这一趟真有重摊数据", /if\(!ST\.重摊\|\|!ST\.重摊\.读法\)\s*return/.test(段2));
}

L("");
L("═══ ④ 出单那道门还在（没读懂的照旧出不去）═══");
ok("「确定订单」还拦着没看清的",
  /function 确定订单\(\)\{[\s\S]{0,900}?if\(数量还空着\(\)\)\s*return;/.test(h));
ok("「导观麦」共用同一份判断，没抄第二份", /if\(数量还空着\(\)\)\{[\s\S]{0,40}return;/.test(h));
ok("客户没确认时整个出单区是藏起来的", /\$\("card-out"\)\.hidden\s*=\s*gate/.test(h));

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
