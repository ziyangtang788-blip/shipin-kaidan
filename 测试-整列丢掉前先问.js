/* 一整列丢掉之前先问一句 —— node 测试-整列丢掉前先问.js

   老板 2026-09-06：
     「类似这种情况，丢掉之前一整列，如果一整列都有东西，
       丢掉之前先弹窗问一下要不要丢掉再说，这是别的东西。
       如果他选择别的东西，就把选择给他，让他去选是备注啊、还是点位啊、还是什么。」

   他 9/4 那张补货单撞出来的：第一列「单位编码」（022567 / 770024 …）
   其实就是送到哪里，被当成【没用的数字列】整列清空，18 样货点位全是白的。

   ★ 这道窗 8/24 就有（老板：「一整列，你凭什么不问就扔掉」），
     可它只装在【近道】那条路上。8/28 加的「自己认列」这条新路自己清整列、谁都不问。
     所以这里补的不是一套新判据，是【把新路接到那道现成的窗上】。
     ⛔ 我原来那套「同一个号跨几样货就算送货点」的猜法，老板当场否了 —— 别再写回来。

   钉五件事：
     ① 人点「点位」→ 那一列当送货点，不再清
     ② 人点「备注」/「规格」→ 那一列留着进备注，不再清
     ③ 人点「不用」→ 照旧清掉（这份名单本来的用处，不许弄丢）
     ④ 没人点过的时候，引擎行为一个字不变
     ⑤ 页面那条新路真的接上了这道窗（不接＝窗永远不弹） */
const fs = require("fs"), path = require("path");
process.chdir(__dirname);
global.window = {};
["数据-价格库.js", "对照-预置.js", "数据-常用规格.js", "数据-换算.js",
  "引擎-解析.js", "引擎-读结构.js", "引擎-认表.js", "引擎-碎片类.js", "引擎-认列.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const T = window.GM_TABLE, S = window.GM_STRUCT, N = window.GM_整表碎片;

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a === b) pass++; else { fail++; L("  ✗ " + name + "\n      应该 " + b + "\n      实际 " + a); }
}

/* 老板那张补货单的形状 —— 号是另编的，不是他单子上那几个 */
const 补货单 = [
  ["", "补货单", "", "9月6日"],
  ["单位编码", "存货名称", "单位", "数量"],
  [": 30分送到", "大板豆腐15斤/板", "板", "22"],
  ["031441", "豆腐(6斤左右/板)", "板", "9"],
  ["880913", "韧豆腐(可煎炸)", "板", "2"],
  ["880914", "日本豆腐", "条", "3"],
  ["031443", "山水豆腐400g", "盒", "8"],
  ["880913", "油豆卜(小)", "斤", "11"],
  ["031444", "中板豆腐", "板", "60"],
  ["031445", "中板豆腐", "板", "1.5"],
  ["880914", "猪红(熟)", "斤", "4"]
];

L("═══ ① 没人点过的时候：行为一个字不变 ═══");
const r0 = N.认列(补货单);
ok("★ 那一列照旧落进「该清掉」的名单", r0.杂数列, [1]);
ok("品名/数量/单位照旧认得出", [r0.品名列, r0.数量列, r0.单位列], [2, 4, 3]);
ok("没人点过就没有备注列", r0.备注列 || 0, 0);
{
  const 备 = N.备好(补货单, r0);
  ok("★ 照旧被清空（这就是老板撞见的那个毛病）", String(备.rows[3][0] || ""), "");
  ok("读法里备注列是 0", 备.读法.备注列 || 0, 0);
}

L("═══ ② 人点了「点位」→ 那一列当送货点，不再清 ═══");
{
  const r = N.认列(补货单, { 地址列: 1 });
  ok("★ 不再落进「该清掉」的名单", r.杂数列, []);
  ok("★ 认成了送货点那一列", r.地址列, 1);
  const 备 = N.备好(补货单, r);
  ok("★ 内容还在，没被清空", String(备.rows[3][0] || ""), "031441");
  const 合 = T.摊平([{ n: 1, rows: 备.rows }], 备.读法);
  const B = S.读结构({ 抬头: 合.抬头, 行: 合.行, 表怎么读的: 合.表怎么读的 });
  ok("★ 9 样货的点位全读出来了",
    B.lines.map(l => ((l.segs || [])[0] || {}).code || ""),
    [": 30分送到", "031441", "880913", "880914", "031443", "880913", "031444", "031445", "880914"]);
  ok("★ 数量一个都没串", B.lines.map(l => l.qty), [22, 9, 2, 3, 8, 11, 60, 1.5, 4]);
}

L("═══ ③ 人点了「备注」→ 留着，不再清 ═══");
{
  const r = N.认列(补货单, { 备注列: 1 });
  ok("★ 不再落进「该清掉」的名单", r.杂数列, []);
  ok("★ 认列把备注列交出来了", r.备注列, 1);
  const 备 = N.备好(补货单, r);
  ok("★ 读法里带上了备注列（不带＝摊平那头看不见）", 备.读法.备注列, 1);
  ok("★ 内容还在，没被清空", String(备.rows[3][0] || ""), "031441");
}

L("═══ ④ 人点了「不用」→ 照旧清掉 ═══");
{
  const r = N.认列(补货单, {});          /* 「不用」= 什么都不填，跟没点过一个待遇 */
  ok("★ 还在「该清掉」的名单里", r.杂数列, [1]);
  const 备 = N.备好(补货单, r);
  ok("★ 真的清掉了", String(备.rows[3][0] || ""), "");
}

L("═══ ⑤ 换一张表：点位号带字母、还多一根序号列 ═══");
{
  const 另一张 = [
    ["序号", "商品名称", "单位", "数量", "分拣号"],
    ["1", "大板豆腐", "板", "22", "A2-1"],
    ["2", "豆腐", "板", "9", "D1-5"],
    ["3", "韧豆腐", "板", "2", "K006"],
    ["4", "日本豆腐", "条", "3", "12-3B"]
  ];
  const r = N.认列(另一张, { 地址列: 5 });
  ok("★ 点了之后，分拣号那列当送货点", r.地址列, 5);
  ok("★ 没点到的列一个都没被牵连", r.杂数列, []);
  const 备 = N.备好(另一张, r);
  const 合 = T.摊平([{ n: 1, rows: 备.rows }], 备.读法);
  const B = S.读结构({ 抬头: 合.抬头, 行: 合.行, 表怎么读的: 合.表怎么读的 });
  ok("★ 四样货的号原样读出来",
    B.lines.map(l => ((l.segs || [])[0] || {}).code || ""), ["A2-1", "D1-5", "K006", "12-3B"]);
}

L("═══ ⑥ 页面那条新路真的接上了这道窗 ═══");
{
  const h = fs.readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  const i认 = h.indexOf("var 认了=GZ.认列(rows0");
  const i问 = h.indexOf("问这几列(待丢");
  const i出 = h.indexOf("if(出单自认(认了)) return;");
  ok("★ 新路里有「先问再清」这一段", i认 > 0 && i问 > i认, true);
  ok("★ 问在「照单摊出去」之前（顺序反了等于没问）", i问 > 0 && i出 > i问, true);
  ok("★ 答完存进列读法（不存＝每张单都要重点一遍）",
    h.indexOf("存列读法(列键B,答)") > 0, true);
  ok("★ 教过的直接套、不再问", h.indexOf("教过B?人定从答(教过B.读)") > 0, true);
  ok("★ 用的是现成那道窗，没另起一套",
    (h.match(/function 问这几列\(/g) || []).length, 1);
  ok("★ 「备注」「规格」都接到备注列上", h.indexOf('角==="备注"||角==="规格"') > 0, true);
}

L(fail ? "\n✗ 没过 " + fail + " 项（过 " + pass + "）" : "\n全部通过：" + pass + " 项");
process.exit(fail ? 1 : 0);
