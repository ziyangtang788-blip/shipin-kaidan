/* 测试-一段的冒号明细.js —— node 测试-一段的冒号明细.js
   ============================================================
   2026-08-22「工作簿1」（一分利／聚农那种「一格挤一串」的明细表）撞出来的。

   表长这样：　商品名称 │ 单位 │ 明细 │ 订购数（按下单单位）
     千张              斤   1524:1斤+1440:1斤            2
     （散装）攸县香干    斤   1496:2斤                     2     ← 只送一个点
     烟香干            斤   1440:2斤                     2     ← 只送一个点
     水豆腐（小板）      板   1372:1板                     1     ← 只送一个点

   8 样货里 3 样整行读不出来，差别只有一个：**有没有那个「+」**。

   ⛔ 两个毛病，一个根子一个报警：

   ① 冒号写法【必须切出 ≥2 片才认】。
      那道闸是给文字路设的 —— 挡「熟猪血：12斤」被读成「点位=熟猪血、数量=12」，
      商品名带个冒号，长得跟点位一模一样，分不开。
      可在格子表的【分布列】那一格里，商品名在第 1 列，要挡的坑根本不存在。
      ★ 对照证据：同一段货写成 (1496)2斤 一段就认，写成 1496:2斤 就不认 ——
        卡的从来不是「一段」，是冒号那条多加的那道闸。
      ★ 而且 引擎-解析.js 里【尖括号】早就为同一件事补过 E5
        （注释原话：「上面那块要求切出 ≥2 片才认，只订一个点位的行会整行丢」），
        冒号一直没补。补上，两种写法待遇一样。

   ② 读不懂的那一行，把表上写的校验码【也一起扔了】。
      表上「订购数」明明写着 2，页面却只说「这一格读不懂」，说不出「表上写着 2」——
      而那正是唯一能告诉人这一行该填几的线索。
      ⚠ 同一件事，隔壁 k8 那条分支（一格好几个点位、没数量）一直是带的，
        k9 这条老分支从来没带 —— 两条写法不一样，才漏了这么久。
      ⚠ 带上之后只当【校验码】，绝不当答案：数量照旧空着（不许瞎填）。

   ★ 最要紧的一组是第三组：文字路一个字都不许变。
     那道「≥2 片」的闸在文字路上仍然是对的，开关不传就照旧。
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js",
 "./引擎-认表.js", "./引擎-点位册.js", "./新-按内容认单.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const W = global.window, P = W.GM_PARSE, T = W.GM_TABLE, S = W.GM_STRUCT, N = W.GM_按内容认单;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}
const 段 = (s, o) => ((P.extractSegs(s, o) || {}).list || []);

/* ══════ 一、★ 文字路一个字都不许变（最要紧）══════
   不传开关 = 文字路。那道「≥2 片」的闸在那儿仍然是对的，一点都不许松。 */
console.log("\n【一、文字路照旧 ★ 最要紧】");
{
  ok("⛔「熟猪血：12斤」照旧不许当成「点位=熟猪血」", 段("熟猪血：12斤").length === 0,
     JSON.stringify(段("熟猪血：12斤")));
  ok("⛔「豆腐: 3板」照旧不认", 段("豆腐: 3板").length === 0, JSON.stringify(段("豆腐: 3板")));
  ok("⛔ 一段的「1496:2斤」不传开关照旧不认（文字路上分不开）",
     段("1496:2斤").length === 0, JSON.stringify(段("1496:2斤")));
  /* 两段的照旧好使 —— 这条一直是对的，别改坏了 */
  ok("两段的照旧切得开", 段("1524:1斤+1440:1斤").length === 2);
  ok("两段的数字也对", 段("1524:1斤+1440:1斤").map(g => g.code + "=" + g.qty).join(" ") === "1524=1 1440=1");
}

/* ══════ 二、★ 分布列那一格：一段的冒号也认 ══════ */
console.log("\n【二、分布列里一段也认 ★】");
{
  const o = { 整格是明细: true };
  ok("★ 1496:2斤 → 1 段", 段("1496:2斤", o).length === 1, JSON.stringify(段("1496:2斤", o)));
  ok("★ 点位和数量都对", (段("1496:2斤", o)[0] || {}).code === "1496" &&
     (段("1496:2斤", o)[0] || {}).qty === 2 && (段("1496:2斤", o)[0] || {}).unit === "斤",
     JSON.stringify(段("1496:2斤", o)[0]));
  ok("★ 1372:1板 → 1 段（板也一样）", 段("1372:1板", o).length === 1);
  ok("小数也认：1446:1.50斤", (段("1446:1.50斤", o)[0] || {}).qty === 1.5,
     JSON.stringify(段("1446:1.50斤", o)[0]));
  ok("中文冒号也认：1496：2斤", 段("1496：2斤", o).length === 1, JSON.stringify(段("1496：2斤", o)));
  /* 多段的走原来那条路，开关不许把它带歪 */
  ok("多段的还是原来那条路，一段不多一段不少",
     段("1489:2斤+1475:3斤+1496:2斤", o).length === 3);
  /* 开关只放行【冒号】这一种，别的写法本来一段就认得，不许顺手改宽 */
  ok("⛔ 开关不许放行没有冒号的整格（「1.5斤*要3块*B006」那种）",
     JSON.stringify(段("1.5斤*要3块*B006", o)) === JSON.stringify(段("1.5斤*要3块*B006")),
     JSON.stringify(段("1.5斤*要3块*B006", o)));
  /* 括号写法一段本来就认 —— 这条是对照，证明卡的是冒号那道闸 */
  ok("（对照）括号写法一段本来就认", 段("(1496)2斤").length === 1);
}

/* ══════ 三、★ 拿工作簿1 那张真表整张跑一遍 ══════ */
console.log("\n【三、工作簿1 整张表 ★】");
const 真表 = [
  ["尝元豆腐(12345678)-2026-08-22&2026-08-22 东莞仓仓库", "", "", ""],
  ["商品名称", "单位", "明细", "订购数（按下单单位）"],
  ["千张", "斤", "1524:1斤+1440:1斤", "2"],
  ["日本豆腐", "件", "1372:1件+1685:1件", "2"],
  ["（散装）攸县香干", "斤", "1496:2斤", "2"],
  ["烟香干", "斤", "1440:2斤", "2"],
  ["水豆腐（小板）", "板", "1372:1板", "1"],
  ["水豆腐 （中板）", "板", "1272:1板+1475:1板+1685:2板", "4"]
];
const 真指认 = {
  版式: "明细",
  有什么: {
    品名: { 有: true, 表头写的是: "商品名称", 第一格是: "千张" },
    数量: { 有: false, 为什么: "数字都挤在明细那一格里" },
    单位: { 有: true, 表头写的是: "单位", 第一格是: "斤" },
    单价: { 有: false }, 备注: { 有: false },
    点位: { 有: true, 表头写的是: "明细", 第一格是: "1524:1斤+1440:1斤" },
    校验数: { 有: true, 表头写的是: "订购数（按下单单位）", 第一格是: "2" }
  },
  第一样货叫: "千张", 最后一样货叫: "水豆腐 （中板）", 数据区一共几行: 6, 不确定的: []
};
{
  const r = N.认(真表, 真指认);
  const J = T.摊平([{ n: 1, rows: 真表 }], Object.assign({ 用第几张表: 1 }, r.读法 || {}));
  const lines = (S.读结构(J).lines) || [];
  const 数 = 名 => { const L = lines.find(x => (x.text || "").indexOf(名) >= 0); return L ? L.qty : null; };
  ok("6 样货一样不少", lines.length === 6, "摊出 " + lines.length + " 样");
  ok("★ （散装）攸县香干 = 2（原来读不懂）", 数("攸县香干") === 2, "读出 " + 数("攸县香干"));
  ok("★ 烟香干 = 2（原来读不懂）", 数("烟香干") === 2, "读出 " + 数("烟香干"));
  ok("★ 水豆腐（小板）= 1（原来读不懂）", 数("小板") === 1, "读出 " + 数("小板"));
  ok("多段的没被带歪：千张还是 2", 数("千张") === 2, "读出 " + 数("千张"));
  ok("多段的没被带歪：中板还是 4", 数("中板") === 4, "读出 " + 数("中板"));
  ok("★ 一条校验都不报（各段之和跟表上订购数全对得上）",
     (S.读结构(J).校验 || []).length === 0,
     JSON.stringify((S.读结构(J).校验 || []).map(z => z.说 || z)));
}

/* ══════ 四、★ 真读不懂的时候，把表上那个数带上 ══════
   这一组守的是【报警要说人话】，跟上面能不能读出来是两件事。 */
console.log("\n【四、读不懂也要说出「表上写着几」★】");
{
  /* 造一格谁也切不出段的：整格就是一句话，没有任何点位/数量的形状 */
  const 怪表 = [
    ["商品名称", "单位", "明细", "订购数"],
    ["某某豆干", "斤", "看群里通知的那个说法", "7"]
  ];
  const J = T.摊平([{ n: 1, rows: 怪表 }],
    { 用第几张表: 1, 版式: "明细", 表头在第几行: 1, 商品列: 1, 单位列: 2, 分布列: 3, 合计列: 4 });
  const 行 = J && J.行 && J.行[0];
  ok("这一格确实切不出段（读不懂）", 行 && (行.分布 || []).some(d => d.读不懂),
     JSON.stringify((行 || {}).分布));
  ok("★ 表上那个 7 带上了（原来整个扔掉）", 行 && 行.表上总数 === 7,
     "表上总数=" + ((行 || {}).表上总数 === undefined ? "没带" : 行.表上总数));

  const rr = S.读结构(J);
  const L = (rr.lines || [])[0] || {};
  ok("⛔ 只当校验码，绝不当答案 —— 数量照旧空着，不许瞎填",
     !(L.qty > 0), "qty=" + JSON.stringify(L.qty));
  ok("⛔ 读不懂这个标记还在（页面靠它拦住确定订单）",
     (L.segs || []).some(g => g.没看清 || g.读不懂), JSON.stringify(L.segs));
  ok("★ 校验网现在喊得出「表上写 7」", (rr.校验 || []).some(z => +z.总 === 7),
     JSON.stringify((rr.校验 || []).map(z => z.行 + " 和" + z.和 + " 总" + z.总)));
}

/* ══════ 五、两条分支待遇要一样 ══════
   k8（一格好几个点位、没数量）一直带着校验码，k9（切不出段）原来不带。
   同一件事两种写法，正是漏这么久的原因 —— 钉住，别再走回去。 */
console.log("\n【五、两条「读不懂」分支待遇一样】");
{
  const src = require("fs").readFileSync(path.resolve(__dirname, "引擎-认表.js"), "utf8");
  const 次数 = (src.match(/组\[k[89]\]\.表上总数=parseFloat/g) || []).length;
  ok("★ 两条分支都把表上那个数带上了", 次数 === 2, "只找到 " + 次数 + " 处");
}

console.log("\n════════════════════════");
console.log(挂 ? "❌ 挂了 " + 挂 + " 项（过 " + 过 + "）" : "✅ 全过 " + 过 + " 项");
process.exit(挂 ? 1 : 0);
