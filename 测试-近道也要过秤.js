/* 测试-近道也要过秤.js —— node 测试-近道也要过秤.js
   ============================================================
   2026-08-22 老板拖佛山俱之盛那张（祺之盛那种「明细写在下一行」的表）撞出来的。

   「按长相直接抓」是条近道：谁都不问、一个 token 不花，自己按长相猜这张表怎么读。
   那张表它猜错了：
     · 「210串(210串)」这种括号里重复一遍的写法，数量整个漏掉
     · 最右边那列的「0」（实采）被当成了点位号
   抓回来 5 行，每行数量都是空的 → 摊出【0 样货】。

   ⛔ 后果三件一起来：
     ① 原文框被清空 —— 拖进来的东西一个字不剩
     ② 屏幕还打绿勾「✅ 读出 0 样货」
     ③ 这条近道 return 了 —— 不再走本子、也不再问 AI，路直接堵死

   跟今天早上给【记住的读法】加的那道秤是同一条道理，当时漏了这条近道。

   新规矩：近道抓完也过一遍秤 —— 摊出【一样货都没有】= 没走通，
   当没有这条近道，原样往下走本子 / 走 AI。不收单、不清原文框。

   ★ 判据卡到最死（第二组专门钉）：只有「一样货都没有」才算没走通。
     37 张真表离线量过：36 张抓得出货的一条都不碰，
     只有祺之盛那张（本来就是坏的、0 样货）会改走 AI。
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读结构.js", "./引擎-认表.js",
 "./引擎-抓取.js"].forEach(f => require(path.resolve(__dirname, f)));
const W = global.window, G = W.GM_抓取, S = W.GM_STRUCT;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}
/* 页面里那道秤，照抄一份来验（页面那头由第三组钉住只有一份） */
const 抓出几样 = 抓好了 => ((S.读结构({ 抬头: {}, 行: 抓好了.行 || [],
  表怎么读的: 抓好了.表怎么读的 || {} }).lines) || []).length;

/* ══════ 一、★ 佛山俱之盛那张：近道抓得出行，却摊出 0 样货 ══════ */
console.log("\n【一、俱之盛那张：抓得出行、摊出 0 样货 ★】");
const 货 = [
  ["豆腐串", "1串/串", 210, "串", "40串**E018-01+10串**E028+25串**E002-01+60串**E005"],
  ["水豆腐（5斤）", "1板/板", 21, "板", "2板**E022+8板**D008+4板**E002+7板**E012"],
  ["白豆干", "1斤/斤", 18, "斤", "3斤**E033+15斤**E010"],
  ["攸县香干", "1斤/斤", 12, "斤", "12斤**D004"]
];
const 俱之盛 = [
  ["采购单位: 佛山俱之盛", "", "", "采购经办: 扎仟松", ""],
  ["打印时间: 2026-08-23 18:55:11", "", "", "预采购金额: 0.00", ""],
  ["任务数: 4", "", "", "", ""],
  ["序号", "商品名", "规格", "计划采购", "实采（基本单位）"]
];
货.forEach((g, i) => {
  俱之盛.push([String(i + 1), g[0], g[1], g[2] + g[3] + "(" + g[2] + g[3] + ")", "0"]);
  俱之盛.push([g[4], "", "", "", ""]);
});
{
  let r = null; try { r = G.抓(俱之盛, {}); } catch (e) { r = null; }
  ok("近道确实抓得出行（所以旧判据拦不住）", !!(r && (r.行 || []).length),
     r ? (r.行 || []).length + " 行" : "null");
  if (r) {
    ok("★ 可摊出来是 0 样货", 抓出几样(r) === 0, "摊出 " + 抓出几样(r) + " 样");
    ok("★ 新判据判它没走通 → 该当没有这条近道", 抓出几样(r) === 0);
    /* 这就是数量丢掉的那一格 —— 顺手把证据钉在这儿 */
    const 头 = (r.行 || [])[0] || {};
    ok("（证据）数量是空的，单位吃进了「串(210串)」",
       ((头.分布 || [])[0] || {}).数量 === "" || ((头.分布 || [])[0] || {}).数量 == null,
       JSON.stringify((头.分布 || [])[0]));
  }
}

/* ══════ 二、★ 抓得出货的表一条都不许碰（最要紧）══════ */
console.log("\n【二、抓得出货的一条不碰 ★ 最要紧】");
{
  /* 一张规规矩矩、近道本来就读得对的表 */
  const 好表 = [
    ["商品名称", "单位", "数量"],
    ["嫩豆腐", "斤", "3"],
    ["老豆腐", "斤", "5"],
    ["千张", "斤", "2"]
  ];
  let r = null; try { r = G.抓(好表, {}); } catch (e) { r = null; }
  ok("近道抓得出来", !!(r && (r.行 || []).length), r ? (r.行 || []).length + " 行" : "null");
  if (r) {
    ok("★ 摊出来有货 → 新判据【不许】拦它", 抓出几样(r) > 0, "摊出 " + 抓出几样(r) + " 样");
    const q = (S.读结构({ 抬头: {}, 行: r.行, 表怎么读的: {} }).lines || []).map(L => L.qty);
    ok("数量照旧是 3/5/2", q.join(",") === "3,5,2", JSON.stringify(q));
  }
}

/* ══════ 三、页面真接上了没 ══════ */
console.log("\n【三、页面真接上了没】");
{
  const H = require("fs").readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  ok("页面算了「抓出几样」这道秤", /var 抓出几样=0;/.test(H));
  ok("★ 0 样货 → 当没有这条近道（抓好了=null）",
     /if\(!抓出几样\) 抓好了=null;/.test(H));
  ok("★ 秤排在「收尾」前面（排后面就已经收单了，白量）",
     H.indexOf("if(!抓出几样) 抓好了=null;") <
     H.indexOf('收尾(抓好了,null,"按长相直接抓的，没问 AI、没花钱")'));
  ok("⛔ 这道秤只写一份", (H.match(/var 抓出几样=0;/g) || []).length === 1);
  /* 秤不过要能接着走本子/AI —— 近道那段是 try 包着的，抓好了=null 就自然往下掉 */
  /* ⚠ 2026-08-28 放宽参数：查读法本 现在收两把钥匙（老指纹 + 骨相），
     守的意图没变 —— 近道过不了秤，照旧得往下走本子那条路。 */
  ok("秤不过之后照旧往下走本子那条路", /if\(抓好了\)\{[\s\S]{0,4000}?查读法本\(fp[,)]/.test(H));

  /* 另一半：0 样货不许打绿勾、要说清「不是没货，是没读懂」 */
  ok("★ 0 样货不许打绿勾", /var 头=\(!ST\.lines\.length\)/.test(H));
  ok("★ 说清「不是这张单没货，是没读懂」", /这不是「这张单没货」/.test(H));
  ok("两处报头都改了（收下格子表 / 收下文字）",
     (H.match(/var 头=\(!ST\.lines\.length\)/g) || []).length === 2);
}

console.log("\n════════════════════════");
console.log(挂 ? "❌ 挂了 " + 挂 + " 项（过 " + 过 + "）" : "✅ 全过 " + 过 + " 项");
process.exit(挂 ? 1 : 0);
