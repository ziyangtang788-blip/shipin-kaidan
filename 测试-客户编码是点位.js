/* 「客户编码」那一列整列点位无声无息地没了（2026-08-24 老板拖的那张单）

   表长这样：
     序号 | 客户编码 | 商品名称 | 订购数量 | 下单单位 | 备注 | 商品描述
      1  | H16     | 熟猪红   |   8     |   斤
      3  | 253     | 大豆泡   |   2     |   斤     ← 序号合并单元格，一样货好几个点
         | 606-2   | 大豆泡   |  15     |   斤

   数量、单位、品名全读对了，可【第 2 列没人管】—— 既不用、也不问，12 行货全没有送货点。
   这是江云那次的翻版：单子照样出，分拣的人不知道往哪送。

   根子：表头词表里那条 /(商品编码|物料编码|存货编码|货号|编码)/ → 「无关」，
   光一个「编码」把【客户编码】也吞了。商品编码确实没用，客户编码是送货点。

   ⛔ 不许靠加词表治（表是无限的，词加不完）—— 靠长相：
     整列混着 H16 / 606-2 / 91 这种编号，又不是 5 位以上的长编码（那才是真商品编码），
     表头说什么都不算数，必须留下来问一句。
   ⚠ 只问、不猜 —— 猜点位跟猜品名是同一个病。 */
const path = require("path");
const 家 = __dirname;
global.window = global.window || {};
["数据-价格库.js", "对照-预置.js", "数据-常用规格.js", "数据-换算.js",
 "引擎-解析.js", "引擎-匹配.js", "引擎-抓取.js"].forEach(f => require(path.join(家, f)));
const G = global.window.GM_抓取;

let 过 = 0, 挂 = [];
function 该(话, 真) { if (真) 过++; else 挂.push(话); }

const 那张单 = [
  ["广东尝元绿色食品有限公司(13288225393)-2026-08-25 默认库房仓库", "", "", "", "", "", ""],
  ["序号", "客户编码", "商品名称", "订购数量", "下单单位", "备注", "商品描述"],
  ["1", "H16", "熟猪红", "8", "斤", "", ""],
  ["2", "91", "白豆腐干/白豆干", "15", "斤", "", ""],
  ["3", "253", "大豆泡", "2", "斤", "", ""],
  ["", "606-2", "大豆泡", "15", "斤", "", ""],
  ["8", "H15-1", "猪红", "20", "斤", "", ""],
  ["", "H15-2", "猪红", "26", "斤", "", ""]
];

/* ── 一、货本身照旧读得对（这次改动一个数都不许动）── */
{
  const r = G.抓(那张单, {});
  该("6 行货一行不少", ((r || {}).行 || []).length === 6);
  const 量 = (r.行 || []).map(L => ((L.分布 || [])[0] || {}).数量);
  该("数量一个不差", JSON.stringify(量) === JSON.stringify([8, 15, 2, 15, 20, 26]));
  该("单位都是斤", (r.行 || []).every(L => L.单位 === "斤"));
}

/* ── 二、★ 那一列必须被问出来，不许静默扔掉 ── */
{
  const r = G.抓(那张单, {});
  const 待 = (r.没抓到的 || []).find(q => q.问点位);
  该("★ 会问「第 2 列是不是送货点位」", !!待);
  该("★ 问的正是「客户编码」那一列", !!待 && String(待.列) === "2");
}

/* ── 三、人答「是点位」之后，点位全接上 ── */
{
  const r0 = G.抓(那张单, {});
  const 待 = (r0.没抓到的 || []).find(q => q.问点位);
  const r = G.抓(那张单, { 点位列: 待 && 待.列 });
  const 点 = (r.行 || []).map(L => { const d = (L.分布 || [])[0] || {}; return d.点位号 || d.点位名 || ""; });
  该("★ 点位一个不少", JSON.stringify(点) === JSON.stringify(["H16", "91", "253", "606-2", "H15-1", "H15-2"]));
  该("同一样货送好几个点，各归各行（猪红 H15-1 / H15-2）",
    点.filter(x => /^H15/.test(x)).length === 2);
}

/* ── 四、别误伤：真商品编码列、序号列，照旧不许烦人 ── */
{
  const 编码表 = [
    ["序号", "商品编码", "商品名称", "数量", "单位"],
    ["1", "36010003", "熟猪红", "8", "斤"],
    ["2", "28000031", "大豆泡", "2", "斤"],
    ["3", "28000032", "攸县香干", "1", "斤"]
  ];
  const r = G.抓(编码表, {});
  该("★ 真商品编码（8 位长数字）不许拿去问人",
    !(r.没抓到的 || []).some(q => q.问点位 && String(q.列) === "2"));
  该("★ 序号列不许拿去问人",
    !(r.没抓到的 || []).some(q => q.问点位 && String(q.列) === "1"));
  该("货照样读得出来", ((r || {}).行 || []).length === 3);
}

if (挂.length) {
  console.log("没过 " + 挂.length + " 项：");
  挂.forEach(t => console.log("  ✗ " + t));
  process.exit(1);
}
console.log("全部通过：" + 过 + " 项");
