(function (root) {
  "use strict";

  function 字(v) { return v === null || v === undefined ? "" : String(v).trim(); }
  /* 比对用的规整：全角转半角、去空白、去掉常见的装饰符号。
     客户表上的「商品名称」和 AI 抄回来的「商品名称 」差一个空格是常态，
     差一个空格就找不到，等于白做。 */
  function 平(s) {
    return 字(s).replace(/[！-～]/g, function (c) {
      return String.fromCharCode(c.charCodeAt(0) - 0xfee0);
    }).replace(/[\s　·・:：*＊|｜]/g, "").toLowerCase();
  }

  /* ══════════════════════════════════════════════
     ① 提示词：只问「这张单有什么」，不问「在第几行第几列」
     ══════════════════════════════════════════════ */
  var 提示词 =
"下面是一张下单表。你的活儿：告诉我【这张表里有哪些东西、长什么样】。\n" +
"**一个行号、一个列号都不要报。一个数字都不要抄。**\n" +
"我们本地会拿你说的字回表里去找 —— 你只负责指认，数格子是我们的活。\n" +
"\n" +
"════════ 回这个格式 ════════\n" +
"{\n" +
'  "版式": "明细",              // 一行一个商品 = "明细"；横着一排收货方 = "矩阵"\n' +
'  "有什么": {\n' +
'    "品名": {"有":true,  "表头写的是":"商品名", "第一格是":"内脂嫩豆腐"},\n' +
'    "数量": {"有":false, "为什么":"没有单独的数量列，数字都挤在明细那一格里"},\n' +
'    "单位": {"有":true,  "表头写的是":"规格",   "第一格是":"1盒/盒"},\n' +
'    "单价": {"有":false},\n' +
'    "点位": {"有":true,  "表头写的是":"明细",   "第一格是":"3盒*欧巢门窗（三厂）【K53】"},\n' +
'    "备注": {"有":false},\n' +
'    "校验数": {"有":true, "表头写的是":"采购总数", "第一格是":"9盒(9盒)"}\n' +
"  },\n" +
'  "第一样货叫": "内脂嫩豆腐",\n' +
'  "最后一样货叫": "水豆腐切块(斤)",\n' +
"\n" +
'  // ★★ 只有 版式="矩阵" 才填这一块；明细表整块省掉。\n' +
'  //    交叉表说到底就【两个轴】：一个轴摆商品，另一个轴摆收货方。\n' +
'  //    正的反的，无非是谁横谁竖 —— 两个轴各说一次，正反都说清了。\n' +
'  "矩阵": {\n' +
'    "商品":   {"怎么排":"竖", "第一个叫":"猪红",   "最后一个叫":"鲜肠粉"},\n' +
'    "收货方": {"怎么排":"横", "第一个叫":"高村店", "最后一个叫":"罗村店"}\n' +
"  },\n" +
'  "数据区一共几行": 13,   // ★ 数【行】，不是数【样】。一行一个送货点的表，\n' +
'                          //   同一样货占好几行是常事（白豆干送 5 个点就占 5 行），\n' +
'                          //   你数 50 行、我们合并同名货后剩 11 样，两边都没错，\n' +
'                          //   但拿来对账就成了假警报。所以统一数行。\n' +
'  "不确定的": ["第5列全是三位数字，看不出是点位号还是别的编号"]\n' +
"}\n" +
"\n" +
"════════ 规矩 ════════\n" +
"1.【只报字，不报数】「表头写的是」「第一格是」都【原样抄】表上的字，一个标点都别改。\n" +
"   抄错一个字我们就找不到，会当场停下来问人 —— 这不算你错，比你猜一个强得多。\n" +
"2.【没有就说没有】这张表没有的东西，"+'"有":false'+"，别硬凑。\n" +
"   ⛔ 硬凑一个是这套里最贵的错：凑出来的单子照样出得来，没人看得见。\n" +
"3.【拿不准就写进「不确定的」】看不出来是什么的，写一句为什么。我们会去问人，不扣你分。\n" +
"   ⛔ 已经想明白并处理掉的事不要写（「第1列是标题，已排除」这种），那是废话。\n" +
"4.【★ 送到哪儿这一列，必答不许跳】\n" +
"   一张下单表最少三样：什么货、要多少、送到哪儿。前两样你一向指得对，\n" +
"   第三样最容易【整列漏掉】—— 漏了单子照样出得来，只是没人知道往哪送。\n" +
"   2026-08-12 江云：表上明明有「订菜分布清单」一整列，没被指出来，\n" +
"   17 行货全部没有送货点，单子还是出了。\n" +
"   它长成三种样子，认准一种填「点位」那一格：\n" +
"     · 一格挤一串   满格都是 (点位)数量 用 + 连着\n" +
"     · 一行一个点   单独一列写着点位号或店名\n" +
"     · 真的没有     写 \"有\":false\n" +
"   ★ 交叉表（版式=\"矩阵\"）不填这一格 —— 收货方去上面那块「矩阵」里说，\n" +
"     那儿两个轴都要交代，正的反的一次说清。\n" +
"   ⛔ 表头带「分布／明细／门店／收货／点位／客户」这类字眼，或者哪一格满是括号加号\n" +
"     —— 就是它，必须指出来。宁可指错让人改，也不许当没看见。\n" +
"5.【★ 交叉表：两个轴都得交代】版式=\"矩阵\" 时必须填「矩阵」那一块。\n" +
"   交叉表说到底就两个轴，一个摆商品、一个摆收货方。\n" +
"   谁横谁竖【两种都有】，你照实说，别往哪个模板上凑：\n" +
"\n" +
"     正的 —— 商品竖着一列，收货方横着一排（一列一个店）\n" +
'       \"矩阵\": {\"商品\":  {\"怎么排\":\"竖\", \"第一个叫\":\"猪红\",  \"最后一个叫\":\"鲜肠粉\"},\n' +
'                \"收货方\":{\"怎么排\":\"横\", \"第一个叫\":\"高村店\",\"最后一个叫\":\"罗村店\"}}\n' +
"\n" +
"     反的 —— 商品横着一排（一列一样货），收货方竖着一列\n" +
'       \"矩阵\": {\"商品\":  {\"怎么排\":\"横\", \"第一个叫\":\"饺子皮\",\"最后一个叫\":\"豆腐丝\"},\n' +
'                \"收货方\":{\"怎么排\":\"竖\", \"第一个叫\":\"东鄱店\"}}\n' +
"\n" +
"   ⚠ 两个轴必须【一横一竖】，不许都填横或都填竖 —— 那样的表不是交叉表。\n" +
"   ⚠ 竖着排的那个轴，名字拉了一长列，中间那些行我们没给你看（骨架省了），\n" +
"     所以【竖的那个只报「第一个叫」就行】，「最后一个叫」看不到就别写，\n" +
"     我们自己从第一个往下数到「合计／总计」那行为止。\n" +
"     横着排的那个挤在一行里，你一眼看得全 —— 【两头都要报】。\n" +
"   ⛔ 报字，不报行号列号。抄错一个字我们找不到，会停下来问人，比你猜强。\n" +
"   ⛔ 别只报收货方的第一个就完事（2026-08-19 尝元）：不知道到哪儿为止，\n" +
"     我们会一路吃到表尾，把「数量」「采购量」「商品代码」全当成收货方 ——\n" +
"     那张单该 164，算成了 1.2 亿。\n" +
"6.【必须有的四样】品名、数量、单位、单价 —— 这四样是单子的骨头。\n" +
"   表上没有单价很正常（我们自己有价格库），照实说没有就行。\n" +
"   但【品名】和【数量】要是都说没有，那多半是你看错表了，回去再看一眼。\n" +
"   ★ 数量藏在别的格子里（比如全挤在「明细」那一列）也算「没有单独的数量列」，\n" +
"     照实写，并把那一列指给我们 —— 我们本地有一套断句规矩去切它，比你现场拆稳。\n" +
"7.【别管的东西】开单员、验收人、税率、毛重、配送车次 —— 跟钱无关，一个字都不用提。\n" +
"7. 只输出 JSON，不要解释，不要 markdown。";

  /* ══════════════════════════════════════════════
     ② 找字：拿 AI 指认的那几个字，回表里定位
     ══════════════════════════════════════════════ */

  /* 在整张表里找一个格子，返回 {行,列}（都从 1 数起）。找不到返回 null。
     先要一模一样的，再退而求其次要「包含」—— 客户表上常有
     「商品名称」vs「商品名称(必填)」这种尾巴。 */
  function 找格(rows, 文字, 限行) {
    var 目标 = 平(文字);
    if (!目标) return null;
    var 松 = null;
    var 到 = 限行 ? Math.min(rows.length, 限行) : rows.length;
    for (var i = 0; i < 到; i++) {
      var r = rows[i] || [];
      for (var j = 0; j < r.length; j++) {
        var v = 平(r[j]);
        if (!v) continue;
        if (v === 目标) return { 行: i + 1, 列: j + 1, 怎么找到的: "一模一样" };
        if (!松 && (v.indexOf(目标) >= 0 || 目标.indexOf(v) >= 0) && Math.min(v.length, 目标.length) >= 2)
          松 = { 行: i + 1, 列: j + 1, 怎么找到的: "对上了大半（表上写的是「" + 字(r[j]) + "」）" };
      }
    }
    return 松;
  }

  /* 一样东西在第几列：表头找一次、第一格内容找一次，两边对一下。
     ★ 两边都找到了却不是同一列 —— 这是最该停下来的时候：
       多半是表头和数据错位（认表提示词里写着「表头 7 列、那一长串落在第 6 格」）。
       这种情况老路子会闷头挑一个，我们不挑，交给人。 */
  function 定一列(rows, 说的, 名字) {
    var 出 = { 名字: 名字, 有: !!(说的 && 说的.有), 列: null, 说法: [] };
    if (!出.有) { 出.说法.push("识别说这张表没有"); return 出; }

    var 由表头 = 说的.表头写的是 ? 找格(rows, 说的.表头写的是, 8) : null;
    var 由内容 = 说的.第一格是 ? 找格(rows, 说的.第一格是) : null;

    if (由表头 && 由内容 && 由表头.列 !== 由内容.列) {
      /* ★ 2026-08-19 尝元「要货交叉表」：一张 27 行分毫不差、完全能出的单被毙了。
         报的是「表头『采购量』在第 11 列，可它说的第一格内容却在第 8 列」。
         两边都没错 —— 那张表第 8 列「数量」和第 11 列「采购量」27 行【一模一样】，
         找格 拿「41」去找，撞上排在前面的第 8 列就返回了。

         漏掉的是最简单的一步：【回头看一眼表头那一列的那一格是什么】。
         一看就知道第 11 列那一格也是 41 —— 两条线索指的本来就是同一列，不矛盾。

         为什么撞车时信表头不信内容：表头是一句话（「采购量」），整张表通常只有一个；
         内容是一个数（「41」），重复列一多就到处都是。谁更能唯一定位就信谁。
         ⚠ 只在【表头那一列的同一格确实等于它说的内容】时才认，差一个字都不认 ——
           那才是真错位（表头 7 列、数据落在第 6 格那种），照旧拦下来问人。 */
      var 同行 = rows[由内容.行 - 1] || [];
      var 表头列那格 = 平(同行[由表头.列 - 1]);
      if (表头列那格 && 表头列那格 === 平(说的.第一格是)) {
        出.列 = 由表头.列;
        出.数据起 = 由内容.行;
        出.说法.push("按表头找到第 " + 由表头.列 + " 列（那一格也是「" + 字(说的.第一格是) +
                    "」；第 " + 由内容.列 + " 列内容一样，按表头定的）");
        return 出;
      }
      出.拿不准 = "表头「" + 说的.表头写的是 + "」在第 " + 由表头.列 +
                  " 列，可它说的第一格内容却在第 " + 由内容.列 + " 列 —— 对不上，得你看一眼";
      return 出;
    }
    var 中 = 由内容 || 由表头;
    if (!中) {
      出.拿不准 = "表里找不到「" + (说的.表头写的是 ||说的.第一格是 || "") + "」这几个字";
      return 出;
    }
    出.列 = 中.列;
    出.说法.push((由内容 ? "按内容" : "按表头") + "找到第 " + 中.列 + " 列（" + 中.怎么找到的 + "）");
    if (由内容) 出.数据起 = 由内容.行;
    return 出;
  }

  /* ══════════════════════════════════════════════
     ③ 把「指认」翻成「读法」—— 出口就这一个
     ══════════════════════════════════════════════
     成功 → {读法:{…跟老的读法一模一样…}, 说法:[…], 版式:…}
     有拿不准的 → {要问的:[…]}，绝不自己挑一个 */
  function 认(rows, 指认) {
    if (!rows || !rows.length) return { 要问的: ["这张表是空的"] };
    if (!指认 || typeof 指认 !== "object") return { 要问的: ["识别没给出指认"] };

    var 有 = 指认.有什么 || {};
    var 要问的 = [], 说法 = [];

    /* —— 数据从哪一行开始：找「第一样货叫」的那几个字 ——
       ★ 这一句是整套的命门。老路子问「表头在第几行」，那是【划范围】：
         上面压着标题行、采购单位行、打印时间行，层数一多就数错，
         数大一行就吃掉一行货，一声不吭（御口福丢了三样、裕丰丢了大豆泡 7 斤）。
       改成找字之后，上面压几层都无所谓 —— 货在哪儿就从哪儿开始。 */
    var 起 = 指认.第一样货叫 ? 找格(rows, 指认.第一样货叫) : null;
    if (指认.第一样货叫 && !起)
      要问的.push("表里找不到「" + 指认.第一样货叫 + "」—— 识别看的和我们读的对不上");

    /* ★ 交叉表的品名和数量【不归这套管】（2026-08-19）：
       这套是按「一列一样东西」算的，交叉表根本不是那个形状 ——
         · 正的（商品竖排）：商品列由「矩阵」那块定，比这儿按列名猜的准
         · 反的（商品横排）：品名是【一行】不是一列，表头和第一格本来就不同列，
           这套必然判「对不上」；数量更是压根没有单独一列，全在交叉格里
       好好多 8.20 就是这么被拦死的：品名对不上、数量找不到、
       「品名那一列没定下来」—— 四条全是拿明细表的尺子量交叉表量出来的。
       交叉表读不读得了，由下面「两个轴」那段负责；那段定不下来照样拦，不会放水。 */
    var 是交叉表 = (指认.版式 === "矩阵");
    var 列 = {};
    [["品名", "商品列"], ["数量", "数量列"], ["单位", "单位列"],
     ["单价", "单价列"], ["点位", "分布列"], ["备注", "备注列"],
     ["校验数", "合计列"]].forEach(function (p) {
      var r = 定一列(rows, 有[p[0]], p[0]);
      if (r.拿不准) {
        /* ★ 点位定不下来【不拦】（老板 2026-08-12：点位这些不用了）。
           点位现在只照搬不挂价，定不下来顶多是这一行没写送到哪儿，钱一分不差。
           数量/单位/单价/品名定不下来照旧拦 —— 那几样错了就是钱错了。 */
        if (p[0] === "点位") 说法.push("点位 → 没定下来（不拦）：" + r.拿不准);
        else if (是交叉表 && (p[0] === "品名" || p[0] === "数量"))
          说法.push(p[0] + " → 没定下来（交叉表不拦，坐标由「两个轴」那段定）：" + r.拿不准);
        else 要问的.push(p[0] + "：" + r.拿不准);
      }
      else if (r.有) { 列[p[1]] = r.列; 说法.push(p[0] + " → " + r.说法.join("；")); }
      else 说法.push(p[0] + " → 这张表没有");
    });

    /* 必须有的四样：品名和数量【都】没有，那就是没看懂这张表。
       单价没有很正常（价格库里有），单位没有也能从规格里反推。
       ⚠ 交叉表豁免这两条 —— 见上面那段注释，它的商品列和数量都不在「一列」里。 */
    if (!列.商品列 && !是交叉表) 要问的.push("品名那一列没定下来 —— 这是骨头，不能没有");
    if (!列.数量列 && !列.分布列 && !是交叉表)
      要问的.push("既没有数量列、也没指出数字挤在哪一格 —— 这单没法出");

    /* ★ 识别自己说不准的：分两种（老板 2026-08-12 定）。
         拦 —— 牵扯【数量 / 单位 / 单价】的。这三样错了就是钱错了，必须停下来。
         不拦 —— 牵扯【点位 / 品名】的，记下来就行：
                 点位这一步先不较真；品名对不上（攸县香干 vs 优质攸县香干）
                 本来就有另一条路管 —— 页面上弹个下拉让人自己挑，
                 在这儿拦住反而是把一件小事升级成拦路虎。
       ⚠ 只筛【识别自己写的那几句话】。列定不下来是另一回事，照旧拦
         （见上面的 定一列 和「品名那一列没定下来」），那是结构问题不是叫法问题。 */
    var 影响钱 = /数量|单位|单价|价格|总数|几斤|几板|几盒|多少|金额|合计/;
    /* ⚠ 提到了钱字眼、但说的是【那一列是空的】—— 那是它看了一眼的观察，不是认不出。
       「采购价、总金额这几列都是空的，不确定是不是全表都空」拦下来毫无意义：
       那几列我们本来就不用，价从价格库来。 */
    var 只是空的 = /(是|都|全)空|没有?填|留空|空白/;
    /* ★ 2026-08-12 大改：识别自己写的那几句话，【一律不拦整张单】。
       原来我把「有个地方拿不准」升级成了「整张表读不了」—— 49 份里有 18 份
       明明列全定得下来、单子出得来，却被我整张停掉了。
       老板原话：「识别不到，直接弹出来让他自己去选择就行了。」
       所以分工是：
         列定不下来 → 拦整单（下面 定一列 那几条），因为表根本读不了；
                      这种拦是【教一次就好】—— 人点一下存进读法本，以后自动。
         识别说不准 → 照常出单，把话摆在旁边让人扫一眼。
       牵扯钱的那几句挂「要紧」，页面上摆显眼点；其余小字带过。 */
    var 记下的 = [], 要紧的 = [];
    (指认.不确定的 || []).forEach(function (s) {
      var t = 字(s);
      if (!t) return;
      if (影响钱.test(t) && !只是空的.test(t)) 要紧的.push(t);
      else 记下的.push(t);
    });

    /* ══════ 交叉表：两个轴各定一次 ══════
       老板 2026-08-19：「交叉表就是这样子的，是不是一个正一个反嘛」——
       别碰上一种补一种。交叉表说到底就【两个轴】：一个摆商品、一个摆收货方，
       正反无非是谁横谁竖。所以两个轴各说一次，两种一次覆盖。

       ★ 为什么非要范围：这条路原来【从来没产生过】横轴起止两个字段，
         摊表那头 横起() 默认 2、横止() 默认吃到表尾 —— 尝元那张 18 列，
         从第 2 列一路吃到第 18 列，商品代码｜条码｜数量｜库存｜采购量 全当收货方：
           整个文件 → 总量 120,812,634（该 164）；只留 9 列 → 328（正好翻倍）
         老板：「两个总数要分开，不要把那个数量也读进去了」。

       ★ 为什么报字不报列号：报列号会数错位（8/11 御口福丢了三样货），报字不会。

       ★ 为什么竖的那个只要「第一个」：骨架只给 AI 看头 4 行 + 尾 2 行，
         竖排的名字拉一长列，中间全省了 —— 好好多那张它自己就说
         「中间省略了 9 行，看不到中间的店名，最后一个是不是樵晖店不敢定」。
         横排的挤在一行里，一眼看得全，所以两头都要。

       ⚠ 只在【矩阵】版式下做，明细表一个字都不碰（测试第一组专门钉这条）。 */
    var 矩阵读法 = null;
    if (指认.版式 === "矩阵") {
      var M = 指认.矩阵 || {};
      var 商 = M.商品 || {}, 收 = M.收货方 || {};
      var 横竖 = function (v) {
        var t = 字(v);
        if (/横/.test(t)) return "横";
        if (/竖|纵/.test(t)) return "竖";
        return "";
      };
      var 商排 = 横竖(商.怎么排), 收排 = 横竖(收.怎么排);

      if (!商排 || !收排)
        要问的.push("交叉表：没说清商品和收货方各自是【横着排还是竖着排】 —— 不敢猜，" +
                   "猜错就是把「数量」「采购量」这些也当成收货方，货会重复算");
      else if (商排 === 收排)
        要问的.push("交叉表：商品和收货方都说成「" + 商排 + "着排」—— 两个轴必须一横一竖，" +
                   "都朝一个方向的话那不是交叉表");
      else {
        /* 竖着排的轴：从第一个往下数，遇到合计行或空格就停。
           跟「数据从第一样货那行开始」是同一个路子 —— 那个已经在跑、验过的。 */
        var 是合计 = /^(总计|合计|小计|共计|总合计|合计数)$/;
        var 竖着数到底 = function (起行, 列) {
          var 止 = 起行;
          for (var i = 起行; i <= rows.length; i++) {
            var v = 字((rows[i - 1] || [])[列 - 1]);
            if (!v || 是合计.test(v)) break;
            止 = i;
          }
          return 止;
        };
        var 横着数到底 = function (行, 起列) {
          var r = rows[行 - 1] || [], 止 = 起列;
          for (var j = 起列; j <= r.length; j++) {
            var v = 字(r[j - 1]);
            if (!v || 是合计.test(v)) break;
            止 = j;
          }
          return 止;
        };
        /* 一个轴的两头 → {起, 止}。横的优先用 AI 报的尾巴，报不出／找不到才自己数。 */
        var 定一轴 = function (轴, 排, 名) {
          var 头 = 轴.第一个叫 ? 找格(rows, 轴.第一个叫) : null;
          if (!头) { 要问的.push("交叉表：表里找不到" + 名 + "的第一个「" + 字(轴.第一个叫) + "」"); return null; }
          var 尾 = 轴.最后一个叫 ? 找格(rows, 轴.最后一个叫) : null;
          var 横的 = (排 === "横");
          /* ★ 报了尾巴、也在表里找着了，可它跟头【不在同一条线上、或者跑到头前面去了】
               —— 那是真搞混了，必须拦。
             ⛔ 不许退回去「从头往后自己数」：2026-08-19 测出来，头尾写反的话
                自己数只会数出头那一格（横轴 8~8），前面几个店闷声漏掉，
                总量还照样对不上人也看不见。漏货比麻烦一次严重得多。
             ⚠ 只有【没报尾巴】或【报了但表里根本找不到】才自己数 ——
                竖着排的轴中间被骨架省了，看不到尾巴是常态，那种情况数到合计行为止。 */
          if (尾) {
            var 顺 = 横的 ? (尾.行 === 头.行 && 尾.列 >= 头.列)
                          : (尾.列 === 头.列 && 尾.行 >= 头.行);
            if (!顺) {
              要问的.push("交叉表：" + 名 + "的「" + 字(轴.第一个叫) + "」在第 " +
                         (横的 ? 头.行 + " 行第 " + 头.列 + " 列" : 头.行 + " 行第 " + 头.列 + " 列") +
                         "，可「" + 字(轴.最后一个叫) + "」却在第 " + 尾.行 + " 行第 " + 尾.列 +
                         " 列 —— 头尾对不上（说好是" + 排 + "着排的），不敢猜");
              return null;
            }
          }
          if (横的) {
            var 止列 = 尾 ? 尾.列 : 横着数到底(头.行, 头.列);
            return { 排: "横", 行: 头.行, 起: 头.列, 止: 止列, 头: 头 };
          }
          var 止行 = 尾 ? 尾.行 : 竖着数到底(头.行, 头.列);
          return { 排: "竖", 列: 头.列, 起: 头.行, 止: 止行, 头: 头 };
        };
        var 商轴 = 定一轴(商, 商排, "商品");
        var 收轴 = 商轴 ? 定一轴(收, 收排, "收货方") : null;

        if (商轴 && 收轴) {
          /* 摊矩阵 的转置分支拿的是【AI 看到的原表】坐标，转置后成对互换：
               表头行 ↔ 商品列　　数据行区间 ↔ 横轴列区间
             所以两种排法填的是同一组字段，只是各自装谁不一样。 */
          if (商排 === "竖") {
            /* 正的：商品竖着一列，收货方横着一排 */
            矩阵读法 = {
              转置: false,
              表头在第几行: 收轴.行,          /* 收货方那一行就是表头行 */
              商品列: 商轴.列,
              数据从第几行开始: 商轴.起, 数据到第几行: 商轴.止,
              横轴从第几列开始: 收轴.起, 横轴到第几列: 收轴.止,
              横轴是什么: "门店"
            };
          } else {
            /* 反的：商品横着一排，收货方竖着一列。转置后行列互换，正好复用同一套。 */
            矩阵读法 = {
              转置: true,
              表头在第几行: 商轴.行,          /* 商品那一行；转完变成商品列 */
              商品列: 收轴.列,                /* 收货方那一列；转完变成表头行 */
              数据从第几行开始: 收轴.起, 数据到第几行: 收轴.止,
              横轴从第几列开始: 商轴.起, 横轴到第几列: 商轴.止,
              横轴是什么: "门店"
            };
          }
          说法.push("交叉表 → 商品" + 商排 + "着排（" +
                   (商排 === "横" ? "第 " + 商轴.起 + "~" + 商轴.止 + " 列" : "第 " + 商轴.列 + " 列，第 " + 商轴.起 + "~" + 商轴.止 + " 行") +
                   "）　收货方" + 收排 + "着排（" +
                   (收排 === "横" ? "第 " + 收轴.起 + "~" + 收轴.止 + " 列" : "第 " + 收轴.列 + " 列，第 " + 收轴.起 + "~" + 收轴.止 + " 行") +
                   "）　两个轴之外一律不碰");
        }
      }
    }

    if (要问的.length) return { 要问的: 要问的, 说法: 说法, 记下的: 记下的, 要紧的: 要紧的 };

    var 读法 = {
      用第几张表: 指认.用第几张表 || 1,
      版式: 指认.版式 === "矩阵" ? "矩阵" : "明细",
      /* ★ 老的读法要「表头在第几行」。我们不问 AI 要，自己算：
         第一样货在第 N 行 → 数据从第 N 行开始 → 表头就当第 N-1 行。
         算出来的和猜出来的差别在于：算出来的有原文兜着，错了立刻看得见。 */
      表头在第几行: 起 ? (起.行 - 1) : 1
    };
    Object.keys(列).forEach(function (k) { 读法[k] = 列[k]; });
    /* ★ 交叉表的坐标【最后盖上去】—— 两个轴是拿名字找出来的，比按列名猜的准。
       尤其是 商品列 和 表头在第几行：上面那套是给明细表算的，
       在交叉表里（特别是反着排的）算出来的是错的，必须让这一份盖掉。 */
    if (矩阵读法) Object.keys(矩阵读法).forEach(function (k) { 读法[k] = 矩阵读法[k]; });

    return {
      读法: 读法,
      说法: 说法,
      /* 识别提过、但不拦单的两档：
           要紧的 —— 牵扯数量/单位/单价，页面上摆显眼点，人扫一眼再确定订单
           记下的 —— 点位/品名那类，小字带过，不打断人 */
      要紧的: 要紧的,
      记下的: 记下的,
      对账: {
        /* 新名字优先，老名字兜底 —— 提示词改过，本子里可能还存着老答案 */
        说好几行: 指认.数据区一共几行 || 指认.一共几样货 || null,
        第一样: 指认.第一样货叫 || "",
        最后一样: 指认.最后一样货叫 || "",
        数据从第几行: 起 ? 起.行 : null
      }
    };
  }

  /* ══════════════════════════════════════════════
     ④ 摊完之后再对一次账 —— 说好 13 样，就得摊出 13 样
     ══════════════════════════════════════════════
     ⚠ 这道账【不依赖表上写没写「任务数」】。很多单子没有那个数，
       但 AI 数得出「一共几样货」—— 拿它当校验码，比什么都通用。 */
  function 对账(合, 对账信息) {
    var 出 = [];
    if (!合 || !合.行) return ["一行都没摊出来"];
    var n = 合.行.length;
    /* ★ 拿【行数】对账，不拿【样数】（2026-08-12 查出来的误报根源）。
         三棵菜那张：AI 数 50 行，我们合并同名货后剩 11 样，一根毛没丢，
         却报了「说好 50 样只摊出 11 样」。误报比不报还糟 ——
         喊多了人就闭眼点确认，真出事那次也跟着被跳过去。
       ⚠ 也【不能】拿分布条数去比 —— 那是另一头的坑：
         御口福那种表一行就是一个商品，明细那一格里挤着十几段，
         13 行摊出 32 条分布，照样是假警报，方向还相反。
       两边唯一对得上的尺子是【代码处理了几行】。
       引擎-认表.js 的逐行点名账里就有：点名.应到。
       它对两种表都成立：三棵菜 50 行→应到 50；御口福 13 行→应到 13。
       拿不到这本账（比如矩阵表）就不对这道账，宁可不报也不许乱报。 */
    var 应到 = 合.点名 && 合.点名.应到;
    var 说 = 对账信息 && 对账信息.说好几行;
    if (说 && 应到 && +说 !== 应到)
      出.push("说好 " + 说 + " 行货，实际读了 " + 应到 + " 行 —— 差 " + Math.abs(说 - 应到) + " 行，先弄清楚再出单");

    var 第一 = 对账信息 && 对账信息.第一样;
    if (第一 && n && 平(合.行[0].品名).indexOf(平(第一)) < 0 && 平(第一).indexOf(平(合.行[0].品名)) < 0)
      出.push("说第一样是「" + 第一 + "」，摊出来第一样却是「" + 合.行[0].品名 + "」—— 开头多半被切掉了");

    var 最后 = 对账信息 && 对账信息.最后一样;
    if (最后 && n && 平(合.行[n - 1].品名).indexOf(平(最后)) < 0 && 平(最后).indexOf(平(合.行[n - 1].品名)) < 0)
      出.push("说最后一样是「" + 最后 + "」，摊出来最后一样却是「" + 合.行[n - 1].品名 + "」—— 尾巴多半被切掉了");

    return 出;
  }

  root.GM_按内容认单 = { 提示词: 提示词, 认: 认, 对账: 对账, 找格: 找格, 平: 平 };
})(typeof window !== "undefined" ? window : globalThis);
