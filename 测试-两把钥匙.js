/* 两把钥匙 —— node 测试-两把钥匙.js
   守的是老板 2026-08-28 定的「A」：

     「你要有一个判定，它到底是新单还是旧单。
     　之前的内容一定不能影响。原来的钥匙保留，两个钥匙一起。」

   为什么非要第二把钥匙 —— 8/28 那次事故的整条链，头一环就是钥匙：
     OCR 把表头「明细」抄成「限额」（一个词）
       → 老指纹（按表头文字算）跟着变
       → 读法本里 17 条一条都对不上，系统当它是没见过的新表
       → 掉进「按长相直接抓」那条近道
       → 把整格当成一个点位，19 行货压在一个点上出了单，钱还一分不差

   骨相钥匙按【每一列是什么类】算 —— 中文和字母数字的边界不会因为抄错字而变。 */
const path = require("path");
global.window = {};
["数据-价格库.js", "引擎-解析.js", "引擎-读结构.js", "引擎-认表.js",
  "引擎-碎片类.js", "引擎-认列.js", "试-轩宝真表.js"]
  .forEach(f => require(path.resolve(__dirname, f)));
const N = global.window.GM_整表碎片, T = global.window.GM_TABLE;
const 轩 = global.window.试轩宝;

let 过 = 0, 挂 = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(题, 真, 补) {
  if (真) { 过++; L("  ✅ " + 题); }
  else { 挂++; L("  ❌ " + 题 + (补 ? "　—— " + 补 : "")); }
}
const 份of = rows => [{ name: "x.png", grid: [{ n: 1, rows }] }];

/* ══════ 一、算得出来 ══════ */
L("\n【一、轩宝那张真单】");
{
  const k = N.钥匙(轩.rows);
  ok("算得出钥匙", !!k, k);
  ok("钥匙里写着有几列", /^8×/.test(k), k);
  ok("★ 一个表头字都没进钥匙（进了就会被 OCR 抄错带歪）",
    !/品名|规格|汇总|客户|数量|备注|参考/.test(k), k);
}

/* ══════ 二、★ 表头被抄错 —— 钥匙不许变 ══════ */
L("\n【二、★ 表头抄错一个词（8/28 事故的头一环）】");
{
  const 坏 = 轩.rows.map(r => r.slice());
  坏[3][6] = "限额";                       /* 「备注」→「限额」，跟 8/28 一模一样 */
  ok("★ 骨相钥匙没变（这是这把钥匙存在的全部理由）",
    N.钥匙(轩.rows) === N.钥匙(坏), N.钥匙(坏));
  /* 对照：老指纹会变 —— 不是要它变好，是钉住「为什么需要第二把」 */
  const 老甲 = T.表样指纹(份of(轩.rows)), 老乙 = T.表样指纹(份of(坏));
  ok("（对照）老指纹确实会变 —— 所以光靠它会把老客户当成新表",
    老甲 !== 老乙, "老指纹居然没变？那这测试就白写了");
}

/* ══════ 三、抬头多压一层 / OCR 加粗 ══════ */
L("\n【三、别的常见变化，钥匙也不许变】");
{
  const 多抬头 = [["打印时间：2026-08-29 07:12", "", "", "", "", "", "", ""]]
    .concat(轩.rows.map(r => r.slice()));
  ok("★ 抬头多压一层，钥匙不变（轩宝那张就是抬头厚栽的）",
    N.钥匙(轩.rows) === N.钥匙(多抬头), N.钥匙(多抬头));

  /* 2026-08-28 真跑 OCR 撞出来的：OCR 会把格子输出成 markdown 粗体 `**5**`。
     星号一带上，那列就从「数字」变成「码」，钥匙跟着变。 */
  const 加粗 = 轩.rows.map(r => r.map(c => /^\d+$/.test(String(c)) ? "**" + c + "**" : c));
  ok("★ OCR 给数字加了粗体星号，钥匙不变（真跑 OCR 撞出来的）",
    N.钥匙(轩.rows) === N.钥匙(加粗), N.钥匙(加粗));

  /* 但当中的星号是数据，一个都不许动 */
  ok("⛔ 只削首尾的星号：「6.5cm*厚1.5cm」当中那个是数据",
    N.量一列([["正方形6.5cm*厚1.5cm"], ["正方形7cm*厚2cm"]], 0, 1).值[0] === "正方形6.5cm*厚1.5cm");
}

/* ══════ 四、坏输入不许抛 ══════ */
L("\n【四、算不出来也不许把页面带塌】");
[null, undefined, [], [[]], [["", ""]]].forEach((x, i) => {
  let 炸 = null, r;
  try { r = N.钥匙(x); } catch (e) { 炸 = e; }
  ok("坏输入 " + i + " 不抛、返回字符串", !炸 && typeof r === "string", 炸 && 炸.message);
});

/* ══════ 五、页面真接上了没 ══════ */
L("\n【五、页面真接上了没】");
{
  const H = require("fs").readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  ok("页面加载了 引擎-认列.js", /<script src="引擎-认列\.js/.test(H));
  ok("页面有 骨钥匙()", /function 骨钥匙\(份\)/.test(H));
  ok("★ 骨钥匙算不出来要吞掉异常（近道坏了不许拖累主流程）",
    /function 骨钥匙\(份\)\{[\s\S]{0,600}?catch\(e\)\{ return ""; \}/.test(H));
  ok("★ 认表那趟两把钥匙都算了", /var fp=表样指纹\(份\);[\s\S]{0,200}?var 骨fp=骨钥匙\(份\);/.test(H));
  ok("★ 查本子两把一起查", /查读法本\(fp,骨fp\)/.test(H));
  ok("★ 老钥匙【先】查（存量记录一条都不许受影响）",
    /function 查读法本\(fp,骨\)\{[\s\S]{0,200}?if\(fp&&本\[fp\]/.test(H));
  ok("★ 存的时候把骨相钥匙一起记进去", /骨钥匙:骨\|\|""/.test(H));
  /* 套本子那条路上有两处要忘掉：人点「忘掉重认」、以及摊出来一行都读不懂时自动忘。
     两处都必须删【命中的那一条】—— 骨相钥匙兜到的可能是别的键，删 fp 等于没忘掉。
     ⚠ 「问读法对不对」那个窗里的 忘掉读法(fp) 不在此列：那是人刚点完「记住」，
       就存在 fp 键底下，删 fp 正是对的。 */
  /* 现在有三处要忘掉：人点「忘掉重认」、摊出来一行都读不懂、
     本子那份是按旧规矩认的（8/28 加的版本闸）。
     ⚠ 钉的是「都删命中的那一条」这个意图，不是死钉几处 —— 以后再加一处也该照这么删。 */
  ok("★ 套本子那条路上，忘掉的是【命中的那一条】（删错等于没忘掉）",
    (H.match(/忘掉读法\(记\.键\)/g) || []).length >= 2,
    "找到 " + (H.match(/忘掉读法\(记\.键\)/g) || []).length + " 处");
  ok("⛔ 钥匙只算一份（页面里没抄第二套）",
    (H.match(/function 骨钥匙\(/g) || []).length === 1);
}

L("\n════════════════════════");
L(挂 ? "❌ 挂了 " + 挂 + " 项（过 " + 过 + "）" : "✅ 全过 " + 过 + " 项");
process.exit(挂 ? 1 : 0);
