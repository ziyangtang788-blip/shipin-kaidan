"use strict";
global.window = global.window || {};
require("./引擎-解析.js");
require("./数据-价格库.js");
require("./引擎-抓取.js");
require("./引擎-读结构.js");
const G = window.GM_抓取, S = window.GM_STRUCT, P = window.GM_PARSE;

const 点 = "广东省中医院/大学城分院";

function 跑(规格, 备注) {
  const rows = [
    ["序号", "客户名称", "产品名称", "规格型号", "预定数量", "预定单位", "备注"],
    ["1", 点, "油炸豆腐", 规格, "100.00", "斤", 备注],
    ["2", 点, "千张/豆皮", "", "7.00", "斤", ""]
  ];
  const r = G.抓(rows);
  if (!r || !(r.行 || []).length) return { 炸: "一行都没读出来" };
  const out = S.读结构({ 抬头: {}, 行: r.行, 没读懂的: [], 表怎么读的: { 版式: "x" } });
  const L = (out.lines || [])[0] || {};
  let 量 = 0, 单 = "", 位 = "";
  (L.segs || []).forEach(g => { 量 += parseFloat(g.qty) || 0; 单 = 单 || g.unit || ""; 位 = 位 || g.code || ""; });
  return {
    行: (out.lines || []).length, 名: L.text || "", 名原: L.名原 || "",
    量, 单: 单 || L.unit || "", 位, 别: (P.别的货() || []).length
  };
}

/* 备注里能出现的真实写法 —— 今天两张真单上出过的都在里面 */
const 备注花样 = [
  "500串", "1件", "10板", "要5板", "共3板", "5板装", "分5板", "3板/份",
  "2个", "0.5斤", "100", "13+100", "13斤+100斤", "1.5斤",
  "大板", "小板", "中板豆腐2板", "小板豆腐1板", "阳山豆腐大板",
  "每一板都贴标签", "粉面", "水煮", "白豆腐干", "纯正豆香, 无发酸",
  "块形完整, 无发酸出水", "厚肉", "要新鲜"
];
/* 规格列里能出现的真实写法 */
const 规格花样 = [
  "400g/盒", "10-12斤/板", "50个/包", "7.2斤/板", "3.5-5斤/板",
  "180g/块", "250g/包", "90g", "435g", "1斤/斤", "15斤"
];

let 过 = 0, 败 = 0;
const 基 = 跑("", "");
if (基.炸) { console.log("• 别的东西不许动这四样\n    没过 ❌　基准单都读不出来：" + 基.炸); process.exit(1); }

function 查(标题, 花样, 位置, 查品名) {
  console.log("  " + 标题);
  花样.forEach(v => {
    const r = 位置 === "备注" ? 跑("", v) : 跑(v, "");
    const 坏 = [];
    if (r.炸) 坏.push("整张读不出来（" + r.炸 + "）");
    else {
      if (r.行 !== 基.行) 坏.push("行数 " + 基.行 + "→" + r.行);
      if (r.量 !== 基.量) 坏.push("数量 " + 基.量 + "→" + r.量);
      if (r.单 !== 基.单) 坏.push("单位 「" + 基.单 + "」→「" + r.单 + "」");
      if (r.位 !== 基.位) 坏.push("点位 「" + 基.位 + "」→「" + r.位 + "」");
      if (r.别 > 0) 坏.push("凭空多加了 " + r.别 + " 行");
      if (查品名 && r.名 !== 基.名) 坏.push("品名 「" + 基.名 + "」→「" + r.名 + "」");
      /* 纯品名（名原）任何时候都不许被污染 —— 学对照拿它当钥匙 */
      if (r.名原 && r.名原 !== 基.名原) 坏.push("纯品名 「" + 基.名原 + "」→「" + r.名原 + "」");
    }
    if (坏.length) { 败++; console.log("      ❌ 塞「" + v + "」　" + 坏.join("；")); }
    else 过++;
  });
}

/* ── 第二种表形：一格挤一串，备注写在点位名后面 ──────────
   8部 真单就是这种：「(广东省中医院/大学城分院-10板)100斤+(...)20斤」。
   ⚠ 这一种跟上面那种走的是【不同的代码】（断句器），
     只造上面那种表，8部 那个 100 斤丢掉的毛病一点都验不出来 ——
     2026-08-18 我第一版体检就是这么漏的。两种表形都得造。 */
function 跑一格(说明) {
  const 格 = "(" + 点 + (说明 ? "-" + 说明 : "") + ")100斤+(某某单位/午餐)20斤";
  const rows = [["商品", "订货明细"], ["油炸豆腐", 格], ["千张/豆皮", "(某某单位/午餐)7斤"]];
  const r = G.抓(rows);
  if (!r || !(r.行 || []).length) return { 炸: "一行都没读出来" };
  const out = S.读结构({ 抬头: {}, 行: r.行, 没读懂的: [], 表怎么读的: { 版式: "x" } });
  const L = (out.lines || [])[0] || {};
  let 量 = 0, 位 = "";
  (L.segs || []).forEach(g => { 量 += parseFloat(g.qty) || 0; 位 = 位 || g.code || ""; });
  return { 行: (out.lines || []).length, 名: L.text || "", 量, 位, 别: (P.别的货() || []).length };
}

function 查一格(花样) {
  console.log("  一格挤一串，说明写在点位名后面（" + 花样.length + " 种）");
  const 基2 = 跑一格("");
  if (基2.炸 || 基2.量 !== 120) {
    败++; console.log("      ❌ 基准就不对：" + (基2.炸 || ("数量 " + 基2.量 + "，该 120")));
    return;
  }
  花样.forEach(v => {
    const r = 跑一格(v);
    const 坏 = [];
    if (r.炸) 坏.push("整张读不出来");
    else {
      if (r.量 !== 基2.量) 坏.push("数量 " + 基2.量 + "→" + r.量);
      if (r.行 !== 基2.行) 坏.push("行数 " + 基2.行 + "→" + r.行);
      if (r.名 !== 基2.名) 坏.push("品名 「" + 基2.名 + "」→「" + r.名 + "」");
      if (r.别 > 0) 坏.push("凭空多加了 " + r.别 + " 行");
    }
    if (坏.length) { 败++; console.log("      ❌ 点位后面写「" + v + "」　" + 坏.join("；")); }
    else 过++;
  });
}

console.log("• 备注、规格里写什么都不许动【品名 数量 单位 点位】");
查("备注（" + 备注花样.length + " 种真实写法）", 备注花样, "备注", true);
查一格(备注花样);
/* ⚠ 规格这一组暂时不查品名 —— 见文件头。数量/单位/点位/行数/纯品名照查。 */
