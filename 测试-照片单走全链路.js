/* ── 把 OCR 存档变成格子表（跟页面同一份代码） ── */
function 存档变表(文件) {
  const j = JSON.parse(fs.readFileSync(文件, "utf8"));
  const 文 = (j.pages || []).map(p => {
    const 表 = (p.tables || []).map(t => t.content || "").join("\n\n");
    return 表 ? (p.markdown || "").replace(/\[tbl-\d+\.(md|html)\]\([^)]*\)/g, 表) : (p.markdown || "");
  }).join("\n\n");
  const g = T.markdown转表(文);
  return g && g[0] ? g[0] : null;      /* 整张工作表还给外面 —— 抬头文挂在它身上 */
}

/* ── 照页面的真顺序读一遍 ── */
function 照页面读(表) {
  const rows = 表.rows;
  const 让 = Z.近道该让开(rows);
  if (!让) {
    let r = null; try { r = G.抓(rows, {}); } catch (e) { r = null; }
    if (r && (r.行 || []).length) return { 谁: "老员工", 合: { 抬头: r.抬头, 行: r.行, 表怎么读的: r.表怎么读的 } };
  }
  let a = null; try { a = N.认列(rows); } catch (e) { a = null; }
  if (!a || a.要问的) return { 谁: "问人", 要问的: a && a.要问的 };
  const 备 = N.备好(rows, a, "");
  if (!备) return { 谁: "问人", 要问的: ["备不好"] };
  let 合 = null;
  try { 合 = T.摊平([{ n: 1, rows: 备.rows, 抬头文: 表.抬头文 }], 备.读法); } catch (e) { 合 = null; }
  if (!合 || !合.行.length) return { 谁: "问人", 要问的: ["摊不出"] };
  return { 谁: "新员工", 合: 合 };
}
/* 只核【号】和【数量】—— 带不带点位名是另一条规矩（老板 9/2「只要号」），
   这儿不掺和，免得两条规矩绑在一起，改一条另一条就红。 */
function 尾号(s) {
  const t = String(s || "");
  const m = t.match(/[A-Za-z0-9]+(?:-[0-9]+)?$/);
  return m ? m[0] : t;
}
function 摆成人话(合) {
  const B = S.读结构({ 抬头: 合.抬头 || {}, 行: 合.行, 表怎么读的: 合.表怎么读的 });
  return (B.lines || []).map(l => (l.segs || []).map(s => 尾号(s.code) + ":" + s.qty).join(","));
}

