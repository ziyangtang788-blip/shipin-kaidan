/* ============================================================
   碎片类 —— 一格切碎成几类，角色问一次，整列都会
   ============================================================

   老板 2026-08-27 拍板的底层逻辑（他要求我挖出来、确认过）：

     「核心不是说它是字母还是纯数字，不能靠这些，你要靠一整列这样子的学习机制。
     　你把它拆开，文字跟字母就可以拆开了。问这一整列是什么，
     　这一整列是字母是什么，这一整列文字是什么？
     　必须要这样子，你才能把以后所有的问题都去解决啊。」

   挖出来的那一句：
     ★ 中文和字母数字的边界，是唯一不会变的东西。★
   `5-9` 会变成 `A59-2`，`A59-2` 还会变成别的写法；
   但「这块是中文、那块是字母数字」永远不变。

   所以分工是：
     代码只干一件事：机械切碎，一个字都不猜
     人只答一次：    这一【类】碎片是什么（不是这一格）
     按整列记住：    以后这一列都这么读

   为什么非这么做（8-27 朱鲜生那张单当场撞的）：
     他家点位号从 `5-9` 换成了 `A59-2`，8/10 他亲手教的两条规矩一条都不中，
     19 格全切 0 段 → 整格当成一个地址名 → 数量没了 → 核对区一次摆 6 行让人点。
     大豆泡那格更糟：找不到 A59-2，退而把备注「大只的」当成了地址。
   ⛔ 那天我的第一反应是往断句里加「第 8 种写法」（引擎-解析.js F 条）。
      老板的评价是对的：来第九种还得再教一次，那不是源头。
      这个文件才是源头 —— 角色由人教，不由代码猜。

   ⚠ 这跟 8/24 已经跑通的「这一列是什么」是【同一套机制，降一层】：
       8/24 问的是「这张表第 4 列是什么」　（表格的列）
       这儿问的是「这一格里的字母数字是什么」（格子里的列）
     不是新东西，是把跑熟的那套用到格子内部。

   ⚠ 本文件【不碰切的逻辑之外的任何事】：不认客户、不存东西、不弹窗。
     存和问在页面里，跟 列读法 那套共用一份（CLAUDE.md：匹配逻辑只准一份）。
   ============================================================ */
(function (root) {
  "use strict";

  function 字(v) { return v === null || v === undefined ? "" : String(v).trim(); }

  /* 五个类。判据只认【中文 / 字母数字 / 数字+单位】这三条最原始的界限，
     没有任何跟客户、跟格式有关的东西 —— 这是这套机制的全部本钱。 */
  var 类们 = ["数字+单位", "中文带尾码", "纯中文", "纯码", "杂"];

  function 量正则() {
    var U = (root.GM_PARSE && root.GM_PARSE.单位字) ||
      "斤|板|盒|包|块|串|条|件|箱|袋|桶|个|只|份|把|碗|公斤|千克|kg|KG";
    return new RegExp("^([0-9]+(?:\\.[0-9]+)?)\\s*(" + U + ")$");
  }

  function 归类(w) {
    w = 字(w); if (!w) return "";
    if (量正则().test(w)) return "数字+单位";
    var 有中 = /[一-龥]/.test(w), 有码 = /[A-Za-z0-9]/.test(w);
    if (有中 && 有码) return "中文带尾码";
    if (有中) return "纯中文";
    if (有码) return "纯码";
    return "杂";
  }

  /* 一格 → [{文, 类}]。只按空白切，不认任何符号。 */
  function 切碎(格) {
    return 字(格).split(/\s+/).map(function (w) {
      var t = 字(w); if (!t) return null;
      return { 文: t, 类: 归类(t) };
    }).filter(Boolean);
  }

  /* ═══ 这一列有几类、稳不稳 ═══
     稳 = 这一列的碎片绝大多数都落在「过半格子里都有」的那几类上。
     老板 8/27 点名：「碧园的不要动」—— 碧源那一列杂音 49%，
     判据把它挡在外面，它照旧走老路，一个字不变。
     ⚠ 不稳的列本来就不该用这套：类都认不齐，问了也是白问。 */
  function 这列怎么样(格们) {
    格们 = (格们 || []).map(字).filter(Boolean);
    var 空 = { 类们: [], 主类: [], 稳: false, 杂音: 1, 格数: 格们.length };
    if (格们.length < 2) return 空;
    var 计 = {}, 出现在几格 = {}, 总 = 0;
    格们.forEach(function (格) {
      var 见 = {};
      切碎(格).forEach(function (b) {
        计[b.类] = (计[b.类] || 0) + 1; 总++;
        if (!见[b.类]) { 见[b.类] = 1; 出现在几格[b.类] = (出现在几格[b.类] || 0) + 1; }
      });
    });
    if (!总) return 空;
    var 主类 = Object.keys(出现在几格).filter(function (k) {
      return 出现在几格[k] >= 格们.length / 2;
    });
    var 杂 = 0;
    Object.keys(计).forEach(function (k) { if (主类.indexOf(k) < 0) 杂 += 计[k]; });
    var 比 = 杂 / 总;
    return {
      类们: Object.keys(计).sort(function (a, b) { return 计[b] - 计[a]; }),
      主类: 主类, 稳: 比 < 0.2, 杂音: Math.round(比 * 100) / 100, 格数: 格们.length
    };
  }

  /* 默认答案 —— 人还没教过时先按这个摆给他看，让他改。
     不是"猜格式"：这是几类碎片最常见的角色，人一眼看得出对不对。
     ⚠ 「纯码」默认成【备注】而不是地址 —— 光秃秃一串码，机械上分不出
       `A030`（中膳世家的地址）和 `400g`（朱鲜生的规格）。
       默认当地址的下场：朱鲜生「…A15 6盒 400g」变成两个地址配一个数量，整格切不出来。
       默认当备注，真是地址的那种会被【地址丢了】那道闸喊出来问一次 —— 问一次就记住了，
       比默认猜错、静默把规格当送货点强得多。 */
  function 角色表默认() {
    return { "数字+单位": "数量", "中文带尾码": "地址", "纯中文": "备注", "纯码": "备注", "杂": "不要" };
  }

  /* ═══ 照角色表切一格 ═══
     地址和数量【按出现顺序】一一配 —— 老板 2026-08-27 拍板：「按照顺序就可以。」
     ⚠ 判据卡死：地址个数必须等于数量个数，而且都 ≥1。对不上就返回 null，
       原样交回给调用方走老路 —— 谁配谁拿不准的时候，宁可不切。
     ⚠ 备注跟着它【前面那个数量】走（「16斤 午餐/切碎」）。
       备注照样带出去印在单子上，只是不参与对账 ——
       老板 8/27：丢掉不行，「大只的」「要大个的」「切碎」是发货的人要看的。 */
  function 照角色切(格, 角色表) {
    var 碎 = 切碎(格); if (!碎.length) return null;
    var R = 角色表 || 角色表默认();
    var 地址 = [], 数量 = [], 顺 = [], 量re = 量正则();
    碎.forEach(function (b) {
      var 是 = R[b.类] || "不要";
      if (是 === "数量") {
        var m = b.文.match(量re); if (!m) { 顺.push({ t: "n", w: b.文 }); return; }
        数量.push({ qty: parseFloat(m[1]), unit: m[2] }); 顺.push({ t: "q", i: 数量.length - 1 });
      } else if (是 === "地址") { 地址.push(b.文); 顺.push({ t: "a" }); }
      else if (是 === "备注") 顺.push({ t: "n", w: b.文 });
      /* 「不要」的直接扔，连备注都不进 */
    });
    if (!地址.length || 地址.length !== 数量.length) return null;
    var 出 = [];
    for (var i = 0; i < 地址.length; i++)
      出.push({ qty: 数量[i].qty, unit: 数量[i].unit, code: 地址[i], note: "" });
    var 上量 = -1;
    顺.forEach(function (x) {
      if (x.t === "q") 上量 = x.i;
      else if (x.t === "n" && 上量 >= 0 && 出[上量])
        出[上量].note = (出[上量].note ? 出[上量].note + " " : "") + x.w;
    });
    return 出;
  }

  /* 拿整列试一遍这份角色表，跟表上的总数对账 —— 页面靠它决定要不要问。
     料 = [{原文, 表上总数}]（跟 引擎-学分法.js 那份料一个形状，不另起一种） */
  function 整列试一遍(料, 角色表) {
    料 = (料 || []).filter(function (x) { return x && 字(x.原文); });
    var 切得出 = 0, 量过 = 0, 对 = 0;
    料.forEach(function (x) {
      var l = 照角色切(x.原文, 角色表);
      if (!l || !l.length) return;
      切得出++;
      if (x.表上总数 == null) return;
      量过++;
      var s = 0; l.forEach(function (g) { s += (+g.qty || 0); });
      if (Math.abs(s - x.表上总数) < 0.001) 对++;
    });
    return { 切得出: 切得出, 量过: 量过, 对: 对, 共: 料.length };
  }

  /* ═══ 自己先把所有可能的角色表试一遍，有几种能过账 ═══
     老板 8/23、8/24 那两条一直管着这儿：
       「账能证明的就没有问的必要。」
       「问哪些要问，你得衡量清楚，不是什么东西都是要问的。」
     所以问人之前先自己算：
       过账的组合 0 种 → 不问（问了也没用，原样走老路）
       　　　　　1 种 → 不问，直接用（账已经证明了）
       　　　　 ≥2 种 → 才问 —— 真有岔路，得人拍板

     ⚠ 只给【这一列真出现过的类】排列组合，没出现的类不参与。
       实测一列最多出现 5 类，4^5=1024 种，本地算得飞快。
     ⚠ 过账 = 整列每一格都切得出来，而且每一行都跟表上的总数对得上。
       表上没写总数的行验不了，量过=0 的一律不算过账 —— 没凭据就不许自作主张。 */
  var 角色们 = ["地址", "数量", "备注", "不要"];
  function 找角色表(料) {
    料 = (料 || []).filter(function (x) { return x && 字(x.原文); });
    if (料.length < 2) return [];
    var 出现 = {};
    料.forEach(function (x) { 切碎(x.原文).forEach(function (b) { 出现[b.类] = 1; }); });
    var 类 = Object.keys(出现);
    if (!类.length || 类.length > 6) return [];
    /* 「数字+单位」这一类只可能是数量或备注 —— 它当不了地址（地址里没有"3斤"这种东西），
       砍掉一半没意义的组合，也免得算出一堆荒唐解摆给人看。 */
    var 可选 = {};
    类.forEach(function (k) {
      可选[k] = (k === "数字+单位") ? ["数量", "备注", "不要"] : 角色们;
    });
    /* ★ 去重按【切出来的货】，不按角色表本身。
       不去重的下场（8-27 当场量到的）：朱鲜生那一列冒出 9 条"岔路"，
       其实全是同一个结果 —— 「纯中文」当备注还是当不要、「杂」当备注还是当不要，
       地址和数量一个字都不差，只是那句备注挂不挂上去。
       那不是岔路，摆 9 条给人挑纯属骚扰。
       ⚠ 指纹只取【地址+数量】：这两样错了才是事故，备注归属不同不算两条路。 */
    function 指纹(t) {
      var s = [];
      料.forEach(function (x) {
        var l = 照角色切(x.原文, t) || [];
        s.push(l.map(function (g) { return g.code + "=" + g.qty + (g.unit || ""); }).join("+"));
      });
      return s.join("|");
    }
    var 全部 = [], 表 = {};
    (function 排(i) {
      if (全部.length > 400) return;               /* 兜底，别把浏览器算住 */
      if (i >= 类.length) {
        var 账 = 整列试一遍(料, 表);
        if (账.切得出 === 料.length && 账.量过 > 0 && 账.对 === 账.量过) {
          var 抄 = {}; Object.keys(表).forEach(function (k) { 抄[k] = 表[k]; });
          全部.push(抄);
        }
        return;
      }
      可选[类[i]].forEach(function (r) { 表[类[i]] = r; 排(i + 1); });
    })(0);
    if (!全部.length) return [];
    /* 先排序【再】去重 —— 顺序反了，留下的就不是最像默认的那个 */
    var D = 角色表默认();
    全部.sort(function (a, b) {
      function 像(t) { var n = 0; 类.forEach(function (k) { if (t[k] === D[k]) n++; }); return n; }
      return 像(b) - 像(a);
    });
    var 成的 = [], 见 = {};
    全部.forEach(function (t) {
      if (成的.length >= 8) return;                /* 岔路多到这个地步，摆给人看也没法挑 */
      var fp = 指纹(t);
      if (!见[fp]) { 见[fp] = 1; 成的.push(t); }
    });
    return 成的;
  }

  root.GM_碎片 = {
    类们: 类们, 归类: 归类, 切碎: 切碎, 这列怎么样: 这列怎么样,
    角色表默认: 角色表默认, 照角色切: 照角色切, 整列试一遍: 整列试一遍,
    找角色表: 找角色表
  };
})(typeof window !== "undefined" ? window : globalThis);
