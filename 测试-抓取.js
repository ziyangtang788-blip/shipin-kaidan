/* 老板 2026-08-16：「你要把这个单子给他出出来，然后他只需要填你不认得的部分」
   所以这一卷考三件事，缺一不可：
     ① 这几样货【必须在单子上】—— 不许整行扔掉
     ② 它们的数量那格【是空的】—— 标成待填，别瞎猜一个数
     ③ 弹窗【从货名开头说】，并说清楚是去单子上填 */
function 卷问(名, rows, 该) {
  const r = G.抓(rows);
  const 行 = (r && r.行) || [];
  const 问 = (r && r.没抓到的) || [];
  const 头 = 问[0];

  const 在单子上 = 该.货.filter(n => 行.some(L => L.品名 === n));
  /* 数量得是「?」—— 页面认这个记号，会画成橙色行并拦住出单 */
  const 留了空 = 该.货.filter(n => 行.some(L =>
    L.品名 === n && (L.分布 || []).some(d => d.待填 && d.数量 === "?")));
  const 报了 = (头 && 头.待填的) || [];

  const 对 = 在单子上.length === 该.货.length &&
             留了空.length === 该.货.length &&
             头 && 头.要手工填 === true &&
             该.货.every(n => 报了.indexOf(n) >= 0) &&
             头.说.indexOf(该.货[0]) === 0;

  if (对) { 过++; console.log("  ✅ " + 名 + "　→ " + 头.说); }
  else {
    败++;
    console.log("  ❌ " + 名);
    console.log("       该：" + 该.货.join("、") + " 都在单子上、数量留空、弹窗从货名开头说");
    console.log("       实：在单子上 " + 在单子上.length + "/" + 该.货.length +
                "，留了空 " + 留了空.length + "/" + 该.货.length);
    console.log("       弹窗：" + (头 ? 头.说 : "（一条都没问）"));
  }
}

