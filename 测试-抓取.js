/* 一套规矩，各种表都得读对 —— node 测试-抓取.js
   拿今天出过事的真单当卷子：不分版式，只按长相抓。 */
global.window = global.window || {};
require("./引擎-解析.js");
require("./引擎-抓取.js");
const G = window.GM_抓取;

let 过 = 0, 败 = 0;
function 卷(名, rows, 该) {
  const r = G.抓(rows);
  const 行 = (r && r.行) || [];
  let 量 = 0, 点 = 0;
  行.forEach(L => (L.分布 || []).forEach(d => {
    const q = parseFloat(d.数量); if (!isNaN(q)) 量 += q;
    if (d.点位号 || d.点位名) 点++;
  }));
  量 = Math.round(量 * 100) / 100;
  const 对 = (该.样 === undefined || 行.length === 该.样) &&
             (该.量 === undefined || 量 === 该.量) &&
             (该.点 === undefined || 点 === 该.点);
  if (对) { 过++; console.log("  ✅ " + 名 + "　" + 行.length + " 样 / 量" + 量 + " / 点位" + 点); }
  else {
    败++;
    console.log("  ❌ " + 名 + "　读出 " + 行.length + " 样 / 量" + 量 + " / 点位" + 点 +
      "　（该 " + (该.样 !== undefined ? 该.样 + " 样" : "") + (该.量 !== undefined ? " / 量" + 该.量 : "") + (该.点 !== undefined ? " / 点位" + 该.点 : "") + "）");
    行.forEach(L => console.log("       " + L.品名 + " = " + (L.分布 || []).map(d => d.数量 + (d.单位 || "") + "@" + (d.点位号 || d.点位名 || "")).join(" + ")));
    if (r) console.log("       挑的列：" + JSON.stringify(r.挑的列));
  }
}

