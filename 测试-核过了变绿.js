/* ============================================================
   核过了就得变绿　★2026-08-11
   ============================================================
   老板 8/11 原话：
     「这个数据…它是对的，总数是没错的，我也检查过了，
     　但是我没有一个确定的按钮让它从红变成绿，它还是分开的。」

   毛病出在哪
   ----------
   「各段之和 ≠ 表上总数」的行会变红、被排到表格最上面。
   顶上那条提示里有个按钮，点了提示就消失（已处理["总数|品名"]=1）。
   可【判颜色的那段代码压根不看这个标记】—— 只看数字对不对。
   于是：提示没了，行还红着，还占在最上面。
   人辛辛苦苦核完一轮，单子看上去跟没核一样，等于这道闸白设。

   这个测试盯三件事：
     ① 判红的时候要看「人处理过没有」
     ② 处理过的行要掉回「没问题」那一堆（不能还分开摆在上面）
     ③ 按钮上写的是人真正要做的动作，不是替客户下结论
   ============================================================ */
const fs = require("fs");
const path = require("path");
const H = fs.readFileSync(path.join(__dirname, "配送开单台.html"), "utf8");

let 过 = 0, 败 = [];
function 该(说法, 真的) { if (真的) 过++; else 败.push(说法); }

/* ① 判红要看人处理过没有 */
该("判「本行对不上」时会看 已处理[\"总数|品名\"]",
  /本行对不上&&已处理\["总数\|"\+r\.L\.text\]\)\s*本行对不上=false/.test(H));
该("这一句排在上色之前（排后面就白写了）", (() => {
  const a = H.indexOf('本行对不上&&已处理["总数|"');
  const b = H.indexOf('else if(本行对不上) tr.className="q-diff"');
  return a > 0 && b > a;
})());

/* ② 处理过的要变回原色。
   ⚠ 2026-08-20 改：原来这条钉的是「红→绿的同时自动掉回下面那一堆」——
     那是 8/4「表格分两块」的行为。老板 8/20 把分块整个去掉了
     （「我想全部按照我给系统的单的顺序出」），所以「掉回下面」这件事不存在了。
     现在只剩「变回原色」要守：核过了就不许还挂着 q-diff。
     行不再挪位置，那是 测试-出单按原顺序.js 在钉。 */
该("核过了就不再上红色（class 是按当前状态现算的）",
  /else if\(本行对不上\) tr\.className="q-diff"/.test(H));
该("⛔ 不许再把行分堆重排（老板 8/20 定：按客户单子的原顺序）",
  !/待排\.push/.test(H));

/* ③ 按钮 */
该("按钮改成了「✓ 核过了，按各段发」", /✓ 核过了，按各段发<\/button>/.test(H));
该("不再叫「客户填错了」（那是在替客户下结论）", H.indexOf(">客户填错了</button>") < 0);
该("按钮还是那一个 skiptz，处理逻辑没动（照旧留痕进 判过的）",
  /class="btn ghost sm skiptz"/.test(H) && /判过的\.push\(\{行:名/.test(H));

/* ④ 一个数字都不许被改 —— 这个按钮只是「不再提醒」，不是拿总数去凑各段 */
{
  const i = H.indexOf('querySelectorAll("button.skiptz")');
  const 段 = H.slice(i, i + 700);
  该("点这个按钮不动任何数量（段里不许出现 .qty= 这种赋值）", !/\.qty\s*=/.test(段));
  该("点这个按钮会留痕（谁、什么时候、按的哪个数）",
    /判过的\.push/.test(段) && /人:\(OV\.who\|\|""\)/.test(段) && /时:new Date/.test(段));
}

if (败.length) {
  console.log("没过 " + 败.length + " 项：");
  败.forEach(s => console.log("  ✗ " + s));
  process.exit(1);
}
console.log("全部通过：" + 过 + " 项");
