let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a === b) pass++; else { fail++; L("  ✗ " + name + "\n      应该 " + b + "\n      实际 " + a); }
}
function 读一格(格) {
  const rows = [["商品名称", "数量", "单位", "送到哪"], ["白豆干", "3", "斤", 格]];
  const 合 = T.摊平([{ n: 1, rows: rows }],
    { 用第几张表: 1, 版式: "明细", 表头在第几行: 0, 商品列: 1, 数量列: 2, 单位列: 3, 分布列: 4 });
  const d = ((合.行[0] || {}).分布 || [])[0] || {};
  return { 号: d.点位号 || "", 名: d.点位名 || "" };
}

