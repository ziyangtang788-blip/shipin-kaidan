/* ── ⑦ 学过的排在通用前面，拿表上总数当裁判（2026-08-24 朱鲜生 8-24 那张单）──
   那张单的明细是「点位 数量」一行一个：
     中板豆腐 5 段 35+2+1+1+18 = 57 板
   通用七种只切得出【第一段】35 板 → 老写法 if(!segs.length) 认为「切出来了」→
   学过的「空格」规矩（8/10 就转正了）根本没上场 → 后面 22 板悄悄没了。 */
{
  require(path.join(家, "数据-切法规矩.js"));
  const T = (require(path.join(家, "引擎-认表.js")), global.window.GM_TABLE);
  const rows = [
    ["序号", "商品名", "总数", "明细"],
    ["1", "中板豆腐", "57板",
      "佛山市高明区沧江中学（学生菜类）（A-4） 35板\n广州市老人院上水院区（老人碎菜）5-9 2板 午餐\n" +
      "广州市老人院（上水院区）（老人糊餐）5-5 1板 午餐\n广州市老人院（上水院区）（老人菜泥）5-6 1板 午餐\n" +
      "广州市老人院（上水院区）（老人餐）5-3 18板 午餐"],
    ["2", "百页", "7斤", "佛山支队执勤一中队11-7 4斤\n佛山支队机动中队11-9 2斤\n佛山支队高明中队11-10 1斤"]
  ];
  const 摊 = 客户号 => T.摊平([{ n: 1, rows }],
    { 用第几张表: 1, 版式: "明细", 表头在第几行: 1, 商品列: 2, 合计列: 3, 分布列: 4, 客户号 });
  const 和 = L => Math.round((L.分布 || []).reduce((a, g) => a + (typeof g.数量 === "number" ? g.数量 : 0), 0) * 100) / 100;

  const 教过 = 摊("S2944");
  该("★ 学过的排前面：中板豆腐切出 5 段、加起来 57（老写法只切出 1 段 35）",
    !!教过 && (教过.行[0].分布 || []).length === 5 && 和(教过.行[0]) === 57);
  该("★ 学过的排前面：百页 3 段加起来 7（通用一段都切不出来）",
    !!教过 && 和(教过.行[1]) === 7);

  /* 别家 / 没选客户：学过的用不上，照旧走通用 —— 一个字都不许变 */
  const 别家 = 摊("");
  该("别家不受影响：学过的规矩只认自家客户号", !!别家 && 和(别家.行[0]) === 35);
}

/* ── ⑧ 教错了得能重教 —— 学过的排前面，唯一的风险就在这儿 ── */
