/* 学分法 —— 一格里挤着好几个点位，到底怎么分开（2026-08-24 老板 8/23-24 定的机制）

   钉三件事：
     ① 账能证明的一句不问　　「这种都没有问的必要，肯定是分成 9 份的」
     ② 没得选的也不问　　　　只有一种切得出来，问了也白问
     ③ 真有岔路才问　　　　　两种都跟表上对得上 → 得人拍板
   外加：页面上那块地方是【单独一块】，不再挤在会被盖掉的那一片。 */
const fs = require("fs"), path = require("path");
const 家 = __dirname;
global.window = global.window || {};
["数据-换算.js", "引擎-解析.js", "引擎-断句规矩.js", "引擎-学分法.js"]
  .forEach(f => require(path.join(家, f)));
const 学 = global.window.GM_学分法;

let 过 = 0, 挂 = [];
function 该(话, 真) { if (真) 过++; else 挂.push(话); }

/* ── ① 江云那种「(点位)数量+(点位)数量」：通用七种切得动，一句不该问 ── */
{
  const 料 = [
    { 原文: "(B163 南方明珠#火锅)0.5斤____+(B135 多宝#员工)3斤____", 表上总数: 3.5 },
    { 原文: "(B157 广美)9斤____+(A017 总部#员工)12斤____+(A811 新华店#月子)5斤____", 表上总数: 26 },
    { 原文: "(A849 增城店#月子)6斤____", 表上总数: 6 }
  ];
  const 法们 = 学.几种分法(料);
  该("江云那种写法：通用七种切得出来", 法们.length > 0 && 法们[0].分隔 === "通用");
  该("江云那种写法：整列的账全对得上", 法们[0].对 === 法们[0].量过 && 法们[0].量过 === 3);
  const 定 = 学.不用问吗(法们);
  该("★ 账能证明的一句不问", !!定 && 定.分隔 === "通用");
}

/* ── ② 一段都切不出来的（朱鲜生：六个点位、一个数量都没抄到）→ 没得教，留人工填 ── */
{
  const 料 = [
    { 原文: "佛山市南海区昆仑实业有限公司33-1 广州市老人院上水院区 (老人碎菜) 5-9", 表上总数: 20 }
  ];
  const 法们 = 学.几种分法(料);
  /* 切得出来也好、切不出来也好，都不许【硬把总数安在一个点位上】 */
  const 硬凑 = 法们.some(f => f.份.length === 1 && f.份[0] && f.份[0].qty === 20);
  该("★ 六个点位一个数量都没有 —— 绝不许把 20 硬安在一个点位上", !硬凑);
}

/* ── ③ 没得选就不问：只有一种切得出东西来 ── */
{
  const 料 = [{ 原文: "(A006 爱儿坊#教师餐)2斤+(B158 茂福#幼儿)9斤", 表上总数: 99 }];  // 账故意对不上
  const 法们 = 学.几种分法(料);
  const 切得出的 = 法们.filter(f => f.切得出 > 0);
  该("账对不上，但只有一种切得出来 → 不问（问了也白问）",
    切得出的.length !== 1 || !!学.不用问吗(法们));
}

/* ── ④ 立成规矩：形状要跟 数据-切法规矩.js 对得上，不然存进去也用不了 ── */
{
  const 条 = 学.立成规矩("S2944", { 分隔: "空格", 合连点: true, 例: "某某食堂A01 2斤" }, "某某食堂A01 2斤");
  该("立成规矩：带客户、分隔、模式、状态", !!条 && 条.客户 === "S2944" && 条.分隔 === "空格" && 条.状态 === "试用");
  该("立成规矩：把「点位被空格拆开要并回去」这面旗带上", 条.合连点 === true);
  该("立成规矩：通用那一种不该被存成规矩（它本来就是默认走的）",
    (() => { const c = 学.立成规矩("X", { 分隔: "通用", 合连点: false }, "x"); return !c || c.分隔 === "通用"; })());
}

/* ── ⑤ 挑例子：要挑最花的那一格，不是头一格 ── */
{
  const 料 = [{ 原文: "1斤**E004" }, { 原文: "35串**E018-01+25串**E002-01+10串**E020" }];
  该("★ 例子挑最花的那一格（拿头一格教，教出来的规矩管不住整列）",
    学.挑例子(料).原文.indexOf("+") >= 0);
}

/* ── ⑥ 页面：第 3 步是单独一块地，老弹窗退到后面当退路 ── */
{
  const H = fs.readFileSync(path.join(家, "配送开单台.html"), "utf8");
  该("页面上有第 3 步那块地（id=stp-learn）", /id="stp-learn"/.test(H));
  该("第 3 步平时收着（hidden）", /id="stp-learn"[^>]*hidden/.test(H));
  该("★ 第 3 步不写在 ocr-msg 那一片（那儿会被回头核的字盖掉）",
    /learn-body/.test(H) && !/ocr-msg[\s\S]{0,80}stp-learn/.test(H));
  该("新入口 学一次分法 接上了", /function 学一次分法\(/.test(H));
  该("老弹窗 问怎么切 还留着当退路（新的坏了不能把人卡死）", /function 问怎么切\(/.test(H));
  该("「分不开，我自己填」之后不许再弹老窗问同一件事", /成==="算了"/.test(H));
  该("引擎-学分法.js 排在 引擎-断句规矩.js 后面（要用 GM_CUT / GM_PARSE）",
    H.indexOf("引擎-学分法.js") > H.indexOf("引擎-断句规矩.js"));
}

if (挂.length) {
  console.log("没过 " + 挂.length + " 项：");
  挂.forEach(t => console.log("  ✗ " + t));
  process.exit(1);
}
console.log("全部通过：" + 过 + " 项");
