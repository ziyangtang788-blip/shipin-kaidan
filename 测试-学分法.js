  该("★ 第 3 步不写在 ocr-msg 那一片（那儿会被回头核的字盖掉）",
    /learn-body/.test(H) && !/ocr-msg[\s\S]{0,80}stp-learn/.test(H));
  该("新入口 学一次分法 接上了", /function 学一次分法\(/.test(H));
  该("老弹窗 问怎么切 还留着当退路（新的坏了不能把人卡死）", /function 问怎么切\(/.test(H));
