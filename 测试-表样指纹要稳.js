/* 表样指纹要稳 —— node 测试-表样指纹要稳.js

   老板 2026-08-18 问到的根子：
     「我现在有这么多真表，为什么反复的错？我的读法表为什么是 0？
       应该有很多的表格已经会读了呀。」

   查出来的答案：读法本按「表长什么样」当钥匙，可那把钥匙天天在变。
   拿他机器上 56 张真表量的 —— 8 家有多张单的客户，只有 3 家「教一次就够」。
   5 家全栽在指纹里的【每列长相】那一项上。铁证：

       轩宝　 5 行 → WWWNWNW【N】
       轩宝　18 行 → WWWNWNW【W】     ← 只差最后一列

   同一家、同一张表，只因为那天备注栏写的是数字不是文字，
   就被当成另一张表，重新问一遍 AI —— 记住的读法一次都套不上，
   所以读法本永远是空的。

   「每列长相」量的是【这一天那一列装了什么】：备注写没写字、
   明细那格今天长不长、这单有几行货。这些天天变，可表的结构一个字没变。

   现在指纹只认结构：【列数 + 表头词】。这里钉三条：
     ① 同一张表，内容变了，指纹不许变
     ② 真换了表（列数或表头不同），指纹必须变
     ③ 指纹太弱（没表头、列又少）→ 不给指纹，照旧每次问，
        不许拿别人的读法开自己的单 */
global.window = global.window || {};
require("./引擎-解析.js");
require("./引擎-认表.js");
const T = window.GM_TABLE;

let pass = 0, fail = 0;
const L = s => process.stdout.write(Buffer.from(s + "\n", "utf8"));
function ok(name, got, want) {
  const a = JSON.stringify(got), b = JSON.stringify(want);
  if (a === b) pass++; else { fail++; L("  ✗ " + name + "\n      应该 " + b + "\n      实际 " + a); }
}
const 指纹 = rows => T.表样指纹([{ grid: [{ n: 1, rows: rows }] }]);

L("═══ ① 同一张表，内容变了，指纹不许变 ═══");
/* 轩宝那两张的骨架：8 列，表头 品名/规格/单位/数量/备注 */
const 轩宝头 = ["序号", "品名", "规格", "单位", "数量", "小计", "备注", "线路"];
const 轩宝甲 = [轩宝头,
  ["1", "尝元韧豆腐", "5斤/板", "板", "3", "28.5", "2", "A"],
  ["2", "千张", "薄", "斤", "6", "19.8", "3", "A"]];
/* 同一张表，只是那天备注写了字（原来这一列会从 N 变 W，指纹就变了） */
const 轩宝乙 = [轩宝头,
  ["1", "尝元韧豆腐", "5斤/板", "板", "3", "28.5", "要厚的", "A"],
  ["2", "千张", "薄", "斤", "6", "19.8", "午餐", "A"],
  ["3", "老豆腐", "", "斤", "10", "33", "切块", "B"]];
ok("★ 备注一天数字一天文字 —— 指纹一样", 指纹(轩宝甲) === 指纹(轩宝乙), true);

/* 行数差很多也不许变（5 行 vs 18 行） */
const 轩宝丙 = [轩宝头].concat(Array.from({ length: 17 }, (_, i) =>
  ["" + (i + 1), "货" + i, "", "斤", "" + (i + 1), "" + i, "", "A"]));
ok("★ 5 行 vs 18 行 —— 指纹一样", 指纹(轩宝甲) === 指纹(轩宝丙), true);

/* 明细那一格今天短明天长（原来 W ↔ S 会翻） */
const 明细头 = ["序号", "商品名", "总数", "明细"];
const 短 = [明细头, ["1", "水豆腐", "1板", "西樵2-8 1板"], ["2", "老豆腐", "3斤", "妇幼4-1 3斤"], ["3", "香干", "2斤", "财政局26-2 2斤"]];
const 长 = [明细头,
  ["1", "中板豆腐", "24板", "广州市天河区人民政府沙河街道（执法队饭堂）13-2 广州市老人院上水院区（老人碎菜）5-9 广州市老人院（上水院区）（老人餐）5-3 1板 5板 18板"],
  ["2", "老豆腐", "3斤", "妇幼4-1 3斤"], ["3", "香干", "2斤", "财政局26-2 2斤"]];
ok("★ 明细格今天短明天长 —— 指纹一样", 指纹(短) === 指纹(长), true);

/* 表头词读出来的先后顺序不同（OCR 常有）也不许变 */
const 乱序 = [["商品名", "序号", "明细", "总数"], ["水豆腐", "1", "西樵2-8 1板", "1板"],
["老豆腐", "2", "妇幼4-1 3斤", "3斤"], ["香干", "3", "财政局26-2 2斤", "2斤"]];
ok("表头词顺序不同 —— 指纹一样", 指纹(短) === 指纹(乱序), true);

L("");
L("═══ ② 真换了表，指纹必须变 ═══");
const 少一列 = [["序号", "品名", "规格", "单位", "数量", "小计", "备注"],
["1", "尝元韧豆腐", "5斤/板", "板", "3", "28.5", ""],
["2", "千张", "薄", "斤", "6", "19.8", ""]];
ok("★ 列数不一样 —— 指纹必须不同", 指纹(轩宝甲) !== 指纹(少一列), true);
const 换表头 = [["序号", "商品名称", "预定数", "单位", "门店", "小计", "备注", "线路"],
["1", "尝元韧豆腐", "3", "板", "A店", "28.5", "", "A"],
["2", "千张", "6", "斤", "B店", "19.8", "", "A"]];
ok("★ 表头不一样 —— 指纹必须不同", 指纹(轩宝甲) !== 指纹(换表头), true);

L("");
L("═══ ③ 指纹太弱的，一律不给（不许拿别人的读法开自己的单）═══");
/* 实测「2列·无表头」被 5 家客户共用 —— 一家教的会套到另外 4 家头上 */
const 两列无头 = [["水豆腐", "3斤"], ["老豆腐", "5斤"], ["香干", "2斤"]];
ok("★ 没表头 + 只有 2 列 → 不给指纹", 指纹(两列无头), "");
const 三列无头 = [["水豆腐", "3", "斤"], ["老豆腐", "5", "斤"], ["香干", "2", "斤"]];
ok("★ 没表头 + 3 列 → 也不给", 指纹(三列无头), "");
const 四列无头 = [["水豆腐", "3", "斤", "西樵2-8"], ["老豆腐", "5", "斤", "妇幼4-1"], ["香干", "2", "斤", "财政局26-2"]];
ok("没表头但有 4 列 → 给（列数够多，还认得出）", 指纹(四列无头) !== "", true);
ok("有表头的照给", 指纹(短) !== "", true);

L("");
L("═══ ④ 拿真表兜一遍（有就跑，没有就跳过）═══");
(function () {
  const fs = require("fs"), path = require("path");
  const dir = path.join(process.env.USERPROFILE || "C:/Users/李正", "Desktop", "OCR缓存");
  if (!fs.existsSync(dir)) { L("  （本机没有 OCR缓存，跳过，不算错）"); return; }
  const 按家 = {};
  fs.readdirSync(dir).forEach(f => {
    let 表 = null;
    try { 表 = T.markdown转表(fs.readFileSync(path.join(dir, f), "utf8")); } catch (e) { }
    if (!表 || !表.length || !表[0] || !表[0].rows) return;
    let fp = "";
    try { fp = T.表样指纹([{ grid: 表 }]) || ""; } catch (e) { }
    if (!fp) return;
    const 家 = f.split("__")[0];
    if (/^hit-/.test(家)) return;
    (按家[家] = 按家[家] || []).push(fp);
  });
  let 稳 = 0, 变 = 0;
  Object.keys(按家).forEach(家 => {
    const a = 按家[家]; if (a.length < 2) return;
    (new Set(a).size === 1 ? 稳++ : 变++);
  });
  L("  多张单的客户：教一次就够 " + 稳 + " 家，每张都变 " + 变 + " 家　（改之前是 3 / 5）");
  ok("比改之前更稳", 稳 >= 4, true);
})();

L("");
L(fail ? ("有 " + fail + " 项没过（通过 " + pass + " 项）") : ("全部通过：" + pass + " 项"));
process.exit(fail ? 1 : 0);
