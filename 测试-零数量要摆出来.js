/* 测试-零数量要摆出来.js —— node 测试-零数量要摆出来.js
   ============================================================
   2026-08-19 老板拿碧源 8-20 那张单撞到的：

     水豆腐（5斤装）　总数 12板+0斤
       明细 (252#02)4板 +(256#05-1砖)0斤 +(79)6板 +(91)1板 +(99#01)1板
       → 「(256#05-1砖)0斤」那一段【被静默丢掉，一句话都没有】

     水豆腐（7斤装）　总数 0板
       明细 (231-8斤)0板
       → 整行全是 0 → 报「没写数量」，弹出来了

   老板原话：「这个没有弹出来，为什么？它总数上也有写加零斤，
              这种一个零的话，特别要注意的都是要弹出来的，
              反而下面那个水豆腐零板那里又有弹出来。」

   我先做成了一条提醒条，老板看过之后说【不要提醒】：
     「我不要一个提示。我需要的是，你把他写明的那一行整一行拉出来，做一个品类，
       让他自己在这个品类里面去选东西，然后自己填数量，
       如果他觉得不要，就自己删掉就可以了。」

   所以现在照「没看清」那一档办：
     · 那一段【留在单子里】当一行（收尾里挂 零数量 记号）
     · 商品照旧能选、数量框【空着】等人填、不要就点那一行的「删」
     · 行标橙色，一眼看得见要处理

   ⚠ 数量框必须空着，不许摆个 0 在那儿 —— 摆 0 人会当成已经填好，
     一路点过去就把这一段放走了，客户到底要不要没人问过。
   ⚠ 老板 8/2「填 0 = 今天不要」没被推翻：0 照旧不进金额，
     只是从「机器替你扔掉」变成「摆出来由你拍板」。
   ⚠ 整行全 0 的照旧整行丢 —— 不然一张全 0 的单会摆出一堆空行让人一个个删。
   ============================================================ */
const path = require("path");
global.window = {};
["./数据-价格库.js", "./对照-预置.js", "./数据-常用规格.js", "./数据-换算.js",
 "./引擎-解析.js", "./引擎-匹配.js", "./引擎-读文件.js", "./引擎-读结构.js"].forEach(f => require(path.resolve(__dirname, f)));
const P = global.window.GM_PARSE;

let 过 = 0, 挂 = 0;
function ok(名, 条件, 说) {
  if (条件) { 过++; console.log("  ✅ " + 名 + (说 ? "　" + 说 : "")); }
  else { 挂++; console.log("  ❌ " + 名 + (说 ? "　" + 说 : "")); }
}

/* 表格路的入口：读结构 → 收尾(out, true)。
   老板 8/19 划的线在这儿 —— 客户写 0 的段，只有【表格路】才留。 */
const 读结构 = () => global.window.GM_STRUCT.读结构;

/* ══════ 一、★ 碧源那一行：有 0 段，其余有货（表格路）══════ */
console.log("\n【一、表格路：明细里写的 0 段一段都不许扔 ★ 碧源 8-20】");
(function () {
  const r = 读结构()({ 行: [{
    品名: "水豆腐（5斤装）", 单位: "板", 表上总数: 12,
    分布: [{ 号: "252#02", 数: 4 }, { 号: "256#05-1砖", 数: 0, 位: "斤" },
           { 号: "79", 数: 6 }, { 号: "91", 数: 1 }, { 号: "99#01", 数: 1 }]
  }]});
  const ls = r.lines || [];
  const 零 = P.零数量的 ? P.零数量的() : [];
  /* 0 那段单位是「斤」、其余是「板」，「单位不同拆两行」那条老规矩正好把它拆成独立一行
     —— 也就是老板要的「把那一整行拉出来做一个品类」。 */
  const 正 = ls.find(x => (x.segs || []).some(g => !g.零数量)) || {};
  const 零行 = ls.find(x => (x.segs || []).some(g => g.零数量));

  ok("★ 0 那一段留下来了，成了单子里的一行（原来整段被扔）", !!零行,
     "出了 " + ls.length + " 行");
  ok("正常那一行照旧 12 板", 正.qty === 12 && 正.unit === "板", 正.qty + (正.unit || ""));
  ok("正常那一行 4 段", (正.segs || []).length === 4, (正.segs || []).length + " 段");
  ok("0 那一行挂着记号（页面靠它把数量框空出来）",
     零行 && (零行.segs || []).every(g => g.零数量));
  ok("0 那一行数量还是 0，不许替人编一个", 零行 && 零行.qty === 0, (零行 || {}).qty);
  ok("点位带着（人要知道是哪个点）",
     零行 && /256#05/.test(String((零行.segs || [])[0].code || "")),
     零行 ? JSON.stringify((零行.segs || [])[0].code) : "");
  ok("名单里也记了一笔", 零.length === 1 && /256#05/.test(String(零[0].点位 || "")),
     JSON.stringify(零));
})();

/* ══════ 二、文字路：8/2 的老规矩一个字不许动 ══════ */
console.log("\n【二、文字路：0 照旧扔（8/2 老规矩）】");
(function () {
  const ls = P.parseOrder("水豆腐（7斤装）\t0板\t(231-8斤)0板");
  ok("整行不出货", ls.length === 0, "出了 " + ls.length + " 行");
  ok("照旧进「没写数量的」", (P.没写数量的() || []).some(x => /水豆腐/.test(String(x))),
     JSON.stringify(P.没写数量的()));
})();

/* ══════ 三、没有 0 的单子，一声都不许吭 ══════
   误报比漏报还烦 —— 天天弹，人就不看了，真出事那次也被当成狼来了。 */
console.log("\n【三、没有 0 就别吵】");
(function () {
  读结构()({ 行: [{ 品名: "水豆腐", 单位: "板",
    分布: [{ 号: "252#02", 数: 4 }, { 号: "79", 数: 6 }] }]});
  ok("不记任何东西", (P.零数量的 ? P.零数量的() : []).length === 0);
})();

/* ══════ 四、「没看清」的不算 0 ══════
   识别拿不准写的 ?，那是另一档（数量框空着等人填），别混进 0 这一堆。 */
console.log("\n【四、? 不是 0，别混一起】");
(function () {
  读结构()({ 行: [{ 品名: "水豆腐", 单位: "板",
    分布: [{ 号: "252#02", 数: "?" }, { 号: "79", 数: 6 }] }]});
  ok("? 不进零数量名单", (P.零数量的 ? P.零数量的() : []).length === 0,
     JSON.stringify(P.零数量的 ? P.零数量的() : []));
  ok("? 照旧进「没看清的」", (P.没看清的() || []).length >= 1);
})();

/* ══════ 五、每跑一遍清一次，不许串上一单 ══════ */
console.log("\n【五、不许串上一单的账】");
(function () {
  读结构()({ 行: [{ 品名: "水豆腐", 单位: "板",
    分布: [{ 号: "252#02", 数: 4 }, { 号: "256#05", 数: 0 }] }]});
  ok("这一单记了 1 条", (P.零数量的 ? P.零数量的() : []).length === 1);
  读结构()({ 行: [{ 品名: "千张", 单位: "斤", 分布: [{ 号: "79", 数: 5 }] }]});
  ok("下一单干净的 → 清零", (P.零数量的 ? P.零数量的() : []).length === 0,
     JSON.stringify(P.零数量的 ? P.零数量的() : []));
})();

/* ══════ 六、页面得真把它摆出来 ══════
   引擎记下来了、页面不显示，等于没修 —— 这个项目栽过好几次
   「页面死了体检却全绿」。node 跑不了页面，只能读源码钉住。 */
console.log("\n【六、页面上真摆成一行了吗】");
(function () {
  const h = require("fs").readFileSync(path.resolve(__dirname, "配送开单台.html"), "utf8");
  ok("行上带着 零数量 记号", /零数量:!!g\.零数量/.test(h));
  ok("算出了「这一行是 0」", /var 本行是零=/.test(h));
  /* ★ 数量框必须空着 —— 摆个 0 在那儿人会当成填好了，一路点过去就放走了 */
  ok("★ 数量框空着等人填（不许摆 0）", /本行没看清\|\|本行是零\?""/.test(h));
  ok("有「填数量」的提示", /本行是零\?' placeholder="填数量"/.test(h));
  ok("行标成橙色（跟没看清同一档）", /本行是零\) tr\.className="q-blur"/.test(h));
  ok("话说明白了：填一个或者删掉", /要发就填个数量，确定不要就点左边的「删」/.test(h));
  /* ⛔ 老板明说不要提醒条 —— 别哪天又有人加回去 */
  ok("⛔ 没有再摆提醒条（老板说不要提示）", !/个点位写的是 0/.test(h));
})();

/* ══════ 七、★ 两条路各归各：8/2 那条规矩只管文字路 ══════
   老板 2026-08-19 说明白了：
     「做个补丁，专门针对这种表格。只要备注明细里面有的，全部都不能扔。
       我之前说的 8 月 2 号，它是针对于文字那条路的，
       并不是针对这个表格这条路的。」

   两条路本来就是两回事：
     文字路 —— 客户微信里常年挂着一份「常订品名单」（三角豆泡斤、豆腐串串…），
              只有名字没数量、或者写着 0。那些不是今天的货，该扔。这是 8/2 定的。
     表格路 —— 明细列里【写出来的每一段】都是客户当天填给你的，
              一段都不许扔。要不要发，是人看了之后拍板的事。

   ⚠ 这也正是 8/18 查到的那个根子：两条路共用最后那道「收尾」，
     而那套规矩本来是给文字路写的（文字没有列），却也压在表格路上。 */
console.log("\n【七、两条路各归各 ★ 老板 8/19 定的】");
(function () {
  /* 表格路：读结构 → 收尾，明细里的 0 段一段都不许扔 */
  const S = require(path.resolve(__dirname, "./引擎-读结构.js")) || global.window.GM_STRUCT;
  const 读结构 = global.window.GM_STRUCT.读结构;
  const r = 读结构({ 行: [{
    品名: "水豆腐（5斤装）", 单位: "板", 表上总数: 12,
    分布: [{ 号: "252#02", 数: 4 }, { 号: "256#05-1砖", 数: 0, 位: "斤" },
           { 号: "79", 数: 6 }, { 号: "91", 数: 1 }, { 号: "99#01", 数: 1 }]
  }]});
  const 全段 = (r.lines || []).reduce((a, L) => a.concat(L.segs || []), []);
  ok("★ 表格路：5 段一段都没少", 全段.length === 5, "剩 " + 全段.length + " 段");
  const 零段 = 全段.filter(g => (g.qty || 0) === 0);
  ok("0 那段还在", 零段.length === 1, JSON.stringify(零段.map(g => g.code)));
  ok("0 那段挂着记号（页面靠它空出数量框）", 零段[0] && 零段[0].零数量 === true);

  /* 表格路：整行全 0 的也不许扔 —— 明细里写了就是写了 */
  const r2 = 读结构({ 行: [{
    品名: "水豆腐（7斤装）", 单位: "板", 表上总数: 0,
    分布: [{ 号: "231-8斤", 数: 0 }]
  }]});
  const 段2 = (r2.lines || []).reduce((a, L) => a.concat(L.segs || []), []);
  ok("★ 表格路：整行全 0 也留着（客户明细里写了就是写了）",
     (r2.lines || []).length === 1 && 段2.length === 1,
     (r2.lines || []).length + " 行 / " + 段2.length + " 段");

  /* 文字路：8/2 的老规矩一个字不许动 */
  const ls = P.parseOrder("水豆腐\t(252#02)4板+(256#05)0斤");
  const 文字段 = ls.reduce((a, L) => a.concat(L.segs || []), []);
  ok("文字路：0 段照旧扔掉（8/2 老规矩不动）",
     文字段.length === 1 && 文字段[0].code === "252#02",
     JSON.stringify(文字段.map(g => g.code + ":" + g.qty)));
  const ls2 = P.parseOrder("三角豆泡斤\n豆腐串串\n炸腐竹包\n千张3斤");
  ok("文字路：常订名单照旧不进单（8/2 的原场景）",
     ls2.length === 1 && /千张/.test(ls2[0].text),
     JSON.stringify(ls2.map(L => L.text)));
})();

/* ══════ 八、⛔ 同一段不许被两条规矩各摆一行（2026-08-21 江云）══════
   老板拖江云 8-21 那张图，「小豆腐卜」那行冒出两条一模一样的：

     小豆腐卜  14.5斤 │ (B128 阅景#幼儿-20个)0斤 + (A018 德艺#教师)1斤 + …

   那一段 `(B128 阅景#幼儿-20个)0斤` 同时撞上两条规矩：
     · 8/19「客户写的 0 不许扔」（格子路）→ 留成一行，数量空着让人填
     · 8/17「备注里写着别的单位就直接加进来」→ 照同一段【另加一行】，20 个
   两条都在管同一段货，各出一行 → 单子上重复。

   ★ 老板 2026-08-21 定：【留下面那个】—— 待在原位那一行留着，顶上那个「手动加的」去掉。
     顶上那行是往队首插的（8/3 定的「添加直接在上面添加」），它跟原位那行长得一样。
     他还定了两条：
       · 数量【不要替他填】—— 框空着，他自己手动加
       · 点位里的「-20个」要挪走 → 点位就是「B128 阅景#幼儿」，
         不挪的话点位册里会多出一个「阅景#幼儿-20个」的假点位

   ⚠ 只在【同一个商品 + 同一个点位】两边都命中时才让路。
     别的 0 段照旧留着（碧源那条 8/19 的硬线一个字不动）。 */
console.log("\n【八、⛔ 同一段不许被两条规矩各摆一行（8/21 江云「小豆腐卜」）】");
(function () {
  const r = 读结构()({ 行: [{
    品名: "小豆腐卜", 单位: "斤", 表上总数: 14.5,
    分布: [{ 号: "B128", 名: "阅景#幼儿-20个", 数: 0, 位: "斤" },
           { 号: "A018", 名: "德艺#教师", 数: 1 },
           { 号: "A805", 名: "镇南#教师", 数: 1.5 }]
  }]});
  const L = (r.lines || [])[0];
  const 别 = P.别的货 ? P.别的货() : [];
  const 零 = P.零数量的 ? P.零数量的() : [];
  const 那段 = L && (L.segs || []).find(g => /B128/.test(g.code || ""));

  ok("★ 顶上那行不再加了（别的货名单里没有它）", 别.length === 0, JSON.stringify(别));
  ok("★ 原位那一行留着（照旧进零数量名单）", 零.length === 1, JSON.stringify(零));
  ok("★ 那一段还在单子上", !!那段, JSON.stringify((L && L.segs || []).map(g => g.code)));
  ok("★ 数量框空着（不许替他填 20）", 那段 && !(那段.qty > 0) && 那段.零数量 === true,
     JSON.stringify(那段));
  ok("★ 点位里的「-20个」挪走了", 那段 && 那段.code === "B128 阅景#幼儿", 那段 && 那段.code);
  ok("★ 「20个」落进备注，一个字没丢", 那段 && /20个/.test(那段.note || ""), 那段 && 那段.note);
  ok("有货的两段照旧在", L && (L.segs || []).length === 3,
     JSON.stringify((L && L.segs || []).map(g => g.qty)));

  /* ⛔ 碧源那条硬线一个字不许动：0 段【没有】撞上别的货时，照旧留着 */
  const r2 = 读结构()({ 行: [{
    品名: "水豆腐（5斤装）", 单位: "板", 表上总数: 12,
    分布: [{ 号: "252#02", 数: 4 }, { 号: "256#05-1砖", 数: 0, 位: "斤" }]
  }]});
  ok("⛔ 没撞上别的货的 0 段，照旧摆出来（碧源 8/19）",
     (P.零数量的 ? P.零数量的() : []).length === 1,
     JSON.stringify(P.零数量的 ? P.零数量的() : []));
})();

console.log("\n════════════════════════");
