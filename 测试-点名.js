/* 点名 —— 表里每一格都得有归宿，剩下的必须喊出来
   node 测试-点名.js

   老板 2026-08-14 定的：
     「表里每个字都得有个归宿，只有三种：认领了 / 明确没用 / 不懂就弹出来问。没有第四种。」
     「剩下的格子先自己判断有没有货，的确没货就没必要问。」
     「拿不准的可以弹出来问，但是一定不能少，不能漏。」

   成功的标准只有一条：不漏。
   所以下面每道题只问两件事：
     ① 该读出来的货，一样不少（数量加起来对得上）
     ② 该问的问了、不该问的没问 */
global.window = global.window || {};
require("./引擎-解析.js");
require("./引擎-抓取.js");
const G = window.GM_抓取;

let 过 = 0, 败 = 0;
function 卷(名, rows, 该) {
  const r = G.抓(rows) || { 行: [], 没抓到的: [] };
  const 行 = r.行 || [], 问 = r.没抓到的 || [];
  let 量 = 0;
  行.forEach(L => (L.分布 || []).forEach(d => {
    const q = parseFloat(d.数量); if (!isNaN(q)) 量 += q;
  }));
  量 = Math.round(量 * 100) / 100;

  const 错 = [];
  if (该.样 !== undefined && 行.length !== 该.样) 错.push(`样数 ${行.length}≠${该.样}`);
  if (该.量 !== undefined && 量 !== 该.量) 错.push(`总量 ${量}≠${该.量}`);
  if (该.问 !== undefined && 问.length !== 该.问) 错.push(`该问 ${该.问} 条，实际 ${问.length} 条`);
  /* 规格不许丢 */
  if (该.规格) {
    const 有 = 行.some(L => L.规格 === 该.规格);
    if (!有) 错.push(`规格「${该.规格}」丢了`);
  }
  /* 点位不许丢 */
  if (该.点位数 !== undefined) {
    let 点 = 0;
    行.forEach(L => (L.分布 || []).forEach(d => { if (d.点位号 || d.点位名) 点++; }));
    if (点 !== 该.点位数) 错.push(`点位 ${点}≠${该.点位数}`);
  }

  if (!错.length) { 过++; console.log(`  ✅ ${名}`); }
  else {
    败++;
    console.log(`  ❌ ${名}　${错.join("　/　")}`);
    行.forEach(L => console.log(`       ${L.品名}${L.规格 ? "(" + L.规格 + ")" : ""} = ` +
      (L.分布 || []).map(d => d.数量 + (d.单位 || "") + "@" + (d.点位号 || d.点位名 || "")).join(" + ")));
    问.forEach(q => console.log(`       要问：第${q.行}行第${q.列}列「${q.原文}」—— ${q.为什么}`));
  }
}

console.log("\n── 一、没有点位的表：不许问（老板：没有点位的就不用管他）──");
卷("只有品名/单位/数量",
  [["商品名", "单位", "数量"],
   ["老豆腐", "斤", "6"],
   ["千张", "斤", "8"]],
  { 样: 2, 量: 14, 问: 0 });

console.log("\n── 二、有货却没人认领：必须问（这就是以前一直在漏的）──");
/* 按列问不按格问：整列没归宿是【一个】问题，不是每格一个。
   一格一问的话真单能问出 418 条，人一条都不会看 —— 等于没问。 */
卷("多出一列「加送 3盒」没被认领",
  [["商品名", "单位", "数量", "加送"],
   ["老豆腐", "斤", "6", "3盒"],
   ["千张", "斤", "8", "2盒"]],
  { 样: 2, 量: 14, 问: 1 });

console.log("\n── 三、跟货无关的：不许烦人 ──");
卷("多一列日期",
  [["商品名", "单位", "数量", "下单日期"],
   ["老豆腐", "斤", "6", "2026-08-14"],
   ["千张", "斤", "8", "2026-08-14"]],
  { 样: 2, 量: 14, 问: 0 });

卷("多一列收货人（表头写明了跟货无关）",
  [["商品名", "单位", "数量", "收货人"],
   ["老豆腐", "斤", "6", "张伟"],
   ["千张", "斤", "8", "李明"]],
  { 样: 2, 量: 14, 问: 0 });

console.log("\n── 四、规格不许丢（老板：规格是所有坑的根）──");
卷("序号/规格/单位/数量/点位号 全套",
  [["序号", "商品名称", "规格", "单位", "数量", "点位号"],
   ["1", "老豆腐", "1斤/斤", "斤", "6", "K53"],
   ["2", "嫩豆腐", "400g/盒", "盒", "32", "515"]],
  { 样: 2, 量: 38, 规格: "1斤/斤", 点位数: 2, 问: 0 });

console.log("\n── 五、点位里带着数量：一段都不许丢 ──");
卷("一格挤一串",
  [["商品名", "订菜分布清单"],
   ["老豆腐", "3盒*欧巢门窗（三厂）【K53】+2盒*A017总部"],
   ["千张", "5斤*B158"]],
  { 样: 2, 量: 10, 点位数: 3, 问: 0 });

console.log("\n── 六、抬头压好几层：抬头不算漏，货一样不少 ──");
卷("御口福那种四层抬头",
  [["御口福经贸发展有限公司"],
   ["采购单位：狮山分公司"],
   ["打印时间：2026-08-14 09:00"],
   ["商品名", "单位", "数量"],
   ["内脂嫩豆腐", "盒", "3"],
   ["老豆腐", "斤", "4"],
   ["素鸡", "斤", "2"]],
  { 样: 3, 量: 9, 问: 0 });

console.log("\n── 七、商品编码不是数量，也不算漏 ──");
卷("编码列 8 位数字",
  [["商品编码", "商品名", "单位", "数量"],
   ["36010003", "老豆腐", "斤", "6"],
   ["28000031", "千张", "斤", "8"]],
  { 样: 2, 量: 14, 问: 0 });

console.log("\n══════════════════════════");
console.log(败 ? `有 ${败} 道没过（过 ${过}）` : `全部通过：${过} 项`);
process.exit(败 ? 1 : 0);
